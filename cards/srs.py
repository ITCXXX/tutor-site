# -*- coding: utf-8 -*-
"""Обёртка над планировщиком FSRS.

Единственное место в проекте, которое знает про библиотеку fsrs. Всё остальное
работает с моделями CardState и CardReview, поэтому планировщик можно заменить
или увезти внутрь проекта, не трогая ни вьюхи, ни шаблоны.

Библиотека — fsrs 6.3.2, лицензия MIT, 1180 строк чистого Python; из
зависимостей только typing-extensions. torch нужен единственно оптимизатору
весов, который подключается лениво и здесь не используется.

Что настраиваем и почему:

* desired_retention — главный рычаг нагрузки. При 0,80 пятый интервал выходит
  под 2800 дней, при 0,95 — 19 дней. Для подготовки к экзамену нужна верхняя
  половина шкалы: цель не «помнить дёшево вечно», а «помнить наверняка в июне».
* maximum_interval — по умолчанию в библиотеке 36500 дней. Для экзамена это
  бессмыслица: карточка, выученная в сентябре, всплыла бы через десять лет.
  Если у колоды указана дата экзамена, потолок равен числу дней до неё.

Веса модели (21 число) по умолчанию стандартные — они обучены на большой чужой
выборке и работают сразу. Личные считает команда `manage.py fsrs_optimize` по
истории конкретного ученика; до 512 повторений это гадание, и команда честно
об этом говорит, ничего не записывая.
"""

from datetime import timedelta, timezone as dt_timezone

from django.utils import timezone

from fsrs import Card as FSRSCard, Rating, Scheduler, State

from .models import CardReview, CardState, SchedulerWeights


# Шаги обучения: карточку показывают через минуту и через десять, и лишь потом
# она уходит в «дни». Так первое знакомство закрепляется в тот же заход.
ШАГИ_ОБУЧЕНИЯ = (timedelta(minutes=1), timedelta(minutes=10))
ШАГИ_ПЕРЕУЧИВАНИЯ = (timedelta(minutes=10),)

# Сутки в учёбе кончаются не в полночь: тот, кто сел заниматься в час ночи,
# считает это вчерашним вечером. Anki по той же причине переводит день в 4 утра.
ЧАС_СМЕНЫ_СУТОК = 4

# Сколько раз подряд карточка может остаться в стадии изучения. В FSRS оценка
# «Трудно» повторяет текущий шаг, не двигая карточку дальше: нажимая её из
# честности, ученик застревает на «через 6 минут» бесконечно. После этого
# предела «Трудно» выпускает карточку в обычные повторения.
ПРЕДЕЛ_ШАГОВ = 6

# Потолок интервала, когда дата экзамена не указана. Пять лет — заведомо
# больше любого учебного горизонта и заведомо меньше библиотечных ста лет.
ПОТОЛОК_БЕЗ_ЭКЗАМЕНА = 1825

# Сколько чисел в модели FSRS и сколько повторений нужно оптимизатору, чтобы
# из них вышло что-то осмысленное. Порог не наш: ниже него библиотека сама
# возвращает стандартные веса.
ЧИСЛО_ВЕСОВ = 21
ПОРОГ_ОБУЧЕНИЯ = 512


def начало_суток(когда=None):
    """Начало учебных суток (4 утра по местному времени) для данного момента."""
    когда = когда or timezone.now()
    местное = timezone.localtime(когда)
    граница = местное.replace(hour=ЧАС_СМЕНЫ_СУТОК, minute=0, second=0, microsecond=0)
    if местное < граница:
        граница -= timedelta(days=1)
    return граница


def _потолок(колода):
    """Максимальный интервал в днях: до экзамена, если он назначен."""
    if not колода.exam_date:
        return ПОТОЛОК_БЕЗ_ЭКЗАМЕНА
    осталось = (колода.exam_date - timezone.localdate()).days
    # Хотя бы день: библиотека не принимает нулевой потолок, да и после
    # экзамена карточки никто не отменял.
    return max(1, осталось)


def веса(user):
    """Личные веса модели, если они посчитаны; иначе None — стандартные.

    Стандартные веса обучены на большой чужой выборке и работают сразу. Личные
    считает команда `fsrs_optimize` по истории конкретного ученика — но только
    когда истории накопилось достаточно (см. ПОРОГ_ОБУЧЕНИЯ).
    """
    if not (user and getattr(user, 'pk', None)):
        return None
    запись = SchedulerWeights.objects.filter(user=user).first()
    if not запись or len(запись.parameters or []) != ЧИСЛО_ВЕСОВ:
        return None
    return запись.parameters


def планировщик(колода, user=None, *, без_шагов=False):
    """Настроенный FSRS для этой колоды и, если веса посчитаны, этого ученика."""
    личные = веса(user)
    ключ = {'parameters': личные} if личные else {}
    try:
        return Scheduler(
            desired_retention=колода.desired_retention,
            learning_steps=() if без_шагов else ШАГИ_ОБУЧЕНИЯ,
            relearning_steps=() if без_шагов else ШАГИ_ПЕРЕУЧИВАНИЯ,
            maximum_interval=_потолок(колода),
            **ключ,
        )
    except ValueError:
        # Веса не прошли проверку границ (испорчены руками в админке или
        # остались от другой версии модели). Занятие важнее настройки —
        # продолжаем на стандартных.
        return Scheduler(
            desired_retention=колода.desired_retention,
            learning_steps=() if без_шагов else ШАГИ_ОБУЧЕНИЯ,
            relearning_steps=() if без_шагов else ШАГИ_ПЕРЕУЧИВАНИЯ,
            maximum_interval=_потолок(колода),
        )


def _в_fsrs(состояние):
    """Состояние из базы → объект библиотеки.

    Идентификатор передаём свой: без него библиотека собирает его из
    миллисекунд эпохи и ради уникальности делает time.sleep(0.001) на каждом
    создании — полторы миллисекунды против четырёх десятитысячных.
    """
    return FSRSCard(
        card_id=состояние.pk or 1,
        state=State(состояние.state),
        step=состояние.step,
        stability=состояние.stability,
        difficulty=состояние.difficulty,
        due=_utc(состояние.due),
        last_review=_utc(состояние.last_review),
    )


def _utc(момент):
    """Библиотека принимает время только в UTC и только с меткой пояса."""
    if момент is None:
        return None
    return момент.astimezone(dt_timezone.utc)


def оценить(состояние, оценка, *, когда=None, длительность=None, набрано=''):
    """Применить оценку: пересчитать состояние и записать строку журнала.

    Возвращает (состояние, следующий_показ) — второй элемент удобно показать
    ученику сразу («увидимся через 3 дня»).
    """
    когда = когда or timezone.now()
    оценка = Rating(int(оценка))
    колода = состояние.card.deck

    застрял = (состояние.state == CardState.ИЗУЧЕНИЕ
               and состояние.reps >= ПРЕДЕЛ_ШАГОВ
               and оценка != Rating.Again)
    планер = планировщик(колода, состояние.user, без_шагов=застрял)

    новая, _журнал = планер.review_card(
        _в_fsrs(состояние), оценка, review_datetime=_utc(когда),
        review_duration=длительность,
    )

    if оценка == Rating.Again and состояние.state == CardState.ПОВТОРЕНИЕ:
        состояние.lapses += 1
    if состояние.reps == 0:
        состояние.started_at = когда

    состояние.state = int(новая.state)
    состояние.step = новая.step
    состояние.stability = новая.stability
    состояние.difficulty = новая.difficulty
    состояние.due = новая.due
    состояние.last_review = новая.last_review
    состояние.reps += 1
    состояние.save()

    CardReview.objects.create(
        user_id=состояние.user_id, card_id=состояние.card_id,
        direction=состояние.direction, rating=int(оценка),
        reviewed_at=когда, duration_ms=длительность, typed=(набрано or '')[:300],
    )
    return состояние, новая.due


def пауза_словами(due, откуда=None):
    """«через 3 дня», «через 10 минут» — то, что показываем на кнопке."""
    откуда = откуда or timezone.now()
    минут = max(0, (due - откуда).total_seconds()) / 60
    if минут < 60:
        return '%d мин' % max(1, round(минут))
    if минут < 60 * 24:
        return '%d ч' % round(минут / 60)
    дней = round(минут / 60 / 24)
    if дней < 31:
        return '%d дн' % дней
    if дней < 365:
        return '%d мес' % round(дней / 30)
    return '%.1f г' % (дней / 365)


def предпросмотр(состояние):
    """Что будет за каждую из четырёх оценок — надписи на кнопках.

    Считается настоящим планировщиком на копии состояния, поэтому цифры на
    кнопках всегда совпадают с тем, что произойдёт при нажатии.
    """
    колода = состояние.card.deck
    сейчас = timezone.now()
    застрял = (состояние.state == CardState.ИЗУЧЕНИЕ
               and состояние.reps >= ПРЕДЕЛ_ШАГОВ)
    итог = {}
    for оценка in (Rating.Again, Rating.Hard, Rating.Good, Rating.Easy):
        планер = планировщик(колода, состояние.user,
                             без_шагов=(застрял and оценка != Rating.Again))
        новая, _ = планер.review_card(_в_fsrs(состояние), оценка,
                                      review_datetime=_utc(сейчас))
        итог[int(оценка)] = пауза_словами(новая.due, сейчас)
    return итог


def состояние_для(user, карточка, направление):
    """Найти или завести состояние пары «ученик — сторона карточки»."""
    состояние, _создано = CardState.objects.get_or_create(
        user=user, card=карточка, direction=направление,
    )
    return состояние


def очередь(user, колода, предел=None):
    """Что показать ученику прямо сейчас, в порядке показа.

    Сначала то, что подошло по сроку (самое просроченное первым), затем новые
    карточки — но не больше дневного потолка. Потолки существуют не для
    строгости: колода в триста карточек без них вываливается вся в первый день,
    и ученик бросает раздел навсегда.
    """
    сейчас = timezone.now()
    сутки = начало_суток(сейчас)

    карточки = list(колода.cards.all())
    по_id = {к.pk: к for к in карточки}
    состояния = list(
        CardState.objects.filter(user=user, card__deck=колода)
        .select_related('card')
    )
    известные = {(с.card_id, с.direction) for с in состояния}

    к_повторению = sorted(
        (с for с in состояния if not с.suspended and с.due <= сейчас),
        key=lambda с: с.due,
    )
    сделано_сегодня = CardReview.objects.filter(
        user=user, card__deck=колода, reviewed_at__gte=сутки,
    ).count()
    если_есть_потолок = колода.reviews_per_day > 0
    if если_есть_потолок:
        осталось = max(0, колода.reviews_per_day - сделано_сегодня)
        к_повторению = к_повторению[:осталось]

    новых_сегодня = sum(
        1 for с in состояния if с.started_at and с.started_at >= сутки
    )
    место_под_новые = max(0, колода.new_per_day - новых_сегодня)
    новые = []
    for карточка in карточки:
        for направление in колода.направления:
            if (карточка.pk, направление) not in известные:
                новые.append((карточка, направление))
    новые = новые[:место_под_новые]

    очередь_ = [(по_id[с.card_id], с.direction, с) for с in к_повторению]
    очередь_ += [(к, н, None) for к, н in новые]
    if предел:
        очередь_ = очередь_[:предел]
    return очередь_


def счётчики(user, колода):
    """Цифры для страницы колоды: сколько ждёт, сколько новых, сколько выучено."""
    сейчас = timezone.now()
    сутки = начало_суток(сейчас)
    состояния = list(CardState.objects.filter(user=user, card__deck=колода))
    всего_сторон = колода.cards.count() * len(колода.направления)

    новых_сегодня = sum(1 for с in состояния if с.started_at and с.started_at >= сутки)
    сделано_сегодня = CardReview.objects.filter(
        user=user, card__deck=колода, reviewed_at__gte=сутки,
    ).count()
    ждут = sum(1 for с in состояния
               if not с.suspended and с.due <= сейчас)
    if колода.reviews_per_day > 0:
        ждут = min(ждут, max(0, колода.reviews_per_day - сделано_сегодня))

    return {
        'всего': всего_сторон,
        'начато': len(состояния),
        'новых_доступно': min(
            всего_сторон - len(состояния),
            max(0, колода.new_per_day - новых_сегодня),
        ),
        'ждут': ждут,
        'сделано_сегодня': сделано_сегодня,
        'выучено': sum(1 for с in состояния
                       if с.state == CardState.ПОВТОРЕНИЕ and (с.stability or 0) >= 21),
    }
