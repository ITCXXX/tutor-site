# -*- coding: utf-8 -*-
"""Разметка в карточках: узкий белый список и чистка на входе.

Раньше текст карточки выводился через textContent — карточка физически не могла
принести на страницу разметку. Как только появилось форматирование, эта защита
исчезла: содержимое пишут ученики, колоды бывают общими, и «жирный шрифт» —
это та же дверь, через которую заходит `<script>`.

Поэтому разметка чистится ОДИН раз, при записи в базу, а не при показе. Так
неочищенного текста в базе не оказывается в принципе: забыть про чистку в одном
из шаблонов легко, забыть в Card.save() — нет.

Что остаётся:

* начертание — `<b>`, `<i>`, `<u>` (устаревшие `strong`/`em` приводятся к ним);
* цвет текста и заливка — `<span style="color: …; background-color: …">`,
  причём цвет обязан быть настоящим цветом, а не любой строкой в style;
* переносы строк — обычным символом перевода строки, а не `<br>`.

Почему без `<br>`. Редактор на contenteditable выдаёт то `<br>`, то `<div>`, то
`<p>` — в зависимости от браузера и от того, как нажали Enter. Приводя всё к
переводу строки, мы получаем одну форму хранения на все случаи, а показываем с
`white-space: pre-wrap`, который уже стоял в шаблонах ради многострочных
карточек из массового ввода.

Ссылок, картинок, таблиц и классов нет намеренно: карточка — это один факт на
две строки, а каждый разрешённый тег надо потом всю жизнь проверять.
"""

import re
from html import escape, unescape
from html.parser import HTMLParser

# Начертания. Ключ — что пришло, значение — во что превращаем.
НАЧЕРТАНИЯ = {
    'b': 'b', 'strong': 'b',
    'i': 'i', 'em': 'i',
    'u': 'u',
}

# Теги, которые сами по себе ничего не значат, но их содержимое нужно.
ПРОЗРАЧНЫЕ = {'span', 'font', 'div', 'p', 'section', 'article', 'ul', 'ol', 'li'}

# Теги, после которых начинается новая строка.
ПЕРЕНОСЫ = {'div', 'p', 'li', 'br', 'tr'}

# Теги, у которых опасно САМО СОДЕРЖИМОЕ: внутри них лежит не текст, а код или
# оформление. Их выбрасываем вместе с начинкой.
#
# Список узкий намеренно. Сначала сюда попали ещё svg, iframe и object, но у
# незакрытого тега (а «<svg/onload=…>» именно такой) выброс не кончается никогда
# и съедает весь текст после него — ученик, вставивший кусок веб-страницы, терял
# бы карточку целиком. Их опасность в атрибутах, а атрибуты мы и так снимаем со
# всех тегов, кроме разрешённых.
ВЫБРОСИТЬ = {'script', 'style', 'noscript', 'template', 'head', 'title'}

# Цвет обязан быть цветом. Проверяем строго: «expression(...)» и «url(...)» в
# style — классический способ вернуть выполнение кода через оформление.
ЦВЕТ = re.compile(
    r'^#(?:[0-9a-f]{3}|[0-9a-f]{4}|[0-9a-f]{6}|[0-9a-f]{8})$'
    r'|^rgba?\(\s*[\d.]+%?\s*,\s*[\d.]+%?\s*,\s*[\d.]+%?\s*(?:,\s*[\d.]+\s*)?\)$'
    r'|^[a-z]{3,20}$',                      # словесные: red, teal, transparent
    re.I,
)

ПРЕДЕЛ_ДЛИНЫ = 4000


class _Чистильщик(HTMLParser):
    """Собирает заново только то, что разрешено; всё прочее становится текстом."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.куски = []
        self.стек = []          # открытые разрешённые теги, чтобы закрыть их парно
        self.молчим = 0         # глубина внутри выброшенного тега

    # ── разбор ────────────────────────────────────────────────────────
    def handle_starttag(self, тег, атрибуты):
        if self.молчим:
            return
        if тег in ВЫБРОСИТЬ:
            self.молчим += 1
            return
        if тег in ПЕРЕНОСЫ and тег != 'br':
            self._перенос()
        if тег == 'br':
            self._перенос()
            return

        начертание = НАЧЕРТАНИЯ.get(тег)
        if начертание:
            self.куски.append('<%s>' % начертание)
            self.стек.append([начертание])
            return

        if тег in ПРОЗРАЧНЫЕ:
            свойства = dict(атрибуты)
            открытые = []
            # Начертание, записанное через style, тоже начертание: так его
            # отдаёт execCommand в режиме styleWithCSS и так оно приезжает из
            # буфера обмена.
            for имя in self._начертания_из_стиля(свойства):
                self.куски.append('<%s>' % имя)
                открытые.append(имя)
            style = self._цвета(свойства)
            if style:
                self.куски.append('<span style="%s">' % style)
                открытые.append('span')
            self.стек.append(открытые)
            return
        # Любой другой тег просто исчезает, а его содержимое остаётся текстом.

    def handle_endtag(self, тег):
        if self.молчим:
            if тег in ВЫБРОСИТЬ:
                self.молчим -= 1
            return
        if тег == 'br':
            return
        if тег in ПЕРЕНОСЫ:
            self._перенос()
        if тег in НАЧЕРТАНИЯ or тег in ПРОЗРАЧНЫЕ:
            if self.стек:
                for имя in reversed(self.стек.pop()):
                    self.куски.append('</%s>' % имя)

    def handle_startendtag(self, тег, атрибуты):
        if тег == 'br':
            self._перенос()
        else:
            self.handle_starttag(тег, атрибуты)
            self.handle_endtag(тег)

    def handle_data(self, текст):
        if not self.молчим:
            self.куски.append(escape(текст, quote=False))

    # ── помощники ─────────────────────────────────────────────────────
    def _перенос(self):
        if self.куски and not self.куски[-1].endswith('\n'):
            self.куски.append('\n')

    def _начертания_из_стиля(self, атрибуты):
        """Жирный, курсив и подчёркивание, записанные свойствами оформления."""
        найдено = []
        for кусок in (атрибуты.get('style') or '').split(';'):
            имя, _, значение = кусок.partition(':')
            имя, значение = имя.strip().lower(), значение.strip().lower()
            if имя == 'font-weight' and (значение in ('bold', 'bolder')
                                         or значение.isdigit() and int(значение) >= 600):
                найдено.append('b')
            elif имя == 'font-style' and значение in ('italic', 'oblique'):
                найдено.append('i')
            elif имя == 'text-decoration' and 'underline' in значение:
                найдено.append('u')
        return найдено

    def _цвета(self, атрибуты):
        """Оставить из style только цвет текста и заливку, и только настоящие."""
        пары = []

        # <font color="..."> — так красит execCommand в некоторых браузерах.
        цвет_шрифта = (атрибуты.get('color') or '').strip()
        if цвет_шрифта and ЦВЕТ.match(цвет_шрифта):
            пары.append('color: %s' % цвет_шрифта)

        for кусок in (атрибуты.get('style') or '').split(';'):
            if ':' not in кусок:
                continue
            имя, _, значение = кусок.partition(':')
            имя = имя.strip().lower()
            значение = значение.strip()
            if имя not in ('color', 'background-color', 'background'):
                continue
            if имя == 'background':
                имя = 'background-color'
            if not ЦВЕТ.match(значение):
                continue
            пары.append('%s: %s' % (имя, значение))

        # Одно и то же свойство могло прийти дважды — оставляем последнее.
        свод = {}
        for пара in пары:
            имя, _, значение = пара.partition(':')
            свод[имя.strip()] = значение.strip()
        return '; '.join('%s: %s' % (и, з) for и, з in свод.items())

    def итог(self):
        while self.стек:
            for имя in reversed(self.стек.pop()):
                self.куски.append('</%s>' % имя)
        return ''.join(self.куски)


def очистить(значение):
    """Привести содержимое карточки к разрешённой разметке.

    Обычный текст проходит насквозь: угловые скобки в нём экранируются, и
    «a < b» остаётся видимым, а не превращается в поломанный тег.
    """
    if not значение:
        return ''
    чистильщик = _Чистильщик()
    чистильщик.feed(str(значение)[:ПРЕДЕЛ_ДЛИНЫ * 4])
    чистильщик.close()
    готово = чистильщик.итог()

    # Пустые теги, оставшиеся от удалённого содержимого, только мешают.
    прежний = None
    while прежний != готово:
        прежний = готово
        готово = re.sub(r'<(b|i|u|span)(?: [^>]*)?>\s*</\1>', '', готово)

    return готово.strip()[:ПРЕДЕЛ_ДЛИНЫ]


def текстом(значение):
    """Голый текст без разметки — для сравнения ответов и для поиска.

    Проверка ответа не должна знать, что слово было выделено жирным: ученик
    набирает «Париж», а в базе может лежать «<b>Париж</b>».
    """
    if not значение:
        return ''
    без_тегов = re.sub(r'<[^>]*>', '', str(значение))
    return unescape(без_тегов).strip()


def пусто(значение):
    """Считается ли содержимое пустым: одни теги и пробелы — это пусто."""
    return not текстом(значение).strip()
