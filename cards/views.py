ГОРИЗОНТ_ПРОГНОЗА = 14      # дней вперёд
ГЛУБИНА_АКТИВНОСТИ = 30     # дней назад
ПОРОГ_ПИЯВКИ = 3            # столько забываний — и карточку пора переписать
ПОРОГ_ЗАКРЕПЛЕНИЯ = 21      # прочность в днях, после которой карточка «выучена»


@login_required
def статистика(request, pk):
    """Что видно про колоду: чем занят ученик и что идёт плохо.

    Отдельная страница, а не блок на колоде: здесь нужны цифры, за которыми
    надо идти в журнал повторений, и грузить их на каждый заход в колоду
    незачем.
    """
    колода = _колода_для_просмотра(request, pk)
    сейчас = timezone.now()
    сегодня = timezone.localdate()

    состояния = list(
        CardState.objects.filter(user=request.user, card__deck=колода)
        .select_related('card')
    )
    сторон = колода.cards.count() * len(колода.направления)

    закрепилось = sum(1 for с in состояния
                      if (с.stability or 0) >= ПОРОГ_ЗАКРЕПЛЕНИЯ)
    на_повторении = sum(1 for с in состояния
                        if с.state == CardState.ПОВТОРЕНИЕ) - закрепилось
    изучается = len(состояния) - закрепилось - max(0, на_повторении)
    не_начато = max(0, сторон - len(состояния))

    # Прогноз: сколько карточек созреет в каждый из ближайших дней. Просроченное
    # сваливаем в «сегодня» — ученику важно, сколько работы сейчас, а не когда
    # именно эта карточка должна была подойти.
    прогноз = [{'день': сегодня + timedelta(days=i), 'сколько': 0}
               for i in range(ГОРИЗОНТ_ПРОГНОЗА)]
    for состояние in состояния:
        if состояние.suspended:
            continue
        сдвиг = (timezone.localtime(состояние.due).date() - сегодня).days
        сдвиг = max(0, сдвиг)
        if сдвиг < ГОРИЗОНТ_ПРОГНОЗА:
            прогноз[сдвиг]['сколько'] += 1
    пик_прогноза = max([д['сколько'] for д in прогноз] + [1])
    for день in прогноз:
        день['доля'] = round(100 * день['сколько'] / пик_прогноза)

    # Активность: сколько повторений сделано в каждый из прошедших дней.
    с_какого = сейчас - timedelta(days=ГЛУБИНА_АКТИВНОСТИ)
    по_дням = {}
    for отметка in (CardReview.objects
                    .filter(user=request.user, card__deck=колода,
                            reviewed_at__gte=с_какого)
                    .values_list('reviewed_at', flat=True)):
        день = srs.начало_суток(отметка).date()
        по_дням[день] = по_дням.get(день, 0) + 1
    активность = [
        {'день': сегодня - timedelta(days=i), 'сколько': по_дням.get(сегодня - timedelta(days=i), 0)}
        for i in range(ГЛУБИНА_АКТИВНОСТИ - 1, -1, -1)
    ]
    пик_активности = max([д['сколько'] for д in активность] + [1])
    for день in активность:
        день['доля'] = round(100 * день['сколько'] / пик_активности)

    трудные = sorted(
        (с for с in состояния if с.lapses >= ПОРОГ_ПИЯВКИ),
        key=lambda с: -с.lapses,
    )[:15]

    всего_повторений = CardReview.objects.filter(
        user=request.user, card__deck=колода,
    ).count()

    return render(request, 'cards/stats.html', {
        'колода': колода,
        'сторон': сторон,
        'закрепилось': закрепилось,
        'на_повторении': max(0, на_повторении),
        'изучается': max(0, изучается),
        'не_начато': не_начато,
        'прогноз': прогноз,
        'активность': активность,
        'трудные': трудные,
        'всего_повторений': всего_повторений,
        'дней_подряд': _дней_подряд(по_дням, сегодня),
        'счёт': srs.счётчики(request.user, колода),
    })


def _дней_подряд(по_дням, сегодня):
    """Сколько дней подряд ученик занимался, считая назад от сегодня.

    Сегодняшний день, если он ещё пустой, серию не обрывает: вечер не наступил.
    """
    серия = 0
    день = сегодня
    if not по_дням.get(день):
        день -= timedelta(days=1)
    while по_дням.get(день):
        серия += 1
        день -= timedelta(days=1)
    return серия


def _когда_отвечали(метка):
    """Время ответа, присланное страницей, — для оценок, накопленных без сети.

    Ученик в метро отвечает на карточки, а отправляются оценки, когда связь
    вернётся. Если считать интервал от момента доставки, всё расписание
    поедет: FSRS смотрит, сколько прошло с прошлого показа.

    Метке из браузера доверяем в узких рамках: не из будущего (кроме минут
    расхождения часов) и не старше двух недель. Всё остальное — сейчас.
    """
    if not метка:
        return None
    try:
        когда = datetime.fromisoformat(str(метка).replace('Z', '+00:00'))
    except (TypeError, ValueError):
        return None
    if когда.tzinfo is None:
        когда = когда.replace(tzinfo=dt_timezone.utc)
    сейчас = timezone.now()
    if когда > сейчас + timedelta(minutes=5) or когда < сейчас - timedelta(days=14):
        return None
    return min(когда, сейчас)


@require_POST
def проверить_многие(request, pk):
    """Проверка пачки ответов разом — для режима «Тест».

    Отдельный адрес, а не цикл по одиночной проверке: в тесте два десятка
    вопросов, и двадцать запросов подряд превратили бы нажатие «Проверить» в
    заметную паузу.
    """
    колода = _колода_для_просмотра(request, pk)
    данные = _разобрать_запрос(request)
    ответы = данные.get('ответы')
    if not isinstance(ответы, list) or len(ответы) > 200:
        return JsonResponse({'ошибка': 'нужен список ответов'}, status=400)

    карточки = {к.pk: к for к in колода.cards.all()}
    итог = []
    for пункт in ответы:
        карточка = карточки.get(пункт.get('card'))
        if карточка is None:
            итог.append({'card': пункт.get('card'), 'верно': False, 'эталон': ''})
            continue
        направление = int(пункт.get('direction') or CardState.ПРЯМОЕ)
        итог.append({
            'card': карточка.pk,
            'верно': _ответ_подходит(колода, карточка, направление,
                                     пункт.get('typed') or ''),
            'эталон': карточка.варианты_ответа(направление)[0],
        })
    return JsonResponse({'ответы': итог})
