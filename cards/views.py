def _сторона(карточка, направление, какая):
    """Что показать: 'вопрос' или 'ответ' с учётом направления."""
    прямое = направление == CardState.ПРЯМОЕ
    if какая == 'вопрос':
        return карточка.front if прямое else карточка.back
    return карточка.back if прямое else карточка.front


@login_required
def учить(request, pk):
    """Экран повторения. Очередь уезжает на страницу целиком одним куском."""
    объект = _колода_для_просмотра(request, pk)
    очередь = srs.очередь(request.user, объект)

    все_карточки = list(объект.cards.all())
    задания = []
    for карточка, направление, состояние in очередь:
        # Для новой карточки строки в базе ещё нет — берём несохранённую,
        # только чтобы посчитать надписи на кнопках. Запись появится, когда
        # ученик впервые её оценит.
        расчётное = состояние or CardState(
            user=request.user, card=карточка, direction=направление,
        )
        задание = _задание(объект, карточка, направление, все_карточки)
        задание.update({
            'новая': состояние is None,
            'кнопки': srs.предпросмотр(расчётное),
        })
        задания.append(задание)

    return render(request, 'cards/study.html', {
        'колода': объект,
        'задания': задания,
        'счёт': srs.счётчики(request.user, объект),
    })


def _задание(колода, карточка, направление, все_карточки):
    """Одна карточка в том виде, в каком её показывает страница.

    Способ вопроса здесь не решается: варианты кладутся в задание всегда, а
    переворотом спросить или выбором — решает человек за экраном и меняет
    посреди захода.
    """
    return {
        'card': карточка.pk,
        'direction': направление,
        # Ключ пары «карточка + сторона»: по нему страница ведёт свой учёт,
        # потому что одна карточка может спрашиваться в обе стороны.
        'ключ': '%d-%d' % (карточка.pk, направление),
        'вопрос': _сторона(карточка, направление, 'вопрос'),
        'ответ': _сторона(карточка, направление, 'ответ'),
        'подсказка': карточка.hint,
        'варианты': варианты_выбора(колода, карточка, направление, все_карточки),
        'свои_неверные': bool(карточка.неверные()) if направление == CardState.ПРЯМОЕ else False,
    }


ВАРИАНТОВ_В_ВОПРОСЕ = 4


def варианты_выбора(колода, карточка, направление, все_карточки):
    """Список вариантов для вопроса с выбором, уже перемешанный.

    Сначала берём неверные ответы, написанные автором карточки: правдоподобная
    ошибка проверяет, отличает ли ученик её от правильного. Если своих не
    хватает, добираем ответами других карточек колоды — они хотя бы из той же
    темы.

    Свои неверные варианты относятся к обороту: в обратную сторону спрашивают
    лицевую, и там они ни при чём.
    """
    верный = _сторона(карточка, направление, 'ответ')
    варианты = []
    if направление == CardState.ПРЯМОЕ:
        варианты = [в for в in карточка.неверные() if в != верный]

    if len(варианты) < ВАРИАНТОВ_В_ВОПРОСЕ - 1:
        занято = set(варианты) | {верный}
        чужие = []
        for другая in все_карточки:
            if другая.pk == карточка.pk:
                continue
            ответ = _сторона(другая, направление, 'ответ')
            if ответ and ответ not in занято:
                занято.add(ответ)
                чужие.append(ответ)
        random.shuffle(чужие)
        варианты += чужие[:ВАРИАНТОВ_В_ВОПРОСЕ - 1 - len(варианты)]
    else:
        random.shuffle(варианты)
        варианты = варианты[:ВАРИАНТОВ_В_ВОПРОСЕ - 1]

    варианты.append(верный)
    random.shuffle(варианты)
    return варианты


def _разобрать_запрос(request):
    try:
        return json.loads(request.body.decode('utf-8'))
    except (ValueError, UnicodeDecodeError):
        return {}


def _похоже(набрано, эталон):
    """Сравнение текстовых ответов с прощением опечатки.

    Мера — расстояние Левенштейна: одна опечатка прощается всегда, дальше —
    не более 15 % длины, как это делает Quizlet. Без этого ученик, написавший
    «биссектрисса», получает «неверно» и перестаёт вводить ответы вообще.
    """
    a = _упростить(набрано)
    b = _упростить(эталон)
    if not a or not b:
        return False
    if a == b:
        return True
    предел = max(1, int(len(b) * 0.15))
    return _левенштейн(a, b, предел) <= предел


def _упростить(строка):
    строка = (строка or '').strip().lower().replace('ё', 'е')
    строка = ' '.join(строка.split())
    return строка.strip(' .,;:!?')


def _левенштейн(a, b, предел):
    """Расстояние Левенштейна, с досрочным выходом за пределом."""
    if abs(len(a) - len(b)) > предел:
        return предел + 1
    предыдущая = list(range(len(b) + 1))
    for i, ca in enumerate(a, 1):
        текущая = [i]
        for j, cb in enumerate(b, 1):
            текущая.append(min(
                предыдущая[j] + 1,
                текущая[j - 1] + 1,
                предыдущая[j - 1] + (ca != cb),
            ))
        if min(текущая) > предел:
            return предел + 1
        предыдущая = текущая
    return предыдущая[-1]


