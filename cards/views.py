@login_required
def импорт(request, pk):
    """Вставка списка одним куском: предпросмотр, потом добавление.

    Предпросмотр обязателен по существу дела: разбор терпим к формату, и автор
    должен увидеть, как именно понята каждая строка, прежде чем в колоде
    появятся полсотни карточек.
    """
    объект = _колода_для_правки(request, pk)
    разобранные, замечания = [], []
    форма = ImportForm()

    if request.method == 'POST':
        форма = ImportForm(request.POST)
        if форма.is_valid():
            текст = форма.cleaned_data['текст']
            уже = list(объект.cards.values_list('front', flat=True))
            разобранные, замечания = разобрать(текст, уже_есть=уже)

            if 'сохранить' in request.POST and разобранные:
                начало = объект.cards.count()
                with transaction.atomic():
                    # bulk_create не зовёт save(), поэтому чистим здесь сами.
                    # Вставленный список — тот же недоверенный ввод.
                    Card.objects.bulk_create([
                        Card(deck=объект, order=начало + i,
                             front=очистить(к['front']), back=очистить(к['back']),
                             hint=очистить(к['hint']),
                             distractors='\n'.join(
                                 очистить(с) for с in к['distractors'].splitlines()
                                 if с.strip()))
                        for i, к in enumerate(разобранные)
                    ])
                messages.success(
                    request, 'Добавлено карточек: %d.' % len(разобранные)
                )
                return redirect('cards:deck', pk=объект.pk)

    return render(request, 'cards/import.html', {
        'колода': объект, 'форма': форма,
        'разобранные': разобранные, 'замечания': замечания,
        'подсказка': ai_prompt.собрать(),
    })


