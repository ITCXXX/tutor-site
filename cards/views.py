# Похоже ли на число или формулу: цифры и знаки без единой буквы слова.
# Делить колоды на «математические» и «текстовые» оказалось незачем — вид
# ответа виден по самому ответу, и в одной колоде спокойно уживаются
# «Париж» и «2,5».
_БУКВЫ = re.compile(r'[а-яёa-z]{2,}', re.I)
_ЦИФРА = re.compile(r'\d')
_МАТЕМАТИКА = re.compile(r'[√π∞\\/^]')


def _числовой(строка):
    строка = (строка or '').strip()
    if not строка:
        return False
    if _БУКВЫ.search(строка):
        return False
    return bool(_ЦИФРА.search(строка) or _МАТЕМАТИКА.search(строка))


def _ответ_подходит(колода, карточка, направление, набрано):
    """Засчитывать ли набранное.

    Сначала обычное сравнение с прощением опечатки — оно годится и для слов, и
    для коротких чисел. Если не сошлось, а ответ похож на число или формулу,
    спрашиваем users/answer_check.py: он знает, что «2,5», «2.5» и «5/2» — одно
    и то же, а «биссектриса» ему сказать нечего.
    """
    for эталон in карточка.варианты_ответа(направление):
        if _похоже(набрано, эталон):
            return True
        if _числовой(эталон) or _числовой(набрано):
            try:
                попал, _сообщение = check_answer(набрано, эталон)
            except Exception:
                попал = False
            if попал:
                return True
    return False


@login_required
@require_POST
def ответ(request, pk):
    """Оценка карточки: пересчёт срока и запись в журнал."""
    объект = _колода_для_просмотра(request, pk)
    данные = _разобрать_запрос(request)
    карточка = get_object_or_404(Card, pk=данные.get('card'), deck=объект)
    направление = int(данные.get('direction') or CardState.ПРЯМОЕ)
    try:
        оценка = int(данные.get('rating'))
    except (TypeError, ValueError):
        return JsonResponse({'ошибка': 'нет оценки'}, status=400)
    if оценка not in (1, 2, 3, 4):
        return JsonResponse({'ошибка': 'оценка вне шкалы'}, status=400)

    длительность = данные.get('duration_ms')
    try:
        длительность = max(0, min(int(длительность), 600000))
    except (TypeError, ValueError):
        длительность = None

    состояние = srs.состояние_для(request.user, карточка, направление)
    состояние, срок = srs.оценить(
        состояние, оценка, когда=_когда_отвечали(данные.get('when')),
        длительность=длительность, набрано=данные.get('typed') or '',
    )

    сейчас = timezone.now()
    # Карточка, назначенная на ближайшие минуты, возвращается в этот же заход —
    # иначе шаги обучения не работают вовсе.
    вернуть = (срок - сейчас).total_seconds() <= 20 * 60

    расчётное = CardState.objects.get(pk=состояние.pk)
    расчётное.card = карточка
    return JsonResponse({
        'пауза': srs.пауза_словами(срок, сейчас),
        'вернуть': вернуть,
        'кнопки': srs.предпросмотр(расчётное),
        'счёт': srs.счётчики(request.user, объект),
    })


