def список(request):
    """Свои колоды и те, что открыли по ссылке."""
    все = Deck.objects.select_related('owner').annotate(карточек=Count('cards'))
    if request.user.is_authenticated:
        мои = list(все.filter(owner=request.user))
        чужие = list(все.filter(shares__user=request.user).exclude(owner=request.user))
    else:
        мои = []
        открытые = request.session.get(СЕССИЯ_ОТКРЫТЫЕ) or []
        чужие = list(все.filter(pk__in=открытые))

    if request.user.is_authenticated:
        _проставить_разбор(request.user, мои + чужие)

    return render(request, 'cards/deck_list.html', {'мои': мои, 'чужие': чужие})


def разложено(user, колода):
    """Сколько карточек колоды лежит в каждой секции у этого ученика.

    Возвращает словарь {номер секции: сколько}. Неразобранные считаются
    вычитанием, а не запросом: строки состояния заводятся только тогда, когда
    ученик впервые карточку куда-то положил, и пока он этого не сделал, её
    просто нет в таблице.
    """
    # Считать через cards.count(), а не через колода.карточек: последнее —
    # аннотация из списка колод, и на одиночной колоде её просто нет.
    сторон = колода.cards.count() * len(колода.направления)
    из_базы = {
        строка['section']: строка['сколько']
        for строка in CardState.objects
        .filter(user=user, card__deck=колода)
        .values('section').annotate(сколько=Count('id'))
    }
    сводка = {номер: из_базы.get(номер, 0)
              for номер, _ in CardState.SECTION_CHOICES}
    сводка[CardState.НЕ_РАЗОБРАНА] = сторон - sum(
        сколько for номер, сколько in сводка.items()
        if номер != CardState.НЕ_РАЗОБРАНА)
    return сводка


def _проставить_разбор(user, колоды):
    """Каждой колоде списка — сколько в ней неразобранного и сколько трудного.

    Одним запросом на весь список: по запросу на колоду страница списка не
    выдержала бы, а класть результат в словарь бесполезно — доставать значение
    по ключу шаблон Django не умеет.
    """
    сводка = {}
    for строка in (CardState.objects
                   .filter(user=user, card__deck__in=[к.pk for к in колоды])
                   .values('card__deck', 'section')
                   .annotate(сколько=Count('id'))):
        сводка.setdefault(строка['card__deck'], {})[строка['section']] = \
            строка['сколько']

    for колода in колоды:
        строки = сводка.get(колода.pk, {})
        сторон = колода.карточек * len(колода.направления)
        разобрано = sum(строки.values())
        колода.неразобрано = max(0, сторон - разобрано)
        колода.трудных = sum(строки.get(н, 0) for н in CardState.ТРУДНЫЕ)


