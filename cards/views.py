#  Режимы тренировки: заучивание, тест, подбор
#
#  Это НЕ интервальное повторение. Режимы ничего не пишут в CardState и не
#  двигают сроки: заучивание за один вечер и планирование на месяцы вперёд —
#  разные задачи, и смешивать их значит испортить обе. Ученик тренируется
#  сколько хочет, а очередь повторений живёт своей жизнью.
# ─────────────────────────────────────────────────────────────────────

def _набор(колода):
    """Карточки колоды для режимов тренировки — в обе стороны, если так задано.

    Обратные карточки здесь не удваивают работу автора: та же заметка просто
    спрашивается с другой стороны, и для «подбора» или «теста» это отдельные
    вопросы со своими вариантами ответа.
    """
    все = list(колода.cards.all())
    набор = []
    for карточка in все:
        for направление in колода.направления:
            набор.append(_задание(колода, карточка, направление, все))
    return набор


