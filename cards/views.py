def список(request):
    """Свои колоды и те, что открыли по ссылке."""
    все = Deck.objects.select_related('owner').annotate(карточек=Count('cards'))
    if request.user.is_authenticated:
        мои = list(все.filter(owner=request.user))
        чужие = list(все.filter(shares__user=request.user).exclude(owner=request.user))
    else:
        мои = []
        открытые = request.session.get(СЕССИЯ_ОТКРЫТЫЕ) or []
        чужие = list(все.filter(pk__in=открытые))

    if request.user.is_authenticated:
        _проставить_очередь(request.user, мои + чужие)

    return render(request, 'cards/deck_list.html', {'мои': мои, 'чужие': чужие})


def _проставить_очередь(user, колоды):
    """Сколько карточек ученик может взять сейчас в каждой колоде.

    Считать надо и созревшие, и ещё не начатые: колода, где все пять карточек
    новые, иначе показывала бы «на сегодня всё». Всё считается двумя запросами
    на весь список — по запросу на колоду раздел бы не выдержал даже при
    нынешних масштабах, а результат класть в словарь бесполезно: доставать
    значение по ключу шаблон Django не умеет.
    """
    сейчас = timezone.now()
    сутки = srs.начало_суток(сейчас)

    сводка = {
        строка['card__deck']: строка
        for строка in CardState.objects
        .filter(user=user, card__deck__in=[к.pk for к in колоды])
        .values('card__deck')
        .annotate(
            начато=Count('id'),
            созрело=Count('id', filter=Q(due__lte=сейчас, suspended=False)),
            новых_сегодня=Count('id', filter=Q(started_at__gte=сутки)),
        )
    }

    for колода in колоды:
        строка = сводка.get(колода.pk, {})
        сторон = колода.карточек * len(колода.направления)
        не_начато = сторон - строка.get('начато', 0)
        место = max(0, колода.new_per_day - строка.get('новых_сегодня', 0))
        колода.ждёт = строка.get('созрело', 0) + min(не_начато, место)


ПРЕДЕЛ_КАРТОЧЕК = 500

# Палитра редактора. Немного и с запасом контраста: пёстрая карточка читается
# хуже простой, а два десятка оттенков превращают выбор в занятие само по себе.
ЦВЕТА_ТЕКСТА = ['#dc2626', '#ea580c', '#16a34a', '#2563eb', '#7c3aed']
ЦВЕТА_ФОНА = ['#fef08a', '#bbf7d0', '#bfdbfe', '#fecaca', '#e9d5ff']


@login_required
def создать(request):
    """Простой путь: название, описание и сразу карточки на одном экране."""
    ошибка = ''
    if request.method == 'POST':
        форма = ПростаяКолодаForm(request.POST)
        карточки, ошибка = _карточки_из_запроса(request)
        if форма.is_valid() and not ошибка:
            if not карточки:
                ошибка = 'Добавьте хотя бы одну карточку.'
            else:
                with transaction.atomic():
                    колода = форма.save(commit=False)
                    колода.owner = request.user
                    колода.save()
                    _записать_карточки(колода, карточки)
                messages.success(request, 'Колода создана.')
                return redirect('cards:deck', pk=колода.pk)
    else:
        форма = ПростаяКолодаForm()
        карточки = []

    return render(request, 'cards/deck_editor.html', {
        'форма': форма, 'колода': None, 'карточки_json': карточки,
        'ошибка': ошибка, 'цвета': ЦВЕТА_ТЕКСТА, 'фоны': ЦВЕТА_ФОНА,
    })


