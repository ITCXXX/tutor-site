def заучивание(request, pk):
    """Режим «Заучивание»: раунды, трудная секция первой.

    Прогресса здесь нет намеренно. Заучивание — это прогон, а не зачёт: считать
    в нём выученное значит подменять занятие отчётом о занятии. Что человек
    считает трудным, он говорит сам, в разборе.
    """
    колода = _колода_для_просмотра(request, pk)
    набор = _по_секциям(request.user, колода, _набор(колода))
    return render(request, 'cards/learn.html', {
        'колода': колода, 'набор': набор,
        'хватает': len(набор) >= 2,
        'есть_выбор': len(набор) >= МИНИМУМ_ДЛЯ_ВЫБОРА,
        'размер_раунда': колода.round_size,
    })


def тест(request, pk):
    """Режим «Тест»: весь набор одним видом вопроса, который выбирает человек.

    Вид выбирается ОДИН раз на весь тест. Вперемешку выбор из вариантов и ввод
    ответа — это не тест, а чересполосица: человек каждый раз заново
    соображает, что от него хотят, и сравнивать такие результаты между собой
    нельзя.

    Раундов в тесте нет: тест проходится целиком, но из него можно выйти с
    сохранением и можно завершить досрочно.
    """
    колода = _колода_для_просмотра(request, pk)
    набор = _набор(колода)
    return render(request, 'cards/test.html', {
        'колода': колода, 'набор': набор,
        'хватает': len(набор) >= 2,
        'есть_выбор': len(набор) >= МИНИМУМ_ДЛЯ_ВЫБОРА,
        # Ввод годится для теста, только когда вердикт выносит сайт:
        # самопроверка каждого вопроса — это не тест.
        'можно_вводить': колода.check_mode == Deck.АВТОМАТ,
    })


def подбор(request, pk):
    """Режим «Подбор»: игра на время, раунд пар за раз."""
    колода = _колода_для_просмотра(request, pk)
    набор = _набор(колода)
    return render(request, 'cards/match.html', {
        'колода': колода, 'набор': набор,
        'хватает': len(набор) >= МИНИМУМ_ДЛЯ_ПОДБОРА,
        'минимум': МИНИМУМ_ДЛЯ_ПОДБОРА,
        'размер_раунда': max(МИНИМУМ_ДЛЯ_ПОДБОРА, колода.round_size),
    })


def _по_секциям(user, колода, набор):
    """Переставить набор так, чтобы трудное шло первым.

    Порядок секций задан в модели (ПОРЯДОК_ЗАУЧИВАНИЯ): сначала то, что ученик
    отметил трудным, потом неразобранное, потом лёгкое. Внутри секции порядок
    остаётся тем, какой был.
    """
    if not (user and user.is_authenticated):
        return набор
    секции = {
        (строка.card_id, строка.direction): строка.section
        for строка in CardState.objects.filter(user=user, card__deck=колода)
    }
    вес = {секция: место
           for место, секция in enumerate(CardState.ПОРЯДОК_ЗАУЧИВАНИЯ)}
    def ключ(задание):
        секция = секции.get((задание['card'], задание['direction']),
                            CardState.НЕ_РАЗОБРАНА)
        return вес.get(секция, len(вес))
    return sorted(набор, key=ключ)



@require_POST
def проверить_многие(request, pk):
    """Проверка пачки ответов разом — для режима «Тест».

    Отдельный адрес, а не цикл по одиночной проверке: в тесте два десятка
    вопросов, и двадцать запросов подряд превратили бы нажатие «Проверить» в
    заметную паузу.
    """
    колода = _колода_для_просмотра(request, pk)
    данные = _разобрать_запрос(request)
    ответы = данные.get('ответы')
    if not isinstance(ответы, list) or len(ответы) > 200:
        return JsonResponse({'ошибка': 'нужен список ответов'}, status=400)

    карточки = {к.pk: к for к in колода.cards.all()}
    итог = []
    for пункт in ответы:
        карточка = карточки.get(пункт.get('card'))
        if карточка is None:
            итог.append({'card': пункт.get('card'), 'верно': False, 'эталон': ''})
            continue
        направление = int(пункт.get('direction') or CardState.ПРЯМОЕ)
        итог.append({
            'card': карточка.pk,
            'верно': _ответ_подходит(колода, карточка, направление,
                                     пункт.get('typed') or ''),
            'эталон': карточка.варианты_ответа(направление)[0],
        })
    return JsonResponse({'ответы': итог})
