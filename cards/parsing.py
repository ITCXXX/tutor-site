# -*- coding: utf-8 -*-
"""Разбор списка карточек, вставленного одним куском текста.

Задумка раздела: списки почти всегда откуда-то копируются — из нейросети, из
Quizlet, из таблицы, из конспекта. Значит, поле ввода должно понимать не один
идеально описанный формат, а то, что люди реально вставляют.

Поэтому разбор терпимый: он снимает нумерацию, маркеры списка, жирное
начертание, ограждения ```, шапки таблиц и разделительные строки Markdown, а
разделитель между сторонами ищет сам — табуляция, вертикальная черта, тире.

Третий и последующие столбцы необязательны: помеченные восклицательным знаком
становятся неверными вариантами для вопроса с выбором, остальные — подсказкой.
Неверных вариантов может быть сколько угодно.

Отдельная забота — формулы. В LaTeX вертикальная черта означает модуль
(«$|x| > 3$»), а длинное тире встречается в тексте задачи. Если бы разбор резал
строку в лоб, каждая такая карточка ломалась бы пополам. Поэтому куски между
знаками доллара сначала прячутся за подстановки, строка режется, и только потом
формулы возвращаются на место.
"""

import re


# Разделители в порядке доверия. Табуляция надёжнее всего: её даёт выгрузка из
# Quizlet, Anki и любой таблицы, и в тексте она не встречается случайно.
РАЗДЕЛИТЕЛИ = ['\t', '|', ' — ', ' – ', ' -- ']

# Строки, которые в списке карточек не значат ничего.
_ОГРАЖДЕНИЕ = re.compile(r'^\s*```')
_КОММЕНТАРИЙ = re.compile(r'^\s*(#|//)')
_МАРКЕР = re.compile(r'^\s*(?:\d+\s*[.)]|[-*•–—])\s+')
_РАЗДЕЛИТЕЛЬНАЯ = re.compile(r'^[\s|:+-]*$')

# Шапки таблиц, которые нейросеть добавляет по привычке.
_ШАПКИ = {
    'термин', 'определение', 'вопрос', 'ответ', 'лицевая сторона', 'оборот',
    'лицо', 'front', 'back', 'term', 'definition', 'question', 'answer',
    'слово', 'перевод', 'понятие', 'формулировка', 'подсказка',
}

# Формула целиком: от доллара до доллара. Двойные доллары тоже сюда попадают —
# внутренняя пара просто съедается вместе с ними.
_ФОРМУЛА = re.compile(r'\$\$.+?\$\$|\$[^$\n]+\$')
_МЕТКА = '\x00%d\x00'
_МЕТКА_ОБРАТНО = re.compile(r'\x00(\d+)\x00')

ПРЕДЕЛ_СТОРОНЫ = 2000

# Чем помечается заведомо неверный ответ в дополнительных столбцах. Восклицание
# выбрано потому, что в начале ячейки оно не значит ничего другого: минус увёл
# бы за собой каждый отрицательный ответ по математике, а звёздочка — умножение
# и разметку. Факториал в математике стоит после числа, а не перед ним.
МЕТКА_НЕВЕРНОГО = '!'


def _спрятать_формулы(строка):
    """Заменить формулы метками, чтобы разделители внутри них не сработали."""
    хранилище = []

    def замена(m):
        хранилище.append(m.group(0))
        return _МЕТКА % (len(хранилище) - 1)

    return _ФОРМУЛА.sub(замена, строка), хранилище


def _вернуть_формулы(кусок, хранилище):
    return _МЕТКА_ОБРАТНО.sub(lambda m: хранилище[int(m.group(1))], кусок)


def _почистить(кусок):
    """Убрать украшения, которые к содержанию карточки не относятся."""
    кусок = кусок.strip()
    # Жирное начертание вокруг термина — привычка нейросетей.
    while кусок.startswith('**') and кусок.endswith('**') and len(кусок) > 4:
        кусок = кусок[2:-2].strip()
    if кусок.startswith('**'):
        кусок = кусок[2:].strip()
    if кусок.endswith('**'):
        кусок = кусок[:-2].strip()
    # Кавычки вокруг ячейки оставляет выгрузка в CSV.
    if len(кусок) > 1 and кусок[0] == '"' and кусок[-1] == '"':
        кусок = кусок[1:-1].strip()
    return кусок


def _разрезать(строка):
    """Разрезать строку на ячейки, не тронув формулы. Вернуть список кусков."""
    спрятанная, хранилище = _спрятать_формулы(строка)

    # Строка таблицы Markdown: «| термин | определение |».
    обрезанная = спрятанная.strip()
    if обрезанная.startswith('|') and обрезанная.endswith('|') and len(обрезанная) > 2:
        ячейки = обрезанная[1:-1].split('|')
    else:
        for разделитель in РАЗДЕЛИТЕЛИ:
            if разделитель in спрятанная:
                ячейки = спрятанная.split(разделитель)
                break
        else:
            ячейки = [спрятанная]

    return [_почистить(_вернуть_формулы(я, хранилище)) for я in ячейки]


def _шапка(ячейки):
    """Похоже ли это на строку заголовков, а не на карточку."""
    значимые = [я.lower().strip() for я in ячейки if я.strip()]
    return len(значимые) >= 2 and all(я in _ШАПКИ for я in значимые)


def разобрать(текст, *, уже_есть=()):
    """Текст → (карточки, замечания).

    карточки — список словарей {'front', 'back', 'hint'} в порядке ввода.
    замечания — понятные человеку строки о том, что не удалось разобрать или
    что было пропущено; они показываются рядом с предпросмотром, чтобы автор
    видел судьбу каждой строки, а не молча терял половину списка.

    уже_есть — лицевые стороны карточек, которые в колоде уже лежат: их
    повторный ввод не ошибка, но о нём стоит сказать.
    """
    карточки = []
    замечания = []
    видели = {str(л).strip().lower() for л in уже_есть}
    была_шапка = False

    for номер, сырая in enumerate(текст.splitlines(), 1):
        if not сырая.strip():
            continue
        if _ОГРАЖДЕНИЕ.match(сырая) or _КОММЕНТАРИЙ.match(сырая):
            continue
        if _РАЗДЕЛИТЕЛЬНАЯ.match(сырая):
            continue

        строка = _МАРКЕР.sub('', сырая)
        ячейки = _разрезать(строка)
        ячейки = [я for я in ячейки if я != '']

        if len(ячейки) < 2:
            замечания.append(
                'Строка %d: не нашёл разделителя — «%s»'
                % (номер, строка.strip()[:60])
            )
            continue

        if ячейки[1].startswith(МЕТКА_НЕВЕРНОГО):
            замечания.append(
                'Строка %d: сразу после вопроса стоит неверный вариант — '
                'верного ответа нет' % номер
            )
            continue

        if not была_шапка and not карточки and _шапка(ячейки):
            была_шапка = True
            continue

        лицо, оборот = ячейки[0], ячейки[1]

        # Дополнительные столбцы: помеченные восклицанием — неверные варианты
        # для вопроса с выбором, остальные — подсказка. Их может быть сколько
        # угодно, поэтому разбираем по одному, а не по номеру столбца.
        неверные, пояснения = [], []
        for ячейка in ячейки[2:]:
            if ячейка.startswith(МЕТКА_НЕВЕРНОГО):
                вариант = ячейка[len(МЕТКА_НЕВЕРНОГО):].strip()
                if вариант:
                    неверные.append(вариант)
            else:
                пояснения.append(ячейка)
        подсказка = ' · '.join(пояснения)

        if len(лицо) > ПРЕДЕЛ_СТОРОНЫ or len(оборот) > ПРЕДЕЛ_СТОРОНЫ:
            замечания.append('Строка %d: слишком длинная, пропущена' % номер)
            continue

        ключ = лицо.strip().lower()
        if ключ in видели:
            замечания.append('Строка %d: «%s» уже есть, пропущена' % (номер, лицо[:40]))
            continue
        видели.add(ключ)

        карточки.append({
            'front': лицо, 'back': оборот, 'hint': подсказка,
            'distractors': '\n'.join(неверные),
        })

    if not карточки and not замечания and текст.strip():
        замечания.append('Не нашёл ни одной карточки. Проверьте разделитель.')
    return карточки, замечания
