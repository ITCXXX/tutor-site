# -*- coding: utf-8 -*-
"""Правило формата, которое автор колоды даёт нейросети.

Это именно правило, а не задание. Задание человек ставит сам — он уже сидит в
чате и обсуждает свой материал; ему нужно только сказать, в каком виде вернуть
результат. Поэтому здесь нет ни темы, ни количества карточек: тему он знает
лучше нас, а сколько их выйдет — зависит от материала, а не от круглого числа.

Правило можно дать и заранее, и после ответа нейросети («переделай в этот
формат»), и приложить к куску учебника. Разбор (cards/parsing.py) всё равно
терпим к отступлениям: он снимает нумерацию, жирный шрифт, вступления и шапки
таблиц, поэтому вычищать ответ вручную не придётся, а лишнее человек и сам
отберёт при вставке.
"""

ОБЩЕЕ = [
    'Оформи карточки для заучивания так — по одной в строке:',
    '',
    'лицевая сторона | оборотная сторона',
    '',
    'Правила:',
    '1. Разделитель сторон — вертикальная черта с пробелами по бокам. '
    'Внутри самих сторон её не используй.',
    '2. Слева вопрос или термин, справа короткий ответ в одну строку.',
    '3. Один факт на карточку. Если ответ тянет на «во-первых, во-вторых» — '
    'сделай две карточки.',
    '4. Не задавай вопросов, ответ на которые уже содержится в самом вопросе.',
]

ПРАВИЛО_ФОРМУЛ = (
    '5. Формулы записывай в LaTeX между знаками доллара: $S = \\pi R^2$. '
    'Модуль пиши как $\\lvert x \\rvert$, дробь как $\\frac{a}{b}$: '
    'вертикальная черта и косая дробь внутри формулы разрежут карточку пополам.'
)

СТОЛБЦЫ = [
    '',
    'После ответа можно добавить сколько угодно столбцов:',
    '   с восклицательным знаком в начале — неверный вариант, '
    'если карточку будут спрашивать выбором;',
    '   без знака — подсказка или пример.',
    '',
    'Знак нужен у КАЖДОГО неверного варианта. Столбец без знака считается '
    'подсказкой, и забытый знак превратит неверный ответ в подсказку.',
]

ПРИМЕРЫ = {
    'math': [
        'Площадь круга радиуса $R$ | $S = \\pi R^2$',
        'Теорема Пифагора | $c^2 = a^2 + b^2$ | только в прямоугольном треугольнике',
        'Сумма углов треугольника | $180^\\circ$ | !$90^\\circ$ | !$360^\\circ$',
    ],
    'text': [
        'Метафора | скрытое сравнение без слова «как»',
        'Оксюморон | сочетание несочетаемого | «горячий снег»',
        'Столица Австралии | Канберра | !Сидней | !Мельбурн',
    ],
}


def собрать(вид='text'):
    """Текст правила. Единственная настройка — есть ли в материале формулы."""
    куски = list(ОБЩЕЕ)
    if вид == 'math':
        куски.append(ПРАВИЛО_ФОРМУЛ)
    куски += СТОЛБЦЫ
    куски += ['', 'Пример:', '']
    куски += ПРИМЕРЫ.get(вид, ПРИМЕРЫ['text'])
    return '\n'.join(куски)
