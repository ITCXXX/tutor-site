# -*- coding: utf-8 -*-
"""Готовая инструкция, которую автор колоды отдаёт нейросети.

Списки для заучивания почти никто не набирает руками — их просят у нейросети, а
потом мучительно переделывают ответ в пригодный вид: убирают нумерацию,
вступление «Конечно! Вот список...», markdown-таблицы и жирный шрифт.

Проще выдать нейросети формат заранее. Эта страница собирает текст задания под
конкретную тему, автор копирует его целиком, вставляет в любой чат и получает
ответ, который сайт принимает без правки. Разбор (cards/parsing.py) всё равно
терпим к отступлениям от формата — инструкция лишь уменьшает их число.
"""

ПРАВИЛА_ОБЩИЕ = [
    'Никакого текста до и после списка: ни вступления, ни выводов, '
    'ни нумерации, ни маркеров списка, ни таблиц.',
    'Разделитель сторон — вертикальная черта с пробелами по бокам. '
    'Внутри самих сторон вертикальную черту не используй.',
    'На лицевой стороне — вопрос или термин, на обороте — короткий ответ.',
    'Один факт на карточку. Если ответ тянет на «во-первых, во-вторых» — '
    'сделай две карточки.',
    'Оборот умещается в одну строку. Без «и так далее», без «и другие».',
    'Не задавай вопросов, ответ на которые уже содержится в самом вопросе.',
]

ПРАВИЛО_ФОРМУЛ = (
    'Формулы записывай в LaTeX между знаками доллара: $S = \\pi R^2$. '
    'Модуль пиши как $\\lvert x \\rvert$, дробь как $\\frac{a}{b}$ — '
    'вертикальную черту и косую дробь в формулах не используй.'
)

# Неверные варианты помечаются восклицательным знаком — тем же, что понимает
# разбор (cards/parsing.py). Их может быть сколько угодно.
ПРАВИЛО_ВАРИАНТОВ = [
    'После верного ответа добавь 3 неверных варианта — каждый в своём столбце',
    'и каждый с восклицательным знаком в начале:',
    '',
    'вопрос | верный ответ | !неверный | !неверный | !неверный',
    '',
    'Неверные варианты должны быть правдоподобными и из той же темы: вариант',
    'из чужой области отсеивается на глаз и ничего не проверяет.',
]

ПРИМЕРЫ = {
    'math': [
        'Площадь круга радиуса $R$ | $S = \\pi R^2$',
        'Сумма углов треугольника | $180^\\circ$',
        'Теорема Пифагора | $c^2 = a^2 + b^2$ | только в прямоугольном треугольнике',
        'Признак делимости на 3 | сумма цифр делится на 3',
    ],
    'text': [
        'Метафора | скрытое сравнение без слова «как»',
        'Оксюморон | сочетание несочетаемого | «горячий снег»',
        'Причастие | признак предмета по действию',
    ],
}

ПРИМЕРЫ_С_ВАРИАНТАМИ = {
    'math': [
        'Площадь круга радиуса $R$ | $\\pi R^2$ | !$2 \\pi R$ | !$\\pi R$ | !$\\pi R^3$',
        'Сумма углов треугольника | $180^\\circ$ | !$90^\\circ$ | !$360^\\circ$ | !$270^\\circ$',
        'Признак делимости на 3 | сумма цифр делится на 3 | !последняя цифра делится на 3',
    ],
    'text': [
        'Метафора | скрытое сравнение | !прямое сравнение с «как» | !преувеличение',
        'Оксюморон | сочетание несочетаемого | !игра слов | !намёк | !обращение',
        'Причастие | признак предмета по действию | !признак действия | !название действия',
    ],
}


def собрать(тема, количество=30, вид='text', с_подсказками=False,
            с_вариантами=False):
    """Текст задания для нейросети под конкретную тему."""
    тема = (тема or '').strip() or 'указанной теме'
    количество = max(1, min(int(количество or 30), 300))

    правила = list(ПРАВИЛА_ОБЩИЕ)
    if вид == 'math':
        правила.insert(4, ПРАВИЛО_ФОРМУЛ)
    правила.append('Сделай ровно %d карточек. Если материала на столько не '
                   'хватает — лучше меньше, но без выдумок.' % количество)

    куски = [
        'Составь список карточек для заучивания по теме «%s».' % тема,
        '',
        'Формат ответа — строго построчно, по одной карточке в строке:',
        '',
        'лицевая сторона | оборотная сторона',
        '',
        'Правила:',
    ]
    куски += ['%d. %s' % (i, п) for i, п in enumerate(правила, 1)]

    if с_вариантами:
        куски += [''] + ПРАВИЛО_ВАРИАНТОВ

    if с_подсказками:
        куски += [
            '',
            'Можно добавить ещё один столбец — короткую подсказку или пример.',
            'Подсказка идёт без восклицательного знака:',
            '',
            'лицевая сторона | оборотная сторона | подсказка',
        ]

    куски += ['', 'Пример правильного ответа:', '']
    куски += (ПРИМЕРЫ_С_ВАРИАНТАМИ if с_вариантами else ПРИМЕРЫ).get(
        вид, (ПРИМЕРЫ_С_ВАРИАНТАМИ if с_вариантами else ПРИМЕРЫ)['text']
    )
    return '\n'.join(куски)
