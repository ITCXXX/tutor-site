  function run(подробно) {
    if (!global.SmartDraw) { console.error('Сначала загрузите smartdraw.js'); return; }
    var т = набор(), ок = 0, плохо = [];
    т.forEach(function (c) {
      var got = global.SmartDraw.recognize(c.pts, c.scale || 1);
      var kind = got ? got.kind : null;
      var прошло = (kind === c.ждём);
      if (прошло) ок++;
      else плохо.push({ имя: c.имя, ждали: c.ждём, получили: kind, зачем: c.зачем });
      if (подробно) {
        console.log((прошло ? '  ok  ' : ' ПЛОХО ') + c.имя +
          '  → ' + kind + (прошло ? '' : ' (ждали ' + c.ждём + ')'));
      }
    });
    console.log('Умное рисование: ' + ок + ' из ' + т.length);
    if (плохо.length) console.table(плохо);
    return { всего: т.length, ок: ок, плохо: плохо };
  }

