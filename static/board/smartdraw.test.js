/*
 * Проверки умного рисования. Запускаются РУКАМИ, страницей не грузятся.
 *
 * Как гонять: открыть любую страницу сайта и в консоли браузера выполнить
 *
 *   (async () => {
 *     for (const f of ['smartdraw.js', 'smartdraw.test.js'])
 *       (0, eval)(await fetch('/static/board/' + f).then(r => r.text()));
 *     SmartDrawTests.run();      // все проверки
 *     await SmartDrawTests.порча();  // и порча кода — она важнее
 *   })();
 *
 * Почему так, а не привычным прогоном тестов: распознавание живёт в браузере, а
 * не на сервере, и Python его не увидит. Холст в проверочной панели не
 * рисуется, кадры в ней заморожены — поэтому смотреть на картинку нельзя, а
 * числа посчитать можно. Ради этого распознавание и сделано чистой функцией:
 * подаём заранее известный штрих, сверяем ответ.
 *
 * Штрихи ниже собраны с ШУМОМ по фиксированному зерну: случайность с
 * постоянным зерном даёт повторяемый результат, и упавшая проверка падает
 * одинаково у меня и потом.
 */
