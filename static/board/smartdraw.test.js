  function отрезок(a, b, n, шум, rnd) {
    var pts = [];
    for (var i = 0; i < n; i++) {
      var t = i / (n - 1);
      pts.push({ x: a.x + (b.x - a.x) * t + (rnd() - 0.5) * 2 * шум,
                 y: a.y + (b.y - a.y) * t + (rnd() - 0.5) * 2 * шум });
    }
    return pts;
  }

  function эллипс(cx, cy, rx, ry, n, шум, rnd, доля) {
    var pts = [], полн = (доля == null ? 1 : доля);
    for (var i = 0; i < n; i++) {
      var a = (i / (n - 1)) * 2 * Math.PI * полн;
      pts.push({ x: cx + rx * Math.cos(a) + (rnd() - 0.5) * 2 * шум,
                 y: cy + ry * Math.sin(a) + (rnd() - 0.5) * 2 * шум });
    }
    return pts;
  }

  // Замкнутая ломаная по вершинам: каждая сторона разбивается на точки.
  function ломаная(вершины, наСторону, шум, rnd, замкнуть) {
    var pts = [], сп = вершины.slice();
    if (замкнуть !== false) сп.push(вершины[0]);
    for (var s = 0; s + 1 < сп.length; s++) {
      var a = сп[s], b = сп[s + 1];
      for (var i = 0; i < наСторону; i++) {
        var t = i / наСторону;
        pts.push({ x: a.x + (b.x - a.x) * t + (rnd() - 0.5) * 2 * шум,
                   y: a.y + (b.y - a.y) * t + (rnd() - 0.5) * 2 * шум });
      }
    }
    pts.push(сп[сп.length - 1]);
    return pts;
  }

  // Синусоида — рука, ведущая волнистую линию. Прямой быть не должна.
  function волна(a, b, амплитуда, периодов, n, rnd) {
    var pts = [];
    for (var i = 0; i < n; i++) {
      var t = i / (n - 1);
      var dx = b.x - a.x, dy = b.y - a.y;
      var L = Math.sqrt(dx * dx + dy * dy);
      var нx = -dy / L, нy = dx / L;
      var о = амплитуда * Math.sin(t * периодов * 2 * Math.PI);
      pts.push({ x: a.x + dx * t + нx * о, y: a.y + dy * t + нy * о });
    }
    return pts;
  }

