/*
 * ПИТОН В БРАУЗЕРЕ — общая клетка для доски.
 *
 * Что это. Настоящий CPython (сборка Pyodide), который работает прямо в
 * браузере участника урока. На сервер код не попадает вовсе: он считается на
 * том устройстве, где его запустили.
 *
 * ПОЧЕМУ КЛЕТКА, А НЕ ПРОСТО «ЗАПУСТИТЬ У СЕБЯ НА СТРАНИЦЕ». Код в окне питона
 * пишет один человек, а нажать «Выполнить» может другой. Если запускать его
 * прямо на странице доски, ученик мог бы написать три строчки, которые в
 * браузере преподавателя сходят к сайту от ЕГО имени — с его правами. Поэтому
 * питон живёт во вложенной рамке с запретами (sandbox="allow-scripts"): у такой
 * рамки нет нашего адреса, а значит нет ни наших cookie, ни доступа к странице
 * доски, ни к нашим адресам на сервере. Разговаривает она с доской только
 * сообщениями, и только теми, что мы разбираем ниже.
 *
 * ПОЧЕМУ ЭТО ЖЕ РЕШАЕТ ЗАВИСАНИЕ. Такая рамка считается браузером отдельно от
 * страницы. Замерено на живой доске: пока внутри крутился цикл на три секунды,
 * стомиллисекундный таймер снаружи сработал через 101 мс — то есть доска
 * рисуется и голос идёт, даже если в окне питона бесконечный цикл. Кнопка
 * «Стоп» просто выбрасывает рамку целиком: это надёжнее любой просьбы
 * остановиться, потому что бесконечный цикл ни о чём попросить нельзя.
 *
 * ЦЕНА ОСТАНОВКИ: вместе с рамкой пропадает и загруженный питон, поэтому
 * следующий запуск снова ждёт несколько секунд. Это честный размен: лучше
 * подождать, чем не иметь возможности остановить.
 */
(function () {
    'use strict';

    // Где лежат файлы питона. Считаем от адреса ЭТОГО файла, а не пишем путь
    // руками: на сервере статика собирается с отпечатком в имени
    // (python_run.abc123.js), но папка остаётся той же — значит «на уровень
    // выше, в vendor/pyodide/» верно и там, и на моей машине, и при любой
    // настройке адреса статики. Путь получается абсолютным, а он и нужен:
    // внутри рамки с запретами своего адреса нет, и считать относительные
    // пути там не от чего.
    const МОЙ_ТЕГ = document.currentScript || document.querySelector('script[src*="python_run"]');
    function базаПитона() {
        // Адрес приходит из страницы (data-pyodide): файлы питона отдаёт наша
        // же вьюха, а не раздача статики — ей нужен разрешающий заголовок для
        // клетки (см. board/views.py, pyodide_file).
        const свой = (МОЙ_ТЕГ && МОЙ_ТЕГ.getAttribute('data-pyodide')) || '/board/py/';
        // В атрибуте лежит адрес ОДНОГО файла (иначе его не построить
        // шаблоном), а нужна папка — отрезаем имя после последней косой.
        return new URL(свой, window.location.href).href.replace(/[^/]*$/, '');
    }

    // Содержимое рамки. Живёт отдельной страницей: всё, что ей нужно знать о
    // нашем мире, — адрес папки с питоном.
    function страницаКлетки(база) {
        return '<!doctype html><meta charset="utf-8"><title>питон</title>'
            + '<script>(' + текстКлетки.toString() + ')(' + JSON.stringify(база) + ');<\/script>';
    }

    // Код, работающий ВНУТРИ клетки. Вынесен функцией, чтобы его было видно
    // обычным кодом, а не строкой: строку никто не читает и не правит.
    function текстКлетки(база) {
        let питон = null;
        const шлём = (m) => { try { parent.postMessage(m, '*'); } catch (e) { /* родитель ушёл */ } };
        const вывод = (текст) => шлём({ вид: 'вывод', текст: String(текст) + '\n' });

        // Снимок картинок matplotlib. Рисунок в браузере некуда «показать», как
        // на компьютере, поэтому после выполнения забираем готовые рисунки
        // картинками и отдаём доске. Если matplotlib не трогали — тут пусто, и
        // лишней работы нет.
        const КОД_КАРТИНОК = [
            'def _доска_картинки():',
            '    import sys',
            '    if "matplotlib.pyplot" not in sys.modules: return []',
            '    import io, base64',
            '    plt = sys.modules["matplotlib.pyplot"]',
            '    out = []',
            '    for n in plt.get_fignums():',
            '        f = plt.figure(n)',
            '        b = io.BytesIO()',
            '        f.savefig(b, format="png", dpi=110, bbox_inches="tight")',
            '        out.append(base64.b64encode(b.getvalue()).decode())',
            '    plt.close("all")',
            '    return out',
            '_доска_картинки()',
        ].join('\n');

        async function поднять() {
            if (питон) return питон;
            await new Promise((готово, беда) => {
                const s = document.createElement('script');
                s.src = база + 'pyodide.js';
                s.onload = готово;
                s.onerror = () => беда(new Error('файлы питона не найдены'));
                document.head.appendChild(s);
            });
            питон = await self.loadPyodide({
                indexURL: база,
                stdout: вывод,
                stderr: вывод,
            });
            return питон;
        }

        async function выполнить(код, номер) {
            try {
                const py = await поднять();
                // Сами подтянем библиотеки, которые упомянуты в import: numpy,
                // sympy, matplotlib и прочее лежат у нас же в папке.
                шлём({ вид: 'этап', текст: 'готовлю библиотеки' });
                await py.loadPackagesFromImports(код);
                шлём({ вид: 'этап', текст: 'считаю' });
                const ответ = await py.runPythonAsync(код);
                // Последняя строка вернула значение — показываем его, как это
                // делает питон в командной строке.
                if (ответ !== undefined && ответ !== null) {
                    // Значение из питона приходит обёрткой; String() зовёт у неё
                    // питоновский str(), то есть человек видит ровно то, что
                    // показал бы питон в командной строке.
                    вывод(String(ответ));
                    if (ответ && ответ.destroy) { try { ответ.destroy(); } catch (e) { /* уже освобождено */ } }
                }
                let картинки = [];
                try {
                    const пы = await py.runPythonAsync(КОД_КАРТИНОК);
                    картинки = пы && пы.toJs ? пы.toJs() : (пы || []);
                    if (пы && пы.destroy) пы.destroy();
                } catch (e) { картинки = []; }
                шлём({ вид: 'конец', номер: номер, картинки: Array.from(картинки || []) });
            } catch (e) {
                шлём({ вид: 'конец', номер: номер, ошибка: String((e && e.message) || e) });
            }
        }

        window.addEventListener('message', (e) => {
            // Слушаем только родителя: чужие сообщения игнорируем.
            if (e.source !== parent) return;
            const m = e.data || {};
            if (m.вид === 'пуск') выполнить(String(m.код || ''), m.номер);
        });

        // Питон поднимаем сразу, не дожидаясь первого «Выполнить»: несколько
        // секунд ожидания лучше провести, пока человек дописывает строку.
        поднять().then(
            () => шлём({ вид: 'готов' }),
            (e) => шлём({ вид: 'беда', текст: String((e && e.message) || e) })
        );
    }

    // ── Сторона доски ────────────────────────────────────────────────────
    let рамка = null;          // сама клетка
    let состояние = 'нет';     // нет | грузится | готов | считает
    let номерЗапуска = 0;
    let текущий = null;        // { номер, приВыводе, приЭтапе, приКонце }
    const ждут = [];           // кто хочет знать о смене состояния

    function сказатьВсем() { ждут.forEach((f) => { try { f(состояние); } catch (e) { /* не наша беда */ } }); }

    function поднятьРамку() {
        if (рамка) return;
        состояние = 'грузится';
        рамка = document.createElement('iframe');
        // allow-scripts и НИЧЕГО больше: без allow-same-origin у рамки нет
        // нашего адреса, а значит ни cookie, ни доступа к странице доски.
        рамка.setAttribute('sandbox', 'allow-scripts');
        рамка.setAttribute('aria-hidden', 'true');
        рамка.style.cssText = 'position:fixed;width:1px;height:1px;left:-10px;top:-10px;border:0;opacity:0;pointer-events:none';
        рамка.srcdoc = страницаКлетки(базаПитона());
        document.body.appendChild(рамка);
        // Сторож. Если клетка не отозвалась «готов» за полминуты, значит питон
        // в ней не поднялся: не доехали файлы, браузер запретил рамку, что-то
        // ещё. Молчать в этом случае нельзя — человек будет смотреть на пустое
        // окно и думать, что считается. Подменять клетку запуском прямо на
        // странице тоже нельзя: это сняло бы защиту, ради которой она и нужна.
        setTimeout(function () {
            if (состояние !== 'грузится') return;
            состояние = 'нет';
            const кто = текущий; текущий = null;
            сказатьВсем();
            if (кто && кто.приКонце) кто.приКонце({ ошибка: 'Питон не запустился в защищённой рамке за 30 секунд. Проверьте связь и сообщите об этом — разберусь.' });
        }, 30000);
        сказатьВсем();
    }

    window.addEventListener('message', (e) => {
        if (!рамка || e.source !== рамка.contentWindow) return;
        const m = e.data || {};
        if (m.вид === 'готов') { if (состояние !== 'считает') состояние = 'готов'; сказатьВсем(); return; }
        if (m.вид === 'беда') {
            состояние = 'нет';
            if (текущий && текущий.приКонце) текущий.приКонце({ ошибка: m.текст });
            текущий = null;
            сказатьВсем();
            return;
        }
        if (!текущий) return;
        if (m.вид === 'вывод') { if (текущий.приВыводе) текущий.приВыводе(m.текст); return; }
        if (m.вид === 'этап') { if (текущий.приЭтапе) текущий.приЭтапе(m.текст); return; }
        if (m.вид === 'конец') {
            if (m.номер !== текущий.номер) return;
            const кто = текущий;
            текущий = null;
            состояние = 'готов';
            сказатьВсем();
            if (кто.приКонце) кто.приКонце({ ошибка: m.ошибка || null, картинки: m.картинки || [] });
        }
    });

    window.ПитонВБраузере = {
        состояние: function () { return состояние; },
        занят: function () { return !!текущий; },
        наСмену: function (f) { ждут.push(f); },
        // Запустить. Вернёт false, если сейчас считается что-то другое: два
        // счёта одновременно в одной клетке невозможны, и молча подменять
        // чужой запуск нельзя — человек не поймёт, куда делся его вывод.
        запустить: function (код, обработчики) {
            if (текущий) return false;
            поднятьРамку();
            номерЗапуска += 1;
            текущий = Object.assign({ номер: номерЗапуска }, обработчики || {});
            состояние = 'считает';
            сказатьВсем();
            const шаг = () => {
                if (!рамка || !рамка.contentWindow) return;
                рамка.contentWindow.postMessage({ вид: 'пуск', код: код, номер: номерЗапуска }, '*');
            };
            // Рамка могла ещё не открыться — тогда ждём её загрузки.
            if (рамка.contentWindow && рамка.dataset.готова === '1') шаг();
            else рамка.addEventListener('load', function один() { рамка.removeEventListener('load', один); рамка.dataset.готова = '1'; шаг(); });
            return true;
        },
        // Остановить. Выбрасываем клетку целиком — единственный надёжный способ
        // прервать бесконечный цикл.
        остановить: function () {
            if (рамка) { рамка.remove(); рамка = null; }
            состояние = 'нет';
            const кто = текущий; текущий = null;
            сказатьВсем();
            if (кто && кто.приКонце) кто.приКонце({ остановлен: true });
        },
    };
})();
