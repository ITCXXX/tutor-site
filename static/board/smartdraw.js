/*
 * Умное рисование: распознавание фигуры в штрихе, нарисованном от руки.
 *
 * ОТДЕЛЬНЫЙ ФАЙЛ намеренно. Здесь чистая геометрия и ни одной строчки про
 * Konva, доску, сеть и историю: на входе точки, на выходе — что это за фигура.
 * Две причины. Первая: такое можно проверить числами, подсунув заранее
 * известный штрих и сравнив ответ, — а холст доски в проверочной панели не
 * рисуется вовсе, кадры в ней заморожены. Вторая: board.js уже на четырнадцать
 * тысяч строк, и складывать туда ещё и математику незачем.
 *
 * ЧЕГО ЗДЕСЬ СОЗНАТЕЛЬНО НЕТ — обучения и подбора по образцам ($1 recognizer и
 * подобное). Оно требует набора эталонов, плохо объясняет свои отказы и путает
 * повёрнутые фигуры. Здесь вместо этого несколько прямых признаков, каждый из
 * которых можно назвать словами: «отклонение от хорды», «разброс радиуса»,
 * «сколько углов». Когда доска ошибётся, будет понятно почему.
 *
 * ГЛАВНОЕ ПРАВИЛО: сомневаешься — не трогай. Отказ (null) стоит человеку
 * ничего, а ложное срабатывание портит рисунок и злит. Поэтому пороги строгие,
 * а мелкие штрихи не рассматриваются вовсе — на этой доске ими пишут формулы.
 */
(function (global) {
  'use strict';

  // ── Настройки. Все в ЭКРАННЫХ пикселях или в долях, не в мировых: человек
  // судит о кривизне глазами, а не в координатах доски.
  var НАСТРОЙКИ = {
    // Короче этого штрих не рассматриваем. Рукописная буква — 10-30 пикселей,
    // и «исправлять» её в отрезок значит сделать письмо невозможным.
    минДлина: 45,
    // Для ЗАМКНУТЫХ фигур порог отдельный и гораздо выше — по диагонали рамки.
    // Причина простая и проверяемая: рукописная «о» высотой 30 пикселей — это
    // замкнутый штрих с ровным радиусом, то есть идеальная окружность по всем
    // признакам. Отличить её от нарочно нарисованного кружка можно только по
    // размеру. Выпрямить почти прямую палочку не страшно (её и рисовали
    // прямой), а вот превратить букву в геометрическую окружность — страшно.
    // Проверка «буква о высотой 55 пикселей» показала, почему порог должен быть
    // именно таким большим: рамка такой буквы по диагонали — 79 пикселей, и при
    // пороге 70 доска превращала её в окружность. Ниже 110 опускать нельзя.
    минФигура: 110,
    // Отклонение от прямой: наибольшее расстояние точки до хорды, делённое на
    // длину хорды. 1/20 — примерно то, что глаз ещё считает прямой.
    прямая: 0.05,
    // Во сколько раз путь может быть длиннее хорды, чтобы считаться прямой.
    // Защита от «туда-обратно»: хорда короткая, а отклонение маленькое.
    прямаяИзвилистость: 1.12,
    // Замкнутость: разрыв между началом и концом, делённый на длину пути.
    замкнутость: 0.22,
    // Настолько стороны рамки могут различаться, чтобы это была окружность,
    // а не эллипс.
    кругВместоЭллипса: 1.25,
    // Разброс радиуса в координатах рамки — подтверждение овала.
    эллипс: 0.15,
    // Угол поворота, начиная с которого точка считается углом фигуры.
    уголГрад: 42,
    // ── Заполнение рамки: главный признак. Числа взяты не из теории, а из
    // замеров на заранее известных штрихах (см. smartdraw.test.js), теория лишь
    // подтверждает: у прямоугольника 1, у овала π/4 ≈ 0.785, у треугольника 0.5.
    // Границы поставлены посередине между замеренными значениями.
    прямоугольникЗаполнение: 0.85,   // замер 0.95-0.97
    // Треугольник проверяется не заполнением рамки, а прямым сравнением: площадь
    // штриха против площади треугольника, построенного по его же трём углам.
    // Так вышло после порчи кода: с границей по заполнению (0.38..0.62) набор
    // ничего не заметил, когда границу убрали, — а разбор показал, что она и не
    // нужна, зато ВРЕДНА. Заполнение рамки у треугольника не 0.5: оно зависит от
    // поворота и у тонкого треугольника падает до 0.1, то есть настоящие
    // треугольники отвергались. Сравнение площадей от поворота не зависит вовсе.
    треугольникТочность: 0.18,       // на сколько площадь штриха может разойтись
    // У овала только НИЖНЯЯ граница. Верхняя (0.86) была лишней: всё, что
    // заполняет рамку плотнее 0.85, забирает себе прямоугольник выше по коду, и
    // до овала такой штрих просто не доходит. Порчей кода это и вскрылось —
    // поднял верхнюю границу до 1.5, и ни одна проверка не покраснела.
    овалОт: 0.68,                    // замер 0.73-0.78
    // Сколько точек оставляем после пересчёта. Больше — точнее углы, дороже.
    точек: 64
  };

  // ─────────────────────────── мелкая геометрия ───────────────────────────

  function расст(a, b) {
    var dx = a.x - b.x, dy = a.y - b.y;
    return Math.sqrt(dx * dx + dy * dy);
  }

  function длинаПути(pts) {
    var s = 0;
    for (var i = 1; i < pts.length; i++) s += расст(pts[i - 1], pts[i]);
    return s;
  }

  function рамка(pts) {
    var minx = Infinity, miny = Infinity, maxx = -Infinity, maxy = -Infinity;
    for (var i = 0; i < pts.length; i++) {
      var p = pts[i];
      if (p.x < minx) minx = p.x;
      if (p.y < miny) miny = p.y;
      if (p.x > maxx) maxx = p.x;
      if (p.y > maxy) maxy = p.y;
    }
    return { x: minx, y: miny, w: maxx - minx, h: maxy - miny,
             cx: (minx + maxx) / 2, cy: (miny + maxy) / 2 };
  }

  function середина(pts) {
    var sx = 0, sy = 0;
    for (var i = 0; i < pts.length; i++) { sx += pts[i].x; sy += pts[i].y; }
    return { x: sx / pts.length, y: sy / pts.length };
  }

  // Расстояние от точки до прямой, заданной двумя точками.
  function доПрямой(p, a, b) {
    var dx = b.x - a.x, dy = b.y - a.y;
    var зн = Math.sqrt(dx * dx + dy * dy);
    if (зн < 1e-9) return расст(p, a);
    return Math.abs(dy * (p.x - a.x) - dx * (p.y - a.y)) / зн;
  }

  // Пересчёт штриха в N точек, равномерно расставленных ПО ДЛИНЕ пути.
  // Без этого углы считались бы неверно: рука в поворотах замедляется и
  // ставит там втрое больше точек, отчего поворот кажется плавнее, чем он есть.
  function пересчитать(pts, n) {
    var L = длинаПути(pts);
    if (L <= 0 || pts.length < 2) return pts.slice();
    var шаг = L / (n - 1), итог = [pts[0]], накоплено = 0, i = 1;
    var текущая = { x: pts[0].x, y: pts[0].y };
    while (i < pts.length && итог.length < n) {
      var d = расст(текущая, pts[i]);
      if (накоплено + d >= шаг) {
        var t = (шаг - накоплено) / d;
        var нов = { x: текущая.x + (pts[i].x - текущая.x) * t,
                    y: текущая.y + (pts[i].y - текущая.y) * t };
        итог.push(нов);
        текущая = нов;
        накоплено = 0;
      } else {
        накоплено += d;
        текущая = pts[i];
        i++;
      }
    }
    while (итог.length < n) итог.push(pts[pts.length - 1]);
    return итог;
  }

  // Площадь замкнутого многоугольника по формуле шнурков (по модулю).
  function площадь(pts) {
    var s = 0;
    for (var i = 0, j = pts.length - 1; i < pts.length; j = i++) {
      s += (pts[j].x + pts[i].x) * (pts[j].y - pts[i].y);
    }
    return Math.abs(s) / 2;
  }

  // ─────────────────────────── признаки ───────────────────────────

  // Углы фигуры: точки, где направление меняется резко. Смотрим не на соседей,
  // а на точки через k: соседние точки после пересчёта почти сонаправлены, и
  // шум руки на них даёт ложные углы.
  function углы(pts, замкнуто) {
    var k = Math.max(2, Math.round(pts.length / 16));
    var порог = НАСТРОЙКИ.уголГрад * Math.PI / 180;
    var повороты = [];
    for (var i = 0; i < pts.length; i++) {
      var a = i - k, b = i + k;
      if (!замкнуто) {
        if (a < 0 || b >= pts.length) { повороты.push(0); continue; }
      } else {
        a = (a + pts.length) % pts.length;
        b = b % pts.length;
      }
      var v1x = pts[i].x - pts[a].x, v1y = pts[i].y - pts[a].y;
      var v2x = pts[b].x - pts[i].x, v2y = pts[b].y - pts[i].y;
      var л1 = Math.sqrt(v1x * v1x + v1y * v1y);
      var л2 = Math.sqrt(v2x * v2x + v2y * v2y);
      if (л1 < 1e-9 || л2 < 1e-9) { повороты.push(0); continue; }
      var cos = (v1x * v2x + v1y * v2y) / (л1 * л2);
      cos = Math.max(-1, Math.min(1, cos));
      повороты.push(Math.acos(cos));
    }
    // Оставляем только местные вершины: иначе один настоящий угол даёт
    // подряд пять «углов» из-за ширины окна k.
    //
    // ЧЕГО ЭТО НЕ УМЕЕТ, и это проверено, а не предположено: два угла, стоящие
    // ближе, чем окно k (около 1/16 длины пути), сливаются в один. У обычного
    // треугольника и рамки такого не бывает; страдает только «щепка» — фигура,
    // у которой одна сторона короче 6% периметра. Прямоугольник от этого больше
    // не зависит (см. ветку rect), а треугольник-щепку доска просто оставит
    // рисунком от руки. Это лучше, чем сузить окно: с окном 20° вместо 42°
    // ложные углы находятся уже на ровной окружности — восемь проверок из
    // набора краснеют разом.
    var найденные = [];
    for (var j = 0; j < повороты.length; j++) {
      if (повороты[j] < порог) continue;
      var лучший = true;
      for (var d = -k; d <= k; d++) {
        var m = замкнуто ? (j + d + повороты.length) % повороты.length : j + d;
        if (m < 0 || m >= повороты.length || m === j) continue;
        if (повороты[m] > повороты[j]) { лучший = false; break; }
      }
      if (лучший) найденные.push({ i: j, p: pts[j], угол: повороты[j] });
    }
    return найденные;
  }

  // Суммарный поворот вдоль пути СО ЗНАКОМ, в радианах. Для одного витка по
  // часовой это +2π, против — -2π, для двух витков ±4π. А для восьмёрки — ноль:
  // петли крутятся в разные стороны и гасят друг друга. Это и позволяет отличить
  // обведённый дважды круг (два витка в одну сторону) от росчерка.
  function поворот(pts) {
    var сумма = 0;
    for (var i = 1; i + 1 < pts.length; i++) {
      var ax = pts[i].x - pts[i - 1].x, ay = pts[i].y - pts[i - 1].y;
      var bx = pts[i + 1].x - pts[i].x, by = pts[i + 1].y - pts[i].y;
      var ла = Math.sqrt(ax * ax + ay * ay), лб = Math.sqrt(bx * bx + by * by);
      if (ла < 1e-9 || лб < 1e-9) continue;
      var скал = (ax * bx + ay * by) / (ла * лб);
      var векм = (ax * by - ay * bx) / (ла * лб);
      сумма += Math.atan2(векм, Math.max(-1, Math.min(1, скал)));
    }
    return сумма;
  }

  // Начало пути длиной в долю от общей. Нужно ровно для одного случая: круг
  // обвели дважды, и разбирать надо первый виток, а не оба сразу.
  function началоПути(pts, доля) {
    var L = длинаПути(pts), надо = L * доля, шёл = 0, out = [pts[0]];
    for (var i = 1; i < pts.length; i++) {
      var d = расст(pts[i - 1], pts[i]);
      if (шёл + d >= надо) {
        var t = d > 1e-9 ? (надо - шёл) / d : 0;
        out.push({ x: pts[i - 1].x + (pts[i].x - pts[i - 1].x) * t,
                   y: pts[i - 1].y + (pts[i].y - pts[i - 1].y) * t });
        break;
      }
      шёл += d;
      out.push(pts[i]);
    }
    return out;
  }

  // ─────────────────────────── распознавание ───────────────────────────

  /**
   * Что это за фигура. Возвращает объект с полем kind или null, если непонятно.
   *
   * pts     — [{x, y}, ...] в мировых координатах доски;
   * scale   — текущий масштаб доски (мировое × scale = экранное);
   * опции   — { минДлина } для проверок.
   */
  function recognize(pts, scale, опции) {
    scale = scale || 1;
    var н = опции || {};
    var минДлина = (н.минДлина != null ? н.минДлина : НАСТРОЙКИ.минДлина);

    if (!pts || pts.length < 4) return null;

    // Сначала выбрасываем повторы: палец и перо на паузе шлют одну и ту же
    // точку десятки раз, и от этого разъезжаются все средние.
    //
    // Честно про эту строку: она СТРАХОВОЧНАЯ. Я нарочно её убирал — ни одна
    // проверка не покраснела, включая нарочно собранный «круг с паузой пера» на
    // 45 одинаковых точек. Так вышло потому, что дальше повторы и так почти
    // везде безвредны (нулевые отрезки пропускаются при счёте поворота, пересчёт
    // по длине их проглатывает). Оставляю: стоит она один проход по массиву, а
    // деление на ноль в середине разбора стоило бы гораздо дороже.
    var чистые = [pts[0]];
    for (var i = 1; i < pts.length; i++) {
      if (расст(pts[i], чистые[чистые.length - 1]) > 1e-6) чистые.push(pts[i]);
    }
    if (чистые.length < 4) return null;

    var L = длинаПути(чистые);
    if (L * scale < минДлина) return null;     // это письмо, а не фигура

    var b = рамка(чистые);
    var диаг = Math.sqrt(b.w * b.w + b.h * b.h);
    if (диаг * scale < минДлина * 0.6) return null;

    var A = чистые[0], B = чистые[чистые.length - 1];
    var хорда = расст(A, B);
    var замкнуто = (хорда < НАСТРОЙКИ.замкнутость * L) && (L > 3 * хорда || хорда < 0.3 * диаг);

    var ровно = пересчитать(чистые, НАСТРОЙКИ.точек);

    // ── Прямая. Проверяем первой: это самая частая и самая полезная фигура,
    // и её признак не пересекается с остальными.
    if (!замкнуто) {
      var макс = 0;
      for (var j = 0; j < ровно.length; j++) {
        var d = доПрямой(ровно[j], A, B);
        if (d > макс) макс = d;
      }
      var отклонение = хорда > 1e-9 ? макс / хорда : 1;
      var извилистость = хорда > 1e-9 ? L / хорда : Infinity;
      if (отклонение <= НАСТРОЙКИ.прямая && извилистость <= НАСТРОЙКИ.прямаяИзвилистость) {
        return { kind: 'line', a: { x: A.x, y: A.y }, b: { x: B.x, y: B.y },
                 score: 1 - отклонение / НАСТРОЙКИ.прямая };
      }
    }

    if (!замкнуто) return null;   // незамкнутое и не прямое — оставляем как есть

    // Замкнутая фигура должна быть КРУПНОЙ. См. «минФигура» выше: маленький
    // замкнутый штрих — это почти наверняка буква, а не фигура.
    var минФ = (н.минФигура != null ? н.минФигура : НАСТРОЙКИ.минФигура);
    if (диаг * scale < минФ) return null;

    // ── Обвели несколько раз. Так делают часто: кружок обводят второй раз, чтобы
    // он был жирнее. Для распознавания это ломает всё сразу — площадь по
    // шнуркам считается дважды (заполнение 1.46 вместо 0.78), а после пересчёта
    // в 64 точки каждый поворот вдвое круче, и на ровной окружности находится
    // восемь «углов». Поэтому просто берём ПЕРВЫЙ виток и разбираем его.
    // Восьмёрку это не пропустит: у неё петли крутятся в разные стороны, поворот
    // выходит нулевым, и витков насчитается ноль.
    if (!н._виток) {
      var витки = Math.round(Math.abs(поворот(ровно)) / (2 * Math.PI));
      if (витки >= 2 && витки <= 6) {
        var первый = началоПути(чистые, 1 / витки);
        var под = {};
        for (var кл in н) под[кл] = н[кл];
        под._виток = true;
        // Порог размера уже пройден целой фигурой, и виток не меньше её — но
        // длина пути у витка вдвое короче, поэтому проверку длины снимаем.
        под.минДлина = 0;
        return recognize(первый, scale, под);
      }
    }

    // ── Сколько у фигуры углов и насколько плотно она заполняет свою рамку.
    //
    // Эти два числа и решают всё. Так вышло не из теории: я собрал десяток
    // заранее известных штрихов и посмотрел, что у них получается. Оказалось,
    // что признаки разводят фигуры почти без перекрытия:
    //
    //     окружность, эллипс   углов 0-2   заполнение 0.74-0.78   (в теории π/4)
    //     прямоугольник        углов 4     заполнение 0.95-0.97   (в теории 1)
    //     треугольник          углов 3     заполнение 0.48        (в теории 0.5)
    //     закорючка, росчерк   углов 6-8   заполнение 0.00
    //
    // Заполнение считается по формуле шнурков, поэтому у самопересекающейся
    // петли части площади гасят друг друга и получается почти ноль — росчерк
    // отсеивается сам собой, отдельного правила для него не нужно.
    //
    // Сначала я пробовал обойтись «разбросом радиуса от середины», и это была
    // ошибка, которую поймали проверки: у квадрата расстояние от центра гуляет
    // от a до a√2, разброс выходит меньше порога, и квадрат уверенно
    // распознавался как ОКРУЖНОСТЬ. Разброс радиуса оставлен, но только как
    // подтверждение после того, как по углам и заполнению уже понятно, что
    // перед нами овал.
    var найденные = углы(ровно, true);
    var заполнение = (b.w * b.h > 1e-9) ? площадь(ровно) / (b.w * b.h) : 0;

    // ── Прямоугольник: почти вся рамка внутри штриха. Углы НЕ считаем, и это
    // важное решение, а не упрощение.
    //
    // Сначала здесь стояло «ровно четыре угла И заполнение», и на квадратных
    // рамках это работало. Сломалось на длинной узкой рамке — той самой, которой
    // на уроке обводят ответ: у рамки 400×40 короткая сторона составляет 4.8%
    // периметра, а угол ищется по окну шириной 1/16 периметра (6.25%). Окно шире
    // стороны, поэтому два угла короткой стороны сливаются в один, находится
    // всего два угла, и рамка не распознавалась вовсе. Замеры: 340×60 — четыре
    // угла, 400×40, 500×30 и 600×24 — по два.
    //
    // Заполнение при этом оставалось 0.87..0.92, то есть признак не пострадал
    // ничуть. И заполнять свою рамку на 85% больше нечему: у овала π/4 ≈ 0.785,
    // у сектора 0.6, у ромба и треугольника около 0.5, у росчерка ноль.
    if (заполнение >= НАСТРОЙКИ.прямоугольникЗаполнение) {
      return { kind: 'rect', x: b.x, y: b.y, w: b.w, h: b.h, score: заполнение };
    }

    // ── Треугольник: три угла, и штрих идёт по сторонам этого треугольника.
    if (найденные.length === 3) {
      var в = найденные.map(function (u) { return { x: u.p.x, y: u.p.y }; });
      var sТр = площадь(в), sШт = площадь(ровно);
      // Сектор («кусок пирога») сюда не попадёт: дуга выпирает наружу, и площадь
      // штриха заметно больше площади треугольника по тем же вершинам.
      if (sТр > 1e-9 && Math.abs(sШт - sТр) / sТр <= НАСТРОЙКИ.треугольникТочность) {
        return { kind: 'triangle', pts: в, score: 1 - Math.abs(sШт - sТр) / sТр };
      }
      return null;
    }

    // ── Овал: углов нет (два допускаются на стыке, где штрих не сомкнулся),
    // заполнение около π/4.
    // Двойная защита, и это НАРОЧНО. Ромб останавливают здесь два независимых
    // правила: у него четыре угла (не проходит по счёту) и заполнение 0.49 (не
    // проходит по заполнению). Порча кода показала, что каждое из них по
    // отдельности лишнее — но лишнее оно только пока цело второе. Ошибка тут
    // стоит дорого: ромб, ставший эллипсом, — это испорченный чертёж.
    if (найденные.length <= 2 && заполнение >= НАСТРОЙКИ.овалОт) {
      var стороны = (b.w > 1e-9 && b.h > 1e-9)
        ? Math.max(b.w / b.h, b.h / b.w) : Infinity;
      // Подтверждение: радиус в координатах рамки должен быть постоянным.
      // Это отсекает «фасолину» и сердечко, у которых заполнение случайно
      // попало в диапазон овала.
      var a2 = b.w / 2, b2 = b.h / 2;
      if (a2 < 1e-9 || b2 < 1e-9) return null;
      var сум = 0, зн = [];
      for (var k1 = 0; k1 < ровно.length; k1++) {
        var nx = (ровно[k1].x - b.cx) / a2, ny = (ровно[k1].y - b.cy) / b2;
        зн.push(Math.sqrt(nx * nx + ny * ny)); сум += зн[k1];
      }
      var ср = сум / зн.length, д = 0;
      for (var k2 = 0; k2 < зн.length; k2++) д += (зн[k2] - ср) * (зн[k2] - ср);
      var разброс = ср > 1e-9 ? Math.sqrt(д / зн.length) / ср : 1;
      if (разброс > НАСТРОЙКИ.эллипс || Math.abs(ср - 1) > 0.25) return null;

      if (стороны <= НАСТРОЙКИ.кругВместоЭллипса) {
        return { kind: 'circle', cx: b.cx, cy: b.cy, r: (b.w + b.h) / 4,
                 score: 1 - разброс / НАСТРОЙКИ.эллипс };
      }
      return { kind: 'ellipse', cx: b.cx, cy: b.cy, rx: a2, ry: b2,
               score: 1 - разброс / НАСТРОЙКИ.эллипс };
    }

    // МНОГОУГОЛЬНИКОВ ЗДЕСЬ НЕТ, И ЭТО РЕШЕНИЕ, А НЕ ЗАБЫВЧИВОСТЬ. Пяти- и
    // шестиугольник от руки на уроке почти не рисуют, зато любая закорючка даёт
    // как раз пять-восемь углов — то есть ветка приносила бы одни ложные
    // срабатывания. Проверка «закорючка» ловила ровно это.

    return null;      // не поняли — и хорошо, оставим как нарисовано
  }

  // Доска хранит штрих иначе: плоский массив [dx0,dy0,dx1,dy1,...] со
  // смещениями от точки первого нажатия (data.x, data.y). Перевод держим
  // здесь, чтобы board.js не занимался разбором формата в двух местах и чтобы
  // проверки шли ровно через тот же код, что и рисование.
  function изПлоского(плоские, x0, y0) {
    var out = [];
    for (var i = 0; i + 1 < плоские.length; i += 2) {
      out.push({ x: x0 + плоские[i], y: y0 + плоские[i + 1] });
    }
    return out;
  }

  global.SmartDraw = {
    recognize: recognize,
    изПлоского: изПлоского,
    НАСТРОЙКИ: НАСТРОЙКИ,
    // Наружу — для проверок: удобно смотреть на признаки по отдельности.
    _внутренности: {
      длинаПути: длинаПути, рамка: рамка, пересчитать: пересчитать,
      углы: углы, площадь: площадь, доПрямой: доПрямой
    }
  };
})(typeof window !== 'undefined' ? window : this);
