/*
 * Общее для режимов тренировки карточек: заучивание, тест, подбор.
 *
 * Текст карточки всегда кладётся через textContent, а формулы дорисовывает
 * MathJax поверх. Так карточка не может принести на страницу разметку: содержимое
 * пишут ученики, и доверять ему нельзя, а innerHTML открыл бы дорогу чему угодно.
 */
(function (window) {
    'use strict';

    function перемешать(массив) {
        var копия = массив.slice();
        for (var i = копия.length - 1; i > 0; i--) {
            var j = Math.floor(Math.random() * (i + 1));
            var временно = копия[i];
            копия[i] = копия[j];
            копия[j] = временно;
        }
        return копия;
    }

    function формулы(узел) {
        if (window.MathJax && window.MathJax.typesetPromise) {
            window.MathJax.typesetPromise([узел]).catch(function () {});
        }
    }

    function написать(узел, текст) {
        узел.textContent = текст;
        формулы(узел);
        return узел;
    }

    /*
     * Содержимое карточки из базы. Разметка в нём уже приведена к белому списку
     * (cards/richtext.py) при записи, поэтому здесь она вставляется как есть.
     * Для всего остального — набранного ответа, служебных надписей — остаётся
     * написать(): то, что не проходило чистку, разметкой быть не должно.
     */
    function разметка(узел, html) {
        узел.innerHTML = html || '';
        формулы(узел);
        return узел;
    }

    /*
     * Ложные варианты ответа. Берём из той же колоды: чужой ответ из соседней
     * темы отличается на глаз, и вопрос перестаёт что-либо проверять.
     */
    function отвлекающие(набор, правильная, сколько) {
        var чужие = набор.filter(function (к) {
            return к.id !== правильная.id && к.ответ !== правильная.ответ;
        });
        return перемешать(чужие).slice(0, сколько);
    }

    function запрос(адрес, тело, csrf) {
        return fetch(адрес, {
            method: 'POST',
            headers: {'Content-Type': 'application/json', 'X-CSRFToken': csrf},
            body: JSON.stringify(тело)
        }).then(function (ответ) { return ответ.json(); });
    }

    function времяСловами(мс) {
        var всего = Math.round(мс / 1000);
        var минуты = Math.floor(всего / 60);
        var секунды = всего % 60;
        return минуты
            ? минуты + ' мин ' + (секунды < 10 ? '0' : '') + секунды + ' с'
            : всего + ' с';
    }

    window.Карточки = {
        перемешать: перемешать,
        написать: написать,
        разметка: разметка,
        формулы: формулы,
        отвлекающие: отвлекающие,
        запрос: запрос,
        времяСловами: времяСловами
    };
})(window);
