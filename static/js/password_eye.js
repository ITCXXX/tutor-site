/*
 * Кнопка «показать пароль» — глазок в правом краю поля.
 *
 * ЗАЧЕМ ЭТО ВООБЩЕ НУЖНО. Два разных неудобства, а лечит их одно и то же.
 *
 * 1. Пароль не виден. Набрал, промахнулся мимо клавиши — и не понять, где.
 *    Особенно на планшете и на телефоне, где клавиши мелкие.
 *
 * 2. Не переключается раскладка. Здесь надо быть точным, иначе обещание выйдет
 *    ложным. Раскладкой ФИЗИЧЕСКОЙ клавиатуры распоряжается только сама
 *    система: страница на неё не влияет никак, и никакой атрибут поля этого не
 *    меняет (в том числе lang — он про язык текста для проверки орфографии).
 *    Если на ноутбуке раскладка сама встаёт английской, причина в настройках
 *    системы, а не в сайте.
 *    А вот на телефоне и планшете разница настоящая: Apple прямо пишет, что в
 *    поле секретного ввода система временно подменяет стороннюю клавиатуру
 *    своей, и если русский добавлен только в сторонней — русских букв в поле
 *    пароля не будет вовсе. Как только пароль показан, поле становится обычным
 *    текстовым, признак секретности снят, и клавиатура возвращается.
 *    Итого: на планшете глазок и вправду даёт ввести по-русски, а на
 *    компьютере лечит другое — видно, что набрано, и промах с раскладкой
 *    замечаешь сразу, а не после отказа во входе.
 *
 * Скрипт подключён в общем шаблоне и сам находит все поля пароля на странице,
 * поэтому разметку страниц менять не нужно: новое поле получит глазок само.
 * Не нужен глазок — поставить полю атрибут data-no-eye.
 */
(function () {
    'use strict';

    var ПОКАЗАТЬ = 'Показать пароль';
    var СКРЫТЬ = 'Скрыть пароль';

    // Два значка: открытый глаз (сейчас пароль скрыт, нажатие покажет) и
    // перечёркнутый (сейчас пароль виден, нажатие скроет). Рисуем линиями
    // цветом текста, чтобы значок жил в любой теме.
    var ГЛАЗ = '<svg viewBox="0 0 24 24" width="18" height="18" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">'
        + '<path d="M1.8 12s3.6-6.6 10.2-6.6S22.2 12 22.2 12s-3.6 6.6-10.2 6.6S1.8 12 1.8 12z"/>'
        + '<circle cx="12" cy="12" r="2.8"/></svg>';
    var ГЛАЗ_ПЕРЕЧЁРКНУТ = '<svg viewBox="0 0 24 24" width="18" height="18" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">'
        + '<path d="M1.8 12s3.6-6.6 10.2-6.6c1.7 0 3.2.4 4.5 1"/>'
        + '<path d="M20.1 8.7c1.3 1.5 2.1 3.3 2.1 3.3s-3.6 6.6-10.2 6.6c-2 0-3.8-.6-5.3-1.4"/>'
        + '<path d="M9.5 9.7a2.8 2.8 0 0 0 3.9 3.9"/>'
        + '<path d="M3.5 3.5l17 17"/></svg>';

    function оснастить(поле) {
        if (!поле || поле.dataset.pwEye === '1') { return; }
        if (poleПропустить(поле)) { return; }
        поле.dataset.pwEye = '1';

        // Обёртка нужна только как точка отсчёта для кнопки. Внешние отступы
        // поля переносим на неё: иначе кнопка, растянутая на всю высоту
        // обёртки, залезла бы на этот отступ и встала ниже поля.
        var стиль = window.getComputedStyle(поле);
        var обёртка = document.createElement('div');
        обёртка.className = 'pw-eye-wrap';
        обёртка.style.marginTop = стиль.marginTop;
        обёртка.style.marginBottom = стиль.marginBottom;
        поле.parentNode.insertBefore(обёртка, поле);
        обёртка.appendChild(поле);
        // Сам отступ у поля гасится в стилях (.pw-eye-wrap > input), а не здесь:
        // классы отступов бутстрапа объявлены «важными», и строка в атрибуте
        // style их не перебивает — отступ остался бы двойным.

        var кнопка = document.createElement('button');
        кнопка.type = 'button';           // иначе кнопка внутри формы отправит её
        кнопка.className = 'pw-eye';
        кнопка.innerHTML = ГЛАЗ;
        кнопка.title = ПОКАЗАТЬ;
        кнопка.setAttribute('aria-label', ПОКАЗАТЬ);
        кнопка.setAttribute('aria-pressed', 'false');
        обёртка.appendChild(кнопка);

        function переключить() {
            var показать = (поле.type === 'password');
            // Где стоял курсор и что было выделено — смена типа это сбрасывает,
            // поэтому запоминаем и возвращаем. Иначе курсор прыгает в начало, и
            // человек дописывает пароль не с того места.
            var нач = null, кон = null;
            try { нач = поле.selectionStart; кон = поле.selectionEnd; } catch (e) { /* поле без выделения */ }
            поле.type = показать ? 'text' : 'password';
            кнопка.innerHTML = показать ? ГЛАЗ_ПЕРЕЧЁРКНУТ : ГЛАЗ;
            кнопка.title = показать ? СКРЫТЬ : ПОКАЗАТЬ;
            кнопка.setAttribute('aria-label', показать ? СКРЫТЬ : ПОКАЗАТЬ);
            кнопка.setAttribute('aria-pressed', показать ? 'true' : 'false');
            обёртка.classList.toggle('pw-eye-on', показать);
            try {
                поле.focus({ preventScroll: true });
                if (нач !== null) { поле.setSelectionRange(нач, кон); }
            } catch (e) { /* некоторые браузеры не дают выделение текстовому полю */ }
        }

        кнопка.addEventListener('click', переключить);
        // Нажатие не должно уводить фокус из поля до того, как мы его вернём:
        // иначе на телефоне экранная клавиатура успевает закрыться и открыться.
        кнопка.addEventListener('mousedown', function (e) { e.preventDefault(); });

        // Отправили форму — пароль снова прячем. На экране остаётся открытая
        // страница, и пароль не должен висеть на виду: у этого сайта уроки
        // идут с показом экрана.
        var форма = поле.form;
        if (форма && !форма.dataset.pwEyeHook) {
            форма.dataset.pwEyeHook = '1';
            форма.addEventListener('submit', function () {
                var поля = форма.querySelectorAll('input[data-pw-eye="1"]');
                for (var i = 0; i < поля.length; i++) {
                    if (поля[i].type === 'text') {
                        поля[i].type = 'password';
                        var об = поля[i].parentNode;
                        var кн = об && об.querySelector ? об.querySelector('.pw-eye') : null;
                        if (кн) {
                            кн.innerHTML = ГЛАЗ;
                            кн.title = ПОКАЗАТЬ;
                            кн.setAttribute('aria-label', ПОКАЗАТЬ);
                            кн.setAttribute('aria-pressed', 'false');
                        }
                        if (об && об.classList) { об.classList.remove('pw-eye-on'); }
                    }
                }
            });
        }
    }

    function poleПропустить(поле) {
        if (поле.hasAttribute('data-no-eye')) { return true; }
        if (поле.type !== 'password') { return true; }
        if (поле.disabled || поле.readOnly) { return true; }
        // Поле, спрятанное вёрсткой (например, в закрытом окне), оснастим
        // позже — когда его покажут; сейчас у него нельзя измерить отступы.
        return false;
    }

    function оснаститьВсе(корень) {
        var поля = (корень || document).querySelectorAll('input[type="password"]');
        for (var i = 0; i < поля.length; i++) { оснастить(поля[i]); }
    }

    function пуск() {
        оснаститьВсе(document);
        // Слежения за новыми полями здесь НЕТ, и это осознанно. Полей пароля в
        // проекте два, оба приходят вместе с готовой страницей. А наблюдатель
        // за всеми добавляемыми узлами работал бы и на доске — она наследует
        // тот же шаблон, узлы там добавляются постоянно, — ради того, чего на
        // доске нет вовсе. Появится поле, создаваемое на ходу, — позвать
        // оснаститьВсе оттуда, где его создают.
    }

    if (document.readyState === 'loading') { document.addEventListener('DOMContentLoaded', пуск); }
    else { пуск(); }
})();
