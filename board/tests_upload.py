# -*- coding: utf-8 -*-
"""Сжатие картинок при загрузке на доску.

Половина проверок — про то, что трогать НЕЛЬЗЯ. Файл человек принёс на урок, и
потерять его из-за неудачного сжатия хуже, чем не сэкономить место.
"""

import io
import os
import shutil
import tempfile

from django.test import TestCase
from PIL import Image

from .views import _ужать_картинку, _МАКС_СТОРОНА


class СжатиеКартинок(TestCase):

    def setUp(self):
        self.папка = tempfile.mkdtemp(prefix='доска-')

    def tearDown(self):
        shutil.rmtree(self.папка, ignore_errors=True)

    def положить(self, имя, картинка=None, формат='JPEG', байты=None):
        путь = os.path.join(self.папка, имя)
        if байты is not None:
            with open(путь, 'wb') as f:
                f.write(байты)
        else:
            картинка.save(путь, формат)
        return путь, os.path.getsize(путь)

    def фото(self, ш=4000, в=3000):
        """Похоже на снимок с телефона.

        Первый заход рисовал редкие точки на чёрном — и проверка справедливо
        упала: такую картинку PNG сжимает лучше JPEG, и правило «не раздувать»
        честно оставляло исходник. Настоящая фотография — плавные переходы плюс
        мелкая зернистость, и вот её JPEG обыгрывает вчистую.
        """
        основа = Image.linear_gradient('L').resize((ш, в))
        второй = Image.linear_gradient('L').rotate(90).resize((ш, в))
        зерно = Image.effect_noise((ш, в), 24)
        return Image.merge('RGB', (основа, второй, зерно))

    # ── что сжимать НАДО ─────────────────────────────────────────────────

    def test_большое_фото_ужимается(self):
        путь, было = self.положить('снимок.jpg', self.фото())
        имя, стало = _ужать_картинку(путь, '.jpg', было)
        self.assertLess(стало, было, 'файл не стал меньше')
        with Image.open(os.path.join(self.папка, имя)) as im:
            self.assertLessEqual(max(im.size), _МАКС_СТОРОНА)

    def test_png_без_прозрачности_становится_jpg(self):
        путь, было = self.положить('скан.png', self.фото(2600, 2000), 'PNG')
        имя, стало = _ужать_картинку(путь, '.png', было)
        self.assertTrue(имя.endswith('.jpg'), 'ожидали переход в jpg: %s' % имя)
        self.assertLess(стало, было)
        self.assertFalse(os.path.exists(путь), 'исходник не убран')

    def test_ужатый_файл_открывается(self):
        """Сжатие не должно оставлять битый файл — это хуже отсутствия сжатия."""
        путь, было = self.положить('снимок.jpg', self.фото())
        имя, _ = _ужать_картинку(путь, '.jpg', было)
        with Image.open(os.path.join(self.папка, имя)) as im:
            im.verify()

    # ── что трогать НЕЛЬЗЯ ───────────────────────────────────────────────

    def test_pdf_не_трогаем(self):
        путь, было = self.положить('задачи.pdf', байты=b'%PDF-1.4\n' + b'x' * 500000)
        имя, стало = _ужать_картинку(путь, '.pdf', было)
        self.assertEqual(стало, было)
        self.assertTrue(os.path.exists(путь))

    def test_gif_не_трогаем(self):
        """Может быть анимацией, и пережатие её убьёт."""
        путь, было = self.положить('анимация.gif', self.фото(800, 600), 'GIF')
        имя, стало = _ужать_картинку(путь, '.gif', было)
        self.assertEqual(стало, было)
        self.assertTrue(os.path.exists(путь))

    def test_прозрачность_сохраняется(self):
        """Вырезанный чертёж поверх клетчатого фона: JPEG сделал бы из
        прозрачности чёрный квадрат."""
        im = Image.new('RGBA', (2600, 2000), (255, 0, 0, 0))
        путь, было = self.положить('вырезка.png', im, 'PNG')
        имя, стало = _ужать_картинку(путь, '.png', было)
        self.assertEqual(стало, было, 'картинку с прозрачностью пережали')
        with Image.open(os.path.join(self.папка, имя)) as проверка:
            self.assertIn(проверка.mode, ('RGBA', 'LA', 'P'))

    def test_мелкий_файл_не_трогаем(self):
        путь, было = self.положить('значок.jpg', self.фото(200, 150))
        имя, стало = _ужать_картинку(путь, '.jpg', было)
        self.assertEqual(стало, было)

    def test_битый_файл_остаётся_как_был(self):
        """Оригинал важнее экономии: человек принёс его на урок."""
        мусор = 'не картинка, а мусор'.encode('utf-8') * 30000
        путь, было = self.положить('битый.jpg', байты=b'\xff\xd8' + мусор)
        имя, стало = _ужать_картинку(путь, '.jpg', было)
        self.assertEqual(стало, было)
        self.assertTrue(os.path.exists(путь), 'битый файл удалили — потеря')

    def test_уже_сжатую_картинку_не_раздуваем(self):
        """Если пережатие вышло в плюс, толку нет — оставляем исходную."""
        мелкая = self.фото(700, 500)
        буфер = io.BytesIO()
        мелкая.save(буфер, 'JPEG', quality=30)
        путь, было = self.положить('сжатая.jpg', байты=буфер.getvalue())
        имя, стало = _ужать_картинку(путь, '.jpg', было)
        self.assertLessEqual(стало, было)
        self.assertTrue(os.path.exists(os.path.join(self.папка, имя)))

    def test_поворот_по_метке_учитывается(self):
        """Снятое боком фото иначе ляжет на доску набок."""
        im = self.фото(2600, 2000)
        буфер = io.BytesIO()
        exif = Image.Exif()
        exif[274] = 6                      # «повернуть на 90°»
        # Качество 95 — как снимает телефон. С низким качеством пережатие вышло
        # бы в плюс, функция оставила бы оригинал, и проверка мерила бы не то.
        im.save(буфер, 'JPEG', exif=exif, quality=95)
        путь, было = self.положить('боком.jpg', байты=буфер.getvalue())
        имя, _ = _ужать_картинку(путь, '.jpg', было)
        with Image.open(os.path.join(self.папка, имя)) as итог:
            self.assertGreater(итог.size[1], итог.size[0],
                               'фото не развернулось: осталось лежать боком')
