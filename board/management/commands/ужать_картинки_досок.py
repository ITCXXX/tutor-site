# -*- coding: utf-8 -*-
"""Ужать картинки, уже лежащие на досках.

Сжатие при загрузке помогает только новым файлам. У досок, набитых до правки,
лежат снимки по три-двенадцать мегабайт, и место они занимают по-прежнему.

БЕЗ ФЛАГА КОМАНДА НИЧЕГО НЕ МЕНЯЕТ — только показывает, что бы сделала. Это
чужие файлы, принесённые на урок; молча переписывать их по одному запуску
нельзя. Чтобы правда ужать, нужен --применить.

    venv/bin/python manage.py ужать_картинки_досок
    venv/bin/python manage.py ужать_картинки_досок --применить

Ссылки в доске не меняются, если имя файла остаётся прежним. У png имя меняется
на .jpg, поэтому такие файлы команда ПРОПУСКАЕТ: переименование потребовало бы
править и записи элементов доски, а это уже не уборка места, а правка данных.
"""

import os

from django.conf import settings
from django.core.management.base import BaseCommand

from board.views import _ужать_картинку, _НЕ_ТРОГАТЬ_МЕНЬШЕ


class Command(BaseCommand):
    help = 'Ужать картинки на досках (по умолчанию только показывает)'

    def add_arguments(self, parser):
        parser.add_argument('--применить', action='store_true',
                            help='действительно переписать файлы')
        parser.add_argument('--доска', default=None,
                            help='код одной доски; по умолчанию все')

    def handle(self, *args, **опции):
        корень = os.path.join(settings.MEDIA_ROOT, 'board')
        if not os.path.isdir(корень):
            self.stdout.write('Папки с файлами досок нет — нечего делать.')
            return

        применить = опции['применить']
        только = опции['доска']
        всего_было = всего_стало = 0
        тронуто = пропущено = 0

        for доска in sorted(os.listdir(корень)):
            if только and доска != только:
                continue
            папка = os.path.join(корень, доска)
            if not os.path.isdir(папка):
                continue
            for имя in sorted(os.listdir(папка)):
                путь = os.path.join(папка, имя)
                ext = os.path.splitext(имя)[1].lower()
                if ext != '.jpg' and ext != '.jpeg':
                    # .png пропускаем намеренно: сжатие сменило бы имя на .jpg,
                    # и ссылку в элементе доски пришлось бы править тоже.
                    continue
                было = os.path.getsize(путь)
                if было < _НЕ_ТРОГАТЬ_МЕНЬШЕ:
                    continue

                if not применить:
                    всего_было += было
                    тронуто += 1
                    self.stdout.write('  %s/%s  %.1f МБ' % (доска, имя, было / 1048576.0))
                    continue

                новое_имя, стало = _ужать_картинку(путь, ext, было)
                if новое_имя != имя:
                    # Такого быть не должно (jpg остаётся jpg), но если вдруг —
                    # вернём как было, лишь бы не порвать ссылку.
                    пропущено += 1
                    continue
                всего_было += было
                всего_стало += стало
                тронуто += 1
                self.stdout.write('  %s/%s  %.1f → %.2f МБ'
                                  % (доска, имя, было / 1048576.0, стало / 1048576.0))

        if not применить:
            self.stdout.write('')
            self.stdout.write('Нашлось %d файлов на %.1f МБ.' % (тронуто, всего_было / 1048576.0))
            self.stdout.write('Ничего не изменено. Чтобы ужать — добавьте --применить')
            return

        self.stdout.write('')
        self.stdout.write('Ужато файлов: %d. Было %.1f МБ, стало %.1f МБ.'
                          % (тронуто, всего_было / 1048576.0, всего_стало / 1048576.0))
        if пропущено:
            self.stdout.write('Пропущено (сменилось бы имя): %d' % пропущено)
