# -*- coding: utf-8 -*-
"""Мелочи русского языка, из-за которых текст на экране выглядит машинным."""


def склонение(n, одна, две, много):
    """Русское согласование числа: 1 задача, 2 задачи, 5 задач.

    Django умеет только две формы (фильтр pluralize), а русскому нужно три,
    и на границах он ошибается заметнее всего: «0 из 1 уроков» и «21 задач»
    сразу читаются как машинный текст.
    """
    n = abs(n) % 100
    if 11 <= n <= 14:
        return много
    n %= 10
    if n == 1:
        return одна
    if 2 <= n <= 4:
        return две
    return много
