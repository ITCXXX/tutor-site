# -*- coding: utf-8 -*-
"""
Чертежи планиметрии в SVG — для задания №24 (задачи на доказательство).

Зачем отдельно от plot_svg: там рисуется график функции в системе координат
с сеткой и осями, здесь — фигура без осей, зато с подписанными вершинами,
штрихами равенства отрезков, дугами углов и прямыми углами. Общее только
то, что картинка уходит текстом внутрь HTML-разбора.

Масштаб подбирается сам: чертёж строится в «мировых» координатах (какие
удобны формулам), а потом вписывается в холст с полями. Пропорции
сохраняются — в геометрии сплющенный чертёж лжёт.

Пример:

    ч = Чертёж()
    A, B, C, D = (0, 0), (2, 3), (7, 3), (10, 0)
    ч.многоугольник([A, B, C, D])
    ч.отрезок(B, D, пунктир=True)
    ч.вершина(A, 'A', 'юз'); ч.вершина(B, 'B', 'сз')
    ч.вершина(C, 'C', 'св'); ч.вершина(D, 'D', 'юв')
    svg = ч.готово()
"""

import math

ЛИНИЯ = '#1f2933'
ВСПОМОГАТЕЛЬНАЯ = '#8a94a6'
ЗАЛИВКА = '#eef2ff'
ПОДПИСЬ = '#1f2933'
ФОН = '#ffffff'

# Насколько подписи обязаны расходиться и как далеко их можно оттолкнуть от
# заданного места. 18 px — примерная ширина буквы с запасом; сдвиг больше 10 px
# уже отрывает букву от её вершины, и лучше оставить тесно, но однозначно.
ЗАЗОР_ПОДПИСЕЙ = 18.0
МАКС_СДВИГ = 10.0

# Куда сдвинуть подпись вершины относительно самой точки, в пикселях.
СТОРОНЫ = {
    'с': (0, -10), 'ю': (0, 16), 'з': (-12, 4), 'в': (12, 4),
    'сз': (-11, -8), 'св': (11, -8), 'юз': (-11, 14), 'юв': (11, 14),
}


class Чертёж(object):
    def __init__(self, width=380, height=280, поле=28):
        self.width = width
        self.height = height
        self.поле = поле
        self._команды = []          # (слой, xml) — подписи рисуем последними
        self._точки = []            # все упомянутые точки, для подбора масштаба

    # ── внутреннее ────────────────────────────────────────────────────────

    def _учесть(self, *точки):
        self._точки.extend(точки)

    def _добавить(self, слой, xml):
        self._команды.append((слой, xml))

    def _преобразование(self):
        if not self._точки:
            return (lambda p: p)
        xs = [p[0] for p in self._точки]
        ys = [p[1] for p in self._точки]
        ширина = max(xs) - min(xs) or 1.0
        высота = max(ys) - min(ys) or 1.0
        доступно_ш = self.width - 2 * self.поле
        доступно_в = self.height - 2 * self.поле
        # Один масштаб на обе оси: разные масштабы превращают квадрат в
        # прямоугольник, а окружность в эллипс — в геометрии это ложь.
        k = min(доступно_ш / ширина, доступно_в / высота)
        сдвиг_x = self.поле + (доступно_ш - ширина * k) / 2 - min(xs) * k
        сдвиг_y = self.поле + (доступно_в - высота * k) / 2 + max(ys) * k

        def в_экран(p):
            return (p[0] * k + сдвиг_x, сдвиг_y - p[1] * k)

        в_экран.k = k
        return в_экран

    @staticmethod
    def _чс(v):
        return ('%.1f' % v).rstrip('0').rstrip('.')

    # ── примитивы ─────────────────────────────────────────────────────────

    def отрезок(self, a, b, пунктир=False, вспомогательный=False, ширина=1.6):
        self._учесть(a, b)
        цвет = ВСПОМОГАТЕЛЬНАЯ if вспомогательный else ЛИНИЯ
        штрих = ' stroke-dasharray="5 4"' if пунктир else ''
        self._добавить(1, ('<line x1="{ax}" y1="{ay}" x2="{bx}" y2="{by}" '
                           'stroke="%s" stroke-width="%s"%s '
                           'stroke-linecap="round"/>' % (цвет, ширина, штрих),
                          (a, b)))

    def многоугольник(self, точки, залить=True):
        self._учесть(*точки)
        self._добавить(0, ('polygon', tuple(точки), залить))

    def окружность(self, центр, радиус, пунктир=False, вспомогательная=False):
        # Крайние точки нужны, чтобы окружность влезла в кадр целиком.
        self._учесть((центр[0] - радиус, центр[1] - радиус),
                     (центр[0] + радиус, центр[1] + радиус))
        цвет = ВСПОМОГАТЕЛЬНАЯ if вспомогательная else ЛИНИЯ
        штрих = ' stroke-dasharray="5 4"' if пунктир else ''
        self._добавить(1, ('circle', центр, радиус, цвет, штрих))

    def точка(self, p, закрашена=True):
        self._учесть(p)
        self._добавить(2, ('dot', p, закрашена))

    def вершина(self, p, подпись, сторона='юв', закрашена=True):
        self.точка(p, закрашена)
        self._добавить(3, ('label', p, подпись, сторона))

    def подпись(self, p, текст, сторона='с'):
        self._учесть(p)
        self._добавить(3, ('label', p, текст, сторона))

    def равенство(self, a, b, штрихов=1):
        """Штрихи на середине отрезка — пометка «эти отрезки равны»."""
        self._учесть(a, b)
        self._добавить(2, ('ticks', a, b, штрихов))

    def прямой_угол(self, вершина, к1, к2, размер=0.5):
        """Квадратик прямого угла при вершине, между направлениями к к1 и к2."""
        self._учесть(вершина)
        self._добавить(1, ('right', вершина, к1, к2, размер))

    def дуга_угла(self, вершина, к1, к2, радиус=0.7, штрихов=1):
        """Дужка при вершине — пометка угла (и его кратности штрихами)."""
        self._учесть(вершина)
        self._добавить(1, ('arc', вершина, к1, к2, радиус, штрихов))

    # ── сборка ────────────────────────────────────────────────────────────

    def _развести_подписи(self, в):
        """
        Раздвинуть подписи, оказавшиеся ближе ЗАЗОР_ПОДПИСЕЙ друг к другу.

        Сторону подписи автор задаёт заранее, но какие вершины окажутся
        рядом — зависит от чисел задачи. Поэтому правим по факту: пары
        толкаем вдоль соединяющего вектора, малыми шагами и не дальше
        МАКС_СДВИГ от исходного места, чтобы буква не оторвалась от своей
        точки. Возвращает {индекс команды: (dx, dy)}.
        """
        позиции = []
        for i, (слой, команда) in enumerate(self._команды):
            if isinstance(команда, tuple) and команда[0] == 'label':
                _, p, текст, сторона = команда
                x, y = в(p)
                dx, dy = СТОРОНЫ.get(сторона, СТОРОНЫ['юв'])
                позиции.append([i, x + dx, y + dy, 0.0, 0.0])

        for _ in range(24):
            двигали = False
            for a in range(len(позиции)):
                for b in range(a + 1, len(позиции)):
                    ia, xa, ya, sxa, sya = позиции[a]
                    ib, xb, yb, sxb, syb = позиции[b]
                    dx, dy = (xb + sxb) - (xa + sxa), (yb + syb) - (ya + sya)
                    d = math.hypot(dx, dy)
                    if d >= ЗАЗОР_ПОДПИСЕЙ:
                        continue
                    if d < 1e-6:
                        dx, dy, d = 1.0, 0.0, 1.0
                    толчок = (ЗАЗОР_ПОДПИСЕЙ - d) / 2.0 * 0.6
                    ux, uy = dx / d, dy / d
                    for поз, знак in ((позиции[a], -1), (позиции[b], +1)):
                        nx = поз[3] + знак * ux * толчок
                        ny = поз[4] + знак * uy * толчок
                        длина = math.hypot(nx, ny)
                        if длина > МАКС_СДВИГ:
                            nx, ny = nx / длина * МАКС_СДВИГ, ny / длина * МАКС_СДВИГ
                        поз[3], поз[4] = nx, ny
                    двигали = True
            if not двигали:
                break
        return {поз[0]: (поз[3], поз[4]) for поз in позиции}

    def готово(self):
        в = self._преобразование()
        k = getattr(в, 'k', 1.0)
        сдвиги = self._развести_подписи(в)
        куски = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" '
                 'width="100%%" style="max-width:%dpx;height:auto;display:block;'
                 'margin:0 auto" role="img">' % (self.width, self.height, self.width),
                 '<rect width="%d" height="%d" fill="%s"/>'
                 % (self.width, self.height, ФОН)]

        порядок = sorted(range(len(self._команды)), key=lambda i: self._команды[i][0])
        for i in порядок:
            слой, команда = self._команды[i]
            куски.append(self._нарисовать(команда, в, k, сдвиги.get(i)))

        куски.append('</svg>')
        return ''.join(куски)

    def _нарисовать(self, команда, в, k, сдвиг=None):
        чс = self._чс

        if isinstance(команда, tuple) and isinstance(команда[0], str) \
                and команда[0] not in ('polygon', 'circle', 'dot', 'label',
                                       'ticks', 'right', 'arc'):
            # Готовый шаблон отрезка: подставляем экранные координаты.
            шаблон, (a, b) = команда
            ax, ay = в(a)
            bx, by = в(b)
            return шаблон.format(ax=чс(ax), ay=чс(ay), bx=чс(bx), by=чс(by))

        вид = команда[0]

        if вид == 'polygon':
            _, точки, залить = команда
            путь = ' '.join('%s,%s' % (чс(x), чс(y)) for x, y in map(в, точки))
            return ('<polygon points="%s" fill="%s" stroke="%s" '
                    'stroke-width="1.6" stroke-linejoin="round"/>'
                    % (путь, ЗАЛИВКА if залить else 'none', ЛИНИЯ))

        if вид == 'circle':
            _, центр, радиус, цвет, штрих = команда
            cx, cy = в(центр)
            return ('<circle cx="%s" cy="%s" r="%s" fill="none" stroke="%s" '
                    'stroke-width="1.6"%s/>'
                    % (чс(cx), чс(cy), чс(радиус * k), цвет, штрих))

        if вид == 'dot':
            _, p, закрашена = команда
            x, y = в(p)
            if закрашена:
                return '<circle cx="%s" cy="%s" r="3.2" fill="%s"/>' % (
                    чс(x), чс(y), ЛИНИЯ)
            return ('<circle cx="%s" cy="%s" r="3.2" fill="%s" stroke="%s" '
                    'stroke-width="1.8"/>' % (чс(x), чс(y), ФОН, ЛИНИЯ))

        if вид == 'label':
            _, p, текст, сторона = команда
            x, y = в(p)
            dx, dy = СТОРОНЫ.get(сторона, СТОРОНЫ['юв'])
            if сдвиг:
                dx, dy = dx + сдвиг[0], dy + сдвиг[1]
            return ('<text x="%s" y="%s" font-size="13" fill="%s" '
                    'text-anchor="middle" font-style="italic" '
                    'stroke="%s" stroke-width="3" paint-order="stroke" '
                    'stroke-linejoin="round">%s</text>'
                    % (чс(x + dx), чс(y + dy), ПОДПИСЬ, ФОН, текст))

        if вид == 'ticks':
            _, a, b, штрихов = команда
            ax, ay = в(a)
            bx, by = в(b)
            сx, сy = (ax + bx) / 2, (ay + by) / 2
            длина = math.hypot(bx - ax, by - ay) or 1.0
            ux, uy = (bx - ax) / длина, (by - ay) / длина
            nx, ny = -uy, ux
            строки = []
            for i in range(штрихов):
                сдвиг = (i - (штрихов - 1) / 2.0) * 4.5
                px, py = сx + ux * сдвиг, сy + uy * сдвиг
                строки.append('<line x1="%s" y1="%s" x2="%s" y2="%s" '
                              'stroke="%s" stroke-width="1.6"/>'
                              % (чс(px - nx * 5), чс(py - ny * 5),
                                 чс(px + nx * 5), чс(py + ny * 5), ЛИНИЯ))
            return ''.join(строки)

        if вид == 'right':
            _, вершина, к1, к2, размер = команда
            vx, vy = в(вершина)
            строки = []
            концы = []
            for к in (к1, к2):
                cx, cy = в(к)
                d = math.hypot(cx - vx, cy - vy) or 1.0
                концы.append(((cx - vx) / d, (cy - vy) / d))
            r = размер * k
            (u1x, u1y), (u2x, u2y) = концы
            p1 = (vx + u1x * r, vy + u1y * r)
            p2 = (vx + u1x * r + u2x * r, vy + u1y * r + u2y * r)
            p3 = (vx + u2x * r, vy + u2y * r)
            строки.append('<polyline points="%s,%s %s,%s %s,%s" fill="none" '
                          'stroke="%s" stroke-width="1.4"/>'
                          % (чс(p1[0]), чс(p1[1]), чс(p2[0]), чс(p2[1]),
                             чс(p3[0]), чс(p3[1]), ЛИНИЯ))
            return ''.join(строки)

        if вид == 'arc':
            _, вершина, к1, к2, радиус, штрихов = команда
            vx, vy = в(вершина)
            углы = []
            for к in (к1, к2):
                cx, cy = в(к)
                углы.append(math.atan2(cy - vy, cx - vx))
            a1, a2 = углы
            # Рисуем меньшую из двух дуг — это и есть сам угол.
            if (a2 - a1) % (2 * math.pi) > math.pi:
                a1, a2 = a2, a1
            строки = []
            for i in range(штрихов):
                r = радиус * k + i * 4
                x1, y1 = vx + r * math.cos(a1), vy + r * math.sin(a1)
                x2, y2 = vx + r * math.cos(a2), vy + r * math.sin(a2)
                большая = 1 if (a2 - a1) % (2 * math.pi) > math.pi else 0
                строки.append('<path d="M%s %s A%s %s 0 %d 1 %s %s" fill="none" '
                              'stroke="%s" stroke-width="1.3"/>'
                              % (чс(x1), чс(y1), чс(r), чс(r), большая,
                                 чс(x2), чс(y2), ЛИНИЯ))
            return ''.join(строки)

        raise ValueError('неизвестная команда чертежа: %r' % (вид,))
