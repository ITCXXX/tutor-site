# -*- coding: utf-8 -*-
"""Напоминания о сроках домашних заданий. Запускается раз в сутки таймером.

ПОЧЕМУ ЧЕРЕЗ homework_for(). Соблазн посчитать сроки здесь заново велик, но
именно так в этом проекте уже разошлось правило зачёта. homework_for — то же
самое, что видит ученик в кабинете: он же учитывает личные продления, задачи,
которые ещё не сданы, и закрытый приём. Значит напоминание и кабинет не смогут
разойтись во мнениях.

ЧТО ИМЕННО ШЛЁМ. Три события, каждое ровно один раз на урок:
  • срок подходит   — за N дней (по умолчанию за один);
  • срок вышел      — но работу ещё принимают;
  • приём закрыт    — сдать уже нельзя.
Разные ключи, поэтому одно не заслоняет другое: ученик получит и «завтра
срок», и потом «срок вышел», и потом «приём закрыт», но каждое по одному разу.

Преподавателю — одна сводка за день, а не письмо на каждого ученика.
"""

from django.core.management.base import BaseCommand
from django.urls import reverse
from django.utils import timezone

from users.homework import homework_for
from users.models import Notification, User
from users.notifications import notify_once


def _склонение(n, одна, две, много):
    """Русское согласование числа: 1 задача, 2 задачи, 5 задач."""
    n = abs(n) % 100
    if 11 <= n <= 14:
        return много
    n %= 10
    if n == 1:
        return одна
    if 2 <= n <= 4:
        return две
    return много


class Command(BaseCommand):
    help = 'Напомнить ученикам о сроках домашних заданий и дать сводку преподавателям'

    def add_arguments(self, parser):
        parser.add_argument(
            '--days', type=int, default=1,
            help='за сколько дней до срока предупреждать (по умолчанию за 1)')
        parser.add_argument(
            '--dry-run', action='store_true',
            help='показать, что было бы отправлено, и ничего не записывать')

    def handle(self, *args, **opts):
        за_сколько = max(0, opts['days'])
        всухую = opts['dry_run']
        сегодня = timezone.localdate()

        # Только те, у кого есть действующая запись на курс: остальным
        # напоминать не о чем, и гонять по ним запросы незачем.
        ученики = (User.objects
                   .filter(role='student', enrollments__is_active=True)
                   .distinct())

        отправлено = {'soon': 0, 'late': 0, 'closed': 0, 'digest': 0}
        долги = {}   # преподаватель -> [(ученик, сколько уроков просрочено)]

        for ученик in ученики:
            просрочено_у_него = 0
            for строка in homework_for(ученик):
                срок = строка['due']
                if not срок:
                    continue                      # бессрочная домашка — молчим

                урок = строка['lesson']
                осталось = строка['left']
                хвост = '%d %s' % (осталось, _склонение(
                    осталось, 'задача', 'задачи', 'задач'))
                # Адрес считаем через reverse: маршрут переименуют — ссылка
                # в уведомлении не станет молча битой.
                адрес = reverse('lesson_detail', args=[урок.id])

                if строка['closed']:
                    # Приём закрыт — сдать уже нельзя. Говорим один раз.
                    просрочено_у_него += 1
                    if self._шлём(всухую, ученик, Notification.KIND_DUE_PASSED,
                                  'Приём закрыт: «%s». Осталось %s — работу уже '
                                  'не сдать, подойдите к преподавателю.'
                                  % (урок.title, хвост),
                                  адрес, 'lesson:%d:closed' % урок.id):
                        отправлено['closed'] += 1

                elif строка['overdue']:
                    просрочено_у_него += 1
                    когда_до = строка['cutoff']
                    добавка = ('' if not когда_до
                               else ' Принимаю до %s.' % когда_до.strftime('%d.%m'))
                    if self._шлём(всухую, ученик, Notification.KIND_DUE_PASSED,
                                  'Срок вышел: «%s». Осталось %s.%s'
                                  % (урок.title, хвост, добавка),
                                  адрес, 'lesson:%d:late' % урок.id):
                        отправлено['late'] += 1

                elif строка['days_left'] is not None and строка['days_left'] <= за_сколько:
                    когда = ('сегодня' if строка['days_left'] == 0
                             else 'завтра' if строка['days_left'] == 1
                             else 'через %d %s' % (строка['days_left'], _склонение(
                                 строка['days_left'], 'день', 'дня', 'дней')))
                    if self._шлём(всухую, ученик, Notification.KIND_DUE_SOON,
                                  'Срок %s: «%s». Осталось %s.'
                                  % (когда, урок.title, хвост),
                                  адрес, 'lesson:%d:soon' % урок.id):
                        отправлено['soon'] += 1

            if просрочено_у_него:
                профиль = getattr(ученик, 'student_profile', None)
                преподаватель = getattr(профиль, 'teacher', None)
                if преподаватель:
                    долги.setdefault(преподаватель, []).append(
                        (ученик, просрочено_у_него))

        # Сводка преподавателю: ОДНА запись за день, а не по штуке на ученика.
        # Ключ включает дату — значит завтра сводка придёт снова, но сегодня
        # второй раз не появится, сколько бы раз команду ни запустили.
        for преподаватель, список in долги.items():
            имена = ', '.join(у.display for у, _ in список[:5])
            если_ещё = '' if len(список) <= 5 else ' и ещё %d' % (len(список) - 5)
            текст = ('Не сдали в срок: %s%s. Всего %d %s.'
                     % (имена, если_ещё, len(список),
                        _склонение(len(список), 'ученик', 'ученика', 'учеников')))
            if self._шлём(всухую, преподаватель, Notification.KIND_DIGEST,
                          текст, reverse('teacher_submissions'),
                          'digest:%s' % сегодня.isoformat()):
                отправлено['digest'] += 1

        итог = ('%sсрок подходит: %d, срок вышел: %d, приём закрыт: %d, сводок: %d'
                % ('(вхолостую) ' if всухую else '',
                   отправлено['soon'], отправлено['late'],
                   отправлено['closed'], отправлено['digest']))
        self.stdout.write(self.style.SUCCESS(итог))

    def _шлём(self, всухую, кому, вид, текст, адрес, ключ):
        if всухую:
            self.stdout.write('  → %s [%s] %s' % (кому.display, ключ, текст))
            return True
        return notify_once(кому, вид, текст, адрес, ключ)
