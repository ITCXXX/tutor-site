def _дуга(ч, O, R, от, до, вспомогательный=False, шагов=48):
    """Дуга окружности (O, R) от угла `от` до `до` в градусах — ломаной из отрезков."""
    prev = None
    for i in range(шагов + 1):
        a = math.radians(от + (до - от) * i / float(шагов))
        p = (O[0] + R * math.cos(a), O[1] + R * math.sin(a))
        if prev is not None:
            ч.отрезок(prev, p, вспомогательный=вспомогательный)
        prev = p


