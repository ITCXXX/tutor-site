def _окружности_через_CD_касающиеся_AB(A, B, C, D):
    """
    Все окружности, проходящие через C и D и касающиеся прямой AB.

    Чистое построение, без формулы ответа: центр O лежит на серединном
    перпендикуляре к CD, O = M + t·n, и его расстояние до прямой AB равно OC.
    Это квадратное уравнение на t. Возвращает список (O, r, E), где E — точка
    касания (проекция центра на прямую AB). Работает при любом положении
    фигуры на плоскости.
    """
    M = середина(C, D)
    dx, dy = D[0] - C[0], D[1] - C[1]
    L = math.hypot(dx, dy)
    n = (-dy / L, dx / L)
    ux, uy = B[0] - A[0], B[1] - A[1]
    LAB = math.hypot(ux, uy)

    def знаковое_расстояние_до_AB(P):
        return (ux * (P[1] - A[1]) - uy * (P[0] - A[0])) / LAB

    alpha = знаковое_расстояние_до_AB(M)
    beta = знаковое_расстояние_до_AB((M[0] + n[0], M[1] + n[1])) - alpha
    d2 = (L / 2.0) ** 2
    # (alpha + beta·t)² = d2 + t²
    qa, qb, qc = beta * beta - 1.0, 2.0 * alpha * beta, alpha * alpha - d2
    if abs(qa) < 1e-12:
        корни = [-qc / qb]
    else:
        disc = qb * qb - 4.0 * qa * qc
        if disc < 0:
            return []
        s = math.sqrt(disc)
        корни = [(-qb - s) / (2.0 * qa), (-qb + s) / (2.0 * qa)]
    результат = []
    for t in корни:
        O = (M[0] + n[0] * t, M[1] + n[1] * t)
        r = расстояние(O, C)
        E = проекция(A, B, O)
        результат.append((O, r, E))
    return результат


