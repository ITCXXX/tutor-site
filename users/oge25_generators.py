# ────────────────────────────────────────────────────────────────────────
# №25, тип 4. Трапеция, углы при одном основании в сумме дают 90°: найти
# ────────────────────────────────────────────────────────────────────────
#
# основания по средней линии и отрезку между серединами оснований.
#
# Условие банка: «Углы при одном из оснований трапеции равны α и β, а отрезки,
# соединяющие середины противоположных сторон трапеции, равны m и n. Найдите
# основания трапеции.» Какой из отрезков — средняя линия, не сказано.
#
# Семейство. Свободные величины — не m и n, а основания: BC = a < AD = b,
# натуральные одной чётности, и угол α (β = 90° − α). Тогда средняя линия
# KL = (a + b)/2 и отрезок между серединами оснований MN = (b − a)/2 — целые,
# их и ставим в условие (как в банке — больший первым). Ответ банка: «b; a».
#
# Почему MN = (b − a)/2. Продолжаем боковые стороны до точки P; ∠APD = 90°.
# PN и PM — медианы прямоугольных треугольников APD и BPC из вершины прямого
# угла, PN = b/2, PM = a/2; P, M, N лежат на одной прямой, MN = PN − PM.
# Средняя линия всегда больше MN, поэтому больший данный отрезок — она.
#
# check() формулу не знает: он строит трапецию по углам α, β и основаниям
# (a, b) в координатах, измеряет KL и MN серединами и расстояниями, и
# численно (метод Ньютона по двум переменным) подбирает (a, b), при которых
# измеренные отрезки совпадают с данными m и n — для обоих вариантов «какой
# отрезок средняя линия». Годится только тот вариант, где получается
# настоящая трапеция (BC > 0 и углы при AD равны данным); второй даёт
# BC < 0. Так координаты проверяют и формулу, и утверждение «средняя
# линия — больший отрезок».


def _трапеция_4(alpha, beta, a, b):
    """
    Трапеция ABCD в координатах: AD = b на оси x, ∠BAD = alpha, ∠CDA = beta
    (градусы), BC = a. Высота — из условия BC ∥ AD:
    h·ctg α + a + h·ctg β = b. Никакой формулы ответа здесь нет.
    Возвращает A, B, C, D или None, если при таких (a, b) углы при AD
    получаются не те (фигура «вывернулась»).
    """
    al, be = math.radians(alpha), math.radians(beta)
    ctg_a, ctg_b = 1.0 / math.tan(al), 1.0 / math.tan(be)
    h = (b - a) / (ctg_a + ctg_b)
    A, D = (0.0, 0.0), (float(b), 0.0)
    B = (h * ctg_a, h)
    C = (b - h * ctg_b, h)
    if abs(угол(B, A, D) - alpha) > 1e-7 or abs(угол(C, D, A) - beta) > 1e-7:
        return None
    return A, B, C, D


