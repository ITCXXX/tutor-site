def _дробь(f):
    """
    LaTeX обыкновенной дроби: 15/16 → \\dfrac{15}{16}.

    Значения sin²α, cos²α и sinα выписываются именно дробями, как в решениях
    банка (11/36, 25/36, 5/6). Десятичная запись здесь читалась бы хуже:
    при u = 4 это 0,609375 и 0,390625, а в итоговой формуле синус всё равно
    нужен дробью.
    """
    f = Fraction(f)
    if f.denominator == 1:
        return str(f.numerator)
    return '\\dfrac{%d}{%d}' % (f.numerator, f.denominator)


def _радикал_дробь(коэф, r):
    """LaTeX числа коэф·√r, коэф — Fraction: \\dfrac{2\\sqrt{2}}{3}, \\dfrac{\\sqrt{11}}{6}."""
    коэф = Fraction(коэф)
    if r == 1:
        return num_latex(коэф)
    числ = '' if коэф.numerator == 1 else str(коэф.numerator)
    корень = '%s\\sqrt{%d}' % (числ, r)
    if коэф.denominator == 1:
        return корень
    return '\\dfrac{%s}{%d}' % (корень, коэф.denominator)


def _построить_12(m, n, cos_a):
    """
    Фигура по данным условия — без формулы ответа.

    A в начале координат, AC — ось x (M = (m, 0), N = (n, 0)), луч AB под
    углом α = arccos(cos_a). Центр O искомой окружности лежит на серединном
    перпендикуляре к MN, то есть на прямой x = (m + n)/2, и на нормали к AB
    в точке касания K = t·(cos α, sin α), t > 0, на расстоянии R от K (с той
    стороны прямой AB, где лежит C). Первое условие выражает R через t:
    t·cos α + R·sin α = (m + n)/2. Остаётся одно неизвестное t — его даёт
    бисекция по условию |OM| = R: на (0, x0/cos α) невязка меняет знак ровно
    один раз (при t = 0 круг заведомо шире, при R = 0 — уже).
    """
    m, n = float(m), float(n)
    c = float(cos_a)
    sn = math.sqrt(1.0 - c * c)
    A = (0.0, 0.0)
    M = (m, 0.0)
    N = (n, 0.0)
    C = (1.2 * n, 0.0)
    x0 = 0.5 * (m + n)

    def центр(t):
        R = (x0 - t * c) / sn
        K = (t * c, t * sn)
        return (K[0] + R * sn, K[1] - R * c), K, R

    def невязка(t):
        O, _, R = центр(t)
        return расстояние(O, M) - R

    if c <= 0:
        raise ValueError('построение рассчитано на острый угол A')
    lo, hi = 0.0, x0 / c
    if not (невязка(lo) < 0 < невязка(hi)):
        raise ValueError('невязка не меняет знак на отрезке поиска')
    for _ in range(200):
        mid = 0.5 * (lo + hi)
        if невязка(mid) < 0:
            lo = mid
        else:
            hi = mid
    t = 0.5 * (lo + hi)
    O, K, R = центр(t)
    B = (1.25 * t * c, 1.25 * t * sn)          # длина AB на ответ не влияет

    # Самопроверка построения по данным условия.
    R_изм = расстояние(O, M)
    if abs(расстояние(O, N) - R_изм) > 1e-9 * R_изм:
        raise ValueError('окружность не проходит через N')
    if abs(расстояние_до_прямой(O, A, B) - R_изм) > 1e-9 * R_изм:
        raise ValueError('окружность не касается прямой AB')
    if t <= 0:
        raise ValueError('точка касания не на луче AB')
    return A, B, C, M, N, K, O


