#   (3, 4): k = 2, 4 (c = 12,5k, AN = 3,5k), P = 50k, S = 150k², ответ 4,32k.
_ВАРИАНТЫ = ([(1, 2, k) for k in range(2, 23, 2)] * 4
             + [(1, 3, k) for k in range(2, 13)] * 2
             + [(3, 4, 2), (3, 4, 4)])


def _дробь_latex(числитель, знаменатель):
    """\\dfrac{a}{b} и, если сокращается, «= \\dfrac{p}{q}»."""
    f = Fraction(числитель, знаменатель)
    текст = '\\dfrac{%d}{%d}' % (числитель, знаменатель)
    if f.denominator != знаменатель:
        текст += ' = \\dfrac{%d}{%d}' % (f.numerator, f.denominator)
    return текст


