_ЦЕЛЫЕ_11 = [(22, 4), (33, 6), (44, 8), (26, 11), (46, 13), (47, 26)]


def _квадрат(n):
    k = math.isqrt(n)
    return k * k == n


def _пара(rng):
    """(AB, CD): 3/5 — целый радиус, 2/5 — как в банке, √N с a ≡ b (mod 3)."""
    if rng.random() < 0.6:
        a, b = rng.choice(_ЦЕЛЫЕ_11)
    else:
        while True:
            a, b = rng.randint(4, 45), rng.randint(4, 45)
            if a != b and (a - b) % 3 == 0 and not _квадрат((a * a + a * b + b * b) // 3):
                break
    if rng.random() < 0.5:
        a, b = b, a
    return a, b


def _построить_11(a, b, theta):
    """
    Вписанный ABCD по диагоналям: K = (0, 0), AC на оси x, BD под 60° к ней,
    ∠KAB = theta — свободный параметр семейства (половина дуги BC).

    KA и KB — из треугольника AKB по теореме синусов (∠K = 60°, AB = a);
    KC и KD — из подобия △AKB ∼ △DKC (KA·KC = KB·KD, коэффициент CD/AB).
    Окружность здесь не строится: что D лежит на описанной около ABC,
    проверяет вызывающий.
    """
    s60 = math.sin(math.radians(60))
    t = math.radians(theta)
    KA = a * math.sin(math.radians(120) - t) / s60
    KB = a * math.sin(t) / s60
    KC = KB * b / a
    KD = KA * b / a
    A, C = (KA, 0.0), (-KC, 0.0)
    B, D = (KB * 0.5, KB * s60), (-KD * 0.5, -KD * s60)
    return A, B, C, D


def _измерить(a, b, theta):
    """Радиус описанной окружности построенного ABCD — по координатам."""
    A, B, C, D = _построить_11(a, b, theta)
    K = (0.0, 0.0)
    O = центр_описанной(A, B, C)
    R = расстояние(O, A)
