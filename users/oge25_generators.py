# полуокружность, она пересекает высоту AD в точке M; H — ортоцентр.
# Даны AD = h и MD = m — найти AH.
#
# Семейство (oge25_setup/TYPES.md, «Тип 9»): два свободных параметра h и m,
# 0 < m < h; форма треугольника на ответ не влияет. Ответ AH = (h² − m²)/h.
# В банке AD ≤ 90, m/h от 1/9 до 6/7, ответы целые или с одним знаком после
# запятой — пары (h, m) перебираются по этим правилам заранее и делятся на
# два ведра, чтобы целые и десятичные ответы выпадали поровну.


def _кандидаты():
    """Пары (AD, MD) с ответом-целым и с ответом-десятичной дробью (один знак)."""
    целые, десятичные = [], []
    for h in range(8, 91):
        for m in range(1, h):
            if not (h <= 9 * m and 7 * m <= 6 * h):          # 1/9 ≤ m/h ≤ 6/7, как в банке
                continue
            f = Fraction(h * h - m * m, h)
            if f.denominator == 1:
                целые.append((h, m))
            elif 10 % f.denominator == 0:
                десятичные.append((h, m))
    return целые, десятичные


_ЦЕЛЫЕ_9, _ДЕСЯТИЧНЫЕ = _кандидаты()


def _пересечение_с_окружностью(P, Q, O, R):
    """Две точки пересечения прямой PQ с окружностью (O, R), в порядке от P к Q."""
    dx, dy = Q[0] - P[0], Q[1] - P[1]
    fx, fy = P[0] - O[0], P[1] - O[1]
    a = dx * dx + dy * dy
    b = 2.0 * (fx * dx + fy * dy)
    c = fx * fx + fy * fy - R * R
    D = b * b - 4.0 * a * c
    if D < 0:
        raise ValueError('прямая не пересекает окружность')
    s = math.sqrt(D)
    t1, t2 = (-b - s) / (2.0 * a), (-b + s) / (2.0 * a)
    return (P[0] + dx * t1, P[1] + dy * t1), (P[0] + dx * t2, P[1] + dy * t2)


def _построить_9(h, m, t):
    """
    Фигура по данным условия — без формулы ответа.

    D в начале координат, A = (0, h), основание BC на оси x, BD : DC = t².
    Масштаб s основания (B = (−s·t, 0), C = (s/t, 0)) подбирается бисекцией
    так, чтобы верхняя точка пересечения окружности на BC с прямой AD
    отстояла от D ровно на m. Ортоцентр H — пересечение AD с высотой из B.
    Возвращает точки A, B, C, D, O, M, H, N, P (N — основание высоты из B,
    P — второй конец хорды MP).
    """
    h, m, t = float(h), float(m), float(t)
    A, D = (0.0, h), (0.0, 0.0)

    def база(s):
        B, C = (-s * t, 0.0), (s / t, 0.0)
        O = середина(B, C)
        R = расстояние(B, C) / 2.0
        P, M = _пересечение_с_окружностью((0.0, -4.0 * h), A, O, R)   # снизу вверх
        return B, C, O, R, M, P

    lo, hi = 0.0, 4.0 * h                 # MD растёт с масштабом основания
    for _ in range(200):
        mid = 0.5 * (lo + hi)
        if база(mid)[4][1] < m:
            lo = mid
        else:
            hi = mid
    B, C, O, R, M, P = база(0.5 * (lo + hi))

    # Высота из B перпендикулярна AC; N — её основание, H — пересечение с AD.
    B2 = (B[0] - (C[1] - A[1]), B[1] + (C[0] - A[0]))
    N = пересечение(B, B2, A, C)
    H = пересечение(B, B2, A, D)

    # Самопроверка построения по данным условия.
    if abs(расстояние(M, D) - m) > 1e-9 * h:
        raise ValueError('MD не сошлось: %r вместо %r' % (расстояние(M, D), m))
    if M[1] <= 0 or abs(M[0]) > 1e-9 * h:
        raise ValueError('M не на высоте AD со стороны A')
    if not (0.0 < H[1] < M[1] < h):
        raise ValueError('порядок точек A, M, H, D нарушен')
    for угл in (угол(B, A, C), угол(A, B, C), угол(A, C, B)):
        if угл >= 90.0 - 1e-7:
            raise ValueError('треугольник не остроугольный')
    return A, B, C, D, O, M, H, N, P


