# №25, тип 1. Биссектриса BE и медиана AD треугольника ABC перпендикулярны и
# ────────────────────────────────────────────────────────────────────────
#
# равны (BE = AD = L) — найти стороны треугольника.
#
# Семейство (oge25_setup/TYPES.md, «Тип 1»): треугольник определён с точностью
# до подобия, единственный свободный параметр — L. Чтобы коэффициенты при
# радикалах были целыми, как в банке, L = 4k:
#     AB = k√13,  BC = 2k√13,  AC = 3k√5.
# В банке k = 2, 3, 4, 7, 8, 9, 10, 11.


def _построить_1(L):
    """
    Треугольник по данным условия — без формулы ответа.

    Система координат: O = BE ∩ AD в начале, AD на оси x, BE на оси y
    (перпендикулярность). A = (−a, 0), D = (L − a, 0), так что AD = L и O лежит
    на отрезке AD; B = (0, b), b > 0; C = 2D − B (D — середина BC); E —
    пересечение прямой AC с прямой BO. Неизвестные a, b находятся из двух
    оставшихся условий: BE = L и BE — биссектриса угла ABC. Обе решаются
    бисекцией: сначала при данном a подбирается b по длине BE (она растёт
    с b монотонно), затем a — по условию биссектрисы.
    """
    L = float(L)

    def фигура(a, b):
        A = (-a, 0.0)
        D = (L - a, 0.0)
        B = (0.0, b)
        C = (2.0 * D[0] - B[0], 2.0 * D[1] - B[1])
        E = пересечение(A, C, B, (0.0, b - 1.0))
        return A, B, C, D, E

    def b_по_длине(a):
        lo, hi = 0.0, 2.0 * L
        for _ in range(200):
            mid = 0.5 * (lo + hi)
            _, B, _, _, E = фигура(a, mid)
            if расстояние(B, E) < L:
                lo = mid
            else:
                hi = mid
        return 0.5 * (lo + hi)

    def невязка_биссектрисы(a):
        # BE — биссектриса ⇔ сумма единичных векторов BA и BC параллельна BE.
        b = b_по_длине(a)
        A, B, C, _, E = фигура(a, b)
        ux, uy = A[0] - B[0], A[1] - B[1]
        vx, vy = C[0] - B[0], C[1] - B[1]
        nu, nv = math.hypot(ux, uy), math.hypot(vx, vy)
        sx, sy = ux / nu + vx / nv, uy / nu + vy / nv
        ex, ey = E[0] - B[0], E[1] - B[1]
        return sx * ey - sy * ex

    # Корни невязки на (0, L): ищем смены знака по сетке, ожидаем ровно одну.
    n = 400
    сетка = [L * (i + 0.5) / n for i in range(n)]
    значения = [невязка_биссектрисы(a) for a in сетка]
    скобки = [(сетка[i], сетка[i + 1]) for i in range(n - 1)
              if значения[i] == 0.0 or значения[i] * значения[i + 1] < 0]
    if len(скобки) != 1:
        raise ValueError('условие биссектрисы даёт %d решений, ожидалось одно' % len(скобки))
    lo, hi = скобки[0]
    f_lo = невязка_биссектрисы(lo)
    for _ in range(200):
        mid = 0.5 * (lo + hi)
        f_mid = невязка_биссектрисы(mid)
        if f_mid == 0.0:
            lo = hi = mid
            break
        if (f_mid > 0) == (f_lo > 0):
            lo, f_lo = mid, f_mid
        else:
            hi = mid
    a = 0.5 * (lo + hi)
    b = b_по_длине(a)
    A, B, C, D, E = фигура(a, b)
    O = (0.0, 0.0)

    # Самопроверка построения по данным условия.
    if abs(расстояние(A, D) - L) > 1e-9 * L or abs(расстояние(B, E) - L) > 1e-9 * L:
        raise ValueError('длины BE и AD не сошлись')
    if abs(угол(A, O, B) - 90.0) > 1e-9:
        raise ValueError('BE и AD не перпендикулярны')
    if abs(угол(A, B, E) - угол(E, B, C)) > 1e-7:
        raise ValueError('BE не биссектриса')
    # E — на отрезке AC, O — внутри обоих отрезков.
    t = (E[0] - A[0]) / (C[0] - A[0])
    if not (0.0 < t < 1.0) or not (0.0 < a < L) or not (0.0 < b < L):
        raise ValueError('точки вышли за пределы отрезков')
    return A, B, C, D, E, O


