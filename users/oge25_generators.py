# №25, тип 15. Параллелограмм ABCD с диагональю AC; O — центр окружности,
# ────────────────────────────────────────────────────────────────────────
#
# вписанной в треугольник ABC. Даны OA = d, расстояние от O до прямой AD = h
# и до прямой AC = r (последнее — радиус окружности). Найти площадь ABCD.
#
# Семейство (oge25_setup/TYPES.md, «Тип 15»): пифагорова тройка (AK, r, d),
# где AK = √(d² − r²) — отрезок касательной из A; целое h, r < h < d.
# Высота параллелограмма MH = r + h (M, O, H на одной прямой); из
# S(ABC) = r·p = ½·BC·(r + h) при p = AK + BC получается BC = 2r·AK/(h − r)
# и S = BC·(h + r). Оставлены только h, при которых BC — конечная десятичная
# дробь: иначе ответ периодический, чего в банке нет.


# (AK, r, d): катет AK, катет r = радиус, гипотенуза d = OA.
ТРОЙКИ = [(4, 3, 5), (8, 6, 10), (12, 5, 13), (12, 9, 15), (15, 8, 17), (24, 7, 25)]
МАКС_ПЛОЩАДЬ = 3000            # банк: 168…1320


def _конечная_15(дробь):
    зн = дробь.denominator
    for p in (2, 5):
        while зн % p == 0:
            зн //= p
    return зн == 1


def _варианты_15():
    """Все допустимые (AK, r, d, h, BC, S); выбор из них равномерный."""
    out = []
    for AK, r, d in ТРОЙКИ:
        for h in range(r + 1, d):                       # h = d вырожденно, исключено
            BC = Fraction(2 * r * AK, h - r)
            S = BC * (h + r)
            if _конечная_15(BC) and S <= МАКС_ПЛОЩАДЬ:
                out.append((AK, r, d, h, BC, S))
    return out


ВАРИАНТЫ_15 = _варианты_15()


def _построить_15(d, h, r, знак=1):
    """
    Фигура по данным условия — без формулы ответа.

    A = (0, 0), прямая AD — ось x. O = (знак·√(d² − h²), h): OA = d и расстояние
    от O до AD равно h; знак = +1 — H на луче AD (как в банке), −1 — на продолжении
    DA за A. Окружность с центром O и радиусом r. AB и AC — касательные из A к ней
    (угол между AO и касательной: sin = r/d), BC — касательная, параллельная AD
    и лежащая по другую сторону от O (y = h + r). B и C — пересечения касательных
    с ней, B левее; D = A + (C − B).
    """
    d, h, r = float(d), float(h), float(r)
    A = (0.0, 0.0)
    O = (знак * math.sqrt(d * d - h * h), h)
    половина = math.asin(r / d)
    направление = math.atan2(O[1], O[0])
    y = h + r
    точки = []
    for θ in (направление - половина, направление + половина):
        s = math.sin(θ)
        if s <= 1e-12:
            raise ValueError('касательная из A не пересекает прямую BC')
        t = y / s
        точки.append((t * math.cos(θ), y))
    B, C = sorted(точки)
    D = (C[0] - B[0], 0.0)
    return A, B, C, D, O


def _проверить_построение(A, B, C, D, O, d, h, r):
    м = max(d, 1.0)
    if abs(расстояние(A, O) - d) > 1e-9 * м:
        raise ValueError('OA не сошлось')
    if abs(расстояние_до_прямой(O, A, D) - h) > 1e-9 * м:
        raise ValueError('расстояние до AD не сошлось')
    for P, Q, имя in ((A, C, 'AC'), (A, B, 'AB'), (B, C, 'BC')):
        if abs(расстояние_до_прямой(O, P, Q) - r) > 1e-9 * м:
            raise ValueError('расстояние до %s не равно радиусу' % имя)
    I = центр_вписанной(A, B, C)
    if расстояние(I, O) > 1e-9 * м:
        raise ValueError('O — не центр вписанной окружности треугольника ABC')
    if not C[0] > B[0]:
        raise ValueError('параллелограмм вырожден')


