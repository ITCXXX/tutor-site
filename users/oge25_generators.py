# №25, тип 14. Трапеция ABCD с основаниями AD = a и BC = b (a > b), сумма углов
# ────────────────────────────────────────────────────────────────────────
#
# при основании AD равна 90°, боковая сторона AB = c. Найти радиус окружности,
# проходящей через A и B и касающейся прямой CD.
#
# Ключ (oge25_setup/TYPES.md, «Тип 14»): продолжения боковых сторон
# пересекаются в точке P, и ∠APD = 180° − (∠A + ∠D) = 90°. Из подобия
# △BPC ~ △APD: PB = x = bc/(a − b). Центр O лежит на серединном перпендикуляре
# к AB; четырёхугольник PEOH (E — точка касания с прямой CD, H — середина AB)
# имеет три прямых угла, то есть прямоугольник, поэтому
#     R = OE = PH = PB + AB/2 = c(a + b)/(2(a − b)).
# Вписанной окружности у трапеции нет — карточки приписывают её ошибочно.
#
# Семейство: три свободные величины c = AB, k = a − b, b = BC; a = b + k.
# Ограничения: k > c (иначе трапеции нет: cos A = c/k), в банке k/c ∈ [1,1; 2];
# x = bc/k — конечная десятичная не длиннее одного знака (10·b·c кратно k),
# тогда и R = x + c/2 имеет не более одного знака после запятой, как в банке
# (14,4; 13,5; 24,5; 19,5). Диапазоны банка: a 18..49, b 2..24, c 7..24.
# Все 10 троек банка входят в перебор.


