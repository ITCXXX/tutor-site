# №25, тип 3. Трапеция: биссектриса угла при большем основании проходит через
# ────────────────────────────────────────────────────────────────────────
#
# середину боковой стороны — найти площадь.
#
# Трапеция ABCD, боковые AB = a и CD = c, основание BC = b. Биссектриса угла
# ADC проходит через середину M стороны AB. Прямая DM пересекает прямую BC в
# точке P (на продолжении CB за точку B); △PBM = △DAM по стороне и двум
# прилежащим углам, откуда BP = AD; из параллельности PC ∥ AD и биссектрисы
# △PCD равнобедренный, PC = CD, значит AD = CD − BC. Через C параллельно AB
# проводится CE (E на AD): ABCE — параллелограмм, CE = AB, ED = CD − 2·BC.
# В банке всегда AB² + ED² = CD², поэтому ∠CED = 90°, высота трапеции равна
# AB и S = AB·CD/2.
#
# Семейство: BC = k·u², AD = k·v², AB = 2kuv, CD = k(u² + v²), u < v взаимно
# простые; S = k²·uv·(u² + v²) — целое. Границы как в банке: CD ≤ 41, S ≤ 1000.


