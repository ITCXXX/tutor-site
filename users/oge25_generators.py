def _трапеция_14(a, b, c):
    """
    Трапеция по данным условия — без формул типа.

    A = (0, 0), D = (a, 0). При угле A = α второй угол при основании равен
    90° − α; лучи из A и D пересекаются в точке P, а B и C — точки этих лучей
    на той высоте, где ширина треугольника APD равна b. Длина AB при этом
    непрерывно убывает по α (от a − b при α → 0 до 0 при α → 90°), поэтому
    α подбирается бисекцией по условию AB = c.
    """
    a, b, c = float(a), float(b), float(c)
    A = (0.0, 0.0)
    D = (a, 0.0)

    def построить(alpha):
        ca, sa = math.cos(alpha), math.sin(alpha)
        P = пересечение(A, (ca, sa), D, (D[0] - sa, ca))   # луч из D под углом 90° − α к DA
        h = P[1] * (1.0 - b / a)                            # сечение треугольника APD ширины b
        B = пересечение(A, P, (0.0, h), (1.0, h))
        C = пересечение(D, P, (0.0, h), (1.0, h))
        return B, C, P

    lo, hi = math.radians(0.01), math.radians(89.99)
    if not (расстояние(A, построить(lo)[0]) > c > расстояние(A, построить(hi)[0])):
        raise ValueError('AB = %g недостижимо при AD = %g, BC = %g' % (c, a, b))
    for _ in range(200):
        mid = 0.5 * (lo + hi)
        if расстояние(A, построить(mid)[0]) > c:
            lo = mid
        else:
            hi = mid
    B, C, P = построить(0.5 * (lo + hi))

    # Самопроверка построения по данным условия.
    if abs(расстояние(A, B) - c) > 1e-9 * c:
        raise ValueError('AB не сошлось')
    if abs(расстояние(B, C) - b) > 1e-9 * b:
        raise ValueError('BC не сошлось')
    if abs(угол(B, A, D) + угол(A, D, C) - 90.0) > 1e-7:
        raise ValueError('сумма углов при AD не 90°')
    return A, B, C, D, P


def _окружности(A, B, C, D):
    """
    Окружности через A и B, касающиеся прямой CD, — по координатам.

    Центр O = M + t·n (M — середина AB, n — единичная нормаль к AB) должен
    быть равноудалён от A и от прямой CD: (s0 + s1·t)² = (AB/2)² + t², где
    s0 — ориентированное расстояние от M до CD, s1 = n·m (m — единичная
    нормаль к CD). Квадратное уравнение на t; возвращаются пары (R, O)
    для всех корней.
    """
    M = середина(A, B)
    c = расстояние(A, B)
    n = ((B[1] - A[1]) / c, -(B[0] - A[0]) / c)
    dCD = расстояние(C, D)
    m = ((D[1] - C[1]) / dCD, -(D[0] - C[0]) / dCD)
    s0 = (M[0] - C[0]) * m[0] + (M[1] - C[1]) * m[1]
    s1 = n[0] * m[0] + n[1] * m[1]
    qa = s1 * s1 - 1.0
    qb = 2.0 * s0 * s1
    qc = s0 * s0 - c * c / 4.0
    if abs(qa) < 1e-12:
        корни = [-qc / qb] if abs(qb) > 1e-12 else []
    else:
        disc = qb * qb - 4.0 * qa * qc
        if disc < -1e-9:
            raise ValueError('нет окружности через A, B, касающейся CD')
        disc = math.sqrt(max(disc, 0.0))
        корни = [(-qb + disc) / (2.0 * qa), (-qb - disc) / (2.0 * qa)]
    результат = []
    for t in корни:
        O = (M[0] + t * n[0], M[1] + t * n[1])
        R = расстояние(O, A)
        if abs(расстояние_до_прямой(O, C, D) - R) > 1e-7 * max(1.0, R):
            raise ValueError('окружность не касается прямой CD')
        результат.append((R, O))
    return результат


def _внутренний_центр(окружности, A, B, D):
    """Центр по ту же сторону от AB, что и D (точка касания на луче PD)."""
    def сторона(X):
        return (B[0] - A[0]) * (X[1] - A[1]) - (B[1] - A[1]) * (X[0] - A[0])
    sD = сторона(D)
    for R, O in окружности:
        if сторона(O) * sD > 0:
            return R, O
    return окружности[0]


def _масштаб(ч, точки):
    """Пикселей на мировую единицу — Чертёж вписывает кадр в холст так же."""
    xs = [p[0] for p in точки]
    ys = [p[1] for p in точки]
    ширина = (max(xs) - min(xs)) or 1.0
    высота = (max(ys) - min(ys)) or 1.0
    return min((ч.width - 2 * ч.поле) / ширина, (ч.height - 2 * ч.поле) / высота)


def _сторона_E(E, подписи, k, кандидаты=('в', 'св', 'юв', 'с'), зазор=16.0):
    """
    Куда отодвинуть букву E — точку касания.

    E лежит на прямой CD и в части задач подходит вплотную к C или к D
    (в банке так в 1C7299 и E4D760, а при c²(a + b) = b(a − b)² точка касания
    попадает ровно в C) — при одной и той же стороне буквы сливаются.
    Обычное положение — «в», снаружи от трапеции; если там буква оказывается
    ближе зазора к чужой подписи, берём сторону с наибольшим просветом.
    """
    def якорь(точка, сторона):
        dx, dy = СТОРОНЫ[сторона]
        return (точка[0] * k + dx, -точка[1] * k + dy)

    чужие = [якорь(точка, сторона) for точка, _, сторона in подписи]

    def просвет(сторона):
        x, y = якорь(E, сторона)
        return min(math.hypot(x - u, y - v) for u, v in чужие)

    if просвет(кандидаты[0]) >= зазор:
        return кандидаты[0]
    return max(кандидаты, key=просвет)


