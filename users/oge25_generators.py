def _разложить_пары():
    """Пары (AD, BC) в диапазоне банка (AD до 20), разложенные по виду ответа."""
    банк, простые, целые = [], [], []
    for a in range(4, 21):
        for b in range(2, a):
            if a > 4 * b:
                continue                       # в банке AD/BC ≤ 2; клин 10:1 на чертеже
            k, m = упростить_корень(a * b)
