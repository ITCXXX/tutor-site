def _угол_A(m, n):
    """
    Угол A (в радианах), при котором биссектриса угла A делит высоту BH как
    m:n, считая от B. Подбирается бисекцией по построению: при AB = 1 и
    произвольном угле α строятся H (проекция B на AC), биссектриса и её точка
    F на BH, измеряется BF/FH. С ростом α от 0 до 90° это отношение растёт
    от 1 до бесконечности, а m/n > 1 — корень один.
    """
    цель = m / n

    def отношение(alpha):
        A = (0.0, 0.0)
        B = (math.cos(alpha), math.sin(alpha))
        C = (1.0, 0.0)                                  # луч AC — ось x
        H = проекция(A, C, B)
        F = пересечение(A, точка_биссектрисы(A, B, C, 1.0), B, H)
        return расстояние(B, F) / расстояние(F, H)

    lo, hi = 1e-6, math.pi / 2 - 1e-6
    if not (отношение(lo) < цель < отношение(hi)):
        raise ValueError('отношение %s:%s недостижимо' % (m, n))
    for _ in range(200):
        mid = 0.5 * (lo + hi)
        if отношение(mid) < цель:
            lo = mid
        else:
            hi = mid
    return 0.5 * (lo + hi)


def _построить_13(m, n, a, доля_AC, AB=None):
    """
    Треугольник по данным условия: биссектриса делит высоту BH как m:n от B,
    BC = a. Условие не задаёт треугольник однозначно — AC свободно, поэтому
    C ставится на луче AC в точке AC = доля_AC·AH (доля > 1 — H внутри AC,
    доля < 1 — C между A и H, угол C тупой). Строится при AB = 1, затем всё
    масштабируется так, чтобы BC = a (или, если задан AB, к этому AB — для
    чертежа). Возвращает A, B, C, H, F, E, где E — конец биссектрисы на BC.
    """
    alpha = _угол_A(m, n)
    A = (0.0, 0.0)
    B = (math.cos(alpha), math.sin(alpha))
    H = (math.cos(alpha), 0.0)
    C = (доля_AC * H[0], 0.0)
    s = (a / расстояние(B, C)) if AB is None else AB
    B = (B[0] * s, B[1] * s)
    H = (H[0] * s, H[1] * s)
    C = (C[0] * s, C[1] * s)
    L = точка_биссектрисы(A, B, C, 1.0)
    F = пересечение(A, L, B, H)
    E = пересечение(A, L, B, C)
    # Самопроверка построения по данным условия.
    BH = расстояние(B, H)
    if not (0 < расстояние(B, F) < BH and abs(расстояние(B, F) + расстояние(F, H) - BH) < 1e-9 * BH):
        raise ValueError('точка F не на отрезке BH')
    if abs(расстояние(B, F) / расстояние(F, H) - m / n) > 1e-9 * (m / n):
        raise ValueError('биссектриса делит высоту не как %s:%s' % (m, n))
    if AB is None and abs(расстояние(B, C) - a) > 1e-9 * a:
        raise ValueError('BC не равно %s' % a)
    return A, B, C, H, F, E


