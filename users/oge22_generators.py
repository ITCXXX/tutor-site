# ────────────────────────────────────────────────────────────────────────
# Тип 16. y = (a|x| − 1)/(|x| − a·x²) = −1/|x| с двумя выколотыми точками;
# ────────────────────────────────────────────────────────────────────────
#
# прямая y = kx без общих точек.
#
# Вся задача держится на одном тождестве: x² = |x|², поэтому знаменатель
# |x| − a·x² = |x|·(1 − a|x|), а числитель a|x| − 1 = −(1 − a|x|). Дробь
# сокращается до −1/|x| всюду, кроме нулей общего множителя, то есть кроме
# двух симметричных точек x = ±1/a; их ординаты одинаковы и равны −a.
#
# График целиком в нижней полуплоскости, поэтому прямая y = kx при k > 0
# встречает только ЛЕВУЮ ветвь, а при k < 0 — только ПРАВУЮ, и всегда ровно
# в одной точке. Значит общих точек нет ровно в трёх случаях: k = 0 (ось Ox —
# горизонтальная асимптота) и два «убийства» единственной точки выколотой:
# k = a² (через левую дырку) и k = −a² (через правую).
#
# В банке a = n/2, n = 2…9. Полуцелое a печатается не десятичной дробью
# (num_latex такого не умеет), а домножением условия на знаменатель: вместо
# (2,5|x| − 1)/(|x| − 2,5x²) выводится (5|x| − 2)/(2|x| − 5x²). Это та же самая
# функция, тот же ответ и та же связка коэффициентов; при целом a запись
# совпадает с банковской буква в букву.


def _узлы(дырка_x):
    """
    Пять абсцисс для таблицы значений правой ветви.

    Классический набор для гиперболы — 1/4, 1/2, 1, 2, 4, но при a = 4; 2; 1
    одно из этих чисел совпадает с 1/a, то есть с только что выколотой точкой.
    Ставить её в таблицу «строим по точкам» нельзя, поэтому такое число
    выбрасывается, а вместо него берётся следующее по красоте.
    """
    пул = [Fraction(1, 4), Fraction(1, 2), Fraction(1), Fraction(2),
           Fraction(4), Fraction(1, 3), Fraction(3)]
    return sorted([x for x in пул if x != дырка_x][:5])


def _таблица_16(xs):
    """Табличка значений y = −1/|x| для ветви: строка x, строка y."""
    ячейка = 'border:1px solid #999;padding:0.35em 0.8em;text-align:center'
    шапка = ячейка + ';background:#eef'
    строки = []
    for имя, значения in (('x', xs), ('y', [-Fraction(1, abs(x)) for x in xs])):
        клетки = ''.join('<td style="%s">\\(%s\\)</td>' % (ячейка, num_latex(v))
                         for v in значения)
        строки.append('<tr><td style="%s">\\(%s\\)</td>%s</tr>' % (шапка, имя, клетки))
    return ('<table style="border-collapse:collapse;margin:0.5em auto;'
            'font-size:0.95em">%s</table>' % ''.join(строки))


