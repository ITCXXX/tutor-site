# ────────────────────────────────────────────────────────────────────────
# Тип 12. y = x|x| + a|x| − bx, прямая y = m, ровно две общие точки.
# ────────────────────────────────────────────────────────────────────────
#
# Модуль раскрывается по знаку x, и график склеивается из двух половинок парабол:
#     x ≥ 0:  y = x² − p·x,   p = b − a   (ветви вверх, вершина (p/2; −p²/4)),
#     x < 0:  y = −x² − q·x,  q = a + b   (ветви вниз,  вершина (−q/2;  q²/4)).
# Обе формулы в нуле дают 0, так что функция непрерывна на всей оси; в O(0;0)
# только излом. Ровно две общие точки с горизонтальной прямой бывают лишь тогда,
# когда прямая проходит через вершину одной половинки (касание — одна точка) и
# режет вторую половинку (ещё одна): m = −p²/4 или m = q²/4.


@тип(12)
def _тип_12(rng):
    # a ≠ 0 — иначе слагаемое a|x| исчезает из записи условия и тип теряется.
    # b > |a| равносильно «p > 0 и q > 0 одновременно»: только тогда у обеих
    # половинок вершина попадает внутрь своего куска и ответ состоит из двух
    # чисел разных знаков, как во всех десяти задачах банка. При b ≤ −|a|
    # функция строго возрастает и «ровно двух» точек нет вовсе.
    while True:
        a = rng.choice([-3, -2, -1, 1, 2, 3])
        b = rng.randint(2, 6)
        p, q = b - a, a + b
        # Верхние границы на p и q держат ответ в банковских пределах |m| ≤ 16.
        if b > abs(a) and p <= 7 and q <= 8:
            break

    # Вершины половинок — они же единственные «двухточечные» высоты.
    x_прав, y_прав = Fraction(p, 2), -Fraction(p * p, 4)
    x_лев, y_лев = -Fraction(q, 2), Fraction(q * q, 4)

    прав = lambda x: x * x - p * x
    лев = lambda x: -x * x - q * x

    # Окно по y: обе вершины с запасом в три единицы.
    ymin = -((p * p + 3) // 4) - 3            # floor(−p²/4) − 3
    ymax = (q * q + 3) // 4 + 3               # ceil(q²/4) + 3
    # Окно по x берём не «на глаз», а из тех же прямых: на высоте ymax правая
    # ветвь пересекается при x = (p + √(p² + 4·ymax))/2, на высоте ymin левая —
    # при x = (−q − √(q² − 4·ymin))/2. Внутри окна видны все пересечения,
    # которые вообще возможны при m из окна.
    xmax = int(math.ceil((p + math.sqrt(p * p + 4 * ymax)) / 2)) + 1
    xmin = int(math.floor((-q - math.sqrt(q * q - 4 * ymin)) / 2)) - 1

    модуль = '\\left|x\\right|'
    формула = 'x%s %s %s - %s' % (модуль, '+' if a > 0 else '-',
                                  коэф(abs(a), модуль), коэф(b, 'x'))
    # p и q положительны, поэтому знак минус перед ними можно писать руками.
    прав_ф = 'x^2 - %s' % коэф(p, 'x')
    лев_ф = '-x^2 - %s' % коэф(q, 'x')

    разбор = (
        '<p>Раскроем модуль по знаку \\(x\\).</p>'
        '<p>При \\(x \\ge 0\\) имеем \\(%s = x\\), и функция превращается в квадратный '
        'трёхчлен:</p>\\[y = x\\cdot x %s\\cdot x - %d\\cdot x = %s.\\]'
        % (модуль, со_знаком(a), b, прав_ф)
        + '<p>При \\(x < 0\\) имеем \\(%s = -x\\), и получается другой трёхчлен:</p>'
          '\\[y = x\\cdot(-x) %s\\cdot(-x) - %d\\cdot x = %s.\\]'
          % (модуль, со_знаком(a), b, лев_ф)
        + '<p>Итак,</p>\\[y = \\begin{cases} %s, & x \\ge 0, \\\\ %s, & x < 0.'
          ' \\end{cases}\\]' % (прав_ф, лев_ф)
        + '<p>Обе строки при \\(x = 0\\) дают \\(y = 0\\), поэтому разрыва нет: половинки '
          'сходятся в одной точке \\(O(0;\\ 0)\\), только с изломом. Выколотых точек у '
          'графика тоже нет.</p>'
        + '<p>Правая половинка — часть параболы ветвями вверх с вершиной '
          '\\(\\left(%s;\\ %s\\right)\\); ось \\(Ox\\) она пересекает при \\(x = 0\\) и '
          '\\(x = %d\\). Вершина — самая низкая её точка.</p>'
          % (num_latex(x_прав), num_latex(y_прав), p)
        + '<p>Левая половинка — часть параболы ветвями вниз с вершиной '
          '\\(\\left(%s;\\ %s\\right)\\) и нулём \\(x = -%d\\); точка \\(x = 0\\) в этот '
          'кусок не входит, она уже посчитана справа. Вершина — самая высокая её '
          'точка.</p>' % (num_latex(x_лев), num_latex(y_лев), q)
        + '<p>Прямая \\(y = m\\) горизонтальна, поэтому общие точки считаются по '
          'высоте:</p><ul>'
        + '<li>\\(m < %s\\) — прямая проходит ниже вершины правой половинки, поэтому '
          'встречает только левую ветвь, уходящую вниз: одна точка;</li>'
          % num_latex(y_прав)
        + '<li>\\(m = %s\\) — прямая касается правой половинки в вершине (одна точка) и '
          'пересекает левую (ещё одна): <b>ровно две</b>;</li>' % num_latex(y_прав)
        + '<li>\\(%s < m < %s\\) — прямая идёт выше вершины правой половинки и ниже '
          'вершины левой, поэтому одну из половинок она пересекает дважды, а другую '
          'один раз (при \\(m \\le 0\\) дважды правую, при \\(m > 0\\) — левую): всего '
          'три (например, при \\(m = 0\\) это \\(x = -%d,\\ x = 0,\\ x = %d\\));</li>'
          % (num_latex(y_прав), num_latex(y_лев), q, p)
        + '<li>\\(m = %s\\) — прямая касается левой половинки в вершине и пересекает '
          'правую: <b>ровно две</b>;</li>' % num_latex(y_лев)
        + '<li>\\(m > %s\\) — выше вершины левой половинки остаётся только правая '
          'ветвь: одна точка.</li></ul>' % num_latex(y_лев)
        + '<p>Значит, ровно две общие точки дают лишь две высоты — ординаты вершин.</p>')

    return {
        'formula_latex': формула,
        # Ноль отдан правому куску (x ≥ 0), левый берётся строго при x < 0:
        # иначе точка O(0;0) считалась бы дважды и при m = 0 выходило бы
        # четыре пересечения вместо трёх.
        'pieces': [(лев, -INF, 0, False, False),
                   (прав, 0, INF, True, False)],
        'holes': [],                       # функция определена и непрерывна всюду
        'dots': [(x_лев, y_лев), (x_прав, y_прав)],
        'window': (xmin, xmax, ymin, ymax),
        'ask': ('hline', 2),
        'answer_set': [(y_прав, True, y_прав, True), (y_лев, True, y_лев, True)],
        'answer_kind': 'roots',
        'solution_steps': разбор,
        'params': {'a': a, 'b': b, 'p': p, 'q': q},
    }


