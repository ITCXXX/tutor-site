# Для наборов вида «одна или две» готовой фразы в словаре нет: числительное
# в такой формулировке стоит без слова «ровно» и согласуется с «точки».
СКОЛЬКО_НАБОРОМ = {1: 'одну', 2: 'две', 3: 'три', 4: 'четыре'}


def сколько_точек(сколько):
    if isinstance(сколько, (tuple, list)):
        части = [СКОЛЬКО_НАБОРОМ[n] for n in сколько]
        слово = 'точку' if list(сколько) == [1] else 'точки'
        return 'имеет с графиком %s общие %s' % (' или '.join(части), слово)
    return СКОЛЬКО[сколько]


def question_html(task):
    вид, сколько = task['ask']
    буква, прямая = ('m', 'y = m') if вид == 'hline' else ('k', 'y = kx')
    return ('<p>Постройте график функции</p>'
            '\\[y = %s\\]'
            '<p>и определите, при каких значениях %s прямая %s %s.</p>'
            % (task['formula_latex'], буква, прямая, сколько_точек(сколько)))


def _картинка(task):
    """График функции плюс прямые, отвечающие граничным значениям ответа."""
    xmin, xmax, ymin, ymax = task['window']
    вид, _ = task['ask']

    границы = []
    for низ, _, верх, _ in task['answer_set']:
        for v in (низ, верх):
            if v not in (INF, -INF) and v not in границы:
                границы.append(v)
    границы = sorted(границы)[:3]      # больше трёх пунктиров рябит в глазах

    hlines, rays = [], []
    for v in границы:
        подпись = '%s = %s' % ('y' if вид == 'hline' else 'k', num22(v))
        if вид == 'hline':
            hlines.append((float(v), подпись))
        else:
            rays.append((float(v), подпись))

    куски = [(f, float(x0), float(x1)) for f, x0, x1, _, _ in task['pieces']]
    куски = [(f, max(x0, xmin), min(x1, xmax)) for f, x0, x1 in куски
             if max(x0, xmin) < min(x1, xmax)]
    return graph_svg(куски, xmin=xmin, xmax=xmax, ymin=ymin, ymax=ymax,
                     holes=[(float(x), float(y)) for x, y in task['holes']],
                     dots=[(float(x), float(y)) for x, y in task.get('dots', ())],
                     hlines=hlines, rays=rays)


def solution_html(task):
    вид, _ = task['ask']
    буква = 'm' if вид == 'hline' else 'k'
    return ('<p><b>Решение.</b></p>'
            + task['solution_steps']
            + '<div class="graph">%s</div>' % _картинка(task)
            + '<p><b>Ответ:</b> \\(%s \\in %s\\).</p>'
              % (буква, answer_latex(task['answer_set'], task['answer_kind'])))


def generate(номер, seed=None):
    """Собрать задачу типа. seed фиксирует случайность — для тестов и сверок."""
    if номер not in GENERATORS:
        raise KeyError('нет генератора типа %s' % номер)
    rng = random.Random(seed)
    task = GENERATORS[номер](rng)
    task['type'] = номер
    task['question_html'] = question_html(task)
    task['answer'] = answer_text(task['answer_set'], task['answer_kind'])
    task['solution_html'] = solution_html(task)
    return task


def as_task(номер, seed=None):
    """Мост к платформе: users/generators/g<id>.py вызывает это."""
    task = generate(номер, seed)
    kind = task['answer_kind']
    return {
        'condition_text': task['question_html'],
        'correct_answer': task['answer'],
        'answer_kind': kind,
        'multi_answer': kind == 'roots' and ';' in task['answer'],
        # Ответы-дроби у типа 6 (k = a²/b²) в десятичную не разворачиваются,
        # поэтому запрет обыкновенных дробей для них снимаем — как в №20.
        'allow_fractions': '/' in task['answer'],
        'solution_html': task['solution_html'],
        'oge22_type': номер,
    }


