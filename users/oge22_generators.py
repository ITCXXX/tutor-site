# -*- coding: utf-8 -*-
"""
Генераторы задания №22 ОГЭ — «Графики функций».

Типология собрана из банка Школково (229 задач, 17 типов ФИПИ и четыре
тематических раздела) и лежит в oge22_setup/TYPES.md. Там же — разбор каждого
типа: общий вид функции, параметрическое семейство, пошаговый алгоритм ответа
и подводные камни. Здесь только код.

Устройство задачи
-----------------
Задача №22 всегда одна и та же по форме: дана функция, надо построить её
график и сказать, при каких значениях параметра прямая имеет с графиком ровно
столько-то общих точек. Прямая бывает двух видов — горизонтальная y = m и
проходящая через начало координат y = kx.

Поэтому генератор типа возвращает не текст, а **саму функцию** — списком
кусков с настоящими областями определения. Из этого потом получается всё
остальное: картинка (users/plot_svg.py), разбор и, главное, независимая
проверка (oge22_setup/verify_oge22.py). Проверяльщик не смотрит в формулу
ответа: он берёт куски, численно считает число пересечений при каждом
значении параметра и сверяет с объявленным множеством. Так ошибка в алгебре
генератора не может проскочить незамеченной.

Контракт функции типа
---------------------
    def _тип_N(rng) -> dict

    {
      'formula_latex': строка для условия, без «y = »;
      'pieces':  [(f, x0, x1, закрыт_слева, закрыт_справа), ...] — настоящая
                 область определения, а не окно рисунка;
      'holes':   [(x, y), ...] выколотые точки;
      'window':  (xmin, xmax, ymin, ymax) — окно рисунка. В него обязаны
                 попадать содержательная часть графика и все границы ответа
                 (границы проверяет verify_oge22.py). Требовать, чтобы за
                 краями окна пересечений вообще не было, нельзя: у гиперболы
                 пересечение с прямой чуть выше асимптоты уходит за любой
                 конечный край — это обычное чтение рисунка;
      'ask':     ('hline', n) для «прямая y = m, ровно n общих точек»
                 или ('ray', n) для «прямая y = kx»; n = 0 значит «не имеет».
                 Вместо числа можно дать набор: ('hline', (1, 2)) — «одна или
                 две общие точки», именно так спрашивает банк в типе 5;
      'answer_set': [(низ, закрыт, верх, закрыт), ...] — ответ как множество;
                 одиночное число задаётся как (v, True, v, True);
      'answer_kind': 'number' | 'roots' | 'interval';
      'solution_steps': HTML разбора без картинки (её добавит as_task);
      'params':  что угодно для отладки и сообщений проверяльщика.
    }
"""

