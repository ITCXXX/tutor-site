def num_latex(v):
    """
    Число в формулах №22 — десятичной дробью, как в банке («y = 2,5x - 3,5»).

    Это не косметика. Разбор кончается строкой «Ответ: m ∈ ...», и ученик её
    списывает. Если там стоит \frac{7}{4}, а поле ответа в ОГЭ-курсе
    обыкновенные дроби не принимает, списавший верное число получает
    «неверно» — худший из возможных исходов. Поэтому везде, где дробь
    конечная, печатаем десятичную запись; непериодические (49/36 у типа 6)
    остаются обыкновенными, для них и запрет дробей снимается.

    Имя намеренно то же, что у помощника из №20: черновики типов импортируют
    num_latex отсюда, и подмена чинит их все разом.
    """
    f = Fraction(v).limit_denominator(10 ** 6)
    текст = num22(f)
    if '/' in текст:
        return _num_latex_дробью(f)
    # В математической записи русская десятичная запятая — {,}: иначе TeX
    # ставит после запятой пробел, как между аргументами.
    return текст.replace(',', '{,}')


def num22(v):
    """
    Число в ответ. Десятичная запись, если дробь конечная, иначе обыкновенная.

    На ОГЭ ответ пишут десятичной дробью, и «-1,5» ученику ближе, чем «-3/2».
    Но у типа 6 ответы вида 49/36 в десятичную не разворачиваются вовсе,
    поэтому запасной вариант обязателен. Проверка принимает обе записи —
    users/answer_check.py сравнивает значения, а не строки.
    """
    f = Fraction(v).limit_denominator(10 ** 6)
    if f.denominator == 1:
        return str(f.numerator)
    зн = f.denominator
    while зн % 2 == 0:
        зн //= 2
    while зн % 5 == 0:
        зн //= 5
    if зн != 1:
        return '%d/%d' % (f.numerator, f.denominator)
    текст = str(float(f))
    if текст.endswith('.0'):
        текст = текст[:-2]
    return текст.replace('.', ',')


def answer_text(множество, kind):
    """Множество (список четвёрок) → строка ответа в записи, понятной проверке."""
    if kind in ('number', 'roots'):
        числа = [низ for низ, _, верх, _ in множество if низ == верх]
        if len(числа) != len(множество):
            raise ValueError('kind=%s, но в множестве есть промежутки' % kind)
        return '; '.join(num22(v) for v in sorted(числа))

    куски = []
    for низ, зл, верх, зп in множество:
        if низ == верх:
            куски.append('{%s}' % num22(низ))
        else:
            куски.append('%s%s; %s%s' % (
                '[' if зл else '(', '-∞' if низ == -INF else num22(низ),
                '+∞' if верх == INF else num22(верх), ']' if зп else ')'))
    return ' + '.join(куски)


def answer_latex(множество, kind):
    if kind in ('number', 'roots'):
        return ';\\ '.join(num_latex(Fraction(низ))
                           for низ, _, верх, _ in sorted(множество) if низ == верх)
    куски = []
    for низ, зл, верх, зп in множество:
        if низ == верх:
            куски.append('\\{%s\\}' % num_latex(Fraction(низ)))
        else:
            куски.append('%s%s;\\ %s%s' % (
                '\\left[' if зл else '\\left(',
                '-\\infty' if низ == -INF else num_latex(Fraction(низ)),
                '+\\infty' if верх == INF else num_latex(Fraction(верх)),
                '\\right]' if зп else '\\right)'))
    return ' \\cup '.join(куски)


def в_множестве(значение, множество):
    """Принадлежит ли число объявленному ответу."""
    for низ, зл, верх, зп in множество:
        if низ == верх:
            if значение == низ:
                return True
            continue
        левее = значение > низ or (зл and значение == низ)
        правее = значение < верх or (зп and значение == верх)
        if левее and правее:
            return True
    return False


