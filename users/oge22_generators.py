def коэф(a, буква='x'):
    """Коэффициент при переменной: 1 и −1 печатаются без единицы."""
    a = Fraction(a)
    if a == 1:
        return буква
    if a == -1:
        return '-' + буква
    return '%s%s' % (num_latex(a), буква)


def со_знаком(v):
    """Слагаемое со своим знаком: '+ 3' или '- 3'."""
    v = Fraction(v)
    return ('+ %s' if v >= 0 else '- %s') % num_latex(abs(v))


def линейный(a, b, буква='x'):
    """ax + b в LaTeX, с опусканием единиц и нулей."""
    if a == 0:
        return num_latex(Fraction(b))
    if b == 0:
        return коэф(a, буква)
    return '%s %s' % (коэф(a, буква), со_знаком(b))


