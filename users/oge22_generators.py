        '<li>\\(%s < m < %s\\) — прямая режет обе половины, причём одну из них '
        'дважды (при \\(m \\le 0\\) правую, при \\(m > 0\\) левую): всего 3. '
        'Отдельно проверим \\(m = 0\\): точек и здесь три — \\(x = %d\\), '
        '\\(x = 0\\) и \\(x = %d\\), — так что ноль в ответ не идёт;</li>'
        '<li>\\(m = %s\\) — прямая касается левой параболы в вершине, справа ещё одна '
