# Тип 1. Кусочно-линейный «зуб»: три куска, прямая y = m, ровно две точки
# ──────────────────────────────────────────────────────────────────────────
#
# Левый луч x < p, средний отрезок p ≤ x ≤ q (убывающий), правый луч x > q.
# Ответ определяется только четырьмя ординатами:
#   A — предел левого луча в p (точка выколота),
#   B — значение среднего куска в p (закрашена),
#   C — значение среднего куска в q (закрашена),
#   D — начало правого луча в q (выколота).
# Число общих точек с y = m: n(m) = [m < A] + [C ≤ m ≤ B] + [m > D].

КОНФИГУРАЦИИ = ('К1', 'К2', 'К3', 'К4', 'К5')


@тип(1)
def _тип_1(rng):
    полушаги = lambda a, b: [Fraction(k, 2) for k in range(2 * a, 2 * b + 1)]

    for _ in range(400):
        p = rng.randint(-3, 3)
        q = p + rng.choice([1, 1, 1, 1, 2, 3])
        if q > 5:
            continue
        a2 = rng.choice([Fraction(-1), Fraction(-3, 2), Fraction(-2),
                         Fraction(-5, 2), Fraction(-3), Fraction(-7, 2)])
        B = Fraction(rng.choice(полушаги(-2, 4)))
        C = B + a2 * (q - p)
        if C < -5:
            continue
        зазор = lambda: Fraction(rng.choice(полушаги(1, 3)))          # 0,5…3,5
        конфиг = rng.choice(КОНФИГУРАЦИИ)
        if конфиг == 'К1':                       # разрыв в q, дырка ниже
            A, D = B, C - зазор()
        elif конфиг == 'К2':                     # разрыв в q, дырка выше
            if B - C < Fraction(3, 2):
                continue
            D = C + Fraction(rng.choice(полушаги(1, 2)))
            if not (C < D < B):
                continue
            A = B
        elif конфиг == 'К3':                     # разрыв в p, дырка ниже
            D = C
            A = B - зазор()
            if not (C < A < B):
                continue
        elif конфиг == 'К4':                     # разрыв в p, дырка выше
            D = C
            A = B + зазор()
        else:                                    # К5 — непрерывная
            A, D = B, C
        if not (-5 <= min(A, B, C, D) and max(A, B, C, D) <= 4):
            continue

        a1 = Fraction(rng.choice(полушаги(1, 4)))
        a3 = Fraction(rng.choice(полушаги(1, 4)))
        b1, b2, b3 = A - a1 * p, B - a2 * p, D - a3 * q
        break
    else:                                        # pragma: no cover
        raise RuntimeError('тип 1: не удалось подобрать параметры')

    # Ответ — по конфигурации; см. таблицу в oge22_setup/TYPES.md.
    if конфиг == 'К1':
        множество = [(D, False, C, False), (B, True, B, True)]
    elif конфиг == 'К2':
        множество = [(C, True, D, True), (B, True, B, True)]
    elif конфиг == 'К3':
        множество = [(C, True, C, True), (A, True, B, True)]
    elif конфиг == 'К4':
        множество = [(C, True, C, True), (B, False, A, False)]
    else:
        множество = [(C, True, C, True), (B, True, B, True)]
    множество.sort()

    ф = lambda a, b: (lambda x: float(a) * x + float(b))
    низ = float(min(A, B, C, D)) - 3
    верх = float(max(A, B, C, D)) + 3

    формула = ('\\begin{cases} %s, & x < %d, \\\\ %s, & %d \\le x \\le %d, \\\\ '
               '%s, & x > %d \\end{cases}'
               % (линейный(a1, b1), p, линейный(a2, b2), p, q, линейный(a3, b3), q))

    разбор = (
        '<p>График состоит из трёх кусков. Важны только ординаты в точках стыка:</p>'
        '<p>левый луч подходит к \\(x = %d\\) на высоте \\(A = %s\\) (точка выколота), '
        'средний отрезок начинается в \\(B = %s\\) и убывает до \\(C = %s\\) '
        '(обе точки закрашены), правый луч выходит из \\(D = %s\\) (выколота).</p>'
        '<p>Каждый кусок монотонен, поэтому прямая \\(y = m\\) пересекает левый луч '
        'при \\(m < A\\), средний отрезок при \\(C \\le m \\le B\\) и правый луч '
        'при \\(m > D\\). Складывая, получаем число общих точек при каждом \\(m\\) '
        'и оставляем те \\(m\\), где их ровно две.</p>'
        % (p, num_latex(A), num_latex(B), num_latex(C), num_latex(D)))

    return {
        'formula_latex': формула,
        'pieces': [(ф(a1, b1), -INF, p, False, False),
                   (ф(a2, b2), p, q, True, True),
                   (ф(a3, b3), q, INF, False, False)],
        # Разрыв ровно один: в К1/К2 A = B (слева непрерывно, дырка в q),
        # в К3/К4 D = C (дырка в p), в К5 разрывов нет вовсе. Ставить дырку
        # там, где куски стыкуются, — значит выколоть закрашенную точку.
        'holes': ([(p, A)] if A != B else []) + ([(q, D)] if D != C else []),
        'dots': [(p, B), (q, C)],
        'window': (p - 5, q + 5, низ, верх),
        'ask': ('hline', 2),
        'answer_set': множество,
        'answer_kind': 'interval',
        'solution_steps': разбор,
        'params': {'конфигурация': конфиг, 'p': p, 'q': q,
                   'A': str(A), 'B': str(B), 'C': str(C), 'D': str(D)},
    }


