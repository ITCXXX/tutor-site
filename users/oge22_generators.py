# ────────────────────────────────────────────────────────────────────────
# Тип 17. y = ½(|x/a − b/x| + x/a + b/x) = max(x/a, b/x), прямая y = m,
# ────────────────────────────────────────────────────────────────────────
#
# ровно одна общая точка.
#
# Тождество ½(u + v + |u − v|) = max(u; v) сворачивает всю запись в максимум двух
# знакомых функций. Дальше решается неравенство x/a ≥ b/x, и график распадается
# на четыре монотонных куска: гипербола — прямая — гипербола — прямая. Стыки
# ±x₀ = ±√(ab), там обе формулы дают одну и ту же точку (±x₀; ±y₀), y₀ = √(b/a).
#
# Множество значений с провалом: E(y) = [−y₀; 0) ∪ [y₀; +∞). Ноль не достигается
# (x = 0 выколот), промежуток (0; y₀) пуст вовсе. Поэтому «ровно одна точка»
# бывает только на краях провала: m = ±y₀ — и ответ равен {−y₀; y₀}.
#
# Почему b ≠ a. В банке всегда b = a, и тогда y₀ = 1 при любом a: все девять
# задач имеют один и тот же ответ {−1; 1}, а варьирование a не меняет ничего.
# Разводим константы: b = a·k², тогда x₀ = ak, y₀ = k, и ответ {−k; k} наконец
# зависит от параметров. Случай k = 1 (то есть b = a) оставлен в списке — это
# дословно банковская задача.


# Пары (k, список масштабов a). k — это и есть ответ: m ∈ {−k; k}.
#
# Отбор a внутри каждой строки подчинён трём условиям.
#   1. b = a·k² обязано записываться «школьным» числом: целым или с одним
#      знаком после запятой. Иначе условие задачи выглядит как опечатка.
#   2. x₀ = ak не должно уезжать далеко: окно рисунка строится от него, а
#      проверяльщик ищет корни лишь при |x| ≤ 60. При m порядка k + 3 линейный
#      кусок пересекается в точке a(k + 3), и она обязана попасть в этот
#      горизонт — отсюда потолок на a.
#   3. a ≠ 1: иначе линейное слагаемое печатается как \dfrac{x}{1}, а в разборе
#      появляются «x²/(1·x)» и «x₀/1 = y₀». Ни одна из этих записей в школьном
#      условии не встречается. Наименьшее a — 1,5, как и в банке.
#
# Строка k = 1 — банковский набор a из TYPES.md (ровно девять значений, пятёрки
# среди них нет), b = a. Остальные строки банк не покрывает, но по построению
# это те же задачи с другой парой констант.
СЕМЕЙСТВА = (
    (Fraction(1, 2), (4, 6, 8, 10, 12)),
    (Fraction(1),    (Fraction(3, 2), 2, Fraction(5, 2), 3, Fraction(7, 2),
                      4, Fraction(9, 2), Fraction(11, 2), 6)),
    (Fraction(3, 2), (2, 4, 6)),
    (Fraction(2),    (Fraction(3, 2), 2, Fraction(5, 2), 3)),
    (Fraction(5, 2), (2,)),
    (Fraction(3),    (Fraction(3, 2), 2)),
)


@тип(17)
def _тип_17(rng):
    k, масштабы = СЕМЕЙСТВА[rng.randrange(len(СЕМЕЙСТВА))]
    a = Fraction(rng.choice(масштабы))
    b = a * k * k

    x0 = a * k                      # стык кусков, он же √(ab)
    y0 = k                          # ордината стыка, она же √(b/a) — и ответ

    прямая = lambda x: x / float(a)
    гипербола = lambda x: float(b) / x

    дес = lambda v: num22(v).replace(',', '{,}')      # 12,5 → 12{,}5 для формул
    A, B, X0, Y0 = дес(a), дес(b), дес(x0), дес(y0)
    # Квадрат десятичной дроби без скобок читается как «4,5 в квадрате от
    # пятёрки»: 4{,}5^2. Скобки ставим ровно там, где x₀ не целое.
    X0КВ = ('%s^2' if x0.denominator == 1 else '\\left(%s\\right)^2') % X0

    дробь = '\\dfrac{x}{%s}' % A
