# ────────────────────────────────────────────────────────────────────────
# Тип 7. y = a − (x − c)/(K·x² − K·c·x) — гипербола с выколотой точкой,
# ────────────────────────────────────────────────────────────────────────
#
# прямая y = m без общих точек.
#
# После сокращения дроби остаётся y = a − 1/(Kx): гипербола с центром (0; a),
# горизонтальной асимптотой y = a и вертикальной x = 0. Из графика выброшена
# ровно одна точка — P(c; a − 1/(Kc)); x = 0 это асимптота, а не дырка.
#
# Функция инъективна (ветви лежат по разные стороны от асимптоты и каждая
# монотонна), поэтому прямая y = m промахивается мимо графика ровно в двух
# случаях: m = a (ординаты, равной a, у гиперболы нет вовсе) и m = a − 1/(Kc)
# (единственный прообраз этой ординаты как раз выколот).


# Множитель при знаменателе: y = a − 1/(Kx).
#
# В банке K = 1, но с ним тип не проходит численную проверку, и дело не в
# придирке к оформлению. Проверяльщик щупает ответ в точках «граница ± 0,01», а
# прямая y = a ± 0,01 пересекает гиперболу y = a − 1/x при x = ∓100 — дальше
# горизонта поиска корней (ОКНО = 60 в verify_oge22.py). Он честно насчитывает
# там ноль пересечений и справедливо ругается: на его окне точек и правда нет.
# K = 2 сжимает гиперболу вдвое по горизонтали, та же точка уезжает лишь на
# x = ∓50 и попадает в зону видимости. Математика типа не меняется: ответ
# по-прежнему ровно два числа, a и a − 1/(Kc).
K = 2

# Абсцисса выколотой точки. c = ±3 дало бы ответ обыкновенной дробью (a ∓ 1/6),
# а c = ±4 — тремя знаками после запятой (a ∓ 0,125); в банке ни того, ни
# другого нет. Остаются ±1 и ±2: ответы вида a ∓ 0,5 и a ∓ 0,25.
#
# c = ±5 отброшено по картинке. Из-за K = 2 зазор между двумя прямыми ответа
# равен 1/(2|c|), при |c| = 5 это 0,1. Подписи «y = a» и «y = a − 0,1» рисуются
# шрифтом 11 px со сдвигом 5 px над своей прямой, а вертикаль окна — 288 px:
# чтобы подписи не налезали, нужно не меньше ~16 px между прямыми, то есть
# высота окна ≤ 18·зазор. При зазоре 0,1 это ≤ 1,8 — окно с нецелым шагом
# сетки (plot_svg берёт шаг только из 1, 2, 5, 10…), гипербола в нём вырождается
# в почти горизонтальную черту. При зазоре 0,25 хватает высоты 4, при 0,5 — 6.
ЦЕНТРЫ = (-2, -1, 1, 2)


@тип(7)
def _тип_7(rng):
    a = rng.choice([-5, -4, -3, -2, -1, 1, 2, 3, 4, 5])
    c = rng.choice(ЦЕНТРЫ)

    y0 = a - Fraction(1, K * c)          # ордината выколотой точки

    числитель = линейный(1, -c)                       # x − c
    # Знаменатель печатаем раскрытым, как в банке: Kx² − Kcx. Коэффициент при x
    # по модулю не меньше двух, так что «1x» тут не вылезет.
    знам = '%s %sx' % (коэф(K, 'x^2'), со_знаком(-K * c))

    # Для рисунка и для проверяльщика нужна обычная функция от float.
    ветвь = lambda x: float(a) - 1.0 / (K * x)

    дес = lambda v: num22(v).replace(',', '{,}')      # 5,1 → 5{,}1 для формул
    ла = num_latex(Fraction(a))
    кx = коэф(K)                                      # «2x» в знаменателе дроби
    # Ординату выколотой точки печатаем в два шага: сначала подстановка x = c
    # в y = a − 1/(Kx), потом та же дробь с положительным знаменателем — иначе
    # в разборе висело бы 1/(−4).
    подстановка = '%s - \\dfrac{1}{%d \\cdot %s}' % (
        ла, K, ('(%d)' % c) if c < 0 else str(c))
    ордината = '%s %s \\dfrac{1}{%d}' % (ла, '-' if K * c > 0 else '+', abs(K * c))
    сдвиг = ('поднятая на %s' % ла) if a > 0 else ('опущенная на %s' % num_latex(-a))

    разбор = (
        '<p>Знаменатель раскладывается на множители: \\(%(знам)s = '
        '%(кx)s\\,(%(чис)s)\\). Значит \\(x \\ne 0\\) и \\(x \\ne %(c)d\\), '
        'а при остальных \\(x\\) дробь сокращается:</p>'
        '\\[y = %(a)s - \\frac{%(чис)s}{%(кx)s\\,(%(чис)s)} '
        '= %(a)s - \\frac{1}{%(кx)s}.\\]'
        '<p>Это гипербола \\(y = -\\dfrac{1}{%(кx)s}\\), %(сдвиг)s: '
        'горизонтальная асимптота \\(y = %(a)s\\), вертикальная \\(x = 0\\). '
        'Около \\(x = 0\\) график уходит в бесконечность — это асимптота, '
        'а не выколотая точка. А вот \\(x = %(c)d\\) выброшено из области '
        'определения, поэтому на графике выколота ровно одна точка — с '
        'абсциссой \\(%(c)d\\) и ординатой</p>'
        '\\[y_0 = %(подст)s = %(орд)s = %(y0)s.\\]'
        '<p>Обе ветви строго монотонны и лежат по разные стороны от асимптоты: '
        'при \\(x &lt; 0\\) выходит \\(y &gt; %(a)s\\), при \\(x &gt; 0\\) — '
        '\\(y &lt; %(a)s\\). Поэтому у целой гиперболы, ещё без выколотой '
        'точки, каждое значение, кроме \\(y = %(a)s\\), достигается ровно '
        'один раз: уравнение \\(%(a)s - \\dfrac{1}{%(кx)s} = m\\) даёт '
        'единственный \\(x = \\dfrac{1}{%(K)d\\left(%(a)s - m\\right)}\\).</p>'
        '<p>Значит общих точек нет ровно в двух случаях:</p>'
        '<ul>'
        '<li>\\(m = %(a)s\\) — прямая совпала с горизонтальной асимптотой, '
        'уравнение \\(\\dfrac{1}{%(кx)s} = 0\\) корней не имеет;</li>'
        # В паре координат ординату берём в фигурные скобки: иначе после «\ »
        # её минус читается как знак вычитания и MathJax раздвигает запись до
        # «(−2;  − 2,75)».
        '<li>\\(m = %(y0)s\\) — единственная точка гиперболы с такой '
        'ординатой это как раз \\((%(c)d;\\ {%(y0)s})\\), а она выколота.</li>'
        '</ul>'
        '<p>При всех прочих \\(m\\) общая точка ровно одна.</p>'
        % {'знам': знам, 'кx': кx, 'чис': числитель, 'c': c, 'a': ла,
           'сдвиг': сдвиг, 'подст': подстановка, 'орд': ордината,
           'y0': дес(y0), 'K': K})

    множество = sorted([(Fraction(a), True, Fraction(a), True),
                        (y0, True, y0, True)])

    # Симметричное окно по x: выколотая точка с запасом 2, но не уже шести.
    предел = max(6, abs(c) + 2)
    # По y окно подбираем под зазор между двумя прямыми ответа, он равен
    # 1/(2|c|). Подписи не налезают, если высота окна не больше 18 зазоров:
    # при c = ±1 (зазор 0,5) это 6, при c = ±2 (зазор 0,25) — 4. Целая
    # полувысота держит сетку на единицах.
    полувысота = 3 if abs(c) == 1 else 2

    return {
        'formula_latex': '%s - \\dfrac{%s}{%s}' % (ла, числитель, знам),
        # Область определения — две ветви гиперболы; выколотая точка живёт
        # отдельным списком, как в типе 6. Ноль — асимптота, а не дырка:
        # кружок там обещал бы ученику третье число в ответе.
        'pieces': [(ветвь, -INF, Fraction(0), False, False),
                   (ветвь, Fraction(0), INF, False, False)],
        'holes': [(Fraction(c), y0)],
        # По x окно охватывает выколотую точку с запасом 2, по y — асимптоту
        # y = a и обе прямые ответа: они отстоят от a не больше чем на 0,5.
        'window': (-предел, предел, a - полувысота, a + полувысота),
        'ask': ('hline', 0),
        'answer_set': множество,
        'answer_kind': 'roots',
        'solution_steps': разбор,
        'params': {'a': a, 'c': c, 'K': K, 'y0': str(y0)},
    }


# ────────────────────────────────────────────────────────────────────────
# Тип 8. Парабола ветвями вниз с выколотой точкой; прямая y = kx, ровно одна точка.
# ────────────────────────────────────────────────────────────────────────
#
#     y = (x² + c)(x − p) / (p − x) ≡ −(x² + c) при x ≠ p.
#
# Разбор типа — в oge22_setup/TYPES.md, здесь только код.


# (|p|, t), где c = (t/2)² — так 2√c = t выходит целым и в ответе нет корней.
#
# Что отсеяно и почему:
#   * t = 2 при |p| = 1 — это c = p², запрещённая пара: одна из касательных
#     проходит через выколотую точку, и ответ схлопывается с трёх чисел
#     до одного (ловушка №2 справочника);
#   * t = 5 при |p| = 1 (c = 6,25) — задача законная и в банке есть (#7, #9),
#     но «дырочная» прямая встречает параболу второй раз в точке
#     (c/p; −(c²/p² + c)) = (±6,25; −45,3125). Выкинуть эту точку из окна
#     нельзя (без неё рисунок врёт: видно только, как прямая проходит через
#     дырку, а обещанной общей точки на картинке нет), а с ней нижний край
#     уезжает до −48. В окне высотой 51 вершина (0; −6,25) и выколотая точка
#     (±1; −7,25) расходятся по высоте на 1 — то есть на шесть пикселей:
#     дырка, сердце задачи, перестаёт читаться. Проверено рисованием;
#     парабола при этом как раз нормальная, дело только в дырке;
#   * t = 6 при |p| = 2 (c = 9) — здесь, наоборот, картинка выходит хорошая
#     (вторая точка всего лишь (±4,5; −29,25), дырка (±2; −13) видна). Пара
#     отброшена по другой причине: c = 9 в банке не встречается вовсе, там
#     t ≤ 5. Захочется расширить семейство — начинать надо с неё.
# Оставшиеся четыре пары со знаком p дают восемь разных ответов, и все восемь
# дословно совпадают с задачами банка (#1–#6, #8, #10).
СЕМЕЙСТВО_8 = ((1, 1), (1, 3), (1, 4), (2, 2))


def дес_8(v):
    """
    Число десятичной дробью для формулы: 0{,}25, а не \\frac{1}{4}.

    В условии банка c всегда записано десятичной дробью, и решение
    воспроизводит эту запись для координат. Фигурные скобки вокруг запятой
    убирают лишний пробел, который MathJax ставит после разделителя списка.
    """
    return num22(v).replace(',', '{,}')


@тип(8)
def _тип_8(rng):
    модуль_p, t = rng.choice(СЕМЕЙСТВО_8)
    p = модуль_p * rng.choice([1, -1])
    c = Fraction(t, 2) ** 2                      # c > 0 и √c = t/2 рационален
    корень = Fraction(t, 2)                      # √c

    # Ключевые точки графика и ответа.
    y_дырки = -(Fraction(p) ** 2 + c)            # ордината выколотой точки H
    k0 = y_дырки / p                             # прямая, проходящая через H
    x2 = c / p                                   # второй корень при k = k0
    y2 = -(x2 ** 2 + c)

    # Страховка на случай правки таблицы: при c = p² второй корень совпал бы
    # с выколотым, а одна из касательных потеряла бы точку — ответ стал бы
    # другим, а формула ниже осталась бы прежней.
    if c == Fraction(p) ** 2:                    # pragma: no cover
        raise RuntimeError('тип 8: пара c = p² запрещена')

    ответ = sorted([-Fraction(t), Fraction(t), k0])

    # Окно. Обязано вмещать вершину, дырку, обе точки касания (±√c; −2c) и
    # вторую точку пересечения (x2; y2) — иначе картинка не объясняет ответ.
    # Ветви параболы уходят вниз; там, где они выходят за нижний край, они
    # уже не могут дать новых пересечений: все корни лежат внутри окна.
    x_ключ = [Fraction(p), корень, -корень, x2]
    y_ключ = [-c, -2 * c, y_дырки, y2]
    xmax = max(4, math.ceil(max(abs(x) for x in x_ключ)) + 2)
    ymin = min(-6, math.floor(min(y_ключ)) - 2)

    парабола = lambda x, c=float(c): -(x * x + c)

    скобка = линейный(1, -p)                     # (x − p) со свёрнутым знаком
    pл = num_latex(Fraction(p))
    # Отрицательное p в записи «... : p» и «p²» берём в скобки.
    pск = ('\\left(%s\\right)' if p < 0 else '%s') % pл
    p_в_кв = pск + '^{2}'
    формула = ('\\dfrac{\\left(x^{2} + %s\\right)\\left(%s\\right)}{%s - x}'
               % (дес_8(c), скобка, pл))

    # Деление на x_H = ±1 отдельной дробью не пишут: при p = 1 наклон равен
    # самой ординате дырки, при p = −1 — ей же с обратным знаком.
    if p == 1:
        цепочка = 'y_H = %s' % num_latex(k0)
    elif p == -1:
        цепочка = '-y_H = %s' % num_latex(k0)
    else:
        цепочка = '\\frac{%s}{%s} = %s' % (дес_8(y_дырки), pл, num_latex(k0))

    разбор = (
        '<p>Знаменатель — это вторая скобка числителя, взятая с противоположным '
        'знаком: \\(%(pл)s - x = -\\left(%(скобка)s\\right)\\). Поэтому при '
        '\\(x \\ne %(pл)s\\) дробь сокращается:</p>'
        '\\[y = \\frac{\\left(x^{2} + %(c)s\\right)\\left(%(скобка)s\\right)}'
        '{-\\left(%(скобка)s\\right)} = -x^{2} - %(c)s.\\]'
        '<p>Это парабола ветвями вниз с вершиной \\(\\left(0;\\ %(верш)s\\right)\\). '
        'В точке \\(x = %(pл)s\\) знаменатель обращается в ноль, поэтому она '
        'выброшена из области определения: из параболы выколота точка '
        '\\(H\\left(%(pл)s;\\ %(yH)s\\right)\\), ведь '
        '\\(-%(pкв)s - %(c)s = %(yH)s\\).</p>'
        '<p>Прямая \\(y = kx\\) встречается с параболой там, где '
        '\\(-x^{2} - %(c)s = kx\\), то есть</p>'
        '\\[x^{2} + kx + %(c)s = 0,\\qquad D = k^{2} - 4\\cdot %(c)s = k^{2} - %(4c)d.\\]'
        '<p>Каждый корень этого уравнения даёт общую точку — кроме \\(x = %(pл)s\\): '
        'он выколот. Переберём все возможности.</p>'
        '<p>1) \\(|k| &lt; %(t)d\\). Тогда \\(D &lt; 0\\), корней нет — и общих '
        'точек нет.</p>'
        '<p>2) \\(|k| = %(t)d\\). Тогда \\(D = 0\\) и корень один: '
        '\\(x = -\\dfrac{k}{2}\\). При \\(k = %(t)d\\) это точка '
        '\\(\\left(%(xк1)s;\\ %(yк)s\\right)\\), при \\(k = -%(t)d\\) — точка '
        '\\(\\left(%(xк2)s;\\ %(yк)s\\right)\\): прямая касается параболы. '
        'Выколотая точка имеет абсциссу \\(%(pл)s\\), с точками касания она не '
        'совпадает, так что оба значения \\(k = \\pm %(t)d\\) подходят.</p>'
        '<p>3) \\(|k| &gt; %(t)d\\). Тогда \\(D &gt; 0\\), корней два, и общих '
        'точек было бы две. Ровно одна останется, только если один из корней '
        'выколот, то есть прямая проходит через \\(H\\):</p>'
        '\\[k_0 = \\frac{y_H}{x_H} = %(цепочка)s.\\]'
        '<p>По теореме Виета произведение корней равно \\(%(c)s\\), а один из них — '
        'тот самый выколотый \\(x = %(pл)s\\), поэтому второй корень равен '
        '\\(%(c)s : %(pск)s = %(x2)s\\). Он не совпадает с выколотым — '
        'значит, корни и правда различны, а единственной общей точкой остаётся '
        'точка с абсциссой \\(%(x2)s\\).</p>'
        '<p>Других возможностей нет: подходят ровно три значения \\(k\\).</p>'
        % {'pл': pл, 'скобка': скобка, 'c': дес_8(c), 'верш': дес_8(-c),
           'yH': дес_8(y_дырки), 'pкв': p_в_кв, 'pск': pск, 't': t, '4c': t * t,
           'xк1': дес_8(-корень), 'xк2': дес_8(корень), 'yк': дес_8(-2 * c),
           'цепочка': цепочка, 'x2': дес_8(x2)})

    return {
        'formula_latex': формула,
        # Область определения — вся прямая без точки p; оба конца открыты.
        'pieces': [(парабола, -INF, Fraction(p), False, False),
                   (парабола, Fraction(p), INF, False, False)],
        'holes': [(Fraction(p), y_дырки)],
        'window': (-xmax, xmax, ymin, 3),
        'ask': ('ray', 1),
        'answer_set': [(v, True, v, True) for v in ответ],
        'answer_kind': 'roots',
        'solution_steps': разбор,
        'params': {'p': p, 'c': str(c), 't': t, 'k0': str(k0),
                   'вторая точка': '(%s; %s)' % (x2, y2)},
    }


# ────────────────────────────────────────────────────────────────────────
# Тип 9. Парабола с модулем («W»), прямая y = m, ровно три общие точки.
# ────────────────────────────────────────────────────────────────────────
#
# y = (x − r)(x − t) − q·|x − r|, где t = r + d, d > 0, q > d.
#
# Весь фокус в том, что r — корень квадратичной части, поэтому множитель
# (x − r) выносится при любом раскрытии модуля и обе ветви получаются сразу
# разложенными:
#
#     x ≥ r:  y = (x − r)(x − t − q)   нули r и t + q, вершина ниже на ((q+d)/2)²
#     x < r:  y = (x − r)(x − t + q)   нули r и t − q, вершина ниже на ((q−d)/2)²
#
# Условие q > d нужно ровно для того, чтобы левый нуль t − q оказался левее
# точки стыка: тогда вершина левой ветви попадает на свой луч и появляется
# «уголок» вверх в (r; 0) — форма W. При q ≤ d вершина съезжает за границу
# куска, буква W не собирается и ровно трёх общих точек не бывает ни при каком m.
#
# Число общих точек с y = m (y_гл = −((q+d)/2)² < y_мел = −((q−d)/2)² < 0):
#     m < y_гл      0
#     m = y_гл      1
#     y_гл < m < y_мел  2
#     m = y_мел     3   ← касание мелкой ямы + две точки на глубокой ветви
#     y_мел < m < 0 4
#     m = 0         3   ← сам угол (r; 0) и по одному нулю на каждой ветви
#     m > 0         2
# Отсюда ответ: два числа, {−((q−d)/2)²; 0}. Глубокая яма — штатный дистрактор:
# на её уровне точка одна, а не три.


def дес_9(v):
    """
    Число десятичной дробью для формулы: -2{,}25, а не -\\frac{9}{4}.

    Ординаты ям и абсциссы вершин здесь — четвертушки и половинки. В ответ
    их пишут десятичной дробью (и подпись прямой на картинке рисуется именно
    так), поэтому и в разборе они должны стоять в том же виде. «{,}» держит
    запятую разделителем целой части, а не знаком препинания.
    """
    return num22(v).replace(',', '{,}')


def скоб(c):
    """Множитель (x − c); при c = 0 скобки вокруг одинокого x только мешают."""
    return 'x' if c == 0 else '\\left(%s\\right)' % линейный(1, -c)


def произв(c1, c2):
    """Произведение (x − c₁)(x − c₂); одинокий множитель x пишем первым."""
    return скоб(c2) + скоб(c1) if c2 == 0 else скоб(c1) + скоб(c2)


# Пары (q, d) из банка. Неравенств два: q > d (существование уголка) и
# q + d ≤ 6 (читаемость — глубокая яма не проваливается ниже −9). Пара (5, 2)
# формально проходит по первому, но даёт яму −12,25 и в банке не встречается.
# Повторы задают частоты: в банке d = 1 в восьми задачах из десяти.
ПАРЫ_9 = [(2, 1), (2, 1), (3, 1), (3, 1), (4, 1), (4, 1), (5, 1), (5, 1),
        (3, 2), (4, 2)]

