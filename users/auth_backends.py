# -*- coding: utf-8 -*-
"""Вход, когда логины могут повторяться.

ЗАЧЕМ. Логины ученикам заводит преподаватель, и удобно давать простые: «полина»,
«ваня». Пока логин был уникальным, второй Полине приходилось выдумывать
«полина2» — и потом вспоминать, кто из них кто. Теперь логин может повторяться.

КАК ЭТО РАБОТАЕТ. Django по умолчанию берёт логин и достаёт ОДНОГО пользователя
(get_by_natural_key). При повторах это падает с MultipleObjectsReturned прямо на
странице входа. Поэтому здесь свой ход: берём ВСЕХ с таким логином и оставляем
тех, чей пароль подошёл.

  • подошёл ровно одному  → пускаем его;
  • подошёл нескольким    → НЕ ПУСКАЕМ НИКОГО;
  • не подошёл никому     → обычный отказ.

Средний случай — главный, и он намеренно строгий. Если у двоих совпали и логин,
и пароль, различить их нечем, а ошибка тут стоит дорого: чужие оценки, чужая
переписка, чужие работы. Отказ с внятным текстом лучше, чем пустить наугад. Пару
«логин + пароль» проверяют на неповторимость ещё при создании ученика
(users/views.py, teacher_student_new), так что до этого случая доходить не должно
— но защита нужна и здесь: пароль можно сменить и позже.

РЕГИСТР. Вторая попытка идёт без учёта регистра: телефонная клавиатура делает
первую букву заглавной, и «Полина» не совпадала с «полина». Сравниваем в Python,
а не через __iexact: SQLite приводит регистр только у латиницы, и локально
кириллический логин вёл бы себя не так, как на боевом PostgreSQL.
"""

from django.contrib.auth import get_user_model
from django.contrib.auth.backends import ModelBackend


class ПовторяющиесяЛогины(ModelBackend):
    """Пускает по паре «логин + пароль», а не по одному логину."""

    def authenticate(self, request, username=None, password=None, **kwargs):
        User = get_user_model()
        if username is None:
            username = kwargs.get(User.USERNAME_FIELD)
        if not username or password is None:
            return None

        # Логин обрезаем: с телефона он приходит с пробелом на конце — клавиатура
        # добавляет его вслед за подсказкой. Пароль НЕ трогаем: пробелы в нём
        # могут быть значащими.
        username = username.strip()

        подходят = self._кому_подходит(User, username, password)

        if not подходят:
            # Точного совпадения нет — пробуем без учёта регистра.
            свёрнутый = username.casefold()
            кандидаты = [u for u in User.objects.all()
                         if u.username.casefold() == свёрнутый]
            подходят = [u for u in кандидаты if u.check_password(password)]

        if not подходят:
            # Ни одного совпадения. Считаем хеш вхолостую, чтобы ответ занимал
            # столько же времени, сколько при существующем логине: иначе по
            # задержке можно перебором узнать, какие логины на сайте есть.
            User().set_password(password)
            return None

        if len(подходят) > 1:
            # Совпали и логин, и пароль у нескольких. Молчаливо выбрать первого
            # нельзя: это пустить человека в чужой кабинет.
            return None

        пользователь = подходят[0]
        if not self.user_can_authenticate(пользователь):
            return None
        return пользователь

    @staticmethod
    def _кому_подходит(User, username, password):
        return [u for u in User.objects.filter(username=username)
                if u.check_password(password)]


def сколько_подходит(username, password):
    """Скольким людям подходит эта пара. Нужно, чтобы отличить «не туда» от
    «вас двое».

    Страница входа спрашивает это только после неудачи, чтобы показать разный
    текст: обычная опечатка и «у вас с кем-то совпали логин и пароль» — разные
    беды, и лечатся они по-разному.
    """
    User = get_user_model()
    точные = ПовторяющиесяЛогины._кому_подходит(User, (username or '').strip(), password or '')
    if точные:
        return len(точные)
    свёрнутый = (username or '').strip().casefold()
    return len([u for u in User.objects.all()
                if u.username.casefold() == свёрнутый and u.check_password(password or '')])
