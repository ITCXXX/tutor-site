def _p(text):
    return '<p>%s</p>' % text


def _disp(latex):
    return '\\[%s\\]' % latex


def _sol(*blocks):
    return ''.join(blocks)


def _task(num_type, title, question, value, blocks, params, unit=''):
    return {
        'type': num_type,
        'title': '№21. Тип %d' % num_type,
        'question_html': _p(question),
        'answer': answer_text(value),
        'answer_kind': 'number',
        'unit': unit,
        'solution_html': _sol(*blocks),
        'params': params,
    }


# --------------------------------------------------------------------------
# Семейство «разница скоростей и разница времени»: типы 1, 2, 3, 16, 17
# --------------------------------------------------------------------------
#
# Пять типов банка описывают одно и то же уравнение в разных декорациях:
# велосипедист туда-обратно, два участника пробега, рабочие у станка, трубы.
#
#     S/v - S/(v + d) = t   ⟹   S = t·v(v + d)/d
#
# Разворачиваем от ответа: берём искомую скорость v, разницу d и разницу
# времени t — и получаем дистанцию S. Условие годности одно: S целое.

def _speed_gap_numbers(rng, v_range, d_choices, t_choices):
    """Подобрать (v, d, t, S) так, чтобы S вышло целым."""
    for _ in range(200):
        v = rng.randint(*v_range)
        d = rng.choice(d_choices)
        t = rng.choice(t_choices)
        S = Fraction(t) * v * (v + d) / d
        if S.denominator == 1 and 20 <= S <= 1200:
            return v, d, t, int(S)
    return 14, 2, 2, 224          # запасной набор — как в банке ФИПИ


def get_type1(rng):
    """Велосипедист туда и обратно: обратно быстрее, но с остановкой."""
    v, d, t, S = _speed_gap_numbers(rng, (10, 25), [1, 2, 3, 4], [1, 2, 3])

    question = (
        'Велосипедист выехал с постоянной скоростью из города A в город B, '
        'расстояние между которыми равно %s. На следующий день он отправился '
        'обратно в A, увеличив скорость на %s. По пути он сделал остановку '
        'на %s, в результате чего затратил на обратный путь столько же '
        'времени, сколько на путь из A в B. Найдите скорость велосипедиста '
        'на пути из A в B. Ответ дайте в км/ч.'
        % (км(S), кмч(d), с_ед(t, ЧАС))
    )
    blocks = [
        _p('<b>Решение.</b>'),
        _p('Пусть \\(v\\) — скорость на пути из A в B. Обратный путь занял '
           'столько же времени вместе с остановкой:'),
        _disp('\\dfrac{%d}{v} = \\dfrac{%d}{v + %d} + %d.' % (S, S, d, t)),
        _p('Приведём к общему знаменателю и упростим:'),
        _disp('%d(v + %d) - %dv = %dv(v + %d),\\qquad %dv^2 + %dv - %d = 0.'
              % (S, d, S, t, d, t, t * d, S * d)),
        _p('Подходит только положительный корень:'),
        _disp('v = %d.' % v),
        _p('<b>Ответ:</b> %d км/ч.' % v),
    ]
    return _task(1, 'Велосипедист туда и обратно', question, v, blocks,
                 {'v': v, 'd': d, 't': t, 'S': S}, unit='км/ч')


