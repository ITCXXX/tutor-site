"""
Параметрические генераторы задач ОГЭ, №21 (текстовые задачи второй части).

Контракт тот же, что у №20 (users/oge20_generators.py):

    get_typeN(rng) -> {
        'type', 'title', 'question_html', 'answer', 'answer_kind',
        'solution_html', 'params'
    }

Чем №21 отличается от №20
-------------------------
Ответ везде одно число, и машинерия проверки для него давно готова. Зато
условие — русский текст, а не формула, и появляется работа, которой в №20
не было: согласование числительных. «На 3 часа быстрее», но «на 5 часов
быстрее»; «21 километр», но «22 километра». Генератор, который этого не
делает, выдаёт условие, которое стыдно показать ученику.

Как устроены сами задачи
------------------------
Как и в №20 — от ответа назад. Сначала выбирается ответ и часть параметров,
оставшийся вычисляется из уравнения задачи. Перебирать «пока не получится
красиво» не приходится, а условие годности у каждого типа одно: чтобы
вычисленный параметр оказался целым.

Самопроверка (из корня проекта):
    venv\\Scripts\\python.exe oge21_setup\\verify_oge21.py
"""

import random
from fractions import Fraction


# --------------------------------------------------------------------------
# Русский язык: числительные и единицы
# --------------------------------------------------------------------------

def plural(n, forms):
    """
    Согласовать существительное с числом.

    forms = ('час', 'часа', 'часов') — для 1, для 2-4, для остальных.
    Работает и с дробными: «1,5 часа» — как и положено, форма родительного
    единственного.
    """
    if isinstance(n, float) and n != int(n):
        return forms[1]
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return forms[0]
    if n % 10 in (2, 3, 4) and n % 100 not in (12, 13, 14):
        return forms[1]
    return forms[2]


ЧАС = ('час', 'часа', 'часов')
МИНУТА = ('минута', 'минуты', 'минут')
МИНУТУ = ('минуту', 'минуты', 'минут')
КИЛОМЕТР = ('километр', 'километра', 'километров')
ДЕТАЛЬ = ('деталь', 'детали', 'деталей')
ЛИТР = ('литр', 'литра', 'литров')
КИЛОГРАММ = ('килограмм', 'килограмма', 'килограммов')
СЕКУНДА = ('секунду', 'секунды', 'секунд')


def с_ед(n, forms):
    """«3 часа» — число и согласованная форма."""
    return '%s %s' % (num(n), plural(n, forms))


def род(n, forms):
    """
    Родительный падеж после предлога: «из 21 детали», «из 22 деталей».

    Отличается от именительного только на числах, оканчивающихся на 1:
    там единственное число, но родительного падежа, а не именительного.
    """
    единственное, множественное = forms
    if isinstance(n, float) and n != int(n):
        return единственное
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return единственное
    return множественное


def с_ед_род(n, forms):
    """«из 341 килограмма» — число и форма родительного падежа."""
    return '%s %s' % (num(n), род(n, forms))


РОД_ДЕТАЛЬ = ('детали', 'деталей')
РОД_КИЛОГРАММ = ('килограмма', 'килограммов')
РОД_ЛИТР = ('литра', 'литров')


def км(n):
    """Расстояние: в условиях ОГЭ пишут сокращением, «224 км»."""
    return '%s км' % num(n)


def кг(n):
    """Масса: тоже сокращением — «341 кг свежих фруктов», как в банке."""
    return '%s кг' % num(n)


def кмч(n):
    """Скорость: «5 км/ч». Слово «километров» тут не разворачивают."""
    return '%s км/ч' % num(n)


def num(value):
    """
    Число в тексте условия: целое без хвоста, дробное — с запятой.

    Запятая, а не точка: в условии это русский текст, а не формула.
    """
    f = Fraction(value).limit_denominator(10 ** 6)
    if f.denominator == 1:
        return str(f.numerator)
    d = float(f)
    s = ('%.4f' % d).rstrip('0').rstrip('.')
    return s.replace('.', ',')


def is_terminating(value):
    """
    Записывается ли число конечной десятичной дробью.

    На ОГЭ ответ пишут десятичной дробью, и генератор обязан выдавать только
    такие: 8,7 годится, а 1/3 ученику записать нечем.
    """
    f = Fraction(value).limit_denominator(10 ** 9)
    d = f.denominator
    for p in (2, 5):
        while d % p == 0:
            d //= p
    return d == 1


def answer_text(value):
    """Ответ для поля ввода: точка как разделитель — так его ждёт проверка."""
    f = Fraction(value).limit_denominator(10 ** 6)
    if f.denominator == 1:
        return str(f.numerator)
    return ('%.6f' % float(f)).rstrip('0').rstrip('.')


# --------------------------------------------------------------------------
# Разметка
