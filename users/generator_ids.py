def закрепить_генератор(имя, defaults):
    """Завести или обновить генератор ПОД ЕГО ЗАКРЕПЛЁННЫМ НОМЕРОМ.

    Замена ProblemGenerator.objects.update_or_create(name=..., defaults=...):
    тот же ответ (генератор, создан ли), но id берётся из таблицы.

    Если генератор с этим именем уже есть под чужим номером — так бывает на
    сервере, наполненном до закрепления, — он переезжает: задания
    перецепляются на новый номер, старая запись удаляется. Порядок важен:
    сначала перецепить, потом удалять, иначе SET_NULL оставит задания без
    генератора. Задачи, уже выданные ученикам, и их попытки не трогаются —
    они висят на задании, а не на генераторе.

    Если закреплённый номер занят генератором с ДРУГИМ именем, молча затирать
    его нельзя: к нему привязаны чьи-то задания. Тогда ошибка, и транзакция
    откатывается целиком.
    """
    from users.models import Assignment, ProblemGenerator

    try:
        номер = ЗАКРЕПЛЁННЫЕ[имя]
    except KeyError:
        raise CommandError(
            'У генератора «%s» нет закреплённого номера. Добавьте строку в '
            'users/generator_ids.py и файл users/generators/g<id>.py с тем же '
            'номером — иначе на другой машине он исполнит чужой файл.' % имя)

    with transaction.atomic():
        занявший = (ProblemGenerator.objects
                    .filter(id=номер).exclude(name=имя).first())
        if занявший:
            raise CommandError(
                'Номер %d закреплён за «%s», но занят генератором «%s». '
                'Если это генератор 16–19, стоящий под чужим номером, сначала '
                'запустите seed_oge16…seed_oge19 — они освободят номера.'
                % (номер, имя, занявший.name))

        переезжающие = list(ProblemGenerator.objects
                            .filter(name=имя).exclude(id=номер))
        # Имя освобождаем заранее: новая запись заводится с тем же именем.
        for старый in переезжающие:
            старый.name = '%s [переезд с id=%d]' % (имя, старый.id)
            старый.save(update_fields=['name'])

        генератор, создан = ProblemGenerator.objects.update_or_create(
            id=номер, defaults=dict(defaults, name=имя))

        for старый in переезжающие:
            Assignment.objects.filter(problem_generator=старый).update(
                problem_generator=генератор)
            старый.delete()

        if создан:
            _сбросить_счётчик()
    return генератор, создан


def _сбросить_счётчик():
    """После вставки с явным id подтянуть счётчик PostgreSQL к максимуму.

    Иначе следующий генератор, заведённый через админку, получит номер из
    счётчика — а он отстаёт и попадёт в закреплённый диапазон. На SQLite
    запрос пустой: там следующий номер и так берётся от максимума.
    """
    from users.models import ProblemGenerator

    запросы = connection.ops.sequence_reset_sql(no_style(), [ProblemGenerator])
    if запросы:
        with connection.cursor() as курсор:
            for запрос in запросы:
                курсор.execute(запрос)
