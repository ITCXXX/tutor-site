# -*- coding: utf-8 -*-
"""Оценки: балл за номер и два способа собрать из них итог.

Проверяем ЧИСЛА. Смысл модуля в том, что «сумма к сумме» и «среднее процентов»
дают РАЗНЫЕ цифры, и обе показываются рядом. Если тест перестанет различать эти
два способа, потеряется всё, ради чего заведён атом-балл за номер.
"""

from .grades import course_score, grades_for_lesson, lesson_score
from .models import Grade
from django.db import IntegrityError, transaction

from .tests_base import (КабинетTestCase, сделать_задачу, сделать_ученика,
                         сделать_урок, сдать)


def оценить(ученик, задача, балл, из_скольких, штраф=0, со_сдачей=True):
    """Оценка за задачу. По умолчанию — со сдачей, как чаще всего в жизни.

    со_сдачей=False — это контрольная на бумаге, устный ответ, разбор у доски:
    работы в системе нет, а оценка есть. Ради этого случая оценка и переехала
    со сдачи на пару «ученик — задача».
    """
    сдача = сдать(ученик, задача) if со_сдачей else None
    return Grade.objects.create(student=ученик, assignment=задача,
                                submission=сдача, value=балл,
                                max_value=из_скольких, penalty=штраф)


class GradeМодельTests(КабинетTestCase):
    """Балл за ОДИН номер: штраф и деление на потолок."""

    def test_final_вычитает_штраф(self):
        """Если сломается — штраф за опоздание перестанет влиять на балл,
        и опоздавший получит столько же, сколько сдавший в срок."""
        оценка = оценить(self.ученик, self.задача1, 8, 10, штраф=3)
        self.assertEqual(оценка.final, 5)

    def test_final_не_уходит_в_минус(self):
        """Если сломается — штраф больше балла даст отрицательный итог, и
        один провальный номер утянет вниз процент за весь урок."""
        оценка = оценить(self.ученик, self.задача1, 2, 10, штраф=5)
        self.assertEqual(оценка.final, 0)

    def test_percent_считается_от_итога_со_штрафом(self):
        """Если сломается — процент за номер будет показан без учёта штрафа:
        в журнале 100%, а баллов у ученика половина."""
        оценка = оценить(self.ученик, self.задача1, 10, 10, штраф=5)
        self.assertEqual(оценка.percent, 50.0)

    def test_percent_при_нулевом_потолке_даёт_None(self):
        """Если сломается — опечатка «из 0» при выставлении уронит страницу
        оценок делением на ноль вместо того, чтобы просто не считаться."""
        оценка = оценить(self.ученик, self.задача1, 3, 0)
        self.assertIsNone(оценка.percent)


class LessonScoreTests(КабинетTestCase):
    """Итог по уроку: обе цифры сразу."""

    def test_главный_пример_двух_способов(self):
        """Если сломается — два способа счёта перестанут различаться, и
        владелец сайта увидит одну цифру вместо тех двух, ради которых
        всё и заводилось: 54.5 (вес по баллам) и 75.0 (вес по номерам)."""
        оценить(self.ученик, self.задача1, 5, 10)   # крупный номер наполовину
        оценить(self.ученик, self.задача2, 1, 1)    # мелкий номер целиком
        свод = lesson_score(self.ученик, self.урок)
        self.assertEqual(свод['by_sum'], 54.5)
        self.assertEqual(свод['by_avg'], 75.0)
        self.assertEqual(свод['earned'], 6.0)
        self.assertEqual(свод['maximum'], 11.0)
        self.assertEqual(свод['graded'], 2)
        self.assertEqual(свод['total'], 2)
        self.assertTrue(свод['has_any'])

    def test_крупный_номер_весит_больше_в_сумме_к_сумме(self):
        """Вторая точка на той же кривой. Если сломается — «сумма к сумме»
        начнёт считать номера равными, и ученик, заваливший главный номер,
        но решивший мелкий, увидит проходной процент вместо 9.1."""
        оценить(self.ученик, self.задача1, 0, 10)
        оценить(self.ученик, self.задача2, 1, 1)
        свод = lesson_score(self.ученик, self.урок)
        self.assertEqual(свод['by_sum'], 9.1)
        self.assertEqual(свод['by_avg'], 50.0)

    def test_в_знаменателе_только_проверенные_работы(self):
        """Если сломается — сдавший половину и ждущий проверки увидит низкий
        процент не потому, что решил плохо, а потому, что до него не дошли
        руки. Число `total` при этом должно честно говорить «номеров два»."""
        оценить(self.ученик, self.задача1, 5, 10)
        свод = lesson_score(self.ученик, self.урок)
        self.assertEqual(свод['graded'], 1)
        self.assertEqual(свод['total'], 2)
        self.assertEqual(свод['by_sum'], 50.0)
        self.assertEqual(свод['by_avg'], 50.0)
        self.assertEqual(свод['maximum'], 10.0)

    def test_без_оценок_проценты_None_а_не_ноль(self):
        """Если сломается — непроверенная домашка покажет «0%», то есть
        «решил на ноль». Ученик увидит двойку там, где его просто не смотрели."""
        сдать(self.ученик, self.задача1)
        свод = lesson_score(self.ученик, self.урок)
        self.assertFalse(свод['has_any'])
        self.assertIsNone(свод['by_sum'])
        self.assertIsNone(свод['by_avg'])
        self.assertEqual(свод['graded'], 0)
        self.assertEqual(свод['total'], 2)

    def test_оценка_переживает_доработку(self):
        """Ученик прислал доработку — оценка за задачу остаётся, а не пропадает.

        Прежде оценка висела на сдаче, и любая доработка обнуляла итог: балл
        уезжал вместе со старой попыткой. Теперь оценка про ЗАДАЧУ, и она живёт,
        пока преподаватель её не изменит. Если этот тест покраснеет — ученик
        после доработки увидит, что его оценка исчезла.
        """
        оценка = оценить(self.ученик, self.задача1, 5, 10)
        старая_сдача = оценка.submission
        старая_сдача.is_latest = False
        старая_сдача.save(update_fields=['is_latest'])
        сдать(self.ученик, self.задача1, text='доработка', attempt=2)

        свод = lesson_score(self.ученик, self.урок)
        self.assertTrue(свод['has_any'])
        self.assertEqual(свод['graded'], 1)
        self.assertEqual(свод['earned'], 5.0)

    def test_чужие_оценки_не_попадают_в_итог(self):
        """Если сломается — ученик увидит в своём итоге чужие баллы."""
        сосед = сделать_ученика(username='sosed', display='Ваня',
                                teacher=self.преподаватель)
        оценить(сосед, self.задача1, 10, 10)
        оценить(self.ученик, self.задача2, 1, 1)
        свод = lesson_score(self.ученик, self.урок)
        self.assertEqual(свод['graded'], 1)
        self.assertEqual(свод['earned'], 1.0)
        self.assertEqual(свод['by_sum'], 100.0)


class CourseScoreTests(КабинетTestCase):
    """Итог по курсу: отношение всего ко всему, по всем урокам сразу."""

    def setUp(self):
        super().setUp()
        self.урок2 = сделать_урок(self.курс, 'Урок 2', order=2)
        self.задача3 = сделать_задачу(self.урок2, 'Задача 3', points=5, order=1)

    def test_складывает_оценки_по_всем_урокам(self):
        """Если сломается — итог за курс покажет только первый урок, и
        ученик, работавший весь месяц, увидит процент за одно занятие."""
        оценить(self.ученик, self.задача1, 5, 10)   # урок 1
        оценить(self.ученик, self.задача3, 5, 5)    # урок 2
        свод = course_score(self.ученик, self.курс)
        self.assertEqual(свод['graded'], 2)
        self.assertEqual(свод['earned'], 10.0)
        self.assertEqual(свод['maximum'], 15.0)
        self.assertEqual(свод['by_sum'], 66.7)
        self.assertEqual(свод['by_avg'], 75.0)

    def test_total_считает_номера_всех_уроков_курса(self):
        """Если сломается — «проверено 1 из 2» вместо «1 из 3», и по курсу
        будет казаться, что проверять почти нечего."""
        оценить(self.ученик, self.задача1, 5, 10)
        self.assertEqual(course_score(self.ученик, self.курс)['total'], 3)

    def test_итог_урока_не_подхватывает_соседний_урок(self):
        """Если сломается — балл за другое занятие попадёт в домашку этого,
        и разбирать, откуда взялся процент, будет невозможно."""
        оценить(self.ученик, self.задача3, 5, 5)    # оценка только во втором уроке
        свод = lesson_score(self.ученик, self.урок)
        self.assertEqual(свод['graded'], 0)
        self.assertEqual(свод['total'], 2)


class GradesForLessonTests(КабинетTestCase):
    """Сводка преподавателя по уроку: строка на каждого ученика."""

    def setUp(self):
        super().setUp()
        self.ученик2 = сделать_ученика(username='uchenik2', display='Боря',
                                       teacher=self.преподаватель)

    def test_ученик_без_оценок_получает_пустой_свод_а_не_пропадает(self):
        """Если сломается — не сдавший ученик исчезнет из сводки, и
        преподаватель не заметит, что от него ничего нет."""
        оценить(self.ученик, self.задача1, 5, 10)
        свод = grades_for_lesson(self.урок, [self.ученик, self.ученик2])
        self.assertIn(self.ученик2.id, свод)
        self.assertFalse(свод[self.ученик2.id]['has_any'])
        self.assertIsNone(свод[self.ученик2.id]['by_sum'])
        self.assertEqual(свод[self.ученик2.id]['graded'], 0)
        self.assertEqual(свод[self.ученик2.id]['total'], 2)

    def test_у_каждого_ученика_свои_числа(self):
        """Если сломается — в сводке класса баллы перемешаются между
        строками, и оценки уйдут не тем людям."""
        оценить(self.ученик, self.задача1, 5, 10)
        оценить(self.ученик, self.задача2, 1, 1)
        оценить(self.ученик2, self.задача2, 0, 1)
        свод = grades_for_lesson(self.урок, [self.ученик, self.ученик2])
        self.assertEqual(свод[self.ученик.id]['by_sum'], 54.5)
        self.assertEqual(свод[self.ученик.id]['by_avg'], 75.0)
        self.assertEqual(свод[self.ученик2.id]['by_sum'], 0.0)
        self.assertEqual(свод[self.ученик2.id]['graded'], 1)

    def test_в_сводку_не_попадают_ученики_вне_списка(self):
        """Если сломается — преподаватель увидит в сводке своего урока
        учеников чужой группы."""
        оценить(self.ученик2, self.задача1, 10, 10)
        свод = grades_for_lesson(self.урок, [self.ученик])
        self.assertEqual(list(свод.keys()), [self.ученик.id])


class ОценкаБезСдачиTests(КабинетTestCase):
    """Контрольная на бумаге: работы в системе нет, а балл есть.

    Ради этого случая оценка и переехала со сдачи на пару «ученик — задача».
    Если этот тест покраснеет — значит вернулись к тому, что оценить можно
    только присланное, и половина занятий останется без отметок.
    """

    def test_оценка_без_сдачи_попадает_в_итог(self):
        оценить(self.ученик, self.задача1, 7, 10, со_сдачей=False)
        свод = lesson_score(self.ученик, self.урок)
        self.assertTrue(свод['has_any'])
        self.assertEqual(свод['graded'], 1)
        self.assertEqual(свод['earned'], 7.0)
        self.assertEqual(свод['by_sum'], 70.0)

    def test_у_оценки_без_сдачи_ссылка_пуста(self):
        оценка = оценить(self.ученик, self.задача1, 7, 10, со_сдачей=False)
        self.assertIsNone(оценка.submission)

    def test_одна_оценка_на_задачу(self):
        """Вторая оценка за тот же номер невозможна: это два разных балла."""
        оценить(self.ученик, self.задача1, 7, 10, со_сдачей=False)
        with self.assertRaises(IntegrityError):
            with transaction.atomic():
                оценить(self.ученик, self.задача1, 3, 10, со_сдачей=False)
