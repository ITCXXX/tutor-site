def num(v):
    """Число для ответа: конечная десятичная — через запятую, иначе дробь a/b."""
    return num22(v)


def num_latex(v):
    """То же для формул: 14{,}4 или \\frac{180}{13}."""
    f = Fraction(v).limit_denominator(10 ** 6)
    т = num(f)
    if '/' in т:
        зн = '-' if f < 0 else ''
        return '%s\\frac{%d}{%d}' % (зн, abs(f.numerator), f.denominator)
    return т.replace(',', '{,}')


def упростить_корень(m):
    """√m = k√r с бесквадратным r. Возвращает (k, r)."""
    k, r = 1, int(m)
    d = 2
    while d * d <= r:
        while r % (d * d) == 0:
            r //= d * d
            k *= d
        d += 1
    return k, r


def root_answer(k, m):
    """
    Число k·√m в записи ответа и в LaTeX.

    Возвращает (строка_ответа, latex, значение). Радикал упрощается:
    root_answer(2, 18) → ('6\\sqrt{2}', '6\\sqrt{2}', 8.485…). При m — полном
    квадрате корень исчезает: root_answer(3, 4) → ('6', '6', 6.0).
    """
    k = Fraction(k)
    k2, r = упростить_корень(m)
    k = k * k2
    if r == 1:
        return num(k), num_latex(k), float(k)
    коэф = '' if k == 1 else ('-' if k == -1 else num_latex(k))
    текст = '%s\\sqrt{%d}' % (коэф, r)
    return текст, текст, float(k) * math.sqrt(r)


def answer_text(значения):
    """Список чисел → «a; b; c» в канонической записи."""
    return '; '.join(num(v) for v in значения)


