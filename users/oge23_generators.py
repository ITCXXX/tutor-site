# ────────────────────────────────────────────────────────────────────────
# Тип 20 (№23). Окружность с центром на стороне AC треугольника ABC проходит
# ────────────────────────────────────────────────────────────────────────
#
# через вершину C и касается прямой AB в точке B. Даны AB и AC, найти диаметр.
#
# Ядро — теорема о касательной и секущей. Второе пересечение окружности с AC —
# точка D; центр лежит на хорде CD, значит CD — диаметр. Из A проведены
# касательная AB и секущая AC с внешней частью AD, поэтому AB² = AC·AD,
# AD = AC − CD и CD = (AC² − AB²)/AC. Уравнение линейное — второго случая нет.
#
# Числа. AB < AC целые (иначе D не попадает внутрь AC и фигуры нет). Ответ
# банка — целое или конечная десятичная дробь с одной-двумя цифрами после
# запятой (3,2; 4,8; 8; 5,25; 7,5), поэтому в пул идут пары с AC ≤ 25, у которых
# (AC² − AB²)/AC записывается не более чем двумя знаками после запятой.
# Форма фигуры зависит только от отношения AB : AC (подобие), поэтому оно
# ограничено границами банка — от 1 : 5 до 9 : 12. Банковские пары (3,5), (1,5),
# (3,9), (9,12), (2,8) в пул входят.
#
# check строит фигуру в координатах без формулы ответа: A — начало, B на оси x,
# центр O — на перпендикуляре к AB в точке B (радиус в точку касания). Высота O
# над AB находится бисекцией из условия «C лежит на луче AO на расстоянии AC от
# A и OC = OB»; затем прямая AC пересекается с окружностью, и измеряется хорда CD.


def _пул():
    """AC → список AB.

    Условия: 4 ≤ AC ≤ 25, AB целое, диаметр — не более двух цифр после запятой,
    и AC/5 ≤ AB ≤ 3·AC/4 — как в банке, где крайние пары (1, 5) и (9, 12).

    Последнее ограничение — про чертёж. Фигура задана отношением AB : AC с
    точностью до подобия, и за границами банка она вырождается: при AB, близком
    к AC, окружность схлопывается и треугольник становится иглой (AB = 24,
    AC = 25 — угол A около 2°), а при малом AB точка D садится на A (AB = 1,
    AC = 25 — на чертеже между ними меньше пикселя).
    """
    пул = {}
    for AC in range(4, 26):
        for AB in range(1, AC):
            if 5 * AB < AC or 4 * AB > 3 * AC:
                continue
            CD = Fraction(AC * AC - AB * AB, AC)
            if (CD * 100).denominator == 1:
                пул.setdefault(AC, []).append(AB)
    return пул


ПУЛ_20 = _пул()
СЕКУЩИЕ = sorted(ПУЛ_20)


@тип(20)
def _тип_20(rng):
    # Сначала AC, потом AB — иначе половина пула приходится на AC = 20 и 25.
    AC = rng.choice(СЕКУЩИЕ)
    AB = rng.choice(ПУЛ_20[AC])
    AD = Fraction(AB * AB, AC)            # внешняя часть секущей
    CD = AC - AD                          # диаметр: (AC² − AB²)/AC
    AB2, AC2 = AB * AB, AC * AC

    условие = (
        '<p>Окружность, центр которой лежит на стороне \\(AC\\) треугольника '
        '\\(ABC\\), проходит через вершину \\(C\\) и касается прямой \\(AB\\) в точке '
        '\\(B\\). Найдите диаметр этой окружности, если \\(AB = %d\\), \\(AC = %d\\).</p>'
        % (AB, AC))

    решение = (
        '<p>1. Пусть \\(D\\) — вторая точка пересечения окружности с прямой \\(AC\\). '
        'Центр окружности лежит на \\(AC\\), то есть лежит на хорде \\(CD\\), а хорда, '
        'проходящая через центр, — это диаметр. Значит, искомый диаметр равен \\(CD\\). '
        'Обозначим \\(CD = x\\).</p>'
        '<p>2. Прямая \\(AB\\) касается окружности в точке \\(B\\), поэтому все её точки, '
        'кроме \\(B\\), лежат вне окружности — в частности, точка \\(A\\). Центр окружности '
        'лежит на стороне \\(AC\\), то есть между \\(A\\) и \\(C\\), поэтому из двух точек '
        'пересечения к \\(A\\) ближе \\(D\\). Значит, \\(D\\) лежит между \\(A\\) и \\(C\\) и '
        '\\(AD = AC - CD = %d - x\\) — внешняя часть секущей \\(AC\\).</p>'
        '<p>3. По теореме о касательной и секущей, проведённых из одной точки, квадрат '
        'отрезка касательной равен произведению всей секущей на её внешнюю часть: '
        '\\(AB^2 = AC \\cdot AD\\).</p>'
        '<p>4. Подставляем числа:</p>'
        '\\[%d^2 = %d \\cdot (%d - x), \\qquad %d = %d - %d x, \\qquad '
        '%d x = %d, \\qquad x = %s.\\]'
        '<p>Диаметр окружности равен \\(%s\\).</p>'
        % (AC, AB, AC, AC, AB2, AC2, AC, AC, AC2 - AB2, num_latex(CD), num_latex(CD)))

    def check():
        # A — начало координат, касательная AB — по оси x. Радиус в точку
        # касания перпендикулярен касательной, поэтому центр O = (AB, t), t > 0.
        A = (0.0, 0.0)
        B = (float(AB), 0.0)

        def построить(t):
            O = (float(AB), t)
            ao = расстояние(A, O)
            C = (O[0] / ao * AC, O[1] / ao * AC)      # C на луче AO, AC задано
            return O, C

        # Условие «C на окружности»: OC = OB. Разность OC − OB убывает по t,
        # при t → 0 она равна AC − AB > 0, при t = AC отрицательна — бисекция.
        lo, hi = 0.0, float(AC)
        for _ in range(200):
            mid = (lo + hi) / 2.0
            O, C = построить(mid)
            if расстояние(O, C) > расстояние(O, B):
                lo = mid
            else:
                hi = mid
        O, C = построить((lo + hi) / 2.0)
        r = расстояние(O, B)
        if abs(расстояние(O, C) - r) > 1e-7:
            raise ValueError('окружность не проходит через C')

        # Пересекаем прямую AC с окружностью: P(s) = A + s·u, |P − O|² = r².
        ux, uy = C[0] / AC, C[1] / AC
        p = ux * O[0] + uy * O[1]
        q = O[0] ** 2 + O[1] ** 2 - r * r
        disc = max(0.0, p * p - q)
        корни = [p - math.sqrt(disc), p + math.sqrt(disc)]
        sC = расстояние(A, C)
        sD = min(корни, key=lambda s: -abs(s - sC))   # корень, отличный от C
        if not (0.0 < sD < sC):
            raise ValueError('вторая точка пересечения не внутри AC')
        D = (ux * sD, uy * sD)
        return расстояние(C, D)

    # Чертёж: точная фигура (здесь формулой пользоваться можно).
    r = float(CD) / 2.0
    A, B = (0.0, 0.0), (float(AB), 0.0)
    O = (float(AB), r)
    ao = расстояние(A, O)
    ex, ey = O[0] / ao, O[1] / ao
    C = (O[0] + r * ex, O[1] + r * ey)
    D = (O[0] - r * ex, O[1] - r * ey)
    ч = Чертёж()
    ч.окружность(O, r)
    ч.отрезок(A, B); ч.отрезок(B, C); ч.отрезок(A, C)
    ч.отрезок(O, B, вспомогательный=True)
    # Размер квадратика — доля от размаха чертежа (иначе на AC = 25 он булавочный).
    ч.прямой_угол(B, A, O, размер=min(0.04 * AC, 0.25 * min(AB, r)))
    ч.точка(O); ч.точка(D)
    подписать_вершины(ч, (A, 'A', 'юз'), (B, 'B', 'ю'), (C, 'C', 'св'),
                      (O, 'O', 'юв'), (D, 'D', 'сз'))

    return {
        'statement_html': условие,
        'answer': num(CD),
        'answer_kind': 'number',
        'answer_value': CD,
        'allow_fractions': CD.denominator != 1,
        'solution_html': решение,
        'params': {'AB': AB, 'AC': AC, 'AD': AD, 'CD': CD},
        'check': check,
        'figure': ч,
    }
