# Чтобы ответ был целым, как во всех задачах банка, обе пары (AB/2, d1) и
# (CD/2, d2) берутся из пифагоровых троек с общей гипотенузой R. Банк всегда
# берёт одну тройку с переставленными катетами (CD/2 = d1, ответ AB/2); здесь
# при R = 25 добавляется и вторая тройка: (7, 24) рядом с (15, 20).


МИН_R, МАКС_R = 10, 30


def _пары_катетов():
    """R → список (катет, другой катет) в обоих порядках, x² + y² = R²."""
    пары = {}
    for R in range(МИН_R, МАКС_R + 1):
        for x in range(1, R):
            y2 = R * R - x * x
            y = math.isqrt(y2)
            if y * y == y2 and y > 0:
                пары.setdefault(R, []).append((x, y))
    return пары


