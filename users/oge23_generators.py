# Тип 15. Окружность на высоте прямоугольного треугольника как на диаметре:
# ────────────────────────────────────────────────────────────────────────
#
# найти хорду PK.
#
# Треугольник ABC, ∠B = 90°, BH — высота к гипотенузе AC. Окружность с диаметром
# BH пересекает катеты AB и CB в точках P и K. Дано BH, найти PK.
#
# Ответ: PK = BH. Угол PBK — это прямой угол B, он вписан в окружность (B лежит
# на ней как конец диаметра). Прямой вписанный угол опирается на диаметр,
# значит PK — диаметр, а все диаметры равны. Эквивалентно: ∠BPH = ∠BKH = 90°
# (опираются на диаметр BH), BPHK — прямоугольник, диагонали равны.
#
# Форма треугольника в условии не задана и на ответ не влияет: при любом остром
# угле A точки P и K — основания перпендикуляров из H на катеты, они всегда
# внутри катетов. Поэтому check строит треугольник со случайным углом A,
# пересекает окружность с катетами и меряет PK; вдобавок повторяет измерение
# на двух заведомо других формах и требует совпадения — так ловилась бы
# зависимость ответа от формы, если бы она была. Углы A и 90° − A для этого не
# годятся: у них катеты BH/sin A и BH/cos A просто меняются местами, то есть
# треугольник получается зеркальным, а значит равным исходному, — совпадение
# PK было бы пустым. Поэтому сравнительные углы берутся вне диапазона A и не
# дополнительные друг другу.
#
# Единственный свободный параметр — BH. В банке 11–15 (целые); здесь целые
# 5–30 и иногда конечные десятичные дроби (знаменатели 2, 4, 5).


def _треугольник_15(BH, угол_A):
    """
    Прямоугольный треугольник с ∠B = 90°, ∠A = угол_A (градусы) и высотой BH.
    Гипотенуза AC — на оси x, B сверху. Возвращает A, B, C, H.
    """
    a = math.radians(угол_A)
    bh = float(BH)
    AB = bh / math.sin(a)             # BH = AB·sin A
    AC = AB / math.cos(a)             # AB = AC·cos A
    A, C = (0.0, 0.0), (AC, 0.0)
    B = (AB * math.cos(a), AB * math.sin(a))
    H = проекция(A, C, B)
    return A, B, C, H


def _окружность_и_луч(O, r, U, V):
    """
    Вторая точка пересечения окружности (O, r) с прямой UV, если U лежит на
    окружности. Возвращает (точка, t), где точка = U + t·(V − U).
    """
    dx, dy = V[0] - U[0], V[1] - U[1]
    fx, fy = U[0] - O[0], U[1] - O[1]
    a = dx * dx + dy * dy
    b = 2 * (fx * dx + fy * dy)
    c = fx * fx + fy * fy - r * r
    D = b * b - 4 * a * c
    if D < -1e-9 * a * r * r:
        raise ValueError('окружность не пересекает прямую')
    sq = math.sqrt(max(D, 0.0))
    корни = [(-b + s * sq) / (2 * a) for s in (1, -1)]
    # Один корень — сама точка U (t ≈ 0); нужен другой.
    t = max(корни, key=abs)
    return (U[0] + t * dx, U[1] + t * dy), t


def _измерить_PK(BH, угол_A):
    """Строит фигуру при данном угле A и меряет PK по координатам."""
    A, B, C, H = _треугольник_15(BH, угол_A)
    O = середина(B, H)
    r = расстояние(B, H) / 2.0
    P, tP = _окружность_и_луч(O, r, B, A)
    K, tK = _окружность_и_луч(O, r, B, C)
    if not (0.0 < tP < 1.0 and 0.0 < tK < 1.0):
        raise ValueError('P или K вне катета: tP=%s, tK=%s' % (tP, tK))
    return расстояние(P, K), (A, B, C, H, O, r, P, K)


