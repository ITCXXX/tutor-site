        '\\(AH^2 = AD^2 - DH^2 = %d^2 - %d^2 = %d - %d = %d\\). '
        'Тот же счёт короче через разность квадратов: '
        '\\(AH^2 = (AD - DH)(AD + DH) = (%d - %d)(%d + %d) = %d \\cdot %d = %d\\).</p>'
        '<p>4. Длина \\(AH\\) положительна, поэтому</p>'
