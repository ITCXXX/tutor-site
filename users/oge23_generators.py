"""
Генераторы задания №23 ОГЭ — геометрические задачи на вычисление.

Типология собрана из банка Школково (214 задач, 20 типов ФИПИ) и лежит в
oge23_setup/TYPES.md: для каждого типа выведена формула ответа и прогнана по
всем задачам банка. Здесь — код.

Как устроена проверка
---------------------
Генератор считает ответ по формуле — той самой, из справочника. Верить ей
на слово нельзя: формула могла быть выведена для одного расположения точек
и молча врать для другого. Поэтому каждый тип обязан вернуть ещё и
`check` — функцию, которая строит фигуру В КООРДИНАТАХ по тем же параметрам
и измеряет искомую величину напрямую: пересекает прямые, считает расстояния,
находит центры окружностей. Никакой формулы ответа внутри `check` быть не
должно. Проверяльщик oge23_setup/verify_geom.py сравнивает два числа,
полученных разными путями, на сотнях сидов.

Контракт функции типа
---------------------
    @тип(N)
    def _тип_N(rng) -> dict

    {
      'statement_html':  условие, формулы в \\( \\);
      'answer':          строка ответа в канонической записи, которую примет
                         users/answer_check.py: «14,4», «180/13», «3\\sqrt{2}»,
                         несколько чисел — через «; »;
      'answer_kind':     'number' | 'roots' (несколько чисел);
      'answer_value':    число (float/Fraction) или список чисел — значение
                         ответа по формуле, для сравнения с check;
      'allow_fractions': True, если ответ — непериодическая дробь или корень;
      'solution_html':   решение по шагам, HTML;
      'params':          исходные данные задачи (для отладки и сообщений);
      'check':           функция без аргументов → число или список чисел,
                         посчитанные ПО КООРДИНАТАМ;
      'figure':          users.geom_svg.Чертёж или None — необязателен.
    }
"""

