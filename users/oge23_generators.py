#
# AB и AC в точках K и P. Дано AP и k = AB/BC («BC в k раза меньше AB»). Найти KP.
#
# KBCP — вписанный четырёхугольник, поэтому ∠APK = ∠ABC (внешний угол вписанного
# четырёхугольника равен противоположному внутреннему). Вместе с общим углом A
# это даёт △APK ~ △ABC, причём P ↔ B, K ↔ C. Отсюда AP/AB = KP/BC и KP = AP/k.
#
# Семейство: k = p/q — конечная десятичная дробь из набора банка и соседей
# (1,2; 1,4; 1,5; 1,6; 1,8; 2; 2,4; 2,5; 3; 4), KP = q·m целое, AP = p·m целое.
# Стороны треугольника в условии не фигурируют, но для check и чертежа фигура
# нужна: AC берём больше AP (P внутри стороны), BC = b и AB = k·b подбираем так,
# чтобы треугольник существовал и вторая точка K пересечения окружности (BCP)
# с прямой AB лежала внутри стороны AB.


# k = AB/BC. Все знаменатели делят 10, поэтому 10·k — целое (нужно в решении).
_ВАРИАНТЫ_K = [Fraction(6, 5), Fraction(7, 5), Fraction(3, 2), Fraction(8, 5),
               Fraction(9, 5), Fraction(2), Fraction(12, 5), Fraction(5, 2),
               Fraction(3), Fraction(4)]


def _построить_18(AP, k, AC, BC):
    """
    Фигура в координатах: A в начале, C на оси x, B над осью (по трём сторонам),
    P на AC на расстоянии AP от A, окружность через B, C, P, K — её вторая точка
    на прямой AB. Возвращает словарь точек и параметр t = AK/AB.
    """
    AB = float(k) * BC
    A = (0.0, 0.0)
    C = (AC, 0.0)
    xB = (AB * AB + AC * AC - BC * BC) / (2 * AC)
    yB = math.sqrt(max(AB * AB - xB * xB, 0.0))
    B = (xB, yB)
    P = (float(AP), 0.0)
    O = центр_описанной(B, C, P)
    # Прямая AB проходит через B, лежащую на окружности; вторая точка пересечения
    # отстоит от B на удвоенную проекцию BO на направление прямой.
    L = расстояние(A, B)
    ux, uy = (A[0] - B[0]) / L, (A[1] - B[1]) / L
    s = 2 * ((O[0] - B[0]) * ux + (O[1] - B[1]) * uy)
    K = (B[0] + s * ux, B[1] + s * uy)
    t = 1.0 - s / L                       # AK / AB
    return {'A': A, 'B': B, 'C': C, 'P': P, 'K': K, 'O': O,
            'R': расстояние(O, B), 't': t}


