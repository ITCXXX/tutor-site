# №23, тип 6. Биссектриса угла параллелограмма отсекает равнобедренный
# ────────────────────────────────────────────────────────────────────────
#
# треугольник; найти периметр.
#
# Банк: «Биссектриса угла A параллелограмма ABCD пересекает сторону BC в точке K.
