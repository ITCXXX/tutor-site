        # приближается к D с ростом угла). Затем измеряем расстояние от A
        # до прямой DC — это и есть высота.
        D, C = (0.0, 0.0), (float(s), 0.0)

        def ромб(угол):
            A = (s * math.cos(угол), s * math.sin(угол))
            B = (A[0] + s, A[1])
            return A, B

        лев, прав = 1e-9, math.pi / 2 - 1e-9
        for _ in range(200):
            сер = (лев + прав) / 2
            A, _B = ромб(сер)
            H = проекция(D, C, A)
