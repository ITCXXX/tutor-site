def generate(номер, seed=None):
    if номер not in GENERATORS:
        raise KeyError('нет генератора типа %s' % номер)
    rng = random.Random(seed)
    task = GENERATORS[номер](rng)
    task['type'] = номер
    task['question_html'] = task['statement_html']
    return task


def as_task(номер, seed=None):
    """Мост к платформе: users/generators/g<id>.py вызывает это."""
    task = generate(номер, seed)
    решение = '<p><b>Решение.</b></p>' + task['solution_html']
    if task.get('figure') is not None:
        решение += '<div class="graph">%s</div>' % task['figure'].готово()
    решение += '<p><b>Ответ:</b> %s.</p>' % task['answer'].replace('; ', ';&nbsp; ')
    return {
        'condition_text': task['question_html'],
        'correct_answer': task['answer'],
        'answer_kind': task.get('answer_kind', 'number'),
        'multi_answer': task.get('answer_kind') == 'roots' and ';' in task['answer'],
        'allow_fractions': bool(task.get('allow_fractions')),
        'solution_html': решение,
        'oge23_type': номер,
    }


