# ────────────────────────────────────────────────────────────────────────
# Тип 8 (№23). Ромб: расстояние от точки пересечения диагоналей до стороны и
# ────────────────────────────────────────────────────────────────────────
#
# одна диагональ → углы ромба.
#
# Ромб ABCD, диагонали пересекаются в O, OH ⊥ AB. Дано OH = h и диагональ d.
# В прямоугольном треугольнике AHO гипотенуза AO = d/2, катет OH = h. В банке
# всегда d = 4h: катет вдвое меньше гипотенузы, ∠HAO = 30°, а так как диагональ
# ромба — биссектриса его угла, ∠BAD = 60° и ∠ABC = 120°.
#
# Целые градусы получаются только при d = 4h (рациональный синус у целого
# числа градусов бывает лишь 0, ±1/2, ±1), поэтому ответ банковской
# формулировки всегда «60; 120» и от h не зависит. Чтобы ответы различались
# от сида к сиду, в одной и той же конфигурации задаётся один из трёх вопросов:
#
#   * «углы»       — как в банке: даны h и диагональ 4h, найти углы ромба;
#   * «расстояние» — даны диагональ d и угол ромба, найти расстояние от O
#                    до стороны AB (d/4);
#   * «диагональ»  — даны h и угол ромба, найти диагональ, выходящую из
#                    вершины острого угла (4h).
#
# Обратные вопросы проходят ту же цепочку теорем в другом порядке. Данная
# диагональ — AC или BD, перпендикуляр всегда опускается на сторону AB.
#
# Дословная банковская формулировка (без букв) отличается от опубликованных
# задач только числом h, поэтому восемь значений h самого банка в ней не
# берутся: задача должна быть узнаваема как банковская, но не быть её
# дословной копией. В остальных формулировках (с буквами, обратные вопросы)
# эти h разрешены — там уже другой текст или другой вопрос.


# V — вершина стороны AB, из которой выходит данная диагональ (при ней острый
# угол 60°), W — вторая вершина стороны AB (при ней тупой угол 120°).
_БУКВЫ = {
    'A': dict(V='A', W='B', диаг='AC', VO='AO', тр='AHO', HVO='HAO',
              углV='BAD', углW='ABC', углV_оп='BCD', углW_оп='ADC'),
    'B': dict(V='B', W='A', диаг='BD', VO='BO', тр='BHO', HVO='HBO',
              углV='ABC', углW='BAD', углV_оп='ADC', углW_оп='BCD'),
}


def _ромб_по_углу(вершина, градусов):
    """Ромб ABCD со стороной 1 и углом `градусов` при вершине A или B."""
    a = math.radians(градусов)
    if вершина == 'A':
        A, D = (0.0, 0.0), (1.0, 0.0)
        B = (math.cos(a), math.sin(a))
        C = (B[0] + D[0], B[1] + D[1])
    else:
        B, A = (0.0, 0.0), (1.0, 0.0)
        C = (math.cos(a), math.sin(a))
        D = (A[0] + C[0], A[1] + C[1])
    return A, B, C, D


def _это_ромб(A, B, C, D):
    s = расстояние(A, B)
    for P, Q in ((B, C), (C, D), (D, A)):
        assert abs(расстояние(P, Q) - s) < 1e-9 * max(1.0, s), 'это не ромб'
    return s


def _шаги(список):
    return ''.join('<p>%d. %s</p>' % (i + 1, т) for i, т in enumerate(список))


