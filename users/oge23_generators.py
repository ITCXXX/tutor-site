# №23, тип 4 — высота к гипотенузе по катету и гипотенузе.
# ────────────────────────────────────────────────────────────────────────
#
# Банк (5 задач, все дословно одинаковые): «Катет и гипотенуза прямоугольного
# треугольника равны a и c. Найдите высоту, проведённую к гипотенузе».
# Решение банка: ABC с прямым углом A, AB = a, BC = c, высота AH; второй катет
# по Пифагору через (c − a)(c + a), затем площадь двумя способами:
# AB·AC = BC·AH, AH = a·b/c.
#
# Семейство (TYPES.md): примитивная тройка (a0, b0, c0) и множитель k;
# a = k·a0 — данный катет (в банке всегда меньший), c = k·c0, скрытый
# катет b = k·b0. Ответ h = k·a0·b0/c0; после сокращения знаменатель делит
# нечётное c0, поэтому конечная десятичная дробь получается только когда
# c0/gcd(k, c0) — степень пятёрки. Три из пяти задач банка этому не
# удовлетворяют (240/13, 360/17, 240/17) и оставлены с пустым полем ответа —
# для числового поля такие пары исключаем. Дополнительно требуем не больше
# двух знаков после запятой, как в банке (33,6; 20,16): это отсекает
# (44, 117, 125)·1 → 41,184.


МАКС_ГИПОТЕНУЗА = 170        # банк: 34…125; (5,12,13)·13 = 169 даёт красивое 60
МИН_КАТЕТ = 12               # банк: 16…35
МАКС_КАТЕТ = 66              # иначе 3-4-5 разгоняется до 102 при c = 170
МИН_ГИПОТЕНУЗА = 30


def _примитивные_тройки(макс_c):
    """(a0, b0, c0), a0 < b0, по формулам Евклида."""
    тройки = []
    m = 2
    while m * m + 1 <= макс_c:
        for n in range(1, m):
            if (m - n) % 2 == 0 or math.gcd(m, n) != 1:
                continue
            c0 = m * m + n * n
            if c0 > макс_c:
                break
            x, y = m * m - n * n, 2 * m * n
            тройки.append((min(x, y), max(x, y), c0))
        m += 1
    return тройки


def _семейства():
    """{(a0, b0, c0): [(a, b, c, h), …]} — все пары «катет, гипотенуза» с ответом
    в виде конечной десятичной дроби не длиннее двух знаков."""
    семейства = {}
    for a0, b0, c0 in _примитивные_тройки(МАКС_ГИПОТЕНУЗА):
        k = 1
        while k * c0 <= МАКС_ГИПОТЕНУЗА:
            a, b, c = k * a0, k * b0, k * c0
            h = Fraction(a * b, c)
            if (МИН_КАТЕТ <= a <= МАКС_КАТЕТ and c >= МИН_ГИПОТЕНУЗА
                    and h.denominator in (1, 5, 25)):
                семейства.setdefault((a0, b0, c0), []).append((a, b, c, h))
            k += 1
    return семейства


СЕМЕЙСТВА = _семейства()
# Получается три семейства: (3,4,5)·k при k = 6…22, (7,24,25)·k при k = 2…6
# и (5,12,13)·13. Выбираем семейство с весом √(число вариантов), чтобы
# тройка 3-4-5 не забивала остальные, а потом вариант — равновероятно.
_КЛЮЧИ = sorted(СЕМЕЙСТВА)
_ВЕСА = [math.sqrt(len(СЕМЕЙСТВА[k])) for k in _КЛЮЧИ]


def _пересечение_окружностей(O1, r1, O2, r2):
    """Точка пересечения двух окружностей, лежащая слева от направления O1→O2."""
    d = расстояние(O1, O2)
    l = (r1 * r1 - r2 * r2 + d * d) / (2 * d)
    hh = math.sqrt(max(0.0, r1 * r1 - l * l))
    ex, ey = (O2[0] - O1[0]) / d, (O2[1] - O1[1]) / d
    return (O1[0] + l * ex - hh * ey, O1[1] + l * ey + hh * ex)


def _квадратные_множители(u, v):
    """Разложение √(u·v) на множители, когда u·v — полный квадрат.

    g = gcd(u, v); частные u/g и v/g взаимно просты, а их произведение —
    квадрат, поэтому каждое из них квадрат: u = g·p², v = g·q². Значит,
    u·v = (g·p·q)². Возвращает множители g, p, q без единиц и без повторов
    (повторяющиеся перемножаются), чтобы в решении не появлялось
    «4^2 · 3^2 · 4^2». Нужно, чтобы корень в решении извлекался на глазах у
    ученика, как в банке («90 · 160 = 3² · 4² · 10²»), а не объявлялся
    готовым числом.
    """
    g = math.gcd(u, v)
    p, q = math.isqrt(u // g), math.isqrt(v // g)
    assert p * p * g == u and q * q * g == v, 'u·v не полный квадрат'
    множители = []
    for x in (g, p, q):
        if x == 1:
            continue
        if x in множители:
            множители[множители.index(x)] *= x
        else:
            множители.append(x)
    return множители


def _вершина_прямого_угла(B, C, a):
    """Вершина A прямого угла: AB = a, а сам угол A прямой — значит, A лежит на
    окружности с диаметром BC (теорема Фалеса). Никакого второго катета и
    никакой высоты здесь не считаем."""
    M = середина(B, C)
    return _пересечение_окружностей(B, a, M, расстояние(B, C) / 2.0)


