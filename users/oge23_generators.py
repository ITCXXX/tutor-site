# Тип 19 (№23). Окружность с центром O на стороне AC треугольника ABC проходит
# ────────────────────────────────────────────────────────────────────────
#
# через вершину C и касается прямой AB в точке B. Даны диаметр d и AB, найти AC.
#
# Ядро — прямоугольный треугольник ABO: OB — радиус в точку касания, поэтому
# OB ⟂ AB. По Пифагору AO = √(AB² + r²), r = d/2, и AC = AO + OC = AO + r,
# потому что O лежит на отрезке AC.
#
# Числа. (AB, r, AO) — пифагорова тройка (a, b, c), растянутая в k раз;
# AB = k·a, d = 2k·b, AC = k·(b + c). В банке k ∈ {1, 1/2, 1/5, 2/5}, AB — любой
# из катетов, ответ всегда целый. Масштаб берём любой кратный 0,1: при целых
# a, b, c это ровно то условие, при котором AB, d и AO записываются не более чем
# одной цифрой после запятой. Тройки — примитивные с m ≤ 8 (гипотенуза до 113);
# из них оставляем варианты с целым AC и числами рядом с банковскими: 2 ≤ AB ≤ 20
# (в банке 4…15), 1 ≤ d ≤ 24 (в банке 3,6…16), 5 ≤ AC ≤ 30 (в банке 10…25).
# Остаётся 28 наборов и 13 разных ответов; вариант берётся из плоского списка
# равновероятно.
#
# Пять опубликованных наборов самого банка из пула выброшены: формулировка здесь
# дословно банковская и отличается от опубликованных задач только числами, а
# повторять условие с известным ответом незачем.


МАКС_МАСШТАБ = 30               # k = j/10, j = 1…30

# Наборы (AB, d) пяти задач банка — в пул не идут.
БАНКОВСКИЕ = {
    (Fraction(4), Fraction(42, 5)),     # D5F808: d = 8,4;  AB = 4  → 10
    (Fraction(15), Fraction(16)),       # C911B9: d = 16;   AB = 15 → 25
    (Fraction(6), Fraction(32, 5)),     # F6CC6F: d = 6,4;  AB = 6  → 10
    (Fraction(4), Fraction(15)),        # 19BB60: d = 15;   AB = 4  → 16
    (Fraction(8), Fraction(18, 5)),     # F0C3BD: d = 3,6;  AB = 8  → 10
}


def _варианты():
    """Список (AB, d, k, (a, b, c)): AB = k·a — касательная, k·b — радиус, k·c — AO."""
    пул = set()
    for m in range(2, 9):
        for n in range(1, m):
            if (m - n) % 2 == 0 or math.gcd(m, n) != 1:
                continue
            x, y, c = m * m - n * n, 2 * m * n, m * m + n * n
            for a, b in ((x, y), (y, x)):           # какой катет — касательная
                for j in range(1, МАКС_МАСШТАБ + 1):
                    k = Fraction(j, 10)
                    AB, r, AO = k * a, k * b, k * c
                    AC = r + AO
                    if AC.denominator != 1:
                        continue
                    if not (2 <= AB <= 20 and 1 <= 2 * r <= 24 and 5 <= AC <= 30):
                        continue
                    if (AB, 2 * r) in БАНКОВСКИЕ:
                        continue
                    пул.add((AB, 2 * r, k, (a, b, c)))
    return sorted(пул)


ВАРИАНТЫ_19 = _варианты()


def _пересечение_прямой_с_окружностью(P, Q, O, r):
    """Обе точки пересечения прямой PQ с окружностью (O, r), параметр t от P к Q."""
    dx, dy = Q[0] - P[0], Q[1] - P[1]
    fx, fy = P[0] - O[0], P[1] - O[1]
    a = dx * dx + dy * dy
    b = 2 * (fx * dx + fy * dy)
    c = fx * fx + fy * fy - r * r
    D = b * b - 4 * a * c
    if D < 0:
        raise ValueError('прямая не пересекает окружность')
    sD = math.sqrt(D)
    return [(P[0] + t * dx, P[1] + t * dy) for t in ((-b - sD) / (2 * a), (-b + sD) / (2 * a))]


def _координаты(AB, d):
    """B в начале координат, касательная AB — ось x, центр O — на перпендикуляре в B."""
    r = float(d) / 2
    B, A, O = (0.0, 0.0), (float(AB), 0.0), (0.0, r)
    # C — та точка пересечения прямой AO с окружностью, для которой O лежит между A и C.
    for P in _пересечение_прямой_с_окружностью(A, O, O, r):
        if abs(расстояние(A, O) + расстояние(O, P) - расстояние(A, P)) < 1e-9:
            C = P
            break
    else:
        raise ValueError('центр не попал на отрезок AC')
    return A, B, C, O, r


