# Семейство чисел. Чтобы AH·AC было точным квадратом, берём AH = q²·t,
# AC = p²·t при взаимно простых p > q: тогда AB = p·q·t — целое. Банк
# использует только q = 1, p ∈ {2, 3} (пары вроде (3, 27), (6, 24)); этот
# случай идёт с наибольшим весом, а (4,1), (3,2), (5,2), (4,3) добавлены для
# разнообразия — решение ученика от них не меняется.
