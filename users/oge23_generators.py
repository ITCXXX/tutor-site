def расстояние(A, B):
    return math.hypot(A[0] - B[0], A[1] - B[1])


def расстояние_до_прямой(P, A, B):
    """От точки P до прямой AB."""
    H = проекция(A, B, P)
    return расстояние(P, H)


def угол(A, B, C):
    """Угол ABC в градусах."""
    ux, uy = A[0] - B[0], A[1] - B[1]
    vx, vy = C[0] - B[0], C[1] - B[1]
    c = (ux * vx + uy * vy) / (math.hypot(ux, uy) * math.hypot(vx, vy))
    return math.degrees(math.acos(max(-1.0, min(1.0, c))))


def центр_описанной(A, B, C):
    ax, ay = A
    bx, by = B
    cx, cy = C
    d = 2 * (ax * (by - cy) + bx * (cy - ay) + cx * (ay - by))
    ux = ((ax * ax + ay * ay) * (by - cy) + (bx * bx + by * by) * (cy - ay)
          + (cx * cx + cy * cy) * (ay - by)) / d
    uy = ((ax * ax + ay * ay) * (cx - bx) + (bx * bx + by * by) * (ax - cx)
          + (cx * cx + cy * cy) * (bx - ax)) / d
    return (ux, uy)


def центр_вписанной(A, B, C):
    a, b, c = расстояние(B, C), расстояние(A, C), расстояние(A, B)
    p = a + b + c
    return ((a * A[0] + b * B[0] + c * C[0]) / p, (a * A[1] + b * B[1] + c * C[1]) / p)


def точка_биссектрисы(B, A, C, длина=1.0):
    """Точка на биссектрисе угла ABC на расстоянии `длина` от B."""
    ux, uy = A[0] - B[0], A[1] - B[1]
    vx, vy = C[0] - B[0], C[1] - B[1]
    nu, nv = math.hypot(ux, uy), math.hypot(vx, vy)
    dx, dy = ux / nu + vx / nv, uy / nu + vy / nv
    n = math.hypot(dx, dy)
    return (B[0] + dx / n * длина, B[1] + dy / n * длина)


def поворот(P, центр, градусов):
    a = math.radians(градусов)
    x, y = P[0] - центр[0], P[1] - центр[1]
    return (центр[0] + x * math.cos(a) - y * math.sin(a),
            центр[1] + x * math.sin(a) + y * math.cos(a))


def площадь(*точки):
    """Площадь многоугольника по вершинам (формула шнурков)."""
    s = 0.0
    for i in range(len(точки)):
        x1, y1 = точки[i]
        x2, y2 = точки[(i + 1) % len(точки)]
        s += x1 * y2 - x2 * y1
    return abs(s) / 2.0


