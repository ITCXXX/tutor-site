# Числа держим у банковских: в банке AH от 3 до 10, AC от 12 до 45, ответ от 6
# до 20. Здесь AH от 3 до 12, AC от 12 до 48, ответ от 6 до 24 — все 10
# банковских пар воспроизводятся, а выход за их край не больше чем на один шаг.
# Проверяются границы явно (_AH_MIN … _AC_MAX), а не подбором пределов для t:
# раньше сюда пролезали AH = 2 и AH = 27 при AC = 54, то есть втрое крупнее
# банковских.


# Границы чисел условия — рядом с банковскими (см. заголовок модуля).
_AH_MIN, _AH_MAX = 3, 12
_AC_MIN, _AC_MAX = 12, 48

_ОТНОШЕНИЯ = ((2, 1), (3, 1), (4, 1), (3, 2), (5, 2), (4, 3))


def _наборы():
    """Все допустимые (p, q, t) со своими весами.

    Вес ставим не отношению, а каждому набору чисел: у (2,1) допустимых t
    десять, а у (4,3) ровно один, и общий вес на отношение сделал бы редкую
    пару (9, 16) вдвое вероятнее любой банковской. Банковские отношения
    (q = 1, p ∈ {2, 3}) идут с весом 2, остальные — с весом 1; получается
    ≈84 % банковских наборов, и ни один набор не берёт больше 7 %.
    """
    наборы = []
    for p, q in _ОТНОШЕНИЯ:
        допустимые = [t for t in range(1, 13)
                      if _AH_MIN <= q * q * t <= _AH_MAX
                      and _AC_MIN <= p * p * t <= _AC_MAX]
        # Отношение без единого подходящего t — опечатка в _ОТНОШЕНИЯ;
        # пусть она вылезет при импорте, а не на редком сиде.
