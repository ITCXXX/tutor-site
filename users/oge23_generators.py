        # прямая CD на нужном расстоянии от центра.
        assert abs(расстояние(O, B) - R_) < 1e-9
        assert abs(расстояние(O, C) - R_) < 1e-9 and abs(расстояние(O, D) - R_) < 1e-9
        assert abs(расстояние_до_прямой(O, C, D) - float(d2)) < 1e-9
