# ────────────────────────────────────────────────────────────────────────
# Тип 9 (№23). Биссектрисы углов при боковой стороне трапеции: AB через AF и BF.
# ────────────────────────────────────────────────────────────────────────
#
# Трапеция ABCD с основаниями AD и BC; биссектрисы углов A и B пересекаются
# в точке F, даны AF и BF. Углы A и B — односторонние при параллельных AD и BC,
# в сумме 180°, поэтому их половины в сумме дают 90° и ∠AFB = 90°. AB —
# гипотенуза прямоугольного треугольника AFB: AB = √(AF² + BF²).
#
# Ответ целый, когда (BF, AF, AB) — пифагорова тройка. Как в банке, AF — больший
# катет (угол A острый, угол B тупой); AF = BF не берём — ответ AF·√2. Пул:
# примитивные тройки и их кратные с гипотенузой от 13 до 50 (в банке от 13
# до 40). Сначала выбирается семейство (примитивная тройка), потом множитель.
# Вес семейства — корень из числа его множителей: при равных весах семейств
# каждое кратное 3-4-5 (их восемь) выпадало бы в восемь раз реже одиночной
# тройки 20-21-29, а при весе, равном числу множителей, семейство 3-4-5
# заняло бы почти половину выборки.
#
# Основания в условии не даны и на ответ не влияют. check строит трапецию
# со случайными (своими для каждого сида) основаниями, лишь бы F лежала
# внутри неё, и измеряет AB, не зная формулы: угол A подбирается бисекцией
# по измеренному отношению BF/AF.


МИН_AB = 13      # минимум банка: AF = 12, BF = 5, AB = 13
МАКС_AB = 50     # банк доходит до 40; выше двузначных не поднимаемся


def _пул_троек_9():
    """(AF, BF, гип, k_min, k_max): примитивная тройка, AF — больший катет.

    Годятся те множители k, при которых гипотенуза кратной тройки k·гип
    попадает в банковский диапазон [МИН_AB; МАКС_AB]; если не годится ни
    один (гип > МАКС_AB), семейство отбрасывается целиком.
    """
    пул = []
    for m in range(2, 8):
        for n in range(1, m):
            if math.gcd(m, n) != 1 or (m - n) % 2 == 0:
                continue
            катеты = sorted((m * m - n * n, 2 * m * n))
            гип = m * m + n * n
            k_min = -(-МИН_AB // гип)      # ceil(МИН_AB / гип)
            k_max = МАКС_AB // гип
            if k_min > k_max:
                continue
            пул.append((катеты[1], катеты[0], гип, k_min, k_max))
    return sorted(пул)


ПУЛ_9 = _пул_троек_9()
