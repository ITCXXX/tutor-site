        '\\(CD = DH + CH = %d + %d = %d\\). У ромба все стороны равны, значит, '
        '\\(AD = CD = %d\\).</p>'
        '<p>2. \\(AH\\) — высота ромба, то есть \\(AH \\perp CD\\). Поэтому треугольник '
        '\\(AHD\\) прямоугольный с прямым углом при вершине \\(H\\): гипотенуза '
