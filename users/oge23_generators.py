    def построить(a, c):
        """Треугольник с катетами BA = a, BC = c, повёрнутый на угол `поворот`.
        Возвращает точки B, A, C, H, P, K."""
        B = (0.0, 0.0)
        A = (a * math.cos(поворот), a * math.sin(поворот))
        C = (-c * math.sin(поворот), c * math.cos(поворот))
        H = проекция(A, C, B)
        O = середина(B, H)
        r = расстояние(O, B)

        def второе_пересечение(X):
            # Прямая B + t·(X − B) с окружностью (O, r): B + t·d, |B + t·d − O|² = r².
            # Один корень — t = 0 (само B); нужен другой. Уравнение решается как
            # общее квадратное, корень с наибольшим |t| — вторая точка.
            dx, dy = X[0] - B[0], X[1] - B[1]
