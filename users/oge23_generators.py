def _трапеция(AD, BC, h, x0, угол=0.0):
    """Вершины A, B, C, D трапеции с основаниями AD и BC; фигура повёрнута на `угол`."""
    A, D = (0.0, 0.0), (float(AD), 0.0)
    B, C = (x0, h), (x0 + BC, h)
    if угол:
        центр = (AD / 2.0, h / 2.0)
        A, B, C, D = (поворот(P, центр, угол) for P in (A, B, C, D))
    return A, B, C, D


def _точки_E_F(A, B, C, D, m, n):
    """F на CD с CF : FD = m : n; E — пересечение прямой через F ∥ AD со стороной AB."""
    t = m / float(m + n)
    F = (C[0] + t * (D[0] - C[0]), C[1] + t * (D[1] - C[1]))
    F2 = (F[0] + (D[0] - A[0]), F[1] + (D[1] - A[1]))      # вторая точка прямой EF
    E = пересечение(A, B, F, F2)
    return E, F


