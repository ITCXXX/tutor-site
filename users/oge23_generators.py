def _внутри(P, многоугольник):
    """Точка строго внутри выпуклого многоугольника (вершины по порядку обхода)."""
    n = len(многоугольник)
    знаки = []
    for i in range(n):
        x1, y1 = многоугольник[i]
        x2, y2 = многоугольник[(i + 1) % n]
        знаки.append((x2 - x1) * (P[1] - y1) - (y2 - y1) * (P[0] - x1))
    return all(s > 1e-9 for s in знаки) or all(s < -1e-9 for s in знаки)


