# Тип 1. Отрезок диагонали трапеции через подобие
# ──────────────────────────────────────────────────────────────────────────
#
# AB ∥ DC, диагонали AC и BD пересекаются в M. Треугольники ABM и CDM подобны
# (вертикальные углы и накрест лежащие при параллельных), поэтому
# AM : MC = AB : DC, и MC = AC·DC/(AB + DC).
#
# Чтобы ответ был целым, берём коэффициент подобия p/q несократимым и
# AC кратным (p + q): AB = q·s, DC = p·s, AC = (p + q)·t, тогда MC = p·t.
# Порядок букв как в банке: «отрезки AB и DC лежат на параллельных прямых,
# AC и BD пересекаются в M».

@тип(1)
def _тип_1(rng):
    while True:
        p, q = rng.randint(2, 6), rng.randint(1, 4)
        if p != q and math.gcd(p, q) == 1:
            break
    s = rng.randint(2, 9)
    t = rng.randint(3, 12)
    AB, DC, AC = q * s, p * s, (p + q) * t
    MC = Fraction(AC * DC, AB + DC)          # = p·t

    условие = (
        '<p>Отрезки \\(AB\\) и \\(DC\\) лежат на параллельных прямых, а отрезки '
        '\\(AC\\) и \\(BD\\) пересекаются в точке \\(M\\). Найдите \\(MC\\), если '
        '\\(AB = %d\\), \\(DC = %d\\), \\(AC = %d\\).</p>' % (AB, DC, AC))

    решение = (
        '<p>1. \\(AB \\parallel DC\\), поэтому \\(\\angle BAM = \\angle DCM\\) как накрест '
        'лежащие при секущей \\(AC\\), а \\(\\angle AMB = \\angle CMD\\) как вертикальные. '
        'Значит, \\(\\triangle ABM \\sim \\triangle CDM\\) по двум углам.</p>'
        '<p>2. Из подобия \\(\\dfrac{AM}{MC} = \\dfrac{AB}{DC} = \\dfrac{%d}{%d} = '
        '\\dfrac{%d}{%d}\\).</p>'
        '<p>3. Точка \\(M\\) лежит на отрезке \\(AC\\), поэтому \\(AM + MC = AC = %d\\). '
        'Отрезок \\(AC\\) делится в отношении \\(%d : %d\\), то есть на \\(%d\\) равных '
        'частей по \\(%d\\); на \\(MC\\) приходится \\(%d\\) таких частей:</p>'
        '\\[MC = \\frac{%d}{%d + %d} \\cdot %d = %s.\\]'
        % (AB, DC, q, p, AC, q, p, p + q, t, p, p, p, q, AC, num_latex(MC)))

    def check():
        # Строим трапецию в координатах и пересекаем диагонали.
        A, B = (0.0, 0.0), (float(AB), 0.0)
        h = 3.7
        сдвиг = 1.3
        D, C = (сдвиг, h), (сдвиг + DC, h)
        # Масштабируем так, чтобы AC стало равным заданному.
        k = AC / расстояние(A, C)
        B, C, D = tuple((x * k, y * k) for x, y in (B, C, D))
        M = пересечение(A, C, B, D)
        return расстояние(M, C)

    # Высоту и свес берём от ширины фигуры: при AB = 9 и DC = 45 фиксированная
    # высота 3,7 сплющивала трапецию в почти сплошную линию, а точки B и M
    # сливались.
    ширина = float(max(AB, DC))
    ч = Чертёж()
    A, B = (0.0, 0.0), (float(AB), 0.0)
    D, C = (0.28 * ширина, 0.5 * ширина), (0.28 * ширина + DC, 0.5 * ширина)
    M = пересечение(A, C, B, D)
    ч.отрезок(A, B); ч.отрезок(D, C)
    ч.отрезок(A, C, вспомогательный=True); ч.отрезок(B, D, вспомогательный=True)
    подписать_вершины(ч, (A, 'A', 'юз'), (B, 'B', 'юв'), (C, 'C', 'св'), (D, 'D', 'сз'), (M, 'M', 'в'))

    return {
        'statement_html': условие,
        'answer': num(MC),
        'answer_kind': 'number',
        'answer_value': MC,
        'allow_fractions': False,
        'solution_html': решение,
        'params': {'AB': AB, 'DC': DC, 'AC': AC, 'p': p, 'q': q},
        'check': check,
        'figure': ч,
    }


