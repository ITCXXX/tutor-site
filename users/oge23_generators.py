def _точка_B(AH, AC):
    """
    Вершина прямого угла в координатах: A = (0, 0), C = (AC, 0), H = (AH, 0).

    Угол B прямой тогда и только тогда, когда B лежит на окружности с
    диаметром AC (теорема Фалеса); высота BH ⟂ AC — значит, B лежит на
    перпендикуляре к AC в точке H. Пересекаем перпендикуляр с окружностью.
    Формула ответа здесь не используется.
    """
    R = AC / 2.0
    Ox = R
    y2 = R * R - (AH - Ox) ** 2
    if y2 <= 0:
        raise ValueError('H вне отрезка AC: AH=%s, AC=%s' % (AH, AC))
    return (float(AH), math.sqrt(y2))


