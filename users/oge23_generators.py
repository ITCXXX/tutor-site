ПАРЫ_10 = [(30, 120), (30, 135), (45, 120), (45, 150), (60, 135), (60, 150)]
ДЕЛИТЕЛЬ = {30: 1, 45: 2, 60: 3}
# sin α = √m / 2 для табличных острых углов.
ПОДКОРЕННОЕ = {30: 1, 45: 2, 60: 3}


def _корень(коэф, m):
    """коэф·√m в LaTeX без десятичных: 34\\sqrt{3}, 34, \\sqrt{2}; радикал упрощается."""
    k, r = упростить_корень(m)
    коэф *= k
    if r == 1:
        return '%d' % коэф
    if коэф == 1:
        return '\\sqrt{%d}' % r
    return '%d\\sqrt{%d}' % (коэф, r)


def _половина(m):
    """√m / 2 в LaTeX: 1/2, √2/2, √3/2."""
    return '\\frac{1}{2}' if m == 1 else '\\frac{\\sqrt{%d}}{2}' % m


def _высота_латех(CD, m):
    """CD·√m/2 в LaTeX: 17\\sqrt{3}, \\frac{25\\sqrt{3}}{2}, 16, \\frac{33}{2}."""
    if CD % 2 == 0:
        return _корень(CD // 2, m)
    return '\\frac{%s}{2}' % _корень(CD, m)


