#
# Решение банка: KBCP — вписанный четырёхугольник, ∠PKB + ∠BCP = 180°; ∠AKP
# смежный с ∠PKB, поэтому ∠AKP = ∠ACB. Угол A общий ⇒ △APK ∼ △ABC по двум
# углам с соответствием A→A, P→B, K→C. Из AK/AC = KP/BC: KP = AK·BC/AC = AK/k.
#
# Семейство параметров. Свободные — целый ответ KP и k = m/10 с одним знаком
# после запятой (m ∈ {12, 14, 15, 16, 18, 20, 25, 30}); AK = KP·k обязано быть
# целым, поэтому сначала выбирается m, потом KP из тех, для которых 10 | KP·m,
# и AK ≤ 40 (в банке AK ≤ 18, KP ≤ 15). Треугольник условием не задан — ответ
# от него не зависит; check строит случайный допустимый треугольник и проводит
# настоящую окружность через B, C, K.
#
# Ограничения на треугольник для построения (BC = b, AC = k·b, AB = c):
#   b(k−1) < c < b(k+1)   — неравенство треугольника;
#   AK < c                — K на стороне AB;
#   AK·c < (k·b)²         — P на стороне AC, а не на продолжении (степень точки:
#                           AP = AK·AB/AC < AC).


# k = m/10; значения банка (12, 14, 15, 16, 20) повторены, чтобы встречаться чаще.
ЗНАМЕНАТЕЛИ_K = (12, 12, 14, 14, 15, 15, 16, 16, 18, 20, 20, 25, 30)
МАКС_AK = 40


def _треугольник_17(AK, k, s, t):
    """
    Треугольник ABC в координатах: A = (0, 0), C на оси x, B в верхней
    полуплоскости; BC = s·AK, AC = k·BC, AB — точка с долей t внутри
    допустимого интервала. Возвращает A, B, C и K (на AB, AK от A).
    """
    b = s * AK
    AC = k * b
    lo = max(b * (k - 1), float(AK))
    hi = min(b * (k + 1), AC * AC / AK)
    assert lo < hi, 'нет допустимого AB: %s ≥ %s' % (lo, hi)
    c = lo + (hi - lo) * t
    A, C = (0.0, 0.0), (AC, 0.0)
    xB = (c * c + AC * AC - b * b) / (2 * AC)
    yB = math.sqrt(max(c * c - xB * xB, 0.0))
    B = (xB, yB)
    K = (B[0] * AK / c, B[1] * AK / c)
    return A, B, C, K


def _второе_пересечение(O, R, A, C):
    """Точка пересечения окружности (O, R) с прямой AC, отличная от C."""
    ux, uy = C[0] - A[0], C[1] - A[1]
    L = math.hypot(ux, uy)
    ux, uy = ux / L, uy / L
    px, py = A[0] - O[0], A[1] - O[1]
    bb = 2 * (px * ux + py * uy)
    cc = px * px + py * py - R * R
    дискр = bb * bb - 4 * cc
    if дискр < 0:
        raise ValueError('прямая AC не пересекает окружность')
    корни = ((-bb - math.sqrt(дискр)) / 2, (-bb + math.sqrt(дискр)) / 2)
    точки = [(A[0] + t * ux, A[1] + t * uy) for t in корни]
    # C — одна из точек пересечения; берём другую.
    return max(точки, key=lambda X: расстояние(X, C))


