# -*- coding: utf-8 -*-
"""Признаки позиции: то, из чего складывается оценка.

Зачем отдельный модуль. Оценка была написана слитно — сразу считала число, и
разобрать её на слагаемые было нельзя. Для подбора весов вручную этого хватало:
восемь чисел можно перебрать матчами. Для обучения не хватает: чтобы подогнать
веса по данным, нужен именно ВЕКТОР — сколько раз в позиции встретился каждый
признак, отдельно от того, сколько он стоит.

Поэтому реализация здесь ровно одна, а bot.evaluate стал скалярным произведением
этого вектора на веса. Держать вторую, «быструю» копию оценки было бы дороже,
чем кажется: две реализации всегда расходятся, и расхождение вылезает не в
тесте, а в партии с учеником.

**Все признаки антисимметричны**: вектор(поз, X) == -вектор(поз, O). Это не
украшение, а условие правильности. Негамакс считает оценку глазами того, чья
очередь, и меняет ей знак на каждом уровне; признак, который не переворачивается
вместе с доской, ломает перебор незаметно — бот начинает предпочитать позиции
по признаку «я играю за крестики». Тест это проверяет.

Почему признаков стало больше восьми. Замеры показали, что руками их добавлять
бесполезно: на глубине 5 перебор и так видит всю тактику, которую мы пытаемся
объяснить. Смысл появляется, когда веса подбираются НЕ матчами. Матч различает
перевес в 2% примерно за 2500 партий, поэтому восемь чисел стоили восьми часов,
а сотню так не подобрать никогда. Обучение на исходах самоигры подгоняет сотни
коэффициентов за минуты — и вот тогда богатый набор начинает окупаться.

Про цену. Признаки, требующие отдельного прохода по доске, здесь не заводятся:
всё считается в тех же циклах, что и раньше. «Есть ли у игрока пара в поле» —
это ровно то, что уже подсчитано при подсчёте пар, поэтому оно бесплатно.
Лишний проход стоил бы полухода глубины, а полуход дороже любого признака.
"""

from .engine import WINNING_LINES

# Словарь доски живёт здесь, а не в bot.py, чтобы импорт шёл в одну сторону:
# оценка не может не знать про признаки, а признаки про перебор знать не должны.
EMPTY, X, O, DRAW = 0, 1, 2, 3

# Линии, проходящие через клетку — чтобы после хода проверять не все восемь.
LINES_THROUGH = [[line for line in WINNING_LINES if i in line] for i in range(9)]

# Вес малого поля в большом: центр входит в четыре линии, угол в три, бок в две.
BOARD_WEIGHT = (3, 2, 3,
                2, 4, 2,
                3, 2, 3)

# То же внутри малого поля — центр и углы ценнее боков.
CELL_WEIGHT = (3, 2, 3,
               2, 4, 2,
               3, 2, 3)

# Углы малого поля: центр уже есть отдельным признаком, бока пусть остаются
# нулевой точкой отсчёта — иначе три признака описывали бы девять клеток дважды.
УГЛЫ = (0, 2, 6, 8)

# Порядок важен: в этом же порядке идут числа в векторе и столбцы в обучении.
# Первые восемь — те, что были в оценке всегда; их веса подобраны матчами, и
# менять смысл имён нельзя, иначе прежние наборы весов станут враньём.
ПРИЗНАКИ = (
    'поле',
    'поле_центр',
    'большая_пара',
    'большая_одна',
    'малая_пара',
    'малая_одна',
    'малый_центр',
    'свободный_выбор',
    # Дальше — новые. Пока их веса нули, оценка не меняется вовсе.
    'поле_ровно_центр',
    'малый_угол',
    'цель_моя_пара',
    'цель_чужая_пара',
    'решающая_пара',
    'угроза_пары',
    'ход',
    'ничьи_в_плюс',
)

ЧИСЛО_ПРИЗНАКОВ = len(ПРИЗНАКИ)


def разбор_линий(значения, me, foe, ничья_губит):
    """Линии из трёх: (мои пары, мои одиночки, чужие пары, чужие одиночки).

    Линия живёт для игрока, только пока в ней нет ничего чужого. Для большого
    поля «чужое» — это и ничейные поля: такую линию уже никто не достроит, и
    платить за пару в ней не за что.

    Ветки взаимоисключающие: линия, где есть и мои значения, и чужие, мертва
    для обоих.
    """
    мп = мо = чп = чо = 0
    for a, b, c in WINNING_LINES:
        va, vb, vc = значения[a], значения[b], значения[c]
        if ничья_губит:
            моя = ((va == EMPTY or va == me) and (vb == EMPTY or vb == me)
                   and (vc == EMPTY or vc == me))
            чужая = ((va == EMPTY or va == foe) and (vb == EMPTY or vb == foe)
                     and (vc == EMPTY or vc == foe))
        else:
            моя = not (va == foe or vb == foe or vc == foe)
            чужая = not (va == me or vb == me or vc == me)
        if моя:
            n = (va == me) + (vb == me) + (vc == me)
            if n == 2:
                мп += 1
            elif n == 1:
                мо += 1
        elif чужая:
            n = (va == foe) + (vb == foe) + (vc == foe)
            if n == 2:
                чп += 1
            elif n == 1:
                чо += 1
    return мп, мо, чп, чо


def _ценность_взятия(доски, i, кто):
    """Что даст выигрыш поля i игроку `кто`: (выигрышей партии, новых пар).

    Считаются только живые линии — без чужих полей и без ничьих.
    """
    решающих = пар = 0
    for a, b, c in LINES_THROUGH[i]:
        va, vb, vc = доски[a], доски[b], доски[c]
        if not ((va == EMPTY or va == кто) and (vb == EMPTY or vb == кто)
                and (vc == EMPTY or vc == кто)):
            continue
        свои = (va == кто) + (vb == кто) + (vc == кто)
        if свои == 2:
            решающих += 1
        elif свои == 1:
            пар += 1
    return решающих, пар


def вектор(поз, me):
    """Признаки позиции глазами игрока `me`, в порядке ПРИЗНАКИ."""
    foe = O if me == X else X
    доски = поз.boards
    клетки = поз.cells

    поле = поле_центр = 0
    for i in range(9):
        v = доски[i]
        if v == me:
            поле += 1
            поле_центр += BOARD_WEIGHT[i]
        elif v == foe:
            поле -= 1
            поле_центр -= BOARD_WEIGHT[i]

    бмп, бмо, бчп, бчо = разбор_линий(доски, me, foe, True)

    малая_пара = малая_одна = малый_центр = малый_угол = 0
    решающая_пара = угроза_пары = 0
    цель = поз.next_local
    свободно = цель is None or доски[цель] != EMPTY
    цель_моя_пара = цель_чужая_пара = 0

    for i in range(9):
        if доски[i] != EMPTY:
            continue
        база = i * 9
        малое = клетки[база:база + 9]
        вес = BOARD_WEIGHT[i]

        мп, мо, чп, чо = разбор_линий(малое, me, foe, False)
        малая_пара += (мп - чп) * вес
        малая_одна += (мо - чо) * вес

        центр = малое[4]
        if центр == me:
            малый_центр += вес
        elif центр == foe:
            малый_центр -= вес
        for у in УГЛЫ:
            к = малое[у]
            if к == me:
                малый_угол += вес
            elif к == foe:
                малый_угол -= вес

        # Взаимодействие уровней: пара внутри поля стоит тем больше, чем важнее
        # само поле в большом. «мп > 0» уже посчитано выше — даром.
        if мп:
            решающих, новых = _ценность_взятия(доски, i, me)
            if решающих:
                решающая_пара += 1
            elif новых:
                угроза_пары += 1
        if чп:
            решающих, новых = _ценность_взятия(доски, i, foe)
            if решающих:
                решающая_пара -= 1
            elif новых:
                угроза_пары -= 1

        # Поле, куда обязан ходить соперник или я. Пара здесь особенная: её
        # можно закрыть прямо сейчас, а не когда-нибудь.
        if not свободно and i == цель:
            if поз.turn == me:
                цель_моя_пара = 1 if мп else 0
                цель_чужая_пара = 1 if чп else 0
            else:
                цель_моя_пара = -1 if чп else 0
                цель_чужая_пара = -1 if мп else 0

    знак_хода = 1 if поз.turn == me else -1

    ничьих = 0
    for v in доски:
        if v == DRAW:
            ничьих += 1
    ничьи_в_плюс = 0
    if ничьих and поле:
        ничьи_в_плюс = ничьих if поле > 0 else -ничьих

    центр_поля = доски[4]
    return (
        поле,
        поле_центр,
        бмп - бчп,
        бмо - бчо,
        малая_пара,
        малая_одна,
        малый_центр,
        знак_хода if свободно else 0,
        1 if центр_поля == me else -1 if центр_поля == foe else 0,
        малый_угол,
        цель_моя_пара,
        цель_чужая_пара,
        решающая_пара,
        угроза_пары,
        знак_хода,
        ничьи_в_плюс,
    )


def кортеж_весов(веса):
    """Веса словарём -> кортеж в порядке ПРИЗНАКИ. Отсутствующие — нули."""
    return tuple(float(веса.get(имя, 0.0)) for имя in ПРИЗНАКИ)


def оценка(поз, me, веса):
    """Скалярное произведение признаков на веса — то же, что bot.evaluate."""
    в = вектор(поз, me)
    w = кортеж_весов(веса)
    return sum(в[k] * w[k] for k in range(ЧИСЛО_ПРИЗНАКОВ))
