# -*- coding: utf-8 -*-
"""Подбор весов оценки самоигрой: отбор вместо угадывания.

Идея та самая, «как эволюция». Берём нынешнего бота чемпионом, делаем от него
несколько слегка изменённых потомков, каждый играет матч против чемпиона.
Потомок, который обыграл его убедительно, сам становится чемпионом. Дальше по
кругу. Проигравшие исчезают.

Три вещи, без которых такой отбор даёт ноль или уводит в сторону.

**Убедительно — значит с запасом на погрешность.** В матче из двухсот партий
счёт 105:95 не значит ничего. Потомок сменяет чемпиона, только если перевес
больше доверительного интервала: иначе отбор пойдёт за шумом и будет гулять
случайно, изображая прогресс.

**Родня — не соперник.** Бот, которого отбирали только против его потомков,
становится мастером по обыгрыванию родни и может при этом ослабеть против
всех прочих. Поэтому каждые несколько поколений чемпион играет «перчатку»
против неподвижных соперников, и её результат пишется в журнал: если он падает,
отбор пошёл не туда.

**Подбирается быстрое, проверяется настоящее.** Матчи идут на среднем уровне —
там партия занимает десятую долю секунды вместо полутора. Что найдено на
среднем, не обязано работать на сильном, поэтому в конце победителя надо
прогнать `arena --gauntlet --a-weights` уже на сильном уровне.

Запуск (ночь):

    manage.py arena_tune --hours 8

Результат кладётся в games/tuned_weights.json после каждого улучшения — если
счёт прервётся, найденное не пропадёт.
"""

import json
import os
import random
import time

from django.core.management.base import BaseCommand

from games import arena, bot

# Каких весов касаемся. BOARD_WEIGHT — это структура доски, а не настройка,
# и её не трогаем: подбирать надо цены, а не геометрию.
КЛЮЧИ = tuple(sorted(bot.ВЕСА))

ФАЙЛ_ВЕСОВ = 'games/tuned_weights.json'
ФАЙЛ_ЖУРНАЛА = 'games/tuned_weights.log'


class Command(BaseCommand):
    help = 'Подобрать веса оценки УТТТ самоигрой (эволюционный отбор)'

    def add_arguments(self, parser):
        parser.add_argument('--hours', dest='часов', type=float, default=8.0)
        parser.add_argument('--games', dest='партий', type=int, default=200,
                            help='партий в матче потомка с чемпионом')
        parser.add_argument('--children', dest='потомков', type=int, default=4)
        parser.add_argument('--level', dest='уровень', default='medium',
                            help='уровень, на котором идут матчи отбора')
        parser.add_argument('--cores', dest='ядер', type=int, default=None)
        parser.add_argument('--sigma', dest='разброс', type=float, default=0.25,
                            help='сила мутации: доля от текущего значения')
        parser.add_argument('--gauntlet-every', dest='перчатка_каждые',
                            type=int, default=5)

    def handle(self, *args, **п):
        ядер = п['ядер'] or max(1, (os.cpu_count() or 2) - 1)
        rng = random.Random(20260906)
        конец = time.time() + п['часов'] * 3600

        чемпион = dict(bot.ВЕСА)
        поколение = 0
        улучшений = 0

        соперники = [
            arena.Игрок('сильный', 'hard'),
            arena.Игрок('средний', 'medium'),
            arena.Игрок('слабый', 'easy'),
        ]

        self._записать('Отбор начат: %d ядер, уровень %s, %d партий в матче, '
                       'потомков %d, до %.1f ч'
                       % (ядер, п['уровень'], п['партий'], п['потомков'], п['часов']))
        self._записать('Стартовые веса: %s' % json.dumps(чемпион, ensure_ascii=False))

        # Замер ДО первого поколения. Без него журнал нечитаем: ровная линия
        # перчатки означает «дальше не растёт», а не «не выросло», — и отличить
        # одно от другого не с чем, потому что рывок обычно приходится на
        # первые же поколения. Один раз это уже стоило разбирательства.
        #
        # И читать перчатку надо с поправкой: слабый соперник даёт треть веса,
        # а на нём все упираются в потолок около 95%, поэтому разница между
        # весами в общей доле выглядит меньше, чем она есть. Настоящую цену
        # показывает прямой матч кандидата против стартовых весов на одном
        # уровне — им и надо проверять победителя.
        _, начальная = arena.перчатка(
            arena.игрок_из_весов('старт', чемпион, п['уровень']),
            соперники, партий=60, ядер=ядер, seed=0,
        )
        self._записать('Поколение 0: перчатка против неподвижных — %.1f%%'
                       % (100 * начальная))

        while time.time() < конец:
            поколение += 1
            лучший, лучший_итог = None, None

            for номер in range(п['потомков']):
                if time.time() >= конец:
                    break
                потомок = self._мутировать(чемпион, rng, п['разброс'])
                итог = arena.матч(
                    arena.игрок_из_весов('потомок', потомок, п['уровень']),
                    arena.игрок_из_весов('чемпион', чемпион, п['уровень']),
                    п['партий'], ядер, seed=поколение * 100 + номер,
                )
                # Сменять чемпиона только на убедительном перевесе: иначе отбор
                # пойдёт за шумом и будет гулять случайно, изображая прогресс.
                if итог.доля > 0.5 + итог.погрешность:
                    if лучший_итог is None or итог.доля > лучший_итог.доля:
                        лучший, лучший_итог = потомок, итог

            if лучший is not None:
                чемпион = лучший
                улучшений += 1
                self._сохранить(чемпион)
                self._записать(
                    'Поколение %d: новый чемпион, %.1f%% ± %.1f%% против прежнего. %s'
                    % (поколение, 100 * лучший_итог.доля,
                       100 * лучший_итог.погрешность,
                       json.dumps(чемпион, ensure_ascii=False)))
            else:
                self._записать('Поколение %d: улучшений нет' % поколение)

            if поколение % п['перчатка_каждые'] == 0 and time.time() < конец:
                _, общая = arena.перчатка(
                    arena.игрок_из_весов('чемпион', чемпион, п['уровень']),
                    соперники, партий=60, ядер=ядер, seed=поколение,
                )
                self._записать('Поколение %d: перчатка против неподвижных — %.1f%%'
                               % (поколение, 100 * общая))

        self._записать('Готово: поколений %d, улучшений %d. Веса в %s'
                       % (поколение, улучшений, ФАЙЛ_ВЕСОВ))
        self.stdout.write('')
        self.stdout.write(self.style.SUCCESS(
            'Проверьте победителя на СИЛЬНОМ уровне — подбор шёл на «%s»:'
            % п['уровень']))
        self.stdout.write('  manage.py arena --a-weights %s --a hard --b hard '
                          '--games 400' % ФАЙЛ_ВЕСОВ)
        self.stdout.write('  manage.py arena --gauntlet --a-weights %s --games 200'
                          % ФАЙЛ_ВЕСОВ)

    def _мутировать(self, веса, rng, разброс):
        """Слегка сдвинуть все числа. Ноль и минус не допускаются: цена не бывает
        отрицательной, а нулевая выключает признак совсем и ломает сравнение."""
        новые = {}
        for ключ in КЛЮЧИ:
            было = веса[ключ]
            сдвиг = rng.gauss(0, разброс * max(1.0, abs(было)))
            новые[ключ] = max(0.1, round(было + сдвиг, 3))
        return новые

    def _сохранить(self, веса):
        with open(ФАЙЛ_ВЕСОВ, 'w', encoding='utf-8') as файл:
            json.dump(веса, файл, ensure_ascii=False, indent=2)

    def _записать(self, строка):
        отметка = time.strftime('%H:%M:%S')
        self.stdout.write('%s  %s' % (отметка, строка))
        self.stdout.flush()
        with open(ФАЙЛ_ЖУРНАЛА, 'a', encoding='utf-8') as файл:
            файл.write('%s %s\n' % (time.strftime('%Y-%m-%d %H:%M:%S'), строка))
