# -*- coding: utf-8 -*-
"""Подобрать веса оценки по данным самоигры.

    manage.py learn_eval --data games/selfplay_positions.txt

Чем это отличается от arena_tune. Там веса подбирались матчами: потомок против
чемпиона, двести партий, кто убедительно лучше. Способ честный, но слепой и
дорогой — двести партий на одно сравнение, и различить перевес в 2% стоит
тысяч партий. Восемь чисел так подобрать можно, сотню нельзя.

Здесь задача другая и решается прямо. У нас есть позиции и то, чем партия
кончилась; надо найти веса, при которых оценка лучше всего предсказывает исход.
Это логистическая регрессия, и для полутора десятков признаков она решается
методом Ньютона за десяток шагов — секунды, а не часы.

Что важно не перепутать. Хорошее предсказание исхода и сильная игра — не одно
и то же. Оценка, которая точнее угадывает победителя в среднем по всем
позициям, может хуже различать близкие ходы, а перебору важно именно это.
Поэтому команда печатает качество предсказания, но НЕ объявляет победителя:
последнее слово за матчем на стенде.

Свободного члена в модели нет, и это не забывчивость. Признаки антисимметричны,
метки тоже: если поменять игроков местами, вектор меняет знак, а метка
превращается в единицу минус себя. Свободный член такую симметрию нарушил бы —
он означал бы «одна из сторон выигрывает чаще просто так».
"""

import json

from django.core.management.base import BaseCommand, CommandError

from games import bot, features, selfplay

ФАЙЛ_ВЕСОВ = 'games/learned_weights.json'

# Оценка используется перебором как число, а не как вероятность, поэтому
# логарифм шансов можно умножить на что угодно — выбор хода от этого не
# изменится. Но не на что угодно безнаказанно: перебор считает выигрыш равным
# WIN_SCORE (сто тысяч) и предпочитает более близкий выигрыш более далёкому,
# прибавляя к нему глубину. Если обычная оценка подберётся к этому числу,
# хорошая позиция станет неотличима от выигранной.
#
# Поэтому масштаб задаётся не «наибольшим весом», а разбросом самой оценки на
# реальных позициях: приводим её к этому среднеквадратичному отклонению.
# Триста — с трёхсоткратным запасом до WIN_SCORE и того же порядка, что
# прежние веса, так что числа в журналах остаются узнаваемыми.
РАЗБРОС_ОЦЕНКИ = 300.0

# Выше этой доли от WIN_SCORE оценка уже опасно близка к выигрышу.
ОПАСНАЯ_ДОЛЯ = 0.1


def _логпотери(z, y):
    """Средние логистические потери. Считается устойчиво к большим |z|."""
    import numpy as np
    # log(1+e^z) без переполнения
    мягкий = np.logaddexp(0.0, z)
    return float(np.mean(мягкий - y * z))


# По скольку строк считать за раз. Матрица целиком в вещественных числах не
# нужна и вредна: миллион строк на полсотни столбцов — это полгигабайта
# временных массивов на каждом шаге Ньютона.
КУСОК = 100000


def _произведения(X, y, w, l2):
    """Градиент и матрица вторых производных, накопленные по кускам."""
    import numpy as np

    n, m = X.shape
    g = np.zeros(m)
    H = np.zeros((m, m))
    for a in range(0, n, КУСОК):
        Xк = X[a:a + КУСОК].astype(np.float64)
        yк = y[a:a + КУСОК].astype(np.float64)
        p = 1.0 / (1.0 + np.exp(-np.clip(Xк @ w, -30, 30)))
        g += Xк.T @ (p - yк)
        H += (Xк.T * np.clip(p * (1.0 - p), 1e-9, None)) @ Xк
    return g / n + l2 * w, H / n + l2 * np.eye(m)


def _обучить(X, y, l2, шагов=25):
    """Логистическая регрессия методом Ньютона. Возвращает веса.

    Ньютон здесь уместен именно потому, что признаков десятки: матрица вторых
    производных мала, зато сходимость — за десяток шагов без подбора длины шага.
    Для таблиц образцов, где параметров тысячи, он уже не годится.
    """
    import numpy as np

    w = np.zeros(X.shape[1])
    for шаг in range(шагов):
        градиент, гессиан = _произведения(X, y, w, l2)
        try:
            шаг_вектор = np.linalg.solve(гессиан, градиент)
        except np.linalg.LinAlgError:            # pragma: no cover
            шаг_вектор = np.linalg.lstsq(гессиан, градиент, rcond=None)[0]
        w = w - шаг_вектор
        if np.max(np.abs(шаг_вектор)) < 1e-10:
            break
    return w


def _подогнать_масштаб(z, y, шагов=40):
    """Один множитель к готовой оценке — чтобы сравнивать честно.

    Прежние веса подобраны матчами, их абсолютная величина случайна. Сравнивать
    их логпотери с обученными без подгонки масштаба значило бы наказать их за
    то, к чему их никто не подбирал.
    """
    import numpy as np
    a = 1e-3
    for _ in range(шагов):
        zz = a * z
        p = 1.0 / (1.0 + np.exp(-np.clip(zz, -30, 30)))
        g = float(np.mean((p - y) * z))
        h = float(np.mean(np.clip(p * (1 - p), 1e-12, None) * z * z))
        if h <= 0:                                # pragma: no cover
            break
        шаг = g / h
        a -= шаг
        if abs(шаг) < 1e-12:
            break
    return a


class Command(BaseCommand):
    help = 'Подобрать веса оценки логистической регрессией по данным самоигры.'

    def add_arguments(self, parser):
        parser.add_argument('--data', dest='данные',
                            default='games/selfplay_positions.txt')
        parser.add_argument('--out', dest='файл', default=ФАЙЛ_ВЕСОВ)
        parser.add_argument('--l2', dest='l2', type=float, default=1e-6,
                            help='штраф за большие веса')
        parser.add_argument('--holdout', dest='отложить', type=float,
                            default=0.2, help='доля данных на проверку')
        parser.add_argument('--phases', dest='стадий', type=int, default=1,
                            help='на сколько стадий партии делить веса')
        parser.add_argument('--scale', dest='масштаб', type=float,
                            default=РАЗБРОС_ОЦЕНКИ,
                            help='к какому разбросу привести оценку')

    def handle(self, *args, **п):
        try:
            import numpy as np
        except ImportError:                       # pragma: no cover
            raise CommandError(
                'нужен numpy: venv\\Scripts\\python.exe -m pip install '
                '-r requirements-dev.txt')

        try:
            имена, X, y, стадии = selfplay.в_числа(
                selfplay.поток(п['данные']), п['стадий'])
        except OSError as беда:
            raise CommandError('не читается %s: %s' % (п['данные'], беда))
        except ValueError as беда:
            raise CommandError(str(беда))

        n = X.shape[0]
        self.stdout.write('Данных: %d позиций, столбцов %d (признаков %d, '
                          'стадий %d)'
                          % (n, X.shape[1], features.ЧИСЛО_ПРИЗНАКОВ,
                             п['стадий']))
        if п['стадий'] > 1:
            self.stdout.write(
                '  по стадиям: %s'
                % ', '.join('%d — %d' % (с, int((стадии == с).sum()))
                            for с in range(п['стадий'])))

        # Отложенная часть отрезается по КОНЦУ файла, а не выбирается вразброс.
        # Позиции одной партии стоят подряд и связаны намертво: у них общая
        # метка — исход этой самой партии. Разбросав строки, мы кладём начало
        # партии в обучение, а её же середину в проверку, и проверка начинает
        # хвалить за подсмотренное. Партии в файле идут подряд, поэтому граница
        # по строкам почти всегда оказывается и границей между партиями.
        граница = int(n * (1 - п['отложить']))
        Xтр, yтр = X[:граница], y[:граница]
        Xпр, yпр = X[граница:], y[граница:]
        self.stdout.write('  обучение %d, проверка %d (проверка — хвост файла, '
                          'то есть другие партии)' % (len(yтр), len(yпр)))

        # Признак, ни разу не встретившийся, получит вес из ниоткуда: его
        # столбец нулевой, и штраф просто оставит там ноль. Сказать всё равно
        # надо — обычно это значит, что признак посчитан неверно.
        пустые = np.max(np.abs(Xтр.astype(np.float64)), axis=0) < 1e-12
        if пустые.any():
            self.stdout.write(self.style.WARNING(
                'Признаки, ни разу не встретившиеся: %s'
                % ', '.join(имена[i] for i in np.nonzero(пустые)[0])))

        w = _обучить(Xтр, yтр, п['l2'])

        # Что было до обучения — с честно подогнанным множителем. Если
        # столбцы разбиты по стадиям, а нынешние веса плоские, один и тот же
        # вес ставится в каждую стадию: это и есть «то же самое, но без
        # разделения», с чем и надо сравнивать.
        w_старые = np.array([
            bot.ВЕСА.get(имя, bot.ВЕСА.get(имя.rsplit('@', 1)[0], 0.0))
            for имя in имена])
        a = _подогнать_масштаб(
            np.concatenate([Xтр[к:к + КУСОК].astype(np.float64) @ w_старые
                            for к in range(0, Xтр.shape[0], КУСОК)]),
            yтр.astype(np.float64))

        def умножить(M, v):
            из = np.empty(M.shape[0])
            for a in range(0, M.shape[0], КУСОК):
                из[a:a + КУСОК] = M[a:a + КУСОК].astype(np.float64) @ v
            return из

        z_старые = умножить(Xпр, w_старые)
        z_новые = умножить(Xпр, w)
        yпр = yпр.astype(np.float64)
        было = _логпотери(a * z_старые, yпр)
        стало = _логпотери(z_новые, yпр)
        монетка = _логпотери(np.zeros(len(yпр)), yпр)

        def доля_угаданных(z):
            есть = yпр != 0.5
            return float(np.mean((z[есть] > 0) == (yпр[есть] > 0.5)))

        self.stdout.write('')
        self.stdout.write('На отложенных данных (меньше — лучше):')
        self.stdout.write('  наугад            логпотери %.4f' % монетка)
        self.stdout.write('  прежние веса      логпотери %.4f, угадано %.1f%%'
                          % (было, 100 * доля_угаданных(a * (Xпр @ w_старые))))
        self.stdout.write('  обученные веса    логпотери %.4f, угадано %.1f%%'
                          % (стало, 100 * доля_угаданных(Xпр @ w)))

        # Масштаб по разбросу оценки, а не по наибольшему весу: важно, каким
        # выходит САМО число, которое увидит перебор.
        разброс = float(np.std(z_новые))
        w = w * (п['масштаб'] / max(1e-12, разброс))

        оценки = z_новые * (п['масштаб'] / max(1e-12, разброс))
        предел = float(np.max(np.abs(оценки)))
        self.stdout.write('')
        self.stdout.write('Оценка на отложенных данных: разброс %.0f, '
                          'наибольшая по модулю %.0f (выигрыш — %d)'
                          % (np.std(оценки), предел, bot.WIN_SCORE))
        if предел > ОПАСНАЯ_ДОЛЯ * bot.WIN_SCORE:
            self.stdout.write(self.style.WARNING(
                'Оценка подобралась к цене выигрыша — перебор перестанет их '
                'различать. Возьмите --scale поменьше.'))

        готовые = {имя: round(float(з), 4) for имя, з in zip(имена, w)}
        with open(п['файл'], 'w', encoding='utf-8') as файл:
            json.dump(готовые, файл, ensure_ascii=False, indent=2)

        self.stdout.write('')
        self.stdout.write('Веса:')
        if п['стадий'] <= 1:
            for имя in features.ПРИЗНАКИ:
                self.stdout.write('  %-18s %10.3f' % (имя, готовые[имя]))
        else:
            шапка = ''.join('%12s' % ('стадия %d' % с)
                            for с in range(п['стадий']))
            self.stdout.write('  %-18s%s' % ('', шапка))
            for имя in features.ПРИЗНАКИ:
                числа = ''.join('%12.1f' % готовые['%s@%d' % (имя, с)]
                                for с in range(п['стадий']))
                self.stdout.write('  %-18s%s' % (имя, числа))

        self.stdout.write('')
        self.stdout.write(self.style.SUCCESS('Записано: %s' % п['файл']))
        self.stdout.write(self.style.WARNING(
            'Логпотери — не сила игры. Последнее слово за матчем:'))
        self.stdout.write('  manage.py arena --a-weights %s --a hard --b hard '
                          '--games 400' % п['файл'])
