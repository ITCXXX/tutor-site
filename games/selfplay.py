# -*- coding: utf-8 -*-
"""Самоигра: партии ботов, из которых учится оценка позиции.

Зачем это. Восемь весов оценки удалось подобрать матчами: потомок против
чемпиона, двести партий, кто убедительно лучше — тот и чемпион. Дальше этот
способ упирается в стену. Матч различает перевес в 2% примерно за 2500 партий,
поэтому каждое отдельное число стоит часов, а набор из сотни чисел так не
подобрать никогда.

Обучение устроено иначе и не требует матчей вовсе. Бот играет сам с собой,
каждая позиция запоминается вместе с тем, чем партия КОНЧИЛАСЬ, и дальше это
обычная задача подгонки: найти веса, при которых оценка лучше всего
предсказывает исход.

**В файл кладутся позиции, а не признаки.** Так было не сразу, и переделка
стоила одного лишнего прогона: стоило поменять набор признаков — и все
собранные данные превращались в мусор, потому что в них лежали числа старого
набора. Позиция же не устаревает никогда. Признаки из неё считаются при чтении,
это секунды, зато любой новый набор — хоть разбиение по стадиям, хоть таблицы
образцов — обходится без переигрывания партий.

Три вещи, без которых данные бесполезны.

**Разнообразие.** Два одинаковых бота из одной позиции сыграют одну и ту же
партию сколько угодно раз. Поэтому партии начинаются со случайного дебюта, а по
ходу дела бот с некоторой вероятностью ходит наугад.

**Исход, а не оценка.** Метка позиции — чем партия кончилась, а не что о
позиции думал бот. Учиться на собственных оценках значит закрепить собственные
ошибки.

**Взгляд ходящего.** Позиция запоминается вместе с тем, чья очередь, а метка
ставится его глазами. Так позиция и её зеркало дают одну и ту же строку.
"""

import random
from concurrent.futures import ProcessPoolExecutor

from . import bot, features
from .arena import ПРЕДЕЛ_ХОДОВ, _случайный_дебют
from .engine import VARIANT_CLASSIC, apply_move, legal_moves

# Доля ходов наугад. Ровно столько, чтобы партии расходились: больше — и мы
# учимся предсказывать исход случайной игры, а не осмысленной.
ДОЛЯ_СЛУЧАЙНЫХ = 0.08

# Первые ходы партии предсказывают исход почти никак: там ещё всё возможно, и
# метка «эта партия кончилась поражением» скорее шум, чем знание.
ПРОПУСК_ДЕБЮТА = 6

# Первая строка файла. Меняется вместе с форматом, чтобы старый файл не
# прочитался молча и не дал весов неизвестно от чего.
ЗАГОЛОВОК = 'uttt-позиции-1'

# Длина упакованной позиции: 81 клетка, 9 полей, куда ходить, чья очередь.
ДЛИНА_УПАКОВКИ = 81 + 9 + 1 + 1


class Позиция:
    """Ровно то, что нужно features.вектор, и ничего больше.

    Настоящий bot.Position умеет делать и откатывать ходы и хранит вариант
    игры; для чтения признаков это лишний вес, а строк здесь миллионы.
    """

    __slots__ = ('cells', 'boards', 'next_local', 'turn')

    def __init__(self, cells, boards, next_local, turn):
        self.cells = cells
        self.boards = boards
        self.next_local = next_local
        self.turn = turn


def упаковать(поз):
    """Позиция -> строка из 92 символов. Цифры, потому что значений всего 4."""
    цель = 9 if поз.next_local is None else поз.next_local
    return '%s%s%d%d' % (''.join(map(str, поз.cells)),
                         ''.join(map(str, поз.boards)), цель, поз.turn)


def распаковать(строка):
    if len(строка) != ДЛИНА_УПАКОВКИ:
        raise ValueError('позиция из %d символов, ожидалось %d'
                         % (len(строка), ДЛИНА_УПАКОВКИ))
    цель = int(строка[90])
    return Позиция(
        cells=[int(с) for с in строка[:81]],
        boards=[int(с) for с in строка[81:90]],
        next_local=None if цель == 9 else цель,
        turn=int(строка[91]),
    )


def партия(seed, уровень='medium', доля_случайных=ДОЛЯ_СЛУЧАЙНЫХ):
    """Одна партия сам с собой. Возвращает список (упакованная позиция, метка).

    Метка — глазами того, чья в этой позиции очередь: 1.0 выигрыш, 0.5 ничья,
    0.0 поражение.
    """
    rng = random.Random(seed)
    состояние = _случайный_дебют(seed)
    записи = []
    ходов = 0

    while not состояние.get('winner') and ходов < ПРЕДЕЛ_ХОДОВ:
        ходы = legal_moves(состояние)
        if not ходы:
            break
        чей = состояние['current']

        if ходов >= ПРОПУСК_ДЕБЮТА:
            записи.append((упаковать(bot.Position(состояние, VARIANT_CLASSIC)),
                           чей))

        if rng.random() < доля_случайных:
            ход = ходы[rng.randrange(len(ходы))]
        else:
            ход = bot.choose_move(состояние, VARIANT_CLASSIC, уровень, rng)
            if ход is None:
                break

        новое, ошибка = apply_move(состояние, чей, ход[0], ход[1], VARIANT_CLASSIC)
        if ошибка:                                   # pragma: no cover
            raise RuntimeError('недопустимый ход в самоигре: %s' % ошибка)
        состояние = новое
        ходов += 1

    исход = состояние.get('winner') or 'D'
    return [(упаковка, 0.5 if исход == 'D' else (1.0 if исход == чей else 0.0))
            for упаковка, чей in записи]


def _пачка(задание):
    """Несколько партий подряд в одном процессе: так меньше накладных расходов."""
    seed0, сколько, уровень, доля = задание
    строки = []
    for i in range(сколько):
        строки.extend(партия(seed0 + i, уровень, доля))
    return строки


def набрать(партий, уровень='medium', ядер=None, seed=0,
            доля_случайных=ДОЛЯ_СЛУЧАЙНЫХ, на_пачку=25, показывать=None):
    """Набрать данные: список (упакованная позиция, метка), параллельно."""
    задания = []
    сделано = 0
    while сделано < партий:
        сколько = min(на_пачку, партий - сделано)
        задания.append((seed * 1000003 + сделано, сколько, уровень,
                        доля_случайных))
        сделано += сколько

    строки = []
    if ядер == 1:
        for задание in задания:
            строки.extend(_пачка(задание))
            if показывать:
                показывать(len(строки))
    else:
        with ProcessPoolExecutor(max_workers=ядер) as пул:
            for кусок in пул.map(_пачка, задания, chunksize=1):
                строки.extend(кусок)
                if показывать:
                    показывать(len(строки))
    return строки


def записать(строки, путь):
    with open(путь, 'w', encoding='utf-8', newline='') as файл:
        файл.write(ЗАГОЛОВОК + '\n')
        for упаковка, метка in строки:
            файл.write('%s %.1f\n' % (упаковка, метка))


def поток(путь):
    """Читать файл по одной позиции: (Позиция, метка).

    Именно поток, а не список. Миллион позиций списком — это больше гигабайта
    объектов Python, и обучение начинается с того, что машина уходит в своп.
    Признаки же считаются построчно и складываются в компактный массив чисел.
    """
    with open(путь, encoding='utf-8') as файл:
        первая = файл.readline().strip()
        if первая != ЗАГОЛОВОК:
            raise ValueError(
                'файл собран другим форматом («%s» вместо «%s») — '
                'переснимите данные командой selfplay' % (первая, ЗАГОЛОВОК))
        for строка in файл:
            упаковка, _, метка = строка.rstrip('\n').partition(' ')
            yield распаковать(упаковка), float(метка)


def читать(путь):
    """То же списком — для тестов и небольших файлов."""
    return list(поток(путь))


def в_числа(источник, стадий=1):
    """(Позиция, метка) -> numpy-матрицы X, y и имена столбцов.

    Принимает и список, и поток из `поток()`.

    При стадий > 1 признаки размножаются по стадиям партии: каждый попадает в
    свой блок, остальные блоки в этой строке нулевые. Так одна и та же оценка
    получает разные веса в дебюте и в эндшпиле, оставаясь скалярным
    произведением — ни перебор, ни стенд об этом даже не знают.

    Признаки складываются в int16: все они целые и невелики (самый большой,
    «малая_одна», не переваливает за пару сотен). На миллионе строк это разница
    между полусотней мегабайт и полугигабайтом.
    """
    import numpy as np

    имена = имена_столбцов(стадий)
    ширина = len(имена)
    куски_X, куски_y, куски_с = [], [], []
    буфер_X = np.zeros((65536, ширина), dtype=np.int16)
    буфер_y = np.zeros(65536, dtype=np.float32)
    буфер_с = np.zeros(65536, dtype=np.int8)
    k = 0
    for поз, метка in источник:
        if k == len(буфер_y):
            куски_X.append(буфер_X.copy())
            куски_y.append(буфер_y.copy())
            куски_с.append(буфер_с.copy())
            k = 0
        с = features.стадия(поз, стадий)
        сдвиг = features.ЧИСЛО_ПРИЗНАКОВ * с
        буфер_X[k] = 0
        буфер_X[k, сдвиг:сдвиг + features.ЧИСЛО_ПРИЗНАКОВ] = features.вектор(
            поз, поз.turn)
        буфер_y[k] = метка
        буфер_с[k] = с
        k += 1
    куски_X.append(буфер_X[:k].copy())
    куски_y.append(буфер_y[:k].copy())
    куски_с.append(буфер_с[:k].copy())
    return (имена, np.concatenate(куски_X), np.concatenate(куски_y),
            np.concatenate(куски_с))


def имена_столбцов(стадий=1):
    if стадий <= 1:
        return features.ПРИЗНАКИ
    return tuple('%s@%d' % (имя, с)
                 for с in range(стадий)
                 for имя in features.ПРИЗНАКИ)
