# -*- coding: utf-8 -*-
"""Турнирный стенд: бот против бота, чтобы «стало сильнее» было измеримым.

Зачем он вообще. Любая правка бота ощущается улучшением — пока не сядешь и не
сыграешь сотню партий. У УТТТ это уже стоило одного неверного вывода: перебор
на глубину 6 кажется сильнее, чем на 5, а на замерах проигрывает, потому что
глубже ищется по неверной оценке. Без стенда такое не видно.

Три вещи, которые стенд делает и без которых он бесполезен.

**Случайные дебюты.** Два одинаковых бота из одной позиции сыграют одну и ту же
партию сто раз. Поэтому каждая партия начинается с нескольких случайных ходов —
и оба соперника играют одну и ту же начальную позицию, по разу за каждый цвет.

**Пары «туда и обратно».** Первый ход в УТТТ стоит дорого. Если не менять
цвета, измеришь не силу, а преимущество выступки.

**Погрешность.** В матче из пятидесяти партий счёт 27:23 не значит ничего: так
ложится монетка. Стенд считает доверительный интервал и прямо говорит, когда
разница неотличима от случайности.

Запуск — через `manage.py arena`, см. games/management/commands/arena.py.
"""

import math
import random
from concurrent.futures import ProcessPoolExecutor
from dataclasses import dataclass, field

from . import bot
from .engine import VARIANT_CLASSIC, apply_move, initial_state, legal_moves

# Сколько случайных полуходов делается перед началом счёта. Четыре — уже
# достаточно разные позиции, но ещё не проигранные заранее.
ДЕБЮТ_ПОЛУХОДОВ = 4

# Предел на партию: если боты зациклились, партия не должна висеть вечно.
ПРЕДЕЛ_ХОДОВ = 200


@dataclass(frozen=True)
class Игрок:
    """Настройка соперника: уровень плюс, если нужно, свои веса оценки."""

    имя: str
    уровень: str = 'hard'
    веса: tuple = field(default=())      # пары (ключ, значение); кортеж — ради хеша

    def как_словарь(self):
        return dict(self.веса) if self.веса else None


def игрок_из_весов(имя, веса, уровень='hard'):
    return Игрок(имя=имя, уровень=уровень, веса=tuple(sorted(веса.items())))


@dataclass
class Итог:
    победы: int = 0
    ничьи: int = 0
    поражения: int = 0

    @property
    def партий(self):
        return self.победы + self.ничьи + self.поражения

    @property
    def очки(self):
        """Очки первого игрока: победа 1, ничья 0,5."""
        return self.победы + 0.5 * self.ничьи

    @property
    def доля(self):
        return self.очки / self.партий if self.партий else 0.0

    @property
    def погрешность(self):
        """Полуширина 95-процентного интервала для доли очков.

        Считается по разбросу самих результатов, а не по формуле для монетки:
        ничьи уменьшают разброс, и без этого интервал выходил бы завышенным.
        """
        n = self.партий
        if n < 2:
            return 1.0
        значения = ([1.0] * self.победы + [0.5] * self.ничьи + [0.0] * self.поражения)
        среднее = sum(значения) / n
        дисперсия = sum((з - среднее) ** 2 for з in значения) / (n - 1)
        return 1.96 * math.sqrt(дисперсия / n)

    @property
    def значимо(self):
        """Отличается ли результат от равной игры сильнее, чем шум."""
        return abs(self.доля - 0.5) > self.погрешность

    def словами(self, кто, против):
        знак = '+' if self.доля >= 0.5 else '−'
        вывод = ('%s против %s: %d побед, %d ничьих, %d поражений — '
                 '%.1f%% ± %.1f%%'
                 % (кто, против, self.победы, self.ничьи, self.поражения,
                    100 * self.доля, 100 * self.погрешность))
        if not self.значимо:
            return вывод + '  (разница неотличима от случайности)'
        return вывод + ('  (%s%.1f%% от равной игры)'
                        % (знак, abs(100 * self.доля - 50)))


def _случайный_дебют(seed, полуходов=ДЕБЮТ_ПОЛУХОДОВ):
    """Позиция после нескольких случайных ходов. Одна и та же для обоих цветов."""
    rng = random.Random(seed)
    while True:
        состояние = initial_state()
        for _ in range(полуходов):
            ходы = legal_moves(состояние)
            if not ходы:
                break
            big, small = rng.choice(ходы)
            новое, ошибка = apply_move(состояние, состояние['current'],
                                       big, small, VARIANT_CLASSIC)
            if ошибка:
                break
            состояние = новое
            if состояние.get('winner'):
                break
        if not состояние.get('winner') and legal_moves(состояние):
            return состояние


def сыграть(за_x, за_o, состояние, seed):
    """Одна партия из заданной позиции. Возвращает 'X', 'O' или 'D'."""
    rng = random.Random(seed)
    ходов = 0
    while not состояние.get('winner') and ходов < ПРЕДЕЛ_ХОДОВ:
        if not legal_moves(состояние):
            break
        чей = состояние['current']
        игрок = за_x if чей == 'X' else за_o
        ход = bot.choose_move(состояние, VARIANT_CLASSIC, игрок.уровень, rng,
                              игрок.как_словарь())
        if ход is None:
            break
        новое, ошибка = apply_move(состояние, чей, ход[0], ход[1], VARIANT_CLASSIC)
        if ошибка:                                   # pragma: no cover
            raise RuntimeError('бот предложил недопустимый ход: %s' % ошибка)
        состояние = новое
        ходов += 1
    return состояние.get('winner') or 'D'


def _пара(задание):
    """Две партии из одной позиции: каждый по разу за X. Для параллельного счёта."""
    первый, второй, seed = задание
    позиция = _случайный_дебют(seed)
    прямая = сыграть(первый, второй, позиция, seed * 2 + 1)
    обратная = сыграть(второй, первый, позиция, seed * 2 + 2)
    return прямая, обратная


def матч(первый, второй, партий=200, ядер=None, seed=0, показывать=None):
    """Матч из `партий` партий (округляется вниз до чётного: пары туда-обратно).

    Возвращает Итог глазами ПЕРВОГО игрока.
    """
    пар = max(1, партий // 2)
    задания = [(первый, второй, seed * 100003 + i) for i in range(пар)]
    итог = Итог()

    def учесть(прямая, обратная):
        # В прямой первый играл за X, в обратной — за O.
        for победитель, первый_был_x in ((прямая, True), (обратная, False)):
            если_первый = 'X' if первый_был_x else 'O'
            if победитель == 'D':
                итог.ничьи += 1
            elif победитель == если_первый:
                итог.победы += 1
            else:
                итог.поражения += 1

    if ядер == 1:
        for задание in задания:
            учесть(*_пара(задание))
            if показывать:
                показывать(итог)
    else:
        with ProcessPoolExecutor(max_workers=ядер) as пул:
            for прямая, обратная in пул.map(_пара, задания, chunksize=1):
                учесть(прямая, обратная)
                if показывать:
                    показывать(итог)
    return итог


def перчатка(кандидат, соперники, партий=100, ядер=None, seed=0):
    """Матчи кандидата против НЕПОДВИЖНОГО набора соперников.

    Главная защита от самообмана. Бот, которого отбирали только против его же
    потомков, становится мастером по обыгрыванию родни — и может при этом
    ослабеть против всех остальных. Поэтому мерить надо против соперников,
    которые не меняются: нынешнего бота, слабого и среднего уровней.

    Возвращает список (соперник, Итог) и общую долю очков.
    """
    итоги = []
    for соперник in соперники:
        итоги.append((соперник, матч(кандидат, соперник, партий, ядер, seed)))
        seed += 1
    всего = sum(и.очки for _, и in итоги)
    партий_всего = sum(и.партий for _, и in итоги)
    return итоги, (всего / партий_всего if партий_всего else 0.0)
