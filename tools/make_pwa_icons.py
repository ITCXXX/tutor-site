# -*- coding: utf-8 -*-
"""Иконки для установки сайта на домашний экран.

Рисуются кодом, а не лежат картинками: так их можно поправить одной строкой,
и не приходится держать в репозитории бинарники, происхождение которых через
полгода никто не вспомнит.

Рисунок — две наложенные карточки на фиолетовом фоне. Мелкий значок на экране
телефона читается только силуэтом, поэтому внутри ничего, кроме двух
прямоугольников: любые буквы и формулы на 48 пикселях превращаются в грязь.

Запуск:  venv\\Scripts\\python.exe tools\\make_pwa_icons.py
"""

import os

from PIL import Image, ImageDraw

КУДА = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                    'static', 'img')

# Те же фиолетовые, что в static/css/tokens.css (--gradient-nav).
ВЕРХ = (109, 40, 217)
НИЗ = (76, 29, 149)
БУМАГА = (255, 255, 255)

# Рисуем в четыре раза крупнее и уменьшаем — дешёвое сглаживание без фильтров.
ЗАПАС = 4


def _фон(размер, радиус_доля):
    """Скруглённый квадрат с вертикальным градиентом."""
    полотно = Image.new('RGBA', (размер, размер), (0, 0, 0, 0))
    градиент = Image.new('RGB', (1, размер))
    for y in range(размер):
        доля = y / max(1, размер - 1)
        градиент.putpixel((0, y), tuple(
            int(ВЕРХ[i] + (НИЗ[i] - ВЕРХ[i]) * доля) for i in range(3)
        ))
    градиент = градиент.resize((размер, размер))

    маска = Image.new('L', (размер, размер), 0)
    ImageDraw.Draw(маска).rounded_rectangle(
        (0, 0, размер - 1, размер - 1),
        radius=int(размер * радиус_доля), fill=255,
    )
    полотно.paste(градиент, (0, 0), маска)
    return полотно


def _карточки(полотно, размер, поле):
    """Одна карточка со строками текста по центру.

    Стопку из двух карточек пробовал — на мелком значке её края читаются как
    заусенцы, а не как вторая карточка. Один чистый силуэт понятнее.
    """
    рисовать = ImageDraw.Draw(полотно, 'RGBA')
    ширина = int(размер * (1 - 2 * поле))
    высота = int(ширина * 0.72)
    левый = (размер - ширина) // 2
    верхний = (размер - высота) // 2
    радиус = int(ширина * 0.09)

    рисовать.rounded_rectangle(
        (левый, верхний, левый + ширина, верхний + высота),
        radius=радиус, fill=БУМАГА + (255,),
    )

    # Строки «текста»: без них карточка читается как просто белый прямоугольник.
    # Разная длина — чтобы было видно, что это текст, а не полосы.
    строка_высота = max(2, int(высота * 0.085))
    отступ = int(ширина * 0.13)
    for номер, доля_ширины in enumerate((0.95, 0.7, 0.45)):
        верх_строки = верхний + int(высота * (0.24 + номер * 0.23))
        рисовать.rounded_rectangle(
            (левый + отступ, верх_строки,
             левый + отступ + int((ширина - 2 * отступ) * доля_ширины),
             верх_строки + строка_высота),
            radius=строка_высота // 2,
            fill=(НИЗ + (215,)) if номер == 0 else (НИЗ + (140,)),
        )
    return полотно


def нарисовать(размер, *, поле=0.16, радиус_доля=0.22):
    крупно = размер * ЗАПАС
    полотно = _фон(крупно, радиус_доля)
    _карточки(полотно, крупно, поле)
    return полотно.resize((размер, размер), Image.LANCZOS)


def main():
    os.makedirs(КУДА, exist_ok=True)
    задания = [
        ('icon-192.png', 192, 0.16, 0.22),
        ('icon-512.png', 512, 0.16, 0.22),
        # Maskable: система может обрезать икону до круга, поэтому рисунок
        # держим внутри центральных 80 %, а углы заливаем фоном целиком.
        ('icon-maskable-512.png', 512, 0.26, 0.5),
        ('apple-touch-icon.png', 180, 0.16, 0.0),
    ]
    for имя, размер, поле, радиус in задания:
        путь = os.path.join(КУДА, имя)
        нарисовать(размер, поле=поле, радиус_доля=радиус).save(путь)
        print('%s — %d×%d' % (имя, размер, размер))


if __name__ == '__main__':
    main()
