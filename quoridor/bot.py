# -*- coding: utf-8 -*-
"""
quoridor/bot.py — соперник для «Заборов» на стороне сервера.

Зачем он, если бот уже есть
---------------------------
Играющий бот живёт в браузере (static/quoridor/js/bot.js): локальная партия
целиком браузерная, и правила там уже лежат. Этот модуль его НЕ заменяет — он
нужен, чтобы бота можно было ИЗМЕРЯТЬ и НАСТРАИВАТЬ.

Никакая настройка невозможна, пока «стало сильнее» проверяется на глаз. Для
крестиков-ноликов это уже стоило одного неверного вывода: перебор на глубину 6
казался сильнее, а на замерах проигрывал. Стенд (quoridor/arena.py) играет
сотни партий бот против бота и говорит, значима ли разница; но стенд не может
работать в браузере — там нет ни пятнадцати ядер, ни возможности прогнать
тысячу партий за минуту.

Поэтому здесь ровно то же, что в bot.js, только на Python: тот же отбор ходов,
тот же перебор, та же оценка. Настроенные числа возвращаются в bot.js —
переезжают именно ЧИСЛА, а не устройство.

Чем этот порт рискован и что с этим сделано
-------------------------------------------
Две реализации одного и того же всегда расходятся. В «Заборах» это уже
учтено для правил: `manage.py quoridor_trace` пишет след серверной партии, а
`tracecheck.js` проигрывает его браузерными правилами. Здесь тот же приём
распространён на бота — след умеет хранить и выбор хода, так что расхождение
видно сразу, а не в партии с игроком.

Оценка
------
Она в «Заборах» на удивление простая и точная: разность длин кратчайших путей
плюс небольшая надбавка за оставшиеся заборы. Побеждает тот, кому осталось
меньше шагов, а заборы — ресурс, чтобы шагов у соперника стало больше.

Числа вынесены в ВЕСА не для красоты: их всего два, и в bot.js они вписаны
прямо в формулу, поэтому подобрать их там нечем.
"""

import random
import time

from .engine import (BLUE, RED, apply_move, apply_wall, other, path_to,
                     pawn_moves, размер, сетка_заборов, shortest_path,
                     wall_problem)

WIN = 10000

# Уровни повторяют bot.js. Срок указан в секундах (в JS — в миллисекундах):
# на сервере счёт времени секундами принят везде, и переводить его туда-сюда
# опаснее, чем один раз записать иначе.
LEVELS = {
    'easy': {
        'title': 'слабый',
        'depth': 1,            # видит только свой ход
        'candidates': 6,
        'budget': 0.10,
        'blunder': 0.25,       # как часто ошибается нарочно
        'wall_need': 1,
    },
    'medium': {
        'title': 'средний',
        'depth': 2,            # свой ход и ответ соперника
        'candidates': 10,
        'budget': 0.30,
        'blunder': 0.05,
        'wall_need': 1,
    },
    'hard': {
        'title': 'сильный',
        'depth': 4,            # по два хода с каждой стороны
        'candidates': 14,
        'budget': 0.90,
        'blunder': 0.0,
        'wall_need': 1,
    },
}

DEFAULT_LEVEL = 'medium'
ALL_LEVELS = tuple(LEVELS)

# Цена каждого признака оценки. Пока их два — столько же, сколько в bot.js.
ВЕСА = {
    'шаг': 10.0,      # каждый шаг, на который соперник дальше от цели, чем я
    'забор': 2.0,     # каждый лишний забор в запасе
}


def level_of(name):
    """Уровень по имени — или готовый набор настроек как есть.

    Словарь принимается ради разбора игры: там нужны уровни, которых на сайте
    нет и быть не должно (глубина 1..6 при снятом сроке). Заводить их в LEVELS
    нельзя — оттуда они попали бы в выбор игрока.
    """
    if isinstance(name, dict):
        return name
    return LEVELS.get(name, LEVELS[DEFAULT_LEVEL])


def _key(r, c):
    return '%d,%d' % (r, c)


# ────────────────────────── оценка ──────────────────────────

def distances(state, side):
    """(мой путь, путь соперника) в шагах. None, если пути нет."""
    foe = other(side)
    n = размер(state)
    return (shortest_path(state['walls'], state['pawns'][side],
                          state['goalRow'][side], n),
            shortest_path(state['walls'], state['pawns'][foe],
                          state['goalRow'][foe], n))


def evaluate(state, side, веса=None):
    """Оценка позиции глазами стороны `side`. Больше — лучше для неё."""
    if state['winner']:
        return WIN if state['winner'] == side else -WIN
    в = веса if веса is not None else ВЕСА
    мой, чужой = distances(state, side)
    if мой is None or чужой is None:          # такого быть не должно
        return 0.0
    foe = other(side)
    return ((чужой - мой) * в['шаг']
            + (state['wallsLeft'][side] - state['wallsLeft'][foe]) * в['забор'])


# ────────────────────── ходы-кандидаты ──────────────────────

def wall_candidates(state, side, limit):
    """Заборы, перекрывающие сопернику его нынешний кратчайший путь.

    Полный перебор невозможен: мест под забор 128, и уже на третьем полуходе
    это миллионы позиций. Но забор, поставленный в стороне от дороги, соперник
    обойдёт не заметив — считать такие варианты значит тратить перебор впустую.
    Поэтому берутся только те, что режут текущий путь: полтора десятка вместо
    ста двадцати восьми.
    """
    if state['wallsLeft'][side] <= 0:
        return []
    foe = other(side)
    n = размер(state)
    сетка = сетка_заборов(n)
    путь = path_to(state['walls'], state['pawns'][foe], state['goalRow'][foe], n)
    if not путь or len(путь) < 2:
        return []

    def зажать(x):
        return max(0, min(сетка - 1, x))

    видели = set()
    из = []
    мой_базовый, чужой_базовый = distances(state, side)

    for i in range(len(путь) - 1):
        a, b = путь[i], путь[i + 1]
        места = []
        if b['r'] != a['r']:                  # шаг по вертикали режет забор «—»
            wr = min(a['r'], b['r'])
            места = [(wr, зажать(a['c'] - 1), 'h'), (wr, зажать(a['c']), 'h')]
        else:                                 # шаг вбок режет забор «|»
            wc = min(a['c'], b['c'])
            места = [(зажать(a['r'] - 1), wc, 'v'), (зажать(a['r']), wc, 'v')]

        for wr, wc, kind in места:
            метка = (wr, wc, kind)
            if метка in видели:
                continue
            видели.add(метка)
            if wall_problem(state, side, wr, wc, kind):
                continue

            проба = dict(state['walls'])
            проба[_key(wr, wc)] = kind
            чужой = shortest_path(проба, state['pawns'][foe],
                                  state['goalRow'][foe], n)
            мой = shortest_path(проба, state['pawns'][side],
                                state['goalRow'][side], n)
            if чужой is None or мой is None:
                continue
            из.append({
                'kind': 'wall', 'wr': wr, 'wc': wc, 'orient': kind,
                'gain': (чужой - чужой_базовый) - (мой - мой_базовый),
            })

    из.sort(key=lambda x: -x['gain'])
    return из[:limit]


def pawn_candidates(state, side):
    """Шаги фишкой, отсортированные по близости к цели."""
    цель = state['goalRow'][side]
    n = размер(state)
    из = []
    for m in pawn_moves(state, side):
        длина = shortest_path(state['walls'], m, цель, n)
        if длина is None:
            continue
        из.append({'kind': 'move', 'r': m['r'], 'c': m['c'], 'len': длина})
    из.sort(key=lambda m: m['len'])
    return из


def candidates(state, side, limit):
    """Ходы к перебору: сначала шаги покороче, потом заборы повреднее."""
    return pawn_candidates(state, side) + wall_candidates(state, side, limit)


def _применить(state, side, ход):
    if ход['kind'] == 'move':
        новое, ошибка = apply_move(state, side, ход['r'], ход['c'])
    else:
        новое, ошибка = apply_wall(state, side, ход['wr'], ход['wc'],
                                   ход['orient'])
    return None if ошибка else новое


# ────────────────────────── перебор ──────────────────────────

class _Срок:
    """Часы, а не счётчик позиций.

    Считать позиции здесь бесполезно: время съедает не сам перебор, а обходы
    поля при отборе заборов. Часы меряют то самое, ради чего потолок и нужен.
    """

    __slots__ = ('до',)

    def __init__(self, сколько):
        self.до = time.monotonic() + сколько

    def вышел(self):
        return time.monotonic() > self.до


def search(state, side, depth, alpha, beta, level, срок, веса):
    """Негамакс с отсечениями. Оценка глазами того, кто ходит."""
    if state['winner']:
        # depth — ОСТАТОК глубины: у победы поближе он больше. Поэтому близкая
        # победа обязана стоить дороже далёкой, иначе бот в шаге от выигрыша
        # предпочтёт выигрыш «через два хода» и будет топтаться.
        return (WIN + depth) if state['winner'] == side else -(WIN + depth)
    if depth <= 0 or срок.вышел():
        return evaluate(state, side, веса)

    лучшее = None
    for ход in candidates(state, side, level['candidates']):
        if срок.вышел():
            break
        следом = _применить(state, side, ход)
        if следом is None:
            continue
        очки = -search(следом, other(side), depth - 1, -beta, -alpha,
                       level, срок, веса)
        if лучшее is None or очки > лучшее:
            лучшее = очки
        if лучшее > alpha:
            alpha = лучшее
        if alpha >= beta:
            break                              # соперник сюда не пойдёт
    return evaluate(state, side, веса) if лучшее is None else лучшее


# ───────────────────────── ход бота ─────────────────────────

def choose_move(state, side, level_name=DEFAULT_LEVEL, rng=None, веса=None):
    """Выбрать ход. Возвращает словарь хода или None, если ходить нечем."""
    level = level_of(level_name)
    rng = rng or random
    список = candidates(state, side, level['candidates'])
    if not список:
        return None

    стоящие = [х for х in список
               if х['kind'] != 'wall' or х['gain'] >= level['wall_need']]
    пул = стоящие or список

    срок = _Срок(level['budget'])
    оценённые = []
    for ход in пул:
        следом = _применить(state, side, ход)
        if следом is None:
            continue
        очки = -search(следом, other(side), level['depth'] - 1,
                       -float('inf'), float('inf'), level, срок, веса)
        оценённые.append((ход, очки))
        # Срок вышел — дальше сравнивать нечестно: у оставшихся перебор
        # оборвался бы на первом узле, и они выглядели бы хуже не по делу.
        if срок.вышел():
            break

    if not оценённые:
        шаг = next((х for х in список if х['kind'] == 'move'), None)
        return шаг

    оценённые.sort(key=lambda п: -п[1])

    # Слабый уровень нарочно ошибается: иначе даже одноходовый бот обыгрывает
    # новичка вчистую, и играть с ним не хочется.
    if level['blunder'] and len(оценённые) > 1 and rng.random() < level['blunder']:
        return оценённые[1 + rng.randrange(len(оценённые) - 1)][0]

    лучшая = оценённые[0][1]
    верхние = [х for х, о in оценённые if о == лучшая]
    if len(верхние) > 1:
        верхние = _ближе_к_цели(state, side, верхние)
    return верхние[rng.randrange(len(верхние))]


def _ближе_к_цели(state, side, ходы):
    """Из равных по оценке ходов оставить те, что ближе подводят к своему краю.

    Это лечение буриданова осла. Замер: на среднем уровне в 2-6% решений первое
    место делят ходы, ведущие в РАЗНЫЕ стороны — один приближает бота к цели,
    другой отдаляет. Оценка их не различает, и бот бросал монетку; со стороны
    это выглядит метанием — шаг вперёд, шаг назад. Партию он всё равно
    выигрывал, поэтому в самоигре беда не видна: она портит не результат, а
    впечатление, и именно её игрок и заметил.

    На слабом уровне такого не бывает: там глубина 1, и оценка прямо видит
    расстояние. Ничьи появляются с глубины 2, когда в счёт входит ответ
    соперника и разница между «вперёд» и «назад» успевает сравняться.

    Случайность при этом не теряется: выбор остаётся случайным среди тех, кто
    одинаково хорош И по оценке, И по продвижению. Заборы не двигают фишку,
    поэтому попадают в ту же корзину, что ходы, не меняющие расстояния.
    """
    n = размер(state)
    цель = state['goalRow'][side]
    сейчас = shortest_path(state['walls'], state['pawns'][side], цель, n)
    if сейчас is None:
        return ходы

    лучшее = None
    с_ценой = []
    for ход in ходы:
        следом = _применить(state, side, ход)
        if следом is None:
            continue
        после = shortest_path(следом['walls'], следом['pawns'][side], цель, n)
        if после is None:
            continue
        с_ценой.append((ход, после))
        if лучшее is None or после < лучшее:
            лучшее = после
    if not с_ценой:
        return ходы
    return [ход for ход, после in с_ценой if после == лучшее]


def apply_choice(state, side, ход):
    """Применить выбранный ход. Возвращает (новое состояние, ошибка)."""
    if ход is None:
        return state, 'ходить нечем'
    if ход['kind'] == 'move':
        return apply_move(state, side, ход['r'], ход['c'])
    return apply_wall(state, side, ход['wr'], ход['wc'], ход['orient'])
