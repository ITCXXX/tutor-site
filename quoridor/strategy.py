# -*- coding: utf-8 -*-
"""Что именно делает выигрывающая сторона в «Заборах» — по точному решению.

Решатель (quoridor/solver.py) отвечает «выигрывает второй». Для игрока это
бесполезно: нужна не пометка позиции, а правило, по которому ходить. Здесь
правило достаётся из решённых таблиц и проверяется ПЕРЕБОРОМ ВСЕХ ПОЗИЦИЙ, а не
на примерах.

ЗЕРКАЛО НЕ РАБОТАЕТ — проверено и записано, чтобы не возвращаться.
Напрашивается мысль: поле симметрично относительно центра, пусть второй
повторяет ходы первого поворотом на 180°. Перебор её убивает. На пустой тройке
из пяти симметричных позиций проиграна для ходящего ровно одна — стартовая, а в
остальных ходящий выигрывает. Причина простая: зеркалящий всегда на темп
позади, и из равного положения гонку выигрывает тот, чья очередь. Проверка
оставлена в `проверить_зеркало` именно как отрицательный результат.

ЧТО РАБОТАЕТ — ПРАВИЛО СОСЕДСТВА. Когда фишки стоят вплотную, ходящий
перепрыгивает через соперника и покрывает два ряда за один ход. Поэтому встать
вплотную — значит подарить сопернику темп. Первый обязан подойти первым, потому
что ходит первым, — отсюда и «выигрывает второй».

Модуль считает три вещи: правило соседства (кто выигрывает, когда фишки рядом),
закон гонки (кто выигрывает в лобовой гонке на расстоянии d) и роль забора
(забор — это ход, не двигающий фишку, то есть способ отдать темп сопернику).
"""

from quoridor import solver


def зеркало_клетки(n, клетка):
    """Поворот на 180°: (r, c) -> (n-1-r, n-1-c). Номер клетки — r * n + c."""
    r, c = divmod(клетка, n)
    return (n - 1 - r) * n + (n - 1 - c)


def зеркало_забора(n, забор):
    """Паз (r, c, вид) -> (n-2-r, n-2-c, тот же вид).

    Горизонтальный забор в пазу (R, C) мешает ходить между рядами R и R+1 в
    столбцах C и C+1. После поворота этот переход становится переходом между
    рядами n-2-R и n-1-R в столбцах n-2-C и n-1-C, а мешает ему паз
    (n-2-R, n-2-C). Для вертикального — то же по симметрии.
    """
    r, c, вид = забор
    return (n - 2 - r, n - 2 - c, вид)


class Зеркало:
    """Отражение позиций решателя поворотом на 180°."""

    def __init__(self, задача):
        self.задача = задача
        self.n = задача.n
        наборы = задача.расстановки.наборы
        по_составу = {frozenset(набор): i for i, набор in enumerate(наборы)}
        self.набор_зеркало = [
            по_составу.get(frozenset(зеркало_забора(self.n, з) for з in набор), -1)
            for набор in наборы
        ]

    def набор_симметричен(self, набор):
        return self.набор_зеркало[набор] == набор

    def симметричные_позиции(self):
        """Позиции вида «синие — отражение красных», ход красных.

        Симметрия означает: расстановка заборов переходит в себя, фишки — друг
        в друга, заборов потрачено поровну.
        """
        задача = self.задача
        n = self.n
        for набор in range(len(задача.расстановки.наборы)):
            if not self.набор_симметричен(набор):
                continue
            всего_на_доске = задача.расстановки.сколько_заборов[набор]
            if всего_на_доске % 2:
                continue
            поставлено = всего_на_доске // 2
            if (поставлено > задача.заборов_красных
                    or поставлено > задача.заборов_синих):
                continue
            for красн in range(задача.клеток):
                син = зеркало_клетки(n, красн)
                if красн == син:            # центр: фишки не совпадают
                    continue
                if красн // n == 0 or син // n == n - 1:
                    continue                # партия уже кончена
                yield задача.номер(набор, поставлено, красн, син,
                                   solver.КРАСНЫЕ)


def проверить_зеркало(задача, исход):
    """Отрицательный результат: симметрия НЕ делает позицию проигранной.

    Возвращает, сколько симметричных позиций проиграно для ходящего. Если бы
    зеркало работало, проигранными были бы все.
    """
    зеркало = Зеркало(задача)
    всего = проигранных = 0
    for номер in зеркало.симметричные_позиции():
        if исход[номер] == solver.НЕВОЗМОЖНА:
            continue
        всего += 1
        if исход[номер] == solver.ПРОИГРЫШ:
            проигранных += 1
    return {'всего': всего, 'проигранных': проигранных}


def правило_соседства(задача, исход):
    """Кто выигрывает, когда фишки стоят вплотную.

    Ожидание: ходящий, потому что он перепрыгивает. Считаются ВСЕ возможные
    позиции, а не только достижимые из начальной: правило должно быть верным
    как правило, а не как наблюдение об одной партии.
    """
    n = задача.n
    рядом = [0, 0, 0]          # выигрыш ходящего, проигрыш, ничья
    порознь = [0, 0, 0]
    ключ = {solver.ВЫИГРЫШ: 0, solver.ПРОИГРЫШ: 1, solver.НЕИЗВЕСТНО: 2}
    for номер, набор, поставлено, красн, син, очередь in задача.все_позиции():
        место = ключ.get(исход[номер])
        if место is None:
            continue
        r1, c1 = divmod(красн, n)
        r2, c2 = divmod(син, n)
        куда = рядом if abs(r1 - r2) + abs(c1 - c2) == 1 else порознь
        куда[место] += 1
    return {'рядом': tuple(рядом), 'порознь': tuple(порознь)}


def закон_гонки(задача, исход):
    """Лобовая гонка: фишки в одном столбце, заборов на доске нет.

    Ключ — не расстояние между фишками, а СКОЛЬКО ШАГОВ ДО ЦЕЛИ осталось
    каждому. Расстояние между фишками путает: на нём смешиваются позиции у
    своего края и у чужого, и правило в такой таблице не видно. Гонка же — это
    арифметика «кому меньше идти», а прыжок через соперника — поправка к ней.

    Красным идти до ряда 0, значит их шаги равны номеру их ряда. Синим идти до
    ряда n-1, значит их шаги равны n-1 минус номер ряда.
    """
    n = задача.n
    итог = {}
    for номер, набор, поставлено, красн, син, очередь in задача.все_позиции():
        if задача.расстановки.сколько_заборов[набор]:
            continue
        состояние = исход[номер]
        if состояние == solver.НЕВОЗМОЖНА:
            continue
        r1, c1 = divmod(красн, n)
        r2, c2 = divmod(син, n)
        if c1 != c2:
            continue
        шаги_красных, шаги_синих = r1, n - 1 - r2
        если_ходят_красные = очередь == solver.КРАСНЫЕ
        мои = шаги_красных if если_ходят_красные else шаги_синих
        чужие = шаги_синих if если_ходят_красные else шаги_красных
        ряд = итог.setdefault((мои, чужие), [0, 0, 0])
        ряд[{solver.ВЫИГРЫШ: 0, solver.ПРОИГРЫШ: 1,
             solver.НЕИЗВЕСТНО: 2}[состояние]] += 1
    return итог


def формула_гонки(мои, чужие, расстояние):
    """Кто выигрывает в лобовой гонке: правило, выведенное из таблиц.

    `мои` и `чужие` — сколько шагов до своего края осталось ходящему и
    сопернику. `расстояние` — на сколько рядов фишки отстоят друг от друга;
    отрицательное означает, что фишки уже разминулись.

    Три случая:

    • фишки разминулись — чистая гонка, выигрывает тот, кому идти не больше
      (ходящий выигрывает при равенстве, потому что ходит первым);

    • расстояние НЕЧЁТНОЕ (вплотную, через две клетки и т. д.) — ходящий
      выигрывает, даже отставая на шаг: подойдя, он прыгает через соперника и
      покрывает два ряда разом;

    • расстояние ЧЁТНОЕ (между фишками одна пустая клетка, три и т. д.) —
      ходящему нужно быть строго впереди. При равных шагах он проигрывает:
      подойти нельзя (подарит прыжок), а стоять на месте правила не дают.
      Это и есть цугцванг, из-за которого проигрывает первый: на старте шаги
      равны, а расстояние n-1 — чётное.
    """
    if расстояние <= 0:
        return мои <= чужие
    if расстояние % 2:
        return чужие >= мои - 1
    return мои < чужие


def проверить_формулу_гонки(задача, исход):
    """Сверить формулу со ВСЕМИ позициями лобовой гонки без заборов.

    Возвращает число совпадений, расхождений и до двадцати расхождений
    подробно. Формула, выведенная по трём таблицам, ничего не стоит, пока не
    проверена перебором.
    """
    n = задача.n
    совпало = 0
    расхождения = []
    for номер, набор, поставлено, красн, син, очередь in задача.все_позиции():
        if задача.расстановки.сколько_заборов[набор]:
            continue
        состояние = исход[номер]
        if состояние == solver.НЕВОЗМОЖНА:
            continue
        r1, c1 = divmod(красн, n)
        r2, c2 = divmod(син, n)
        if c1 != c2:
            continue
        шаги_красных, шаги_синих = r1, n - 1 - r2
        если_красные = очередь == solver.КРАСНЫЕ
        мои = шаги_красных if если_красные else шаги_синих
        чужие = шаги_синих if если_красные else шаги_красных
        расстояние = r1 - r2
        ждём = формула_гонки(мои, чужие, расстояние)
        на_деле = состояние == solver.ВЫИГРЫШ
        if ждём == на_деле:
            совпало += 1
        elif len(расхождения) < 20:
            расхождения.append((мои, чужие, расстояние, 'ждали выигрыш'
                                if ждём else 'ждали проигрыш', состояние))
        else:
            расхождения.append(None)
    return {'совпало': совпало,
            'расхождений': len([р for р in расхождения if р is not None
                                or р is None]),
            'примеры': [р for р in расхождения if р is not None]}


def роль_забора(задача, исход, предел=300000):
    """Забор — это ход, не двигающий фишку, то есть способ отдать темп.

    Считается, в скольких выигранных позициях забор вообще выигрывает и в
    скольких он ЕДИНСТВЕННЫЙ выигрывающий ход. Второе и означает, что без
    забора позиция не берётся.

    Ходы порождаются дёшево, без имён: на семёрке позиций миллионы, и сборка
    строки на каждый ход превратила бы разбор в часы. Сверх `предел` позиций
    разбор останавливается и честно помечает себя выборкой — лучше выборка с
    пометкой, чем цифра, которой никто не дождался.
    """
    if not (задача.заборов_красных or задача.заборов_синих):
        return None
    n = задача.n
    выигранных = забор_среди_выигрышных = только_забор = 0
    осмотрено = 0
    выборка = False
    for номер, набор, поставлено, красн, син, очередь in задача.все_позиции():
        if исход[номер] != solver.ВЫИГРЫШ:
            continue
        if осмотрено >= предел:
            выборка = True
            break
        осмотрено += 1
        выигранных += 1
        я, соперник = ((красн, син) if очередь == solver.КРАСНЫЕ
                       else (син, красн))
        мой_ряд = 0 if очередь == solver.КРАСНЫЕ else n - 1
        следующая = (solver.СИНИЕ if очередь == solver.КРАСНЫЕ
                     else solver.КРАСНЫЕ)

        фишкой_выигрышных = 0
        for куда in задача.ходы_фишкой(набор, я, соперник):
            if куда // n == мой_ряд:
                фишкой_выигрышных += 1
                break
            если_красные = (куда, син) if очередь == solver.КРАСНЫЕ else (красн, куда)
            дальше = задача.номер(набор, поставлено, если_красные[0],
                                  если_красные[1], следующая)
            if исход[дальше] == solver.ПРОИГРЫШ:
                фишкой_выигрышных += 1
                break

        всего_на_доске = задача.расстановки.сколько_заборов[набор]
        осталось = (задача.заборов_красных - поставлено
                    if очередь == solver.КРАСНЫЕ
                    else задача.заборов_синих - (всего_на_доске - поставлено))
        забором_выигрышных = 0
        if осталось > 0:
            новое_поставлено = поставлено + (1 if очередь == solver.КРАСНЫЕ else 0)
            for новый in задача.заборы_отсюда(набор, красн, син):
                дальше = задача.номер(новый, новое_поставлено, красн, син,
                                      следующая)
                if исход[дальше] == solver.ПРОИГРЫШ:
                    забором_выигрышных += 1
                    break

        if забором_выигрышных:
            забор_среди_выигрышных += 1
            if not фишкой_выигрышных:
                только_забор += 1
    return {'выигранных': выигранных,
            'забор_среди_выигрышных': забор_среди_выигрышных,
            'только_забор': только_забор,
            'выборка': выборка}


def _это_забор(запись):
    """Запись хода: «c2» — клетка, «b3г» или «b3в» — забор."""
    return len(запись) > 2 and not запись[-1].isdigit()
