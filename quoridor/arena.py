# -*- coding: utf-8 -*-
"""Турнирный стенд «Заборов»: бот против бота, чтобы «стало сильнее» было измеримым.

Зачем он вообще. Любая правка бота ощущается улучшением — пока не сядешь и не
сыграешь сотню партий. У крестиков-ноликов это уже стоило одного неверного
вывода: перебор на глубину 6 казался сильнее, а на замерах проигрывал, потому
что глубже искалось по неверной оценке. Без стенда такое не видно.

Устройство повторяет games/arena.py, и это намеренно: приём там уже выверен, а
две разные статистики в одном проекте — верный способ однажды поверить не той.
Класс `Итог` прямо оттуда и берётся, чтобы доверительный интервал считался в
проекте ровно одним способом.

Три вещи, без которых стенд бесполезен.

**Случайные дебюты.** Два одинаковых бота из одной позиции сыграют одну и ту же
партию сто раз. В «Заборах» дебют вдобавок почти вынужден — оба идут вперёд, —
поэтому случайности добавляется и заборами, а не только шагами.

**Пары «туда и обратно».** Первый ход в «Заборах» стоит дорого: красные ходят
первыми и им до края столько же, сколько синим. Не меняя цвета, измеришь не
силу, а преимущество выступки.

**Погрешность.** В матче из пятидесяти партий счёт 27:23 не значит ничего: так
ложится монетка. Стенд считает доверительный интервал и прямо говорит, когда
разница неотличима от случайности.
"""

import random
from concurrent.futures import ProcessPoolExecutor
from dataclasses import dataclass, field

from games.arena import Итог          # одна статистика на весь проект
from . import bot
from .engine import (BLUE, RED, apply_move, apply_wall, initial_state,
                     other, pawn_moves, размер, сетка_заборов, wall_problem)

# Сколько случайных полуходов делается перед началом счёта.
ДЕБЮТ_ПОЛУХОДОВ = 4

# Доля заборов среди случайных дебютных ходов. Только шагами дебют почти не
# расходится: обоим сторонам выгодно идти прямо, и партии выходят похожими.
ДОЛЯ_ЗАБОРОВ_В_ДЕБЮТЕ = 0.4

# Предел на партию: если боты зациклились, партия не должна висеть вечно.
ПРЕДЕЛ_ХОДОВ = 400


@dataclass(frozen=True)
class Игрок:
    """Настройка соперника: уровень плюс, если нужно, свои веса оценки."""

    имя: str
    уровень: str = 'hard'
    веса: tuple = field(default=())      # пары (ключ, значение); кортеж — ради хеша

    def как_словарь(self):
        return dict(self.веса) if self.веса else None


def игрок_из_весов(имя, веса, уровень='hard'):
    return Игрок(имя=имя, уровень=уровень, веса=tuple(sorted(веса.items())))


def _случайный_забор(состояние, сторона, rng):
    """Случайный законный забор или None. Ищем наугад, а не перебором всех:
    законных мест почти всегда много, и десяти попыток хватает с запасом."""
    if состояние['wallsLeft'][сторона] <= 0:
        return None
    сетка = сетка_заборов(размер(состояние))
    for _ in range(10):
        wr = rng.randrange(сетка)
        wc = rng.randrange(сетка)
        kind = 'h' if rng.random() < 0.5 else 'v'
        if wall_problem(состояние, сторона, wr, wc, kind) is None:
            return (wr, wc, kind)
    return None


def _случайный_дебют(seed, полуходов=ДЕБЮТ_ПОЛУХОДОВ, n=None):
    """Позиция после нескольких случайных полуходов. Партия не должна успеть
    решиться: дебют нужен ради разнообразия, а не ради форы."""
    rng = random.Random(seed)
    состояние = initial_state() if n is None else initial_state(n)
    for _ in range(полуходов):
        сторона = состояние['turn']
        забор = None
        if rng.random() < ДОЛЯ_ЗАБОРОВ_В_ДЕБЮТЕ:
            забор = _случайный_забор(состояние, сторона, rng)
        if забор is not None:
            новое, ошибка = apply_wall(состояние, сторона, *забор)
        else:
            ходы = pawn_moves(состояние, сторона)
            if not ходы:
                break
            куда = ходы[rng.randrange(len(ходы))]
            новое, ошибка = apply_move(состояние, сторона, куда['r'], куда['c'])
        if ошибка or новое['winner']:
            break
        состояние = новое
    return состояние


def сыграть(за_red, за_blue, состояние, seed):
    """Одна партия из заданной позиции. Возвращает 'red', 'blue' или 'D'."""
    rng = random.Random(seed)
    ходов = 0
    while not состояние['winner'] and ходов < ПРЕДЕЛ_ХОДОВ:
        сторона = состояние['turn']
        игрок = за_red if сторона == RED else за_blue
        ход = bot.choose_move(состояние, сторона, игрок.уровень, rng,
                              игрок.как_словарь())
        if ход is None:
            break
        новое, ошибка = bot.apply_choice(состояние, сторона, ход)
        if ошибка:                                   # pragma: no cover
            raise RuntimeError('бот предложил недопустимый ход: %s' % ошибка)
        состояние = новое
        ходов += 1
    return состояние['winner'] or 'D'


def _пара(задание):
    """Две партии из одной позиции: каждый по разу за красных."""
    первый, второй, seed, n = задание
    позиция = _случайный_дебют(seed, n=n)
    прямая = сыграть(первый, второй, позиция, seed * 2 + 1)
    обратная = сыграть(второй, первый, позиция, seed * 2 + 2)
    return прямая, обратная


def матч(первый, второй, партий=100, ядер=None, seed=0, показывать=None,
         n=None):
    """Матч из `партий` партий (округляется вниз до чётного: пары туда-обратно).

    `n` — сторона поля; None означает стандартную девятку.

    Возвращает Итог глазами ПЕРВОГО игрока.
    """
    пар = max(1, партий // 2)
    задания = [(первый, второй, seed * 100003 + i, n) for i in range(пар)]
    итог = Итог()

    def учесть(прямая, обратная):
        # В прямой первый играл за красных, в обратной — за синих.
        for победитель, первый_был_red in ((прямая, True), (обратная, False)):
            если_первый = RED if первый_был_red else BLUE
            if победитель == 'D':
                итог.ничьи += 1
            elif победитель == если_первый:
                итог.победы += 1
            else:
                итог.поражения += 1

    if ядер == 1:
        for задание in задания:
            учесть(*_пара(задание))
            if показывать:
                показывать(итог)
    else:
        with ProcessPoolExecutor(max_workers=ядер) as пул:
            for прямая, обратная in пул.map(_пара, задания, chunksize=1):
                учесть(прямая, обратная)
                if показывать:
                    показывать(итог)
    return итог


def перчатка(кандидат, соперники, партий=60, ядер=None, seed=0, n=None):
    """Матчи кандидата против НЕПОДВИЖНОГО набора соперников.

    Бот, которого отбирали только против его же потомков, становится мастером
    по обыгрыванию родни и может при этом ослабеть против всех остальных.

    Читать её надо с поправкой: слабый соперник даёт свою долю веса и упирается
    в потолок, поэтому разница между весами в общей доле выглядит меньше, чем
    она есть. Настоящую цену показывает прямой матч на одном уровне.
    """
    итоги = []
    for соперник in соперники:
        итоги.append((соперник,
                      матч(кандидат, соперник, партий, ядер, seed, n=n)))
        seed += 1
    всего = sum(и.очки for _, и in итоги)
    партий_всего = sum(и.партий for _, и in итоги)
    return итоги, (всего / партий_всего if партий_всего else 0.0)
