# -*- coding: utf-8 -*-
"""Проверка правил, вытащенных из точного решения «Заборов».

Зачем эти тесты. Решатель отвечает «выигрывает второй» — пометкой позиции.
Играть по такому ответу нельзя, поэтому из таблиц вытащено правило гонки, и оно
сверено перебором со всеми позициями. Правило легко испортить незаметно:
достаточно поменять порядок направлений в решателе или знак расстояния — и
формула начнёт «почти совпадать». Тесты держат её на маленьких полях, где всё
считается за секунды.
"""

from django.test import SimpleTestCase

from quoridor import solver, strategy


class ФормулаГонки(SimpleTestCase):
    """Закон лобовой гонки: чётность расстояния плюс сравнение шагов."""

    def test_совпадает_со_всеми_позициями_маленьких_полей(self):
        """Главное: формула проверяется перебором, а не примерами."""
        for n in (3, 5, 7):
            задача = solver.Задача(n, 0)
            исход, _ = задача.решить()
            итог = strategy.проверить_формулу_гонки(задача, исход)
            self.assertGreater(итог['совпало'], 0, 'поле %d' % n)
            self.assertEqual(итог['расхождений'], 0,
                             'поле %d: формула разошлась с перебором: %s'
                             % (n, итог['примеры'][:3]))

    def test_старт_это_цугцванг_первого(self):
        """На старте шаги равны, а расстояние n-1 чётное — ходящий проигрывает.

        Отсюда и «выигрывает второй»: первому нечем передать очередь.
        """
        for n in (3, 5, 7, 9):
            self.assertFalse(strategy.формула_гонки(n - 1, n - 1, n - 1),
                             'поле %d' % n)

    def test_нечётное_расстояние_прощает_отставание_на_шаг(self):
        """Подошедший вплотную дарит прыжок — значит, можно отставать на шаг."""
        self.assertTrue(strategy.формула_гонки(4, 3, 1))
        self.assertFalse(strategy.формула_гонки(4, 2, 1))

    def test_чётное_расстояние_требует_быть_впереди(self):
        """При равных шагах и одной пустой клетке между фишками ходящий стоит
        перед выбором: подойти нельзя, стоять нельзя."""
        self.assertFalse(strategy.формула_гонки(4, 4, 2))
        self.assertTrue(strategy.формула_гонки(3, 4, 2))

    def test_разминувшиеся_фишки_просто_бегут(self):
        self.assertTrue(strategy.формула_гонки(3, 3, -2))
        self.assertFalse(strategy.формула_гонки(4, 3, -2))


class ГонкаВнеСтолбца(SimpleTestCase):
    """Вне одного столбца всё решает длина пути — и ничего больше.

    Это половина закона: там, где фишки не встречаются лоб в лоб, прыжок не
    работает и чётность ни при чём. Тест держит границу: если правило начнёт
    ошибаться вне столбца, значит в решателе поехали ходы.
    """

    def test_вне_столбца_правило_не_ошибается(self):
        for n in (5, 7):
            задача = solver.Задача(n, 0)
            исход, _ = задача.решить()
            итог = strategy.проверить_гонку_вне_столбца(задача, исход)
            self.assertGreater(итог['совпало'], 0, 'поле %d' % n)
            self.assertEqual(итог['расхождений'], 0,
                             'поле %d: вне столбца гонка должна решать всё, '
                             'а разошлось: %s' % (n, итог['примеры'][:3]))


class ЗеркалоНеРаботает(SimpleTestCase):
    """Отрицательный результат, записанный тестом, чтобы к нему не возвращались.

    Соблазн очевиден: поле симметрично, пусть второй повторяет ходы первого
    поворотом на 180°. Но зеркалящий всегда на темп позади, и из равного
    положения гонку выигрывает тот, чья очередь.
    """

    def test_симметричная_позиция_не_значит_проигранная(self):
        задача = solver.Задача(5, 0)
        исход, _ = задача.решить()
        итог = strategy.проверить_зеркало(задача, исход)
        self.assertGreater(итог['всего'], 0)
        self.assertLess(итог['проигранных'], итог['всего'],
                        'если бы зеркало работало, проиграны были бы все '
                        'симметричные позиции — а это не так')


class Отражение(SimpleTestCase):
    """Сама арифметика поворота на 180°: клетки и пазы заборов."""

    def test_клетки_переходят_в_противоположные(self):
        n = 5
        # Левый нижний угол -> правый верхний.
        self.assertEqual(strategy.зеркало_клетки(n, (n - 1) * n + 0), 0 * n + n - 1)
        # Центр неподвижен — единственная такая клетка.
        центр = (n // 2) * n + n // 2
        self.assertEqual(strategy.зеркало_клетки(n, центр), центр)

    def test_у_пазов_забора_неподвижных_нет(self):
        """Поле нечётное, поэтому паз (r, c) никогда не совпадает со своим
        отражением (n-2-r, n-2-c) — иначе n было бы чётным."""
        for n in (3, 5, 7, 9):
            for r in range(n - 1):
                for c in range(n - 1):
                    self.assertNotEqual(
                        strategy.зеркало_забора(n, (r, c, 'h')), (r, c, 'h'),
                        'поле %d, паз %d,%d' % (n, r, c))
