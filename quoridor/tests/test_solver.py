# -*- coding: utf-8 -*-
"""
Проверка точного решателя «Заборов».

Главное здесь — не арифметика, а СВЕРКА ПРАВИЛ. Решатель считает по своим,
быстрым таблицам, и это уже третья реализация одних и тех же правил рядом с
engine.py и rules.js. Разойдись она хоть в прыжке через соперника, хоть в
запрете отрезать дорогу — и «доказанный перебором» ответ оказался бы ответом на
другую игру, причём совершенно убедительным на вид.

Поэтому на случайных позициях ходы решателя сверяются с engine.pawn_moves и
engine.wall_problem. Позиции берутся не из головы: они получаются случайной
расстановкой заборов и фишек, включая тесные положения, где и живут прыжки.
"""

import random

from django.test import SimpleTestCase

from quoridor import engine, solver


def _в_движок(задача, набор_номер, красн, син, очередь, поставлено):
    """Позиция решателя -> состояние для engine."""
    n = задача.n
    состояние = engine.initial_state(n)
    состояние['pawns'][engine.RED] = {'r': красн // n, 'c': красн % n}
    состояние['pawns'][engine.BLUE] = {'r': син // n, 'c': син % n}
    состояние['walls'] = {'%d,%d' % (r, c): k
                          for (r, c, k) in задача.расстановки.наборы[набор_номер]}
    всего = задача.расстановки.сколько_заборов[набор_номер]
    состояние['wallsLeft'][engine.RED] = задача.заборов - поставлено
    состояние['wallsLeft'][engine.BLUE] = задача.заборов - (всего - поставлено)
    состояние['turn'] = engine.RED if очередь == solver.КРАСНЫЕ else engine.BLUE
    return состояние


class СверкаПравил(SimpleTestCase):
    """Решатель обязан ходить ровно так же, как движок сайта."""

    # Позиций берётся с запасом: в проверке заборов годится не всякая — у
    # ходящего должен остаться забор, а таких примерно каждая десятая.
    ПОЗИЦИЙ = 6000

    def _случайные_позиции(self, задача, зерно=1):
        rng = random.Random(зерно)
        клеток = задача.клеток
        из = []
        while len(из) < self.ПОЗИЦИЙ:
            набор = rng.randrange(len(задача.расстановки.наборы))
            всего = задача.расстановки.сколько_заборов[набор]
            низ = max(0, всего - задача.заборов)
            верх = min(задача.заборов, всего)
            поставлено = rng.randint(низ, верх)
            красн = rng.randrange(клеток)
            син = rng.randrange(клеток)
            if красн == син:
                continue
            if красн // задача.n == 0 or син // задача.n == задача.n - 1:
                continue
            # Расстановка могла бы отрезать дорогу — движок такую не создал бы.
            if not задача.расстановки.достижим_верх[набор][красн]:
                continue
            if not задача.расстановки.достижим_низ[набор][син]:
                continue
            из.append((набор, поставлено, красн, син,
                       rng.choice((solver.КРАСНЫЕ, solver.СИНИЕ))))
        return из

    def test_ходы_фишкой_совпадают_с_движком(self):
        задача = solver.Задача(5, 1)
        n = задача.n
        for набор, поставлено, красн, син, очередь in \
                self._случайные_позиции(задача):
            состояние = _в_движок(задача, набор, красн, син, очередь, поставлено)
            сторона = engine.RED if очередь == solver.КРАСНЫЕ else engine.BLUE
            я, соперник = ((красн, син) if очередь == solver.КРАСНЫЕ
                           else (син, красн))

            мои = задача.ходы_фишкой(набор, я, соперник)
            движка = [m['r'] * n + m['c']
                      for m in engine.pawn_moves(состояние, сторона)]
            self.assertEqual(
                мои, движка,
                'ходы фишкой разошлись: набор %d, я %d, соперник %d, очередь %s'
                % (набор, я, соперник, сторона))

    def test_постановка_заборов_совпадает_с_движком(self):
        # Два забора на игрока, а не один: при одном у ходящего почти всегда
        # заборов уже нет, и сверять оказывается нечего — из трёх тысяч
        # случайных позиций подходила едва сотня.
        задача = solver.Задача(5, 2)
        места = задача.расстановки.места
        сверено = 0
        for набор, поставлено, красн, син, очередь in \
                self._случайные_позиции(задача, зерно=2):
            состояние = _в_движок(задача, набор, красн, син, очередь, поставлено)
            сторона = engine.RED if очередь == solver.КРАСНЫЕ else engine.BLUE
            if состояние['wallsLeft'][сторона] <= 0:
                continue
            переход = задача.расстановки.переход[набор]
            разрешил_решатель = set()
            for место in range(len(места)):
                новый = переход[место]
                if новый < 0:
                    continue
                if not задача.расстановки.достижим_верх[новый][красн]:
                    continue
                if not задача.расстановки.достижим_низ[новый][син]:
                    continue
                разрешил_решатель.add(места[место])

            разрешил_движок = set()
            for (r, c, k) in места:
                if engine.wall_problem(состояние, сторона, r, c, k) is None:
                    разрешил_движок.add((r, c, k))

            self.assertEqual(разрешил_решатель, разрешил_движок,
                             'заборы разошлись на наборе %d' % набор)
            сверено += 1
        self.assertGreater(сверено, 500)


class Решение(SimpleTestCase):

    def test_поле_три_на_три_без_заборов_проигрышно_для_первого(self):
        """Разобрано вручную и совпадает с перебором.

        Красным до края два шага, синим тоже, и красные ходят первыми — казалось
        бы, они и успевают. Но шаг в центр ставит их прямо перед синими, и те
        ПРЫГАЮТ через них сразу на свой край, выигрывая первым же ходом. Шаг
        вбок теряет темп, и тогда синие доходят обычным путём. Выхода нет.
        """
        задача = solver.Задача(3, 0)
        исход, тупиков = задача.решить()
        self.assertEqual(исход[задача.начальная()], solver.ПРОИГРЫШ)
        self.assertEqual(тупиков, 0)

    def test_выигрыш_в_один_ход_виден(self):
        задача = solver.Задача(3, 0)
        n = задача.n
        # Красные в ряду 1 — им остался шаг до ряда 0.
        номер = задача.номер(0, 0, 1 * n + 0, 0 * n + 2, solver.КРАСНЫЕ)
        сразу, _ = задача.следом(номер)
        self.assertTrue(сразу)

    def test_нумерация_обратима(self):
        задача = solver.Задача(5, 1)
        rng = random.Random(7)
        for _ in range(5000):
            номер = rng.randrange(задача.всего)
            self.assertEqual(задача.номер(*задача.разобрать(номер)), номер)
