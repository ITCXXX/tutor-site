# -*- coding: utf-8 -*-
"""Разбор «Заборов» на полях разного размера.

    manage.py quoridor_study --sizes 5,7,9 --out quoridor/study.txt

Зачем маленькие поля. На девятке одна партия сильного уровня идёт три четверти
минуты, и любая статистика по ней стоит часов. На пятёрке — меньше секунды,
поэтому там можно набрать тысячи партий и разглядеть то, что на девятке тонет
в погрешности: насколько велико преимущество выступки, сколько на самом деле
стоит забор, когда партия решается гонкой, а когда заборами.

Маленькое поле — это не другая игра, а та же с меньшим числом клеток: правила,
бот и оценка ровно те же. Поэтому найденное на пятёрке имеет смысл проверять на
девятке, а не переносить вслепую.

Результаты дописываются в файл по мере готовности: батарея идёт долго, и обрыв
на середине не должен стоить всего.
"""

import os
import time
from collections import Counter

from django.core.management.base import BaseCommand

from quoridor import arena, bot, engine

# Цены забора для перебора. Шаг оставлен равным десяти: для выбора хода важно
# только отношение, поэтому менять достаточно одно число.
ЦЕНЫ_ЗАБОРА = (0.0, 0.5, 1.0, 2.0, 4.0, 7.0, 12.0, 20.0)


class Command(BaseCommand):
    help = 'Батарея замеров «Заборов» на полях разного размера.'

    def add_arguments(self, parser):
        parser.add_argument('--sizes', dest='размеры', default='5,7,9')
        parser.add_argument('--games', dest='партий', type=int, default=400)
        parser.add_argument('--hard-games', dest='партий_сильных', type=int,
                            default=100)
        parser.add_argument('--cores', dest='ядер', type=int, default=None)
        parser.add_argument('--out', dest='файл', default='quoridor/study.txt')
        parser.add_argument('--only', dest='только', default='',
                            help='какие части считать: ladder,first,sweep,shape')

    # ── вывод ──────────────────────────────────────────────────────────────

    def _сказать(self, строка=''):
        self.stdout.write(строка)
        with open(self.файл, 'a', encoding='utf-8') as ф:
            ф.write(строка + '\n')

    # ── части батареи ──────────────────────────────────────────────────────

    def лестница(self, n, партий, партий_сильных, ядер):
        """Держится ли порядок уровней на этом поле."""
        self._сказать('  Лестница уровней (кто кого):')
        пары = (('medium', 'easy', партий),
                ('hard', 'medium', партий_сильных),
                ('hard', 'easy', партий_сильных))
        for сильнее, слабее, сколько in пары:
            t = time.perf_counter()
            итог = arena.матч(arena.Игрок(сильнее, сильнее),
                              arena.Игрок(слабее, слабее),
                              партий=сколько, ядер=ядер, seed=11, n=n)
            self._сказать('    %-7s против %-7s  %5.1f%% ± %.1f%%%s  [%.0f с]'
                          % (сильнее, слабее, 100 * итог.доля,
                             100 * итог.погрешность,
                             '' if итог.значимо else '  (неотличимо)',
                             time.perf_counter() - t))

    def выступка(self, n, партий, ядер):
        """Сколько стоит право первого хода.

        Матч тут не годится: он нарочно меняет цвета, чтобы выступка
        сократилась. Здесь наоборот — считаем, как часто выигрывают красные,
        которые ходят первыми.
        """
        self._сказать('  Преимущество выступки (одинаковые боты):')
        for уровень in ('easy', 'medium'):
            красные = сыграно = 0
            t = time.perf_counter()
            игрок = arena.Игрок(уровень, уровень)
            задания = [(игрок, игрок, 900000 + i, n) for i in range(партий)]
            for прямая, обратная in _параллельно(задания, ядер):
                for победитель in (прямая, обратная):
                    сыграно += 1
                    if победитель == engine.RED:
                        красные += 1
            доля = красные / max(1, сыграно)
            # Погрешность доли по формуле для монетки: тут каждая партия —
            # именно бросок «выиграли красные или нет», ничьих почти не бывает.
            погр = 1.96 * (доля * (1 - доля) / max(1, сыграно)) ** 0.5
            self._сказать('    %-7s красные выигрывают %5.1f%% ± %.1f%% '
                          'из %d партий  [%.0f с]'
                          % (уровень, 100 * доля, 100 * погр, сыграно,
                             time.perf_counter() - t))

    def цена_забора(self, n, партий, ядер):
        """Сколько на самом деле стоит забор относительно шага."""
        self._сказать('  Цена забора (шаг = 10, против нынешних 10 и 2):')
        нынешний = arena.игрок_из_весов('нынешний', dict(bot.ВЕСА), 'medium')
        for цена in ЦЕНЫ_ЗАБОРА:
            веса = dict(bot.ВЕСА)
            веса['забор'] = цена
            кандидат = arena.игрок_из_весов('забор=%g' % цена, веса, 'medium')
            t = time.perf_counter()
            итог = arena.матч(кандидат, нынешний, партий=партий, ядер=ядер,
                              seed=23, n=n)
            self._сказать('    забор=%-5g %5.1f%% ± %.1f%%%s  [%.0f с]'
                          % (цена, 100 * итог.доля, 100 * итог.погрешность,
                             '' if итог.значимо else '  (неотличимо)',
                             time.perf_counter() - t))

    def облик(self, n, партий, ядер):
        """Как выглядит типичная партия: длина, сколько заборов ушло в дело."""
        self._сказать('  Облик партии:')
        for уровень in ('easy', 'medium'):
            игрок = arena.Игрок(уровень, уровень)
            задания = [(игрок, игрок, 700000 + i, n) for i in range(партий // 2)]
            длины, заборов, исходы = [], [], Counter()
            t = time.perf_counter()
            for итог in _подробно(задания, ядер):
                длины.append(итог['полуходов'])
                заборов.append(итог['заборов'])
                исходы[итог['победитель']] += 1
            длины.sort()
            всего = max(1, len(длины))
            self._сказать(
                '    %-7s длина: медиана %d, макс %d | заборов поставлено '
                '%.1f из %d | не кончилось %d из %d  [%.0f с]'
                % (уровень, длины[всего // 2], длины[-1],
                   sum(заборов) / всего, 2 * engine.заборов_на_игрока(n),
                   исходы.get('D', 0), всего, time.perf_counter() - t))

    # ── запуск ─────────────────────────────────────────────────────────────

    def handle(self, *args, **п):
        self.файл = п['файл']
        ядер = п['ядер'] or max(1, (os.cpu_count() or 2) - 1)
        размеры = [int(x) for x in п['размеры'].split(',') if x.strip()]
        части = set(x.strip() for x in п['только'].split(',') if x.strip()) or \
            {'ladder', 'first', 'sweep', 'shape'}

        начало = time.perf_counter()
        self._сказать('')
        self._сказать('=' * 72)
        self._сказать('Разбор «Заборов»: поля %s, ядер %d, %s'
                      % (размеры, ядер, time.strftime('%d.%m %H:%M')))
        self._сказать('=' * 72)

        for n in размеры:
            self._сказать('')
            self._сказать('Поле %dx%d, заборов по %d на игрока'
                          % (n, n, engine.заборов_на_игрока(n)))
            if 'ladder' in части:
                self.лестница(n, п['партий'], п['партий_сильных'], ядер)
            if 'first' in части:
                self.выступка(n, п['партий'], ядер)
            if 'sweep' in части:
                self.цена_забора(n, п['партий'], ядер)
            if 'shape' in части:
                self.облик(n, п['партий'], ядер)

        self._сказать('')
        self._сказать('Вся батарея заняла %.1f мин'
                      % ((time.perf_counter() - начало) / 60))


# ── параллельный счёт партий ───────────────────────────────────────────────

def _параллельно(задания, ядер):
    from concurrent.futures import ProcessPoolExecutor
    if ядер == 1:
        for задание in задания:
            yield arena._пара(задание)
        return
    with ProcessPoolExecutor(max_workers=ядер) as пул:
        for итог in пул.map(arena._пара, задания, chunksize=1):
            yield итог


def _подробно(задания, ядер):
    from concurrent.futures import ProcessPoolExecutor
    if ядер == 1:
        for задание in задания:
            yield подробная_партия(задание)
        return
    with ProcessPoolExecutor(max_workers=ядер) as пул:
        for итог in пул.map(подробная_партия, задания, chunksize=1):
            yield итог


def подробная_партия(задание):
    """Одна партия с подробностями: длина, сколько заборов ушло, чем кончилась."""
    import random
    первый, второй, seed, n = задание
    состояние = arena._случайный_дебют(seed, n=n)
    rng = random.Random(seed * 7 + 1)
    ходов = 0
    while not состояние['winner'] and ходов < arena.ПРЕДЕЛ_ХОДОВ:
        сторона = состояние['turn']
        игрок = первый if сторона == engine.RED else второй
        ход = bot.choose_move(состояние, сторона, игрок.уровень, rng,
                              игрок.как_словарь())
        if ход is None:
            break
        состояние, ошибка = bot.apply_choice(состояние, сторона, ход)
        if ошибка:                                    # pragma: no cover
            break
        ходов += 1
    return {
        'полуходов': ходов,
        'заборов': len(состояние['walls']),
        'победитель': состояние['winner'] or 'D',
    }
