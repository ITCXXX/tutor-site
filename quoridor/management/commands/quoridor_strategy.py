# -*- coding: utf-8 -*-
"""Достать из точного решения «Заборов» не исход, а правило игры.

    manage.py quoridor_strategy --size 5 --walls 1
    manage.py quoridor_strategy --ladder

Решатель отвечает «выигрывает второй». Игроку от этого пользы нет: нужно
правило, по которому ходить. Команда проверяет правила ПЕРЕБОРОМ ВСЕХ ПОЗИЦИЙ:

  • соседство — кто выигрывает, когда фишки стоят вплотную;
  • гонка — кто выигрывает в лобовой гонке на расстоянии d;
  • забор — бывает ли забор единственным выигрывающим ходом;
  • зеркало — отрицательный результат: симметрия НЕ делает позицию проигранной.
"""

import time

from django.core.management.base import BaseCommand, CommandError

from quoridor import solver, strategy

ЛЕСТНИЦА = ((3, 0), (5, 0), (7, 0), (9, 0), (11, 0), (13, 0),
            (3, 1), (3, 2), (5, 1), (5, 2), (7, 1))

ИМЕНА = {
    solver.ВЫИГРЫШ: 'выигрывает ПЕРВЫЙ',
    solver.ПРОИГРЫШ: 'выигрывает ВТОРОЙ',
    solver.НЕИЗВЕСТНО: 'вечная ничья',
}


class Command(BaseCommand):
    help = 'Достать правило игры из точного решения «Заборов».'

    def add_arguments(self, parser):
        parser.add_argument('--size', dest='размер', type=int, default=5)
        parser.add_argument('--walls', dest='заборов', type=int, default=1)
        parser.add_argument('--ladder', dest='лестница', action='store_true')
        parser.add_argument('--race', dest='гонка', action='store_true',
                            help='показать закон гонки по расстояниям')

    def handle(self, *args, **п):
        задачи = ЛЕСТНИЦА if п['лестница'] else [(п['размер'], п['заборов'])]
        for n, заборов in задачи:
            if n < 3 or n % 2 == 0:
                raise CommandError('сторона поля нечётная и не меньше трёх')
            self._одна(n, заборов, п['гонка'] or not п['лестница'])

    def _одна(self, n, заборов, показать_гонку):
        начало = time.perf_counter()
        задача = solver.Задача(n, заборов)
        исход, _ = задача.решить()
        старт = задача.начальная()

        соседство = strategy.правило_соседства(задача, исход)
        зеркало = strategy.проверить_зеркало(задача, исход)

        self.stdout.write('%dx%d, заборов по %d: %s, полуходов до конца %d  [%.0f с]'
                          % (n, n, заборов, ИМЕНА.get(исход[старт], '?'),
                             задача.глубина[старт], time.perf_counter() - начало))

        рв, рп, рн = соседство['рядом']
        пв, пп, пн = соседство['порознь']
        всего_рядом = рв + рп + рн
        self.stdout.write(
            '   фишки вплотную: ходящий выигрывает в %d из %d (%.1f%%), '
            'проигрывает в %d, ничья %d'
            % (рв, всего_рядом, 100.0 * рв / всего_рядом if всего_рядом else 0,
               рп, рн))
        self.stdout.write(
            '   фишки порознь:  ходящий выигрывает в %d, проигрывает в %d, ничья %d'
            % (пв, пп, пн))
        self.stdout.write(
            '   зеркало (отрицательный результат): симметричных позиций %d, '
            'проиграно для ходящего %d — будь зеркало стратегией, было бы всё'
            % (зеркало['всего'], зеркало['проигранных']))

        забор = strategy.роль_забора(задача, исход)
        if забор:
            self.stdout.write(
                '   забор: выигранных позиций %d, забор среди выигрывающих ходов '
                'в %d, забор — ЕДИНСТВЕННЫЙ выигрывающий ход в %d'
                % (забор['выигранных'], забор['забор_среди_выигрышных'],
                   забор['только_забор']))

        if показать_гонку:
            гонка = strategy.закон_гонки(задача, исход)
            if гонка:
                self.stdout.write('   лобовая гонка (один столбец, заборов нет):')
                self.stdout.write('     расст.  ход красных (в/п/н)   ход синих (в/п/н)')
                for расстояние in sorted(гонка):
                    к = гонка[расстояние]['ход красных']
                    с = гонка[расстояние]['ход синих']
                    self.stdout.write('     %5d   %4d/%4d/%4d        %4d/%4d/%4d'
                                      % (расстояние, к[0], к[1], к[2],
                                         с[0], с[1], с[2]))
        self.stdout.write('')
