# -*- coding: utf-8 -*-
"""Решить «Заборы» на маленьком поле перебором до конца.

    manage.py quoridor_solve --size 5 --walls 2
    manage.py quoridor_solve --ladder

Ответ не «этот бот сильнее того», а «при безошибочной игре выигрывает такой-то».
Печатается и главная линия — как именно партия идёт при точной игре обеих
сторон.

Меру осторожности стоит держать в голове: перебирается УМЕНЬШЕННАЯ игра.
Настоящая девятка с десятью заборами не перебирается никакой техникой, и
переносить вывод на неё вслепую нельзя.
"""

import time

from django.core.management.base import BaseCommand, CommandError

from quoridor import solver

ИМЕНА = {
    solver.ВЫИГРЫШ: 'выигрывает ПЕРВЫЙ (красные)',
    solver.ПРОИГРЫШ: 'выигрывает ВТОРОЙ (синие)',
    solver.НЕИЗВЕСТНО: 'вечная ничья',
    solver.НЕВОЗМОЖНА: 'ошибка: стартовая позиция помечена невозможной',
}

# Что успевает посчитаться за разумное время. Пятёрка с тремя заборами — это
# уже полмиллиарда позиций, и она сюда не входит.
ЛЕСТНИЦА = ((3, 0), (5, 0), (7, 0), (9, 0), (3, 1), (3, 2), (5, 1), (5, 2))


class Command(BaseCommand):
    help = 'Точное решение «Заборов» на маленьком поле.'

    def add_arguments(self, parser):
        parser.add_argument('--size', dest='размер', type=int, default=5)
        parser.add_argument('--walls', dest='заборов', type=int, default=1,
                            help='заборов на игрока')
        parser.add_argument('--ladder', dest='лестница', action='store_true',
                            help='посчитать всё, что успевается')
        parser.add_argument('--line', dest='линия', action='store_true',
                            help='показать главную линию')
        parser.add_argument('--dead-end-loses', dest='тупик_проигрыш',
                            action='store_true',
                            help='считать поражением позицию, где ходить нечем')

    def handle(self, *args, **п):
        задачи = ЛЕСТНИЦА if п['лестница'] else [(п['размер'], п['заборов'])]
        for n, заборов in задачи:
            if n < 3 or n % 2 == 0:
                raise CommandError('сторона поля должна быть нечётной и не '
                                   'меньше трёх, а не %d' % n)
            self._одна(n, заборов, п['линия'] or not п['лестница'],
                       п['тупик_проигрыш'])

    def _одна(self, n, заборов, показать_линию, тупик_проигрыш):
        начало = time.perf_counter()
        задача = solver.Задача(n, заборов)
        исход, тупиков = задача.решить(тупик_проигрыш=тупик_проигрыш)
        старт = задача.начальная()

        self.stdout.write(
            '%dx%d, заборов по %d: %-28s  позиций %d, полуходов до конца %d, '
            'тупиков %d, %.0f с'
            % (n, n, заборов, ИМЕНА[исход[старт]], задача.всего,
               задача.глубина[старт], тупиков, time.perf_counter() - начало))

        if показать_линию:
            self.stdout.write('')
            self.stdout.write('  Главная линия (выигрывающий кончает быстрее '
                              'всех, проигрывающий тянет дольше всех):')
            for i, (запись, _) in enumerate(задача.главная_линия(исход, старт), 1):
                self.stdout.write('    %2d. %-8s %s'
                                  % (i, 'красные' if i % 2 else 'синие', запись))
            self.stdout.write('')
